"""As tabelas dos avisos de andamento ao cliente — o consentimento e a fila.

    «quero que implementemos o acompanhamento de protocolo com notificacao
     automatica para o cliente por whatsapp e email para saber do andamento do
     protocolo, caso deseje» — o oficial, 25/10/2026

    «caso deseje» é a regra que manda: sem o SIM do cliente, gravado com data
    e com quem o registrou, nada sai.

AS DUAS TABELAS
    `av_consentimentos`  o SIM do cliente, por CANAL (e-mail, WhatsApp), no
                         protocolo geral (`cx_protocolos`) ou na prenotação do
                         RI (`ri_protocolos`). Guarda o endereço ao qual ele
                         disse sim — se o telefone do cadastro mudar depois, o
                         aviso não vai a um número que ninguém autorizou.
                         Desmarcar NÃO apaga: grava quando e quem revogou. A
                         pergunta «ele tinha autorizado?» precisa de resposta
                         daqui a dois anos.
    `av_avisos`          a fila e o registro do que saiu: um aviso por
                         EVENTO, por canal e por destino (índice único). Diz o
                         que saiu, quando, para onde e em que situação ficou
                         (ENVIADO, FALHOU, PENDENTE_CONFIG, PENDENTE,
                         DESCARTADO).

O «PRONTO PARA RETIRAR» NÃO MORA AQUI
    É coluna do protocolo geral (`cx_protocolos.pronto_retirar_em`), nas
    migrações do `caixa_schema`: é um estado do protocolo, que a tela dele
    mostra, e não um dado dos avisos.

TABELA NOVA VAI NO `SCHEMA`, E NÃO EM `MIGRACOES`
    Regra da casa, a mesma do `automacao_schema`.
"""
from __future__ import annotations

import re

from bd_nativo import banco

# ---------------------------------------------------------------- de onde

PROTOCOLO_GERAL, PRENOTACAO = "PROTOCOLO_GERAL", "PRENOTACAO"
ORIGENS = (PROTOCOLO_GERAL, PRENOTACAO)
NOME_DA_ORIGEM = {PROTOCOLO_GERAL: "protocolo geral", PRENOTACAO: "prenotação do RI"}

# ---------------------------------------------------------------- por onde

EMAIL, WHATSAPP = "EMAIL", "WHATSAPP"
CANAIS = (EMAIL, WHATSAPP)
NOME_DO_CANAL = {EMAIL: "e-mail", WHATSAPP: "WhatsApp"}

# ---------------------------------------------------------------- o quê

#: Os três andamentos que o oficial escolheu avisar (26/10/2026). Só o
#: STATUS: nem CPF, nem valor, nem o teor do ato ou da nota.
EXIGENCIA, PRONTO, PRAZO = "EXIGENCIA", "PRONTO", "PRAZO"
EVENTOS = (EXIGENCIA, PRONTO, PRAZO)
NOME_DO_EVENTO = {
    EXIGENCIA: "exigência (nota devolutiva)",
    PRONTO: "pronto para retirar",
    PRAZO: "prenotação perto de vencer",
}

# ---------------------------------------------------------------- a situação

#: As três primeiras são as mesmas palavras dos avisos da automação
#: (`automacao_schema`), de propósito: quem lê uma tela lê a outra.
ENVIADO, FALHOU, PENDENTE_CONFIG = "ENVIADO", "FALHOU", "PENDENTE_CONFIG"
#: Na fila, esperando a próxima rodada do despachante.
PENDENTE = "PENDENTE"
#: Não sai mais: o andamento passou (a nota foi cumprida, o protocolo foi
#: entregue, a prenotação venceu) ou o cliente desmarcou antes de sair.
DESCARTADO = "DESCARTADO"
SITUACOES = (PENDENTE, ENVIADO, FALHOU, PENDENTE_CONFIG, DESCARTADO)
ROTULO_DA_SITUACAO = {
    PENDENTE: ("na fila", ""),
    ENVIADO: ("enviado", "ok"),
    FALHOU: ("falhou", "critica"),
    PENDENTE_CONFIG: ("não configurado", "media"),
    DESCARTADO: ("descartado", ""),
}


def selo(situacao) -> dict[str, str]:
    texto, classe = ROTULO_DA_SITUACAO.get(str(situacao or ""), (str(situacao or "—"), ""))
    return {"situacao": str(situacao or ""), "texto": texto, "classe": classe}


SCHEMA = """
CREATE TABLE IF NOT EXISTS av_consentimentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem TEXT NOT NULL,
    origem_id bigint NOT NULL,
    canal TEXT NOT NULL,
    destino TEXT NOT NULL,
    ativo INTEGER NOT NULL DEFAULT 1,
    registrado_em TEXT NOT NULL,
    registrado_por TEXT,
    revogado_em TEXT,
    revogado_por TEXT
);
CREATE INDEX IF NOT EXISTS idx_av_consentimentos_origem ON av_consentimentos(origem, origem_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_av_consentimentos_um_ativo
    ON av_consentimentos(origem, origem_id, canal) WHERE ativo = 1;

CREATE TABLE IF NOT EXISTS av_avisos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento TEXT NOT NULL,
    chave TEXT NOT NULL,
    origem TEXT NOT NULL,
    origem_id bigint NOT NULL,
    canal TEXT NOT NULL,
    destino TEXT NOT NULL,
    consentimento_id bigint,
    situacao TEXT NOT NULL DEFAULT 'PENDENTE',
    tentativas INTEGER NOT NULL DEFAULT 0,
    assunto TEXT,
    criado_em TEXT NOT NULL,
    tentado_em TEXT,
    enviado_em TEXT,
    erro TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_av_avisos_um_por_evento
    ON av_avisos(chave, canal, destino);
CREATE INDEX IF NOT EXISTS idx_av_avisos_origem ON av_avisos(origem, origem_id, id);
CREATE INDEX IF NOT EXISTS idx_av_avisos_situacao ON av_avisos(situacao);
"""

MIGRACOES: tuple[tuple[str, str, str], ...] = ()


def init_andamento_schema(con) -> None:
    """Cria as tabelas. Idempotente — o despachante também chama, porque ele
    não sobe o esquema inteiro (`automacao.database_leve`)."""
    bd = banco(con)
    for comando in re.split(r";[ \t]*\n", SCHEMA):
        if re.sub(r"--[^\n]*", "", comando).strip():
            bd.escrever(comando)
    for tabela, coluna, tipo in MIGRACOES:
        if not bd.tem_coluna(tabela, coluna):
            bd.escrever(f"ALTER TABLE {tabela} ADD COLUMN {coluna} {tipo}")
