def eh_so_averbacoes(atribuicao: str, dados: dict,
                     ato_ids: Sequence[int] | None) -> bool:
    """O REGISTRO foi desmarcado, e só averbações restaram? Só LÊ.

    Usada em dois lugares que precisam da MESMA resposta: `montar_teor`
    (para trocar a frase de abertura e não incluir o corpo do registro) e
    `emitir` (para saber que não pode usar o modelo padrão do catálogo —
    ver o comentário lá). Duas contas divergentes da mesma pergunta
    seriam a certidão dizendo uma coisa e escolhendo o modelo de outra.
    """
    p = painel(atribuicao)
    if p["chave"] != "RCPJ_RTD" or ato_ids is None:
        return False
    registro_ato = next(
        (a for a in dados["atos"] if a.get("tipo") == "REGISTRO"), None)
    if registro_ato is None:
        return False
    ids_filtro = {int(x) for x in ato_ids}
    return int(registro_ato["id"]) not in ids_filtro


def _onde(reg: dict, registro_ato: dict | None, con=None) -> str:
    """O `{onde}` do RCPJ/RTD: o livro, a folha, o número e a data. Só monta.

    Saiu de `montar_teor` no LD05 (21/10/2026) sem mudar uma letra: o breve
    relato diz o mesmo lugar do registro, e duas montagens divergiriam.
    """
    serie = reg.get("serie")
    atribuicao_numero = (LN.serie(serie).atribuicao if serie in LN.SERIES
                         else reg.get("atribuicao"))
    nome_registro = frase(PECA_DO_REGISTRO.get(atribuicao_numero, "registro"), con)
    # O volume do acervo vale primeiro (é o que as 38 certidões de lá dizem);
    # sem ele, o número do livro em que o registro foi lavrado aqui (LT05).
    volume = reg.get("volume") or (registro_ato or {}).get("livro_numero")
    onde = _preencher(frase("onde", con), {
        "livro": _livro_impresso(serie, volume),
        "registro": nome_registro}, "onde")
    if registro_ato and registro_ato.get("folha"):
        onde += _preencher(frase("onde_folha", con),
                           {"folha": registro_ato["folha"]}, "onde_folha")
    if reg.get("numero"):
        onde += _preencher(frase("onde_ato", con),
                           {"numero": reg["numero"]}, "onde_ato")
    if registro_ato and registro_ato.get("data_ato"):
        onde += " " + _preencher(frase("onde_data", con),
                                 {"data": _dia(registro_ato["data_ato"])},
                                 "onde_data")
    return onde


# ------------------------------------------------- o breve relato do RCPJ
#
# CN-MA art. 420, II (LD05, 21/10/2026): a certidão do RCPJ «em breve relato
# da situação atual da pessoa jurídica», com a denominação, a sede, o CNPJ, o
# objeto, o capital, os sócios e as participações (fins lucrativos) ou a
# diretoria (sem fins lucrativos), e a data do último ato. A casa só emitia o
# inteiro teor. Os dados vêm da FICHA (`rg_registro.gravar_dados_da_pj`) —
# gravados por quem leu o estatuto e as atas —, e não do balcão; e a leitura
# tem de ser posterior ao último ato, senão não é a situação atual.
CHAVE_BREVE_RELATO = "RCPJ_CERTIDAO_BREVE_RELATO"
FORMAS = ("INTEIRO_TEOR", "BREVE_RELATO")
_TIPO_POR_EXTENSO = {"REGISTRO": "registro", "AVERBACAO": "averbação",
                     "CANCELAMENTO": "cancelamento"}


def teor_do_breve_relato(dados: dict, *, con=None,
                         modelo: str | None = None) -> str:
    """O teor da certidão em breve relato. Só monta (lê o ajuste com `con`)."""
    from cpf_cnpj import formatar_documento
    reg, atos = dados["registro"], dados["atos"]
    if reg.get("serie") != "PJ_A":
        raise CertidaoError(
            "O breve relato é da pessoa jurídica — do registro do Livro A do "
            "RCPJ (CN-MA art. 420, II).")
    faltam = [rotulo for campo, rotulo in (
        ("requerente_nome", "a denominação"), ("pj_sede", "o endereço da sede"),
        ("pj_objeto", "o objeto social")) if not str(reg.get(campo) or "").strip()]
    if not (str(reg.get("pj_socios") or "").strip()
            or str(reg.get("pj_diretoria") or "").strip()):
        faltam.append("os sócios ou a diretoria")
    if faltam:
        raise CertidaoError(
            f"Para o breve relato falta, na ficha do registro, {', '.join(faltam)} "
            f"(CN-MA art. 420, II). A certidão não se redige no balcão: quem lê "
            f"o estatuto e as atas grava os dados da pessoa jurídica na ficha.")
    ultimo = max(atos, key=lambda a: (str(a.get("data_ato") or "")[:10],
                                      int(a.get("id") or 0)), default=None)
    lido_em = str(reg.get("pj_dados_em") or "")
    depois = [a for a in atos if str(a.get("criado_em") or "") > lido_em]
    if depois:
        a = depois[-1]
        raise CertidaoError(
            f"Os dados da pessoa jurídica na ficha são de {_dia(lido_em) or 'antes'}, "
            f"e o ato n. {a.get('numero_ordem') or ''} ({a.get('tipo')}) foi lavrado "
            f"depois. O breve relato é da situação ATUAL: confira o que o ato mudou "
            f"e grave os dados de novo na ficha.")
    registro_ato = next((a for a in atos if a.get("tipo") == "REGISTRO"), None)

    def peca(nome: str, valor: str) -> str:
        valor = str(valor or "").strip()
        if not valor:
            return ""
        chave = f"{CHAVE_BREVE_RELATO}__{nome}"
        texto = (MODELOS.padrao_de(chave) if con is None
                 else MODELOS.texto_do_papel(con, chave))
        # a quebra de linha que cola a peça é do código: o ajuste da casa é
        # gravado com `strip()`
        return "\n" + _preencher(texto, {nome: valor}, chave)

    claros = {
        "onde": _onde(reg, registro_ato, con),
        "denominacao": str(reg.get("requerente_nome")).strip(),
        "sede": str(reg.get("pj_sede")).strip(),
        "cnpj": (formatar_documento(reg.get("requerente_documento"))
                 if str(reg.get("requerente_documento") or "").strip()
                 else "não consta do registro"),
        "objeto": str(reg.get("pj_objeto")).strip(),
        "capital": peca("capital", reg.get("pj_capital")),
        "socios": peca("socios", reg.get("pj_socios")),
        "diretoria": peca("diretoria", reg.get("pj_diretoria")),
        "ultimo_ato": (f"{_dia(ultimo.get('data_ato'))} ("
                       f"{_TIPO_POR_EXTENSO.get(str(ultimo.get('tipo') or '').upper(), 'ato')}"
                       f" n. {ultimo.get('numero_ordem') or ''})") if ultimo else "",
    }
    texto = modelo if modelo is not None else (
        MODELOS.texto_do_papel(con, CHAVE_BREVE_RELATO) if con is not None
        else MODELOS.padrao_de(CHAVE_BREVE_RELATO))
    return _preencher(texto, claros, CHAVE_BREVE_RELATO).strip()


def conferir_breve_relato(corpo: str) -> str:
    """O breve relato que a tela vai gravar monta? Devolve o erro, ou ``""``."""
    try:
        (corpo or "").format(onde='no Livro "A-1"', denominacao="ASSOCIAÇÃO DE EXEMPLO",
                             sede="Rua de Exemplo, 1", cnpj="00.000.043/0001-77",
                             objeto="Exemplo.", capital="", socios="",
                             diretoria="", ultimo_ato="01/10/2026")
    except (KeyError, ValueError, IndexError) as erro:
        return (f"O modelo usa um claro que esta certidão não tem ({erro}). Os "
                "que ela tem: {onde}, {denominacao}, {sede}, {cnpj}, {objeto}, "
                "{capital}, {socios}, {diretoria} e {ultimo_ato}.")
    return ""


def montar_teor(atribuicao: str, dados: dict, *, modelo: str | None = None,
                 ato_ids: Sequence[int] | None = None,
                 modelo_so_averbacoes: str | None = None, con=None,
                 sv: dict | None = None) -> str:
    """O teor da certidao, nas palavras que esta casa usa.

    Nao grava nada: recebe o que `registro()` devolveu. So le o banco quando
    recebe `con`, e so para o TEXTO das frases — o ajuste da casa nas pecas de
    RCPJ_CERTIDAO (LF06F, ver `frase`) e na frase do Livro 3 que saiu do
    codigo no LF06B (`RI_LIVRO3_SEM_ATOS`); sem `con`, o padrao da base.

    No RCPJ/RTD, cada ato reproduzido leva o fecho do termo dele e o selo
    (`fecho_do_ato`, LD05) — com `con` e `sv` (a serventia: cidade e UF do
    local e data); sem eles, so o selo que o ato tiver.
    """
    p = painel(atribuicao)
    reg, atos = dados["registro"], dados["atos"]
    registro_ato = next((a for a in atos if a.get("tipo") == "REGISTRO"), None)
    ids_filtro = {int(x) for x in ato_ids} if ato_ids is not None else None

    # **O OBJETO CERTIFICADO É O QUE FOI MARCADO, E NÃO SEMPRE O REGISTRO**
    # — pedido do oficial em 11/09/2026: «apesar de ter escolhido duas
    # averbações para constar na certidão, foi erroneamente como objeto o
    # registro da assembleia de constituição». Se o operador desmarcou o
    # próprio ato de REGISTRO (só quer as averbações), a certidão não pode
    # continuar afirmando «encontrei o seguinte registro» com o corpo dele
    # — o objeto agora é a(s) averbação(ões) escolhida(s).
    so_averbacoes = eh_so_averbacoes(atribuicao, dados, ato_ids)

    teor = ""
    if not so_averbacoes:
        teor = (reg.get("teor") or "").strip()
        if not teor:
            # Se o REGISTRO nao tem teor, o ato de registro pode ter: no
            # RCPJ/RTD a carga poe o inteiro teor nos dois.
            teor = next((str(a.get("teor") or "").strip() for a in atos
                        if str(a.get("teor") or "").strip()), "")
        if not teor:
            raise CertidaoError(
                f"O registro n. {reg.get('numero')} existe no livro, mas o "
                f"acervo do sistema antigo não trouxe o teor dele — e certidão de "
                f"inteiro teor sem o teor seria papel que promete o que não "
                f"entrega. A cópia se tira do livro físico.")

    if p["chave"] == "LIVRO3":
        # **AS AVERBAÇÕES ENTRAM NO TEOR — 21/09/2026.** Ver o comentário do
        # modelo: até aqui elas eram ignoradas em silêncio, e uma certidão do
        # registro 1.243 sairia sem dizer que ele foi cancelado.
        return _teor_do_livro3(modelo or MODELOS.padrao_de("RI_LIVRO3_CERTIDAO"),
                               reg, atos,
                               teor, ids_filtro,
                               partes=dados.get("partes"), con=con)

    # RCPJ / RTD
    #
    # O `{onde}` SE MONTA DE FRASES, E A REGRA DE CADA UMA FICA AQUI: o livro e
    # o nome do registro sempre; a folha, o número do ato e a data só se o
    # registro os tem. O texto de cada frase é peça de RCPJ_CERTIDAO desde o
    # LF06F (`frase`), com a vírgula do começo, que é dela.
    #
    # **O ESPAÇO QUE COLA A DATA É DO CÓDIGO, E NÃO DA PEÇA** (a regra do
    # LF06C): o ajuste da casa é gravado com `strip()`, e uma peça « datada
    # de …» o perderia no primeiro ajuste — «ATO n. 148datada de …».
    onde = _onde(reg, registro_ato, con)
    natureza = (reg.get("natureza") or "").strip()
    # Averbações posteriores ao registro entram no teor textual — o oficial
    # precisa vê-las na certidão depois de averbar (11/09/2026). Só o que
    # já está em rg_atos; não se inventa conteúdo.
    blocos_av = []
    blocos_cancelamento = []
    separador_av = None
    for a in atos:
        tipo_a = str(a.get("tipo") or "").upper()
        if tipo_a not in ("AVERBACAO", "CANCELAMENTO"):
            continue
        # O ATO DE CANCELAMENTO ENTRA SEMPRE — LT05, 20/10/2026. A certidão
        # do registro cancelado dizia «encontra-se CANCELADO» e calava o ato
        # que o cancelou: número, data e a razão que a Lei 6.015, art. 165,
        # manda certificar na coluna das averbações. A frase de cancelado
        # entra sem depender da marcação da tela, e o ato que a explica
        # também; a tela nem oferece marcá-lo.
        if (tipo_a == "AVERBACAO" and ids_filtro is not None
                and int(a["id"]) not in ids_filtro):
            continue
        teor_av = (a.get("teor") or "").strip()
        if tipo_a == "CANCELAMENTO":
            teor_av = teor_av or (a.get("motivo_cancelamento") or "").strip()
        if not teor_av:
            continue
        teor_av = _com_fecho(teor_av, fecho_do_ato(a, reg, sv=sv, con=con))
        ordem = a.get("numero_ordem") or a.get("rotulo") or ""
        if separador_av is None:
            separador_av = frase("averbacao", con)
        bloco = _preencher(separador_av, {"ordem": ordem, "teor": teor_av},
                           "averbacao")
        (blocos_cancelamento if tipo_a == "CANCELAMENTO" else blocos_av).append(bloco)

    if so_averbacoes:
        if not blocos_av:
            raise CertidaoError(
                "Nenhuma averbação com teor foi selecionada para esta "
                "certidão, e o registro-base também não foi marcado — "
                "marque ao menos um ato com conteúdo para certificar.")
        teor_final = "\n\n".join(blocos_av + blocos_cancelamento)
        # **`modelo` NÃO SE USA AQUI** — achado do oficial em 12/09/2026:
        # a certidão continuava dizendo «encontrei o seguinte registro»
        # mesmo com o registro desmarcado. A causa: `mo_modelos` está
        # vazio (nenhum ajuste salvo), e o catálogo (`modelos_da_casa`)
        # devolve, como PISO, o texto de `MODELO_CERTIDAO_RCPJ_RTD` — o
        # modelo de SEMPRE, não o de só-averbações, porque ainda não havia
        # uma chave própria no catálogo para este caso. `modelo` chegava
        # aqui sempre preenchido com o texto errado, e `modelo or ...`
        # nunca chegava a usar o padrão certo.
        #
        # **A CHAVE PRÓPRIA EXISTE DESDE O LF06F** (19/10/2026):
        # RCPJ_RTD_CERTIDAO_SO_AVERBACOES. `emitir()` a busca na casa e a
        # manda em `modelo_so_averbacoes`; `modelo` continua sem uso aqui,
        # que é a segunda trava para quem chamar `montar_teor` direto.
        try:
            return (modelo_so_averbacoes
                    or MODELOS.padrao_de(CHAVE_SO_AVERBACOES)).format(
                onde=onde, natureza=(", " + natureza if natureza else ""),
                teor=teor_final, numero=reg.get("numero") or "")
        except (KeyError, ValueError) as erro:
            raise CertidaoError(f"O modelo da certidão de averbação está incompleto: {erro}.") from erro

    if registro_ato:
        teor = _com_fecho(teor, fecho_do_ato(registro_ato, reg, sv=sv, con=con))
    if blocos_av or blocos_cancelamento:
        teor = (teor.rstrip() + "\n\n"
                + "\n\n".join(blocos_av + blocos_cancelamento))
    try:
        # Sem modelo, o PADRÃO da base. RCPJ_CERTIDAO e RTD_CERTIDAO nasceram da
        # mesma constante e são o mesmo texto (o teste confere); o nome antigo
        # `MODELO_CERTIDAO_RCPJ_RTD` respondia pelo primeiro, e este também.
        return (modelo or MODELOS.padrao_de("RCPJ_CERTIDAO")).format(
            onde=onde, natureza=(", " + natureza if natureza else ""),
            teor=teor, numero=reg.get("numero") or "")
    except (KeyError, ValueError) as erro:
        raise CertidaoError(f"O modelo da certidão de inteiro teor está incompleto: {erro}.") from erro


def teor_traz_cabecalho(teor: str | None) -> bool:
    """O teor ja comeca com o cabecalho da serventia?

    O E-OFICIO GUARDAVA A PAGINA INTEIRA. `memInteiroTeorSemFormatacao` nao e
    so o registro: e a folha como saia impressa, com "REPUBLICA FEDERATIVA DO
    BRASIL", a comarca, o endereco e o nome do oficial no alto.

    Quem imprime decide o que fazer com isso: se o teor ja traz cabecalho, o
    `.odt` NAO poe o dele em cima — sairiam dois. E nao se corta nada do teor:
    texto de certidao nao se edita, so se decide onde ele entra na folha.
    """
    # Procura no TEXTO INTEIRO, e nao so no comeco: o cabecalho antigo fica
    # dentro do teor do registro, que na certidao ja vem depois da frase de
    # abertura. E exige as DUAS marcas — so "Republica Federativa do Brasil"
    # apareceria num registro que a cite por outro motivo.
    todo = " ".join(str(teor or "").split()).upper()
    tem_brasao = ("REPÚBLICA FEDERATIVA DO BRASIL" in todo
                  or "REPUBLICA FEDERATIVA DO BRASIL" in todo)
    return tem_brasao and "SERVENTIA EXTRAJUDICIAL" in todo


def papel_por_texto(con, certidao: dict, *, sv: dict, hoje: str) -> str:
    """O papel da certidão do RCPJ/RTD por texto — o HTML que vira `.odt`. Só lê.

    **ERA UMA F-STRING NA ROTA** (`atribuicoes_web.atribuicoes_certidao_odt`)
    e virou o papel RCPJ_RTD_CERTIDAO_ODT do catálogo no LF06F (19/10/2026):
    o cabeçalho, o «CERTIDÃO n.», o «CERTIDÃO CANCELADA», o local e a data, a
    assinatura e a autenticidade passam a ser editáveis na tela de Modelos.

    **A REGRA FICA AQUI, E O TEOR NÃO SE MEXE**: o cabeçalho da casa só sai se
    o teor não trouxer o dele (`teor_traz_cabecalho`), a certidão cancelada
    diz que é, e o teor congelado entra como está, partido nas linhas em
    branco — texto de certidão não se edita, só se decide onde ele entra.
    """
    return _montar_papel_por_texto(
        MODELOS.texto_do_papel(con, CHAVE_PAPEL_POR_TEXTO), certidao, sv=sv,
        hoje=hoje)


def _montar_papel_por_texto(modelo: str, certidao: dict, *, sv: dict,
                            hoje: str) -> str:
    from jinja2.sandbox import SandboxedEnvironment
    teor = str(certidao["teor"])
    papel = SandboxedEnvironment(autoescape=False).from_string(modelo).render(
        c=certidao, sv=sv, hoje=hoje,
        com_cabecalho=not teor_traz_cabecalho(teor),
        cancelada=bool(int(certidao["cancelada"] or 0)),
        blocos=[bloco for bloco in teor.split("\n\n") if bloco.strip()])
    # O AJUSTE DA CASA SAI SEM O QUE EXECUTA (revisão de segurança de
    # 22/10/2026, A7): o modelo é editável na tela de Modelos e o papel vai ao
    # navegador com `|safe`. O teor congelado é da casa e passa como está; o
    # padrão de fábrica sai byte a byte como saía.
    return MODELOS.sem_o_que_executa(modelo, papel)


# A CONFERÊNCIA DA TELA DE MODELOS (LF06F). O boneco geral da tela não tem
# `c` nem `blocos`, e recusaria todo papel por texto que usasse um claro; e
# não conhece os claros das chaves, e aprovaria um `{inventado}` que só
# estouraria na emissão, com o cliente na frente. Cada papel confere com a
