# ------------------------------------------------- a certidão negativa
#
# «a tabela tem os itens (serviços 314 e 315, "Certidão Negativa para Pessoas
# Jurídicas / Títulos e Documentos"), mas a casa só emite certidão de um
# registro que existe» — o defeito que o LT05 achou, e o LD05 conserta
# (21/10/2026). LRP arts. 16, 17 e 19; CN-MA art. 963, § 3º: o oficial fornece
# as certidões pedidas pelo NOME das partes que figurem, por qualquer modo, nos
# livros de registro ou averbação.
#
#   A PESQUISA É A DO INDICADOR DA CASA: o requerente do registro (nome ou
#   CPF/CNPJ) e o nome no texto do registro e das averbações — o «por qualquer
#   modo» da norma. Registro cancelado também CONSTA: a certidão dele é a
#   positiva, que diz que foi cancelado. Achou alguma coisa, a negativa é
#   recusada ANTES de numerar, dizendo onde está: certidão negativa de quem
#   consta é a pior mentira que esta casa pode assinar.
#
#   UMA CERTIDÃO COMO AS OUTRAS: mesma numeração do exercício, mesmo teor
#   congelado com sha256, mesmo papel por texto. O que ela não tem é registro
#   — `registro_id` 0 (`eh_negativa`).
CHAVE_NEGATIVA = "RCPJ_RTD_CERTIDAO_NEGATIVA"
ATRIBUICOES_DA_NEGATIVA = {"RTD": 4, "RCPJ": 3}
_COM_ACENTO = "áàâãäéèêëíìîïóòôõöúùûüçñÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑ"
_SEM_ACENTO = "aaaaaeeeeiiiiooooouuuucnAAAAAEEEEIIIIOOOOOUUUUCN"


def eh_negativa(certidao: dict) -> bool:
    """A certidão é negativa — não tem registro? Só calcula."""
    return not int((certidao or {}).get("registro_id") or 0)


def _nome_de_busca(nome: Any) -> str:
    """Sem acento, em caixa alta, com um espaço entre as palavras — a mesma
    régua dos dois lados da comparação (o banco é `C`: o `upper` dele não
    conhece acento, e por isso o acento sai antes)."""
    import unicodedata
    sem = "".join(c for c in unicodedata.normalize("NFD", str(nome or ""))
                  if unicodedata.category(c) != "Mn")
    return " ".join(sem.upper().split())


def consta_em_nome_de(con, *, atribuicao: int, nome: Any,
                      documento: Any = None) -> list[dict]:
    """Os registros da atribuição em que a pessoa figura. Só LÊ.

    Pelo requerente (nome igual, ou o mesmo CPF/CNPJ) e pelo nome no texto do
    registro e de qualquer ato dele.
    """
    alvo = _nome_de_busca(nome)
    doc = "".join(c for c in str(documento or "") if c.isdigit())
    return banco(con).ler(
        """SELECT r.id, r.numero, r.serie, r.situacao, r.requerente_nome
             FROM rg_registros r
            WHERE r.atribuicao = %(a)s
              AND ((%(doc)s <> '' AND digitos(r.requerente_documento) = %(doc)s)
                OR upper(translate(coalesce(r.requerente_nome, ''), %(de)s, %(para)s))
                   = %(nome)s
                OR upper(translate(coalesce(r.teor, ''), %(de)s, %(para)s))
                   LIKE %(trecho)s
                OR EXISTS (SELECT 1 FROM rg_atos a
                            WHERE a.registro_id = r.id
                              AND upper(translate(coalesce(a.teor, ''), %(de)s,
                                                  %(para)s)) LIKE %(trecho)s))
            ORDER BY r.id""",
        {"a": int(atribuicao), "doc": doc, "nome": alvo,
         "trecho": f"%{alvo}%", "de": _COM_ACENTO, "para": _SEM_ACENTO})


def teor_da_negativa(*, atribuicao: str, nome: Any, documento: Any = None,
                     con=None, modelo: str | None = None) -> str:
    """O teor da certidão negativa. Só monta (lê o ajuste da casa com `con`)."""
    from cpf_cnpj import formatar_documento
    sigla = str(atribuicao or "").strip().upper()
    if sigla not in ATRIBUICOES_DA_NEGATIVA:
        raise CertidaoError(
            "Diga se a certidão negativa é do RTD ou do RCPJ — a pesquisa é "
            "nos livros de uma atribuição.")
    quem = " ".join(str(nome or "").split())
    if len(quem) < 3:
        raise CertidaoError(
            "Escreva o nome de quem se pesquisa — a certidão negativa é pelo "
            "nome (CN-MA art. 963, § 3º).")
    doc = "".join(c for c in str(documento or "") if c.isdigit())
    claros = {
        "registro": frase("registro_rcpj" if sigla == "RCPJ" else "registro_rtd", con),
        "nome": quem,
        "documento": (_preencher(frase_da_negativa("documento", con),
                                 {"documento": formatar_documento(doc)},
                                 f"{CHAVE_NEGATIVA}__documento") if doc else ""),
    }
    texto = modelo if modelo is not None else (
        MODELOS.texto_do_papel(con, CHAVE_NEGATIVA) if con is not None
        else MODELOS.padrao_de(CHAVE_NEGATIVA))
    return _preencher(texto, claros, CHAVE_NEGATIVA).strip()


def frase_da_negativa(peca: str, con=None) -> str:
    """A peça `RCPJ_RTD_CERTIDAO_NEGATIVA__<peca>`, com o ajuste da casa. Só lê."""
    chave = f"{CHAVE_NEGATIVA}__{peca}"
    return MODELOS.padrao_de(chave) if con is None else MODELOS.texto_do_papel(con, chave)


def conferir_negativa(corpo: str) -> str:
    """A negativa que a tela vai gravar monta? Devolve o erro, ou ``""``."""
    try:
        (corpo or "").format(registro="Registro de Títulos e Documentos",
                             nome="FULANO DE EXEMPLO", documento="")
    except (KeyError, ValueError, IndexError) as erro:
        return (f"O modelo usa um claro que esta certidão não tem ({erro}). Os "
                "que ela tem: {registro}, {nome} e {documento}.")
    return ""


def emitir_negativa(con, *, atribuicao: str, nome: Any, documento: Any = None,
                    hoje: str, agora: str, requerente: str | None = None,
                    requerente_documento: str | None = None,
                    finalidade: str | None = None, usuario: str | None = None,
                    usuario_nome: str | None = None,
                    usuario_funcao: str | None = None) -> dict:
    """Emite a certidão negativa do RTD ou do RCPJ. ESCREVE.

    Pesquisa ANTES de numerar: se a pessoa consta, recusa dizendo onde — a
    certidão dela é a do registro, pela ficha.
    """
    bd = banco(con)
    sigla = str(atribuicao or "").strip().upper()
    teor = teor_da_negativa(atribuicao=sigla, nome=nome, documento=documento,
                            con=bd)
    achados = consta_em_nome_de(bd, atribuicao=ATRIBUICOES_DA_NEGATIVA[sigla],
                                nome=nome, documento=documento)
    if achados:
        onde = ", ".join(
            f"Registro n. {a['numero'] or '—'} ({a['serie']}"
            + (", cancelado" if str(a["situacao"] or "").upper() == "CANCELADO"
               else "") + ")" for a in achados[:5])
        raise CertidaoError(
            f"Consta registro em que figura {' '.join(str(nome).split())}: "
            f"{onde}. A certidão não é negativa — emita a do registro, pela "
            f"ficha dele. Nada foi emitido.")
    p = painel("RCPJ_RTD")
    ano = int(str(hoje)[:4])
    bd.travar("at_certidoes.numero")
    numero = proximo_numero(bd, p["chave"], ano)
    teor = sem_linha_de_assinatura_a_mao(teor)
    impressao = hash_certidao(p["chave"], numero, ano, teor, agora)
    novo = bd.escrever(
        """INSERT INTO at_certidoes(atribuicao, numero, ano, tabela,
               registro_id, registro_numero, requerente, requerente_documento,
               finalidade, atos, teor, hash_certidao, validade_ate, emitida_em,
               emitida_por, emitida_por_nome, emitida_por_funcao, fonte_corpo)
           VALUES (%s,%s,%s,%s,0,NULL,%s,%s,%s,0,%s,%s,%s,%s,%s,%s,%s,'TEXTO')
           RETURNING id""",
        (p["chave"], numero, ano, p["tabela"], (requerente or "").strip() or None,
         ("".join(c for c in str(requerente_documento or "") if c.isdigit())
          or None),
         (finalidade or "").strip() or None, teor, impressao, validade_de(hoje),
         agora, usuario, (usuario_nome or "").strip() or None,
         (usuario_funcao or "").strip() or None))
    return {"certidao_id": int(novo[0]["id"]), "numero": numero, "ano": ano,
            "atribuicao": p["chave"], "nome": p["nome"], "teor": teor,
            "hash": impressao, "sigla": sigla}


def hash_certidao(atribuicao: str, numero: int, ano: int, teor: str,
                  emitida_em: str) -> str:
    """Impressao digital da certidao, para provar que a segunda via e a mesma."""
    bruto = f"{atribuicao}|{numero}|{ano}|{emitida_em}|{teor}"
    return hashlib.sha256(bruto.encode("utf-8")).hexdigest()


