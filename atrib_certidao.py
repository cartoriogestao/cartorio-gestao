def _dia(data: Any) -> str:
    """`2022-01-31` -> `31/01/2022`. E como as certidoes do acervo escrevem."""
    s = str(data or "")[:10]
    if len(s) == 10 and s[4] == "-":
        return f"{s[8:10]}/{s[5:7]}/{s[:4]}"
    return s


