def registro(con, atribuicao: str,
             registro_id: int) -> dict | None:
    """O registro e os atos dele, para a certidao. So LE."""
    p = painel(atribuicao)
    bd = banco(con)
    linha = bd.um(f"SELECT * FROM {p['tabela']} WHERE id = %s",
                  (int(registro_id),))
    if not linha:
        return None
    if p["chave"] == "RCPJ_RTD":
        # O NÚMERO DO LIVRO VEM JUNTO — LT05, 20/10/2026. O registro lavrado
        # por esta casa não tem `volume` (é coluna da carga do E-Ofício); o
        # livro dele está em `nu_livros`, e sem isto a certidão dizia só
        # `no Livro "B"`, sem o número do volume que a Lei 6.015, art. 18,
        # manda mencionar.
        atos = bd.ler(
            """SELECT a.*, (SELECT l.numero FROM nu_livros l
                             WHERE l.id = a.livro_id) AS livro_numero
                 FROM rg_atos a WHERE a.registro_id = %s ORDER BY a.id""",
            (int(registro_id),))
    else:
        atos = bd.ler(
            f"SELECT * FROM {p['atos']} WHERE registro_id = %s ORDER BY id",
            (int(registro_id),))
    out: dict = {"painel": p, "registro": linha, "atos": atos}
    if p["chave"] == "LIVRO3":
        out["partes"] = bd.ler(
            "SELECT * FROM ra_partes WHERE registro_id = %s ORDER BY id",
            (int(registro_id),))
    return out


def certidao(con, certidao_id: int) -> dict | None:
    """A certidao, como foi emitida. So LE."""
    return banco(con).um("SELECT * FROM at_certidoes WHERE id = %s",
                         (int(certidao_id),))


def listar(con, *, atribuicao: str | None = None,
           termo: str = "", limite: int = 100) -> list[dict]:
    """As certidoes emitidas, da mais nova para a mais velha. So LE."""
    onde, params = [], []
    if atribuicao:
        onde.append("atribuicao = %s")
        params.append(painel(atribuicao)["chave"])
    t = (termo or "").strip()
    if t:
        onde.append("(registro_numero ILIKE %s OR requerente ILIKE %s "
                    "OR numero::text = %s)")
        params += [f"%{t}%", f"%{t}%", t]
    filtro = (" WHERE " + " AND ".join(onde)) if onde else ""
    return banco(con).ler(
        f"""SELECT * FROM at_certidoes{filtro}
             ORDER BY ano DESC, numero DESC, id DESC LIMIT %s""",
        (*params, int(limite)))


def proximo_numero(con, atribuicao: str, ano: int) -> int:
    """O proximo numero do exercicio, naquela atribuicao. So LE.

    GET nao abre transacao de escrita: a tela de conferencia chama isto, e
    contador consumido num GET fica preso no `busy_timeout`.
    """
    n = banco(con).valor(
        """SELECT MAX(numero) AS n FROM at_certidoes
            WHERE atribuicao = %s AND ano = %s""",
        (painel(atribuicao)["chave"], int(ano)))
    return int(n or 0) + 1


