"""A COMUNICAÇÃO DA CASA — conversas entre todos e avisos da gerência (T028).

    «o nosso modulo precisa ser de facil acesso na coluna da direita, precisa ter
     opcao dos admins e gerentes de colocar comunicacoes que ficam (harmonicamente)
     insistentes na tela ate o escrevente clicar que esta fazendo [...] o sistema de
     comunicacao precisa ser simples e efetivo»            — o titular, 28/11/2026

    «todos do cartorio devem conseguir mandar mensagem para qualquer outro usuario e
     conversar com fluidez e recursos essenciais que tornam um mensageiro amigavel e
     util [...] destinatarios podem ser toda equipe, usuarios selecionados em grupo
     (podendo criar grupo por atribuicao, por exemplo) ou apenas um escrevente»
                                                         — o titular, 28/11/2026

DOIS PEDAÇOS, UM MÓDULO
    Este arquivo é o MENSAGEIRO: conversa direta com qualquer pessoa, grupos com
    nome, mensagens com resposta, anexo, edição e «vista». `comunicacao_avisos.py`
    são os AVISOS DA GERÊNCIA, que insistem na tela em três graus até a pessoa
    marcar «estou fazendo». Os dois usam os mesmos grupos: o grupo de conversa é
    também destino de aviso (o «grupo por atribuição» do titular).

O QUE SE APROVEITOU DE QUEM JÁ FAZ ISSO (só a ideia; nenhuma linha copiada)
    - Mattermost (`ChannelMember.LastViewedAt`/`MsgCount`): o «lido» é UM
      ponteiro por pessoa e conversa (`cm_participantes.ultima_lida_id`), e não
      uma linha por mensagem. As não lidas são as mensagens dos outros depois
      dele; o «vista por N de M» compara os ponteiros dos outros.
    - Zulip (`Message.edit_history`): a mensagem editada ou apagada guarda o
      texto de antes (`cm_mensagens_historico`). Cartório não perde o que disse.
    - WhatsApp/Slack: editar e apagar só por 15 minutos; Enter envia e
      Shift+Enter quebra a linha; o rascunho fica por conversa (o script).

O QUE ESTE MÓDULO NÃO FAZ
    Não tem Flask e não lê sessão: quem chama diz quem é e que horas são
    (`agora`, texto ISO da casa). Não abre transação: quem grava passa a
    conexão da transação (`db.transaction()`), e o que se grava aqui vai junto
    com o `audit_logs` dela ou não vai.
"""
