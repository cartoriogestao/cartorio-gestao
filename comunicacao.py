_SELECT_MENSAGEM = """
    SELECT m.id, m.conversa_id, m.autor_id, m.texto, m.resposta_a, m.anexo_id,
           m.criada_em, m.editada_em, m.apagada_em,
           u.full_name AS autor,
           r.texto AS resposta_texto, r.apagada_em AS resposta_apagada,
           ru.full_name AS resposta_autor,
           a.nome_original AS anexo_nome, a.tamanho AS anexo_tamanho, a.tipo_mime AS anexo_tipo
      FROM cm_mensagens m
      JOIN users u ON u.id = m.autor_id
 LEFT JOIN cm_mensagens r ON r.id = m.resposta_a
 LEFT JOIN users ru ON ru.id = r.autor_id
 LEFT JOIN cm_anexos a ON a.id = m.anexo_id
"""


def mensagens(con, conversa_id: int, user_id: int, *, depois: int = 0,
              antes: int | None = None, limite: int = MENSAGENS_POR_PAGINA) -> list[dict]:
    """As mensagens em ordem de envio. `depois` = as novas; `antes` = as anteriores."""
    bd = banco(con)
    _participa(bd, conversa_id, user_id)
    if antes:
        linhas = bd.ler(_SELECT_MENSAGEM + " WHERE m.conversa_id=%s AND m.id < %s "
                        "ORDER BY m.id DESC LIMIT %s", (int(conversa_id), int(antes), int(limite)))
        return list(reversed(linhas))
    if depois:
        return bd.ler(_SELECT_MENSAGEM + " WHERE m.conversa_id=%s AND m.id > %s "
                      "ORDER BY m.id LIMIT 500", (int(conversa_id), int(depois)))
    linhas = bd.ler(_SELECT_MENSAGEM + " WHERE m.conversa_id=%s ORDER BY m.id DESC LIMIT %s",
                    (int(conversa_id), int(limite)))
    return list(reversed(linhas))


def mensagens_alteradas(con, conversa_id: int, user_id: int, *, desde: str,
                        ate_id: int) -> list[dict]:
    """As já mostradas que alguém editou ou apagou depois de `desde`."""
    bd = banco(con)
    _participa(bd, conversa_id, user_id)
    return bd.ler(_SELECT_MENSAGEM + """ WHERE m.conversa_id=%s AND m.id <= %s
                    AND (m.editada_em >= %s OR m.apagada_em >= %s) ORDER BY m.id""",
                  (int(conversa_id), int(ate_id), desde, desde))


def mensagem(con, mensagem_id: int, user_id: int) -> dict:
    bd = banco(con)
    m = bd.um(_SELECT_MENSAGEM + " WHERE m.id=%s", (int(mensagem_id),))
    if not m:
        raise SemAcesso("Mensagem não encontrada.")
    _participa(bd, m["conversa_id"], user_id)
    return m


def pode_mudar(m: dict, user_id: int, agora: str) -> bool:
    """Editar ou apagar: só quem escreveu, só nos primeiros 15 minutos."""
    if int(m.get("autor_id") or 0) != int(user_id) or m.get("apagada_em"):
        return False
    criada = _dt(m.get("criada_em"))
    return bool(criada and _dt(agora) - criada <= timedelta(minutes=MINUTOS_PARA_MUDAR))


def enviar(con, conversa_id: int, autor_id: int, *, texto: str, agora: str,
           resposta_a: int | None = None, anexo_id: int | None = None,
           token: str | None = None) -> int:
    """Grava a mensagem e devolve o id. ESCREVE.

    O `token` vem do script, um por envio: o mesmo envio repetido (rede que
    caiu, duplo clique) devolve a mesma mensagem, em vez de mandar duas.
    """
    bd = banco(con)
    _participa(bd, conversa_id, autor_id)
    texto = _texto_limpo(texto)
    if not texto and not anexo_id:
        raise ComunicacaoErro("Escreva a mensagem ou anexe um arquivo.")
    token = (str(token or "").strip()[:64]) or None
    if token:
        ja = bd.valor("SELECT id FROM cm_mensagens WHERE autor_id=%s AND token_envio=%s",
                      (int(autor_id), token))
        if ja:
            return int(ja)
    if resposta_a:
        if not bd.valor("SELECT 1 FROM cm_mensagens WHERE id=%s AND conversa_id=%s",
                        (int(resposta_a), int(conversa_id))):
            resposta_a = None
    if anexo_id:
        dono = bd.valor("SELECT enviado_por FROM cm_anexos WHERE id=%s", (int(anexo_id),))
        if int(dono or 0) != int(autor_id):
            raise ComunicacaoErro("Anexo não encontrado.")
    mid = int(bd.escrever(
        """INSERT INTO cm_mensagens (conversa_id, autor_id, texto, resposta_a, anexo_id,
                                     token_envio, criada_em)
           VALUES (%s, %s, %s, %s, %s, %s, %s) RETURNING id""",
        (int(conversa_id), int(autor_id), texto, resposta_a, anexo_id, token, agora))[0]["id"])
    bd.escrever("UPDATE cm_conversas SET ultima_mensagem_id=%s, ultima_em=%s WHERE id=%s",
                (mid, agora, int(conversa_id)))
    # O que eu mesmo escrevi está lido por mim.
    bd.escrever(
        """UPDATE cm_participantes SET ultima_lida_id = GREATEST(ultima_lida_id, %s),
                  ultima_lida_em = %s
            WHERE conversa_id = %s AND user_id = %s""", (mid, agora, int(conversa_id), int(autor_id)))
    return mid


def editar(con, mensagem_id: int, user_id: int, *, texto: str, agora: str) -> None:
    bd = banco(con)
    m = mensagem(con, mensagem_id, user_id)
    if not pode_mudar(m, user_id, agora):
        raise ComunicacaoErro(f"Só dá para editar a própria mensagem nos primeiros "
                              f"{MINUTOS_PARA_MUDAR} minutos.")
    novo = _texto_limpo(texto)
    if not novo and not m.get("anexo_id"):
        raise ComunicacaoErro("A mensagem não pode ficar vazia. Para tirá-la, apague.")
    if novo == (m.get("texto") or ""):
        return
    bd.escrever("""INSERT INTO cm_mensagens_historico (mensagem_id, evento, texto_antes, em, por)
                   VALUES (%s, 'EDITADA', %s, %s, %s)""", (m["id"], m["texto"] or "", agora, int(user_id)))
    bd.escrever("UPDATE cm_mensagens SET texto=%s, editada_em=%s WHERE id=%s", (novo, agora, m["id"]))


def apagar(con, mensagem_id: int, user_id: int, *, agora: str) -> None:
    bd = banco(con)
    m = mensagem(con, mensagem_id, user_id)
    if not pode_mudar(m, user_id, agora):
        raise ComunicacaoErro(f"Só dá para apagar a própria mensagem nos primeiros "
                              f"{MINUTOS_PARA_MUDAR} minutos.")
    antes = m["texto"] or ""
    if m.get("anexo_nome"):
        antes = (antes + f"\n[anexo: {m['anexo_nome']}]").strip()
    bd.escrever("""INSERT INTO cm_mensagens_historico (mensagem_id, evento, texto_antes, em, por)
                   VALUES (%s, 'APAGADA', %s, %s, %s)""", (m["id"], antes, agora, int(user_id)))
    bd.escrever("UPDATE cm_mensagens SET texto='', apagada_em=%s WHERE id=%s", (agora, m["id"]))


def marcar_lida(con, conversa_id: int, user_id: int, *, ate: int, agora: str) -> int:
    """Avança o ponteiro do «lido» (nunca recua, nunca passa da última). ESCREVE."""
    bd = banco(con)
    c = _participa(bd, conversa_id, user_id)
    limite = int(c.get("ultima_mensagem_id") or 0)
    alvo = min(int(ate or 0), limite)
    if alvo <= int(c.get("ultima_lida_id") or 0):
        return int(c.get("ultima_lida_id") or 0)
    bd.escrever(
        """UPDATE cm_participantes SET ultima_lida_id = %s, ultima_lida_em = %s
            WHERE conversa_id = %s AND user_id = %s AND ultima_lida_id < %s""",
        (alvo, agora, int(conversa_id), int(user_id), alvo))
    return alvo


def recibo(con, conversa: dict, user_id: int) -> dict | None:
    """O «vista» da MINHA última mensagem: ✓ enviada, ✓✓ vista (ou por N de M)."""
    bd = banco(con)
    minha = bd.um(
        """SELECT id FROM cm_mensagens WHERE conversa_id=%s AND autor_id=%s AND apagada_em IS NULL
            ORDER BY id DESC LIMIT 1""", (conversa["id"], int(user_id)))
    if not minha:
        return None
    outros = [m for m in membros(con, conversa["id"]) if int(m["id"]) != int(user_id)]
    viram = [m for m in outros if int(m["ultima_lida_id"] or 0) >= int(minha["id"])]
    return {
        "mensagem_id": int(minha["id"]),
        "total": len(outros),
        "viram": len(viram),
        "nomes": [m["nome"] for m in viram],
        "quando": max((m["ultima_lida_em"] or "" for m in viram), default=""),
        "direta": conversa["tipo"] == DIRETA,
    }


def buscar(con, user_id: int, termo: str, *, limite: int = 50) -> list[dict]:
    """Procura nas conversas desta pessoa, sem diferença de acento nem de caixa."""
    termo = re.sub(r"\s+", " ", str(termo or "")).strip()
    if len(termo) < 2:
        return []
    de, para = "áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ", "aaaaaeeeeiiiiooooouuuucaaaaaeeeeiiiiooooouuuuc"
    # Cada palavra tem de aparecer, em qualquer ordem: «certidao onus» acha
    # «Certidão de ônus». A barra invertida, o `%` e o `_` do que se digitou valem como letra.
    palavras = [p.translate(str.maketrans(de, para)).replace("\\", "\\\\").replace("%", "\\%")
                .replace("_", "\\_") for p in termo.lower().split(" ")[:6]]
    filtro = " AND ".join(["translate(lower(m.texto), %s, %s) LIKE %s"] * len(palavras))
    parametros: list = [int(user_id)]
    for p in palavras:
        parametros += [de, para, f"%{p}%"]
    return banco(con).ler(
        f"""SELECT m.id, m.conversa_id, m.texto, m.criada_em, u.full_name AS autor,
                  c.tipo, c.nome
             FROM cm_mensagens m
             JOIN cm_participantes p ON p.conversa_id = m.conversa_id
                  AND p.user_id = %s AND p.saiu_em IS NULL
             JOIN cm_conversas c ON c.id = m.conversa_id AND c.arquivada_em IS NULL
             JOIN users u ON u.id = m.autor_id
            WHERE m.apagada_em IS NULL AND {filtro}
         ORDER BY m.id DESC LIMIT %s""", tuple(parametros + [int(limite)]))


