# ---------------------------------------------------------------- utilidades

def _dt(texto: str | datetime | None) -> datetime | None:
    if texto is None or texto == "":
        return None
    if isinstance(texto, datetime):
        return texto
    return datetime.fromisoformat(str(texto).strip().replace(" ", "T")[:19])


def _iso(momento: datetime) -> str:
    return momento.replace(microsecond=0).strftime("%Y-%m-%dT%H:%M:%S")


def _texto_limpo(texto: Any, maximo: int = TEXTO_MAXIMO) -> str:
    limpo = str(texto or "").replace("\r\n", "\n").replace("\r", "\n")
    limpo = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", limpo).strip()
    if len(limpo) > maximo:
        raise ComunicacaoErro(f"A mensagem passou de {maximo} caracteres.")
    return limpo


def auditar(bd, *, user_id: int, acao: str, entidade: str, entidade_id: int | None,
            detalhes: dict, agora: str, ip: str | None = None) -> None:
    """A linha do `audit_logs` na MESMA transação de quem grava (a função da casa)."""
    quem = bd.um("SELECT username FROM users WHERE id=%s", (user_id,)) or {}
    IDR.registrar(bd, ts=agora, user_id=user_id, username=quem.get("username"),
                  action=acao, entity_type=entidade, entity_id=entidade_id,
                  details=json.dumps(detalhes, ensure_ascii=False), ip_address=ip)


