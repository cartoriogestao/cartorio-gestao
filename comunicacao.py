def _participa(bd, conversa_id: int, user_id: int) -> dict:
    linha = bd.um(
        """SELECT c.*, p.ultima_lida_id, p.entrou_em
             FROM cm_conversas c
             JOIN cm_participantes p ON p.conversa_id = c.id
            WHERE c.id = %s AND p.user_id = %s AND p.saiu_em IS NULL
              AND c.arquivada_em IS NULL""", (int(conversa_id), int(user_id)))
    if not linha:
        raise SemAcesso("Você não participa desta conversa.")
    return linha


def conversa_da_pessoa(con, conversa_id: int, user_id: int) -> dict:
    """A conversa, com o nome que esta pessoa vê. Recusa quem não participa."""
    bd = banco(con)
    c = _participa(bd, conversa_id, user_id)
    c = dict(c)
    if c["tipo"] == DIRETA:
        outro = bd.um(
            """SELECT u.id, u.full_name, u.active FROM cm_participantes p
                 JOIN users u ON u.id = p.user_id
                WHERE p.conversa_id = %s AND p.user_id <> %s""", (c["id"], int(user_id)))
        c["titulo"] = (outro or {}).get("full_name") or "Conversa"
        c["outro_id"] = (outro or {}).get("id")
        c["outro_ativo"] = bool((outro or {}).get("active", 1))
    else:
        c["titulo"] = c["nome"]
    c["membros"] = membros(con, c["id"])
    return c


def membros(con, conversa_id: int) -> list[dict]:
    return banco(con).ler(
        """SELECT u.id, u.full_name AS nome, u.role AS papel, u.active,
                  p.ultima_lida_id, p.ultima_lida_em
             FROM cm_participantes p JOIN users u ON u.id = p.user_id
            WHERE p.conversa_id = %s AND p.saiu_em IS NULL
            ORDER BY lower(u.full_name)""", (int(conversa_id),))


def direta_existente(con, a: int, b: int) -> int | None:
    chave = f"{min(int(a), int(b))}:{max(int(a), int(b))}"
    return banco(con).valor("SELECT id FROM cm_conversas WHERE chave_direta=%s", (chave,))


def abrir_direta(con, de: int, para: int, *, agora: str) -> int:
    """A conversa direta entre duas pessoas — a mesma sempre (ESCREVE na 1ª vez)."""
    de, para = int(de), int(para)
    if de == para:
        raise ComunicacaoErro("Escolha outra pessoa para conversar.")
    bd = banco(con)
    alvo = pessoa(con, para)
    if not alvo or not int(alvo.get("active") or 0):
        raise ComunicacaoErro("Esta pessoa não está ativa no sistema.")
    chave = f"{min(de, para)}:{max(de, para)}"
    criada = bd.escrever(
        """INSERT INTO cm_conversas (tipo, chave_direta, criada_por, criada_em)
           VALUES ('DIRETA', %s, %s, %s)
           ON CONFLICT (chave_direta) DO NOTHING RETURNING id""", (chave, de, agora))
    cid = int(criada[0]["id"]) if criada else int(
        bd.valor("SELECT id FROM cm_conversas WHERE chave_direta=%s", (chave,)))
    for uid in (de, para):
        bd.escrever(
            """INSERT INTO cm_participantes (conversa_id, user_id, entrou_em)
               VALUES (%s, %s, %s) ON CONFLICT (conversa_id, user_id) DO NOTHING""",
            (cid, uid, agora))
    return cid


def _nome_de_grupo(nome: Any) -> str:
    limpo = re.sub(r"\s+", " ", str(nome or "")).strip()
    if not limpo:
        raise ComunicacaoErro("Dê um nome ao grupo.")
    if len(limpo) > NOME_DE_GRUPO_MAXIMO:
        raise ComunicacaoErro(f"O nome do grupo vai até {NOME_DE_GRUPO_MAXIMO} caracteres.")
    return limpo


def _grupo_com_nome(bd, nome: str, exceto: int | None = None) -> bool:
    return bool(bd.valor(
        """SELECT 1 FROM cm_conversas WHERE tipo='GRUPO' AND arquivada_em IS NULL
              AND lower(nome) = lower(%s) AND id <> %s""", (nome, int(exceto or 0))))


def criar_grupo(con, *, nome: str, membros_ids: Iterable[int], criado_por: int,
                agora: str, descricao: str = "", ip: str | None = None) -> int:
    """Qualquer pessoa cria um grupo; quem cria entra nele. ESCREVE."""
    bd = banco(con)
    nome = _nome_de_grupo(nome)
    if _grupo_com_nome(bd, nome):
        raise ComunicacaoErro(f"Já existe um grupo chamado «{nome}».")
    ids = _ids_de_pessoas_ativas(bd, membros_ids) | {int(criado_por)}
    if len(ids) < 2:
        raise ComunicacaoErro("Escolha ao menos uma pessoa para o grupo.")
    cid = int(bd.escrever(
        """INSERT INTO cm_conversas (tipo, nome, descricao, criada_por, criada_em)
           VALUES ('GRUPO', %s, %s, %s, %s) RETURNING id""",
        (nome, _texto_limpo(descricao, 300), int(criado_por), agora))[0]["id"])
    for uid in sorted(ids):
        bd.escrever(
            "INSERT INTO cm_participantes (conversa_id, user_id, entrou_em) VALUES (%s, %s, %s)",
            (cid, uid, agora))
    auditar(bd, user_id=int(criado_por), acao="COMUNICACAO_GRUPO_CRIADO",
            entidade="cm_conversas", entidade_id=cid,
            detalhes={"nome": nome, "membros": sorted(ids)}, agora=agora, ip=ip)
    return cid


def _ids_de_pessoas_ativas(bd, ids: Iterable[Any]) -> set[int]:
    pedidos = {int(i) for i in ids if str(i).strip().isdigit()}
    if not pedidos:
        return set()
    linhas = bd.ler("SELECT id FROM users WHERE active = 1 AND id = ANY(%s)", (list(pedidos),))
    return {int(x["id"]) for x in linhas}


def pode_gerir_grupo(conversa: dict, user_id: int, papel: str | None) -> bool:
    if conversa.get("tipo") != GRUPO:
        return False
    return int(conversa.get("criada_por") or 0) == int(user_id) or (papel in GEREM_TODOS_OS_GRUPOS)


def grupos(con, *, de: int | None = None) -> list[dict]:
    """Os grupos ativos, com quantos membros têm (todos, ou só os desta pessoa)."""
    filtro, params = "", ()
    if de is not None:
        filtro = """AND EXISTS (SELECT 1 FROM cm_participantes p2 WHERE p2.conversa_id = c.id
                     AND p2.user_id = %s AND p2.saiu_em IS NULL)"""
        params = (int(de),)
    return banco(con).ler(
        f"""SELECT c.id, c.nome, c.descricao, c.criada_por,
                   (SELECT COUNT(*) FROM cm_participantes p JOIN users u ON u.id = p.user_id
                     WHERE p.conversa_id = c.id AND p.saiu_em IS NULL AND u.active = 1) AS quantos
              FROM cm_conversas c
             WHERE c.tipo = 'GRUPO' AND c.arquivada_em IS NULL {filtro}
             ORDER BY lower(c.nome)""", params)


def gerir_grupo(con, conversa_id: int, *, por: int, papel: str | None, acao: str,
                agora: str, nome: str = "", membros_ids: Iterable[int] = (),
                ip: str | None = None) -> str:
    """renomear | adicionar | remover | sair | arquivar. Devolve a frase do feito."""
    bd = banco(con)
    c = bd.um("SELECT * FROM cm_conversas WHERE id=%s AND arquivada_em IS NULL", (int(conversa_id),))
    if not c or c["tipo"] != GRUPO:
        raise SemAcesso("Grupo não encontrado.")
    participa = bool(bd.valor(
        "SELECT 1 FROM cm_participantes WHERE conversa_id=%s AND user_id=%s AND saiu_em IS NULL",
        (c["id"], int(por))))
    if acao == "sair":
        if not participa:
            raise ComunicacaoErro("Você não está neste grupo.")
        bd.escrever("UPDATE cm_participantes SET saiu_em=%s WHERE conversa_id=%s AND user_id=%s",
                    (agora, c["id"], int(por)))
        frase = "Você saiu do grupo."
    else:
        if not pode_gerir_grupo(c, por, papel):
            raise SemAcesso("Só quem criou o grupo, um administrador ou um gerente muda o grupo.")
        if acao == "renomear":
            novo = _nome_de_grupo(nome)
            if _grupo_com_nome(bd, novo, exceto=c["id"]):
                raise ComunicacaoErro(f"Já existe um grupo chamado «{novo}».")
            bd.escrever("UPDATE cm_conversas SET nome=%s WHERE id=%s", (novo, c["id"]))
            frase = f"O grupo agora se chama «{novo}»."
        elif acao == "adicionar":
            ids = _ids_de_pessoas_ativas(bd, membros_ids)
            if not ids:
                raise ComunicacaoErro("Escolha quem entra no grupo.")
            for uid in ids:
                bd.escrever(
                    """INSERT INTO cm_participantes (conversa_id, user_id, entrou_em)
                       VALUES (%s, %s, %s)
                       ON CONFLICT (conversa_id, user_id)
                       DO UPDATE SET saiu_em = NULL, entrou_em = EXCLUDED.entrou_em
                       WHERE cm_participantes.saiu_em IS NOT NULL""", (c["id"], uid, agora))
            frase = f"{len(ids)} pessoa(s) no grupo."
        elif acao == "remover":
            ids = {int(i) for i in membros_ids if str(i).strip().isdigit()}
            if not ids:
                raise ComunicacaoErro("Escolha quem sai do grupo.")
            bd.escrever(
                """UPDATE cm_participantes SET saiu_em=%s
                    WHERE conversa_id=%s AND user_id = ANY(%s) AND saiu_em IS NULL""",
                (agora, c["id"], list(ids)))
            frase = "Retirado(s) do grupo."
        elif acao == "arquivar":
            bd.escrever("UPDATE cm_conversas SET arquivada_em=%s WHERE id=%s", (agora, c["id"]))
            frase = "Grupo arquivado. As mensagens ficam guardadas."
        else:
            raise ComunicacaoErro("Ação desconhecida.")
    auditar(bd, user_id=int(por), acao=f"COMUNICACAO_GRUPO_{acao.upper()}",
            entidade="cm_conversas", entidade_id=int(c["id"]),
            detalhes={"nome": nome or c["nome"], "membros": sorted(int(i) for i in membros_ids
                                                                  if str(i).strip().isdigit())},
            agora=agora, ip=ip)
    return frase


def conversas_da_pessoa(con, user_id: int) -> list[dict]:
    """A lista de conversas: a última mensagem primeiro, com prévia e não lidas.

    A conversa direta sem nenhuma mensagem não aparece (abrir não é conversar);
    o grupo aparece sempre, para quem entrou nele saber que está lá.
    """
    uid = int(user_id)
    return banco(con).ler(
        """SELECT c.id, c.tipo, c.nome, c.criada_em,
                  COALESCE(c.ultima_em, c.criada_em) AS quando,
                  (SELECT COUNT(*) FROM cm_mensagens m
                    WHERE m.conversa_id = c.id AND m.id > p.ultima_lida_id
                      AND m.autor_id <> %s AND m.apagada_em IS NULL) AS nao_lidas,
                  um.texto AS ult_texto, um.autor_id AS ult_autor_id,
                  um.apagada_em AS ult_apagada, um.anexo_id AS ult_anexo,
                  ua.full_name AS ult_autor,
                  o.id AS outro_id, o.full_name AS outro_nome, o.active AS outro_ativo
             FROM cm_participantes p
             JOIN cm_conversas c ON c.id = p.conversa_id
        LEFT JOIN cm_mensagens um ON um.id = c.ultima_mensagem_id
        LEFT JOIN users ua ON ua.id = um.autor_id
        LEFT JOIN cm_participantes po ON c.tipo = 'DIRETA' AND po.conversa_id = c.id
                                     AND po.user_id <> p.user_id
        LEFT JOIN users o ON o.id = po.user_id
            WHERE p.user_id = %s AND p.saiu_em IS NULL AND c.arquivada_em IS NULL
              AND (c.tipo = 'GRUPO' OR c.ultima_mensagem_id IS NOT NULL)
         ORDER BY COALESCE(c.ultima_em, c.criada_em) DESC, c.id DESC""", (uid, uid))


def total_nao_lidas(con, user_id: int) -> int:
    return int(banco(con).valor(
        """SELECT COUNT(*) FROM cm_participantes p
             JOIN cm_conversas c ON c.id = p.conversa_id AND c.arquivada_em IS NULL
             JOIN cm_mensagens m ON m.conversa_id = p.conversa_id AND m.id > p.ultima_lida_id
            WHERE p.user_id = %s AND p.saiu_em IS NULL
              AND m.autor_id <> %s AND m.apagada_em IS NULL""",
        (int(user_id), int(user_id))) or 0)


def ultima_nao_lida(con, user_id: int) -> dict | None:
    """A mensagem mais nova que a pessoa não leu — o aviso discreto («toast»)."""
    return banco(con).um(
        """SELECT m.id, m.conversa_id, m.texto, m.anexo_id, u.full_name AS autor,
                  c.tipo, c.nome
             FROM cm_participantes p
             JOIN cm_conversas c ON c.id = p.conversa_id AND c.arquivada_em IS NULL
             JOIN cm_mensagens m ON m.conversa_id = p.conversa_id AND m.id > p.ultima_lida_id
             JOIN users u ON u.id = m.autor_id
            WHERE p.user_id = %s AND p.saiu_em IS NULL
              AND m.autor_id <> %s AND m.apagada_em IS NULL
         ORDER BY m.id DESC LIMIT 1""", (int(user_id), int(user_id)))


