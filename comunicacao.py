def guardar_anexo(con, arquivo, *, raiz: Path, por: int, agora: str) -> int:
    """Salva o arquivo enviado na pasta da casa e devolve o id do anexo. ESCREVE.

    O nome no disco é sorteado (o nome do usuário não vira caminho) e a
    extensão tem de estar na lista: o arquivo sai depois sempre com o tipo
    da lista, e nunca como HTML.
    """
    original = Path(str(getattr(arquivo, "filename", "") or "")).name.strip()
    if not original:
        raise ComunicacaoErro("Escolha o arquivo.")
    extensao = Path(original).suffix.lower()
    if extensao not in TIPOS_DE_ANEXO:
        raise ComunicacaoErro("Este tipo de arquivo não vai pela comunicação. Vão PDF, imagem, "
                              "texto, planilha, documento e ZIP.")
    conteudo = arquivo.read(ANEXO_MAXIMO + 1)
    if len(conteudo) > ANEXO_MAXIMO:
        raise ComunicacaoErro("O arquivo passou de 10 MB.")
    if not conteudo:
        raise ComunicacaoErro("O arquivo está vazio.")
    mes = str(agora)[:7]
    relativo = Path(PASTA_DOS_ANEXOS) / mes / f"{secrets.token_hex(12)}{extensao}"
    destino = Path(raiz) / relativo
    destino.parent.mkdir(parents=True, exist_ok=True)
    destino.write_bytes(conteudo)
    return int(banco(con).escrever(
        """INSERT INTO cm_anexos (nome_original, caminho, tipo_mime, tamanho, sha256,
                                  enviado_por, enviado_em)
           VALUES (%s, %s, %s, %s, %s, %s, %s) RETURNING id""",
        (original[:200], relativo.as_posix(), TIPOS_DE_ANEXO[extensao], len(conteudo),
         hashlib.sha256(conteudo).hexdigest(), int(por), agora))[0]["id"])


def anexo_para_baixar(con, anexo_id: int, user_id: int, *, raiz: Path) -> dict:
    """O anexo, se a pessoa participa da conversa e a mensagem não foi apagada."""
    bd = banco(con)
    a = bd.um(
        """SELECT a.*, m.conversa_id, m.apagada_em FROM cm_anexos a
             JOIN cm_mensagens m ON m.anexo_id = a.id
            WHERE a.id = %s ORDER BY m.id LIMIT 1""", (int(anexo_id),))
    if not a or a.get("apagada_em"):
        raise SemAcesso("Anexo não encontrado.")
    _participa(bd, a["conversa_id"], user_id)
    caminho = (Path(raiz) / a["caminho"]).resolve()
    if Path(raiz).resolve() not in caminho.parents or not caminho.is_file():
        raise SemAcesso("O arquivo não está mais na pasta.")
    extensao = caminho.suffix.lower()
    return {**a, "arquivo": caminho, "imagem": extensao in IMAGENS,
            "tipo_mime": TIPOS_DE_ANEXO.get(extensao, "application/octet-stream")}


def tamanho_legivel(n: Any) -> str:
    n = int(n or 0)
    if n < 1024:
        return f"{n} B"
    if n < 1024 * 1024:
        return f"{n / 1024:.0f} KB"
    return f"{n / (1024 * 1024):.1f} MB".replace(".", ",")
