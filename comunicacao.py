_PESSOA_ATIVA = "u.active = 1 AND COALESCE(u.eh_robo, 0) = 0"


def pessoas(con, *, exceto: int | None = None) -> list[dict]:
    """Toda pessoa ativa da casa (sem conta de robô), em ordem de nome."""
    bd = banco(con)
    if not bd.tem_coluna("users", "eh_robo"):
        filtro = "u.active = 1"
    else:
        filtro = _PESSOA_ATIVA
    return bd.ler(
        f"""SELECT u.id, u.full_name AS nome, u.username, u.role AS papel
              FROM users u WHERE {filtro} AND u.id <> %s
             ORDER BY lower(u.full_name)""", (int(exceto or 0),))


def pessoa(con, user_id: int) -> dict | None:
    return banco(con).um(
        "SELECT id, full_name AS nome, username, role AS papel, active FROM users WHERE id=%s",
        (int(user_id),))


def primeiro_nome(nome: str) -> str:
    partes = str(nome or "").split()
    return partes[0].title() if partes else ""


