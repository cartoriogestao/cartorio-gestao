def da_pessoa(con, user_id: int, *, agora: str, dias_feitos: int = 7) -> dict[str, list[dict]]:
    """Os avisos desta pessoa: esperando (com o grau), fazendo e feitos há pouco."""
    linhas = banco(con).ler(
        """SELECT a.id, a.titulo, a.texto, a.urgencia, a.criado_em, a.criado_por,
                  a.criado_por_nome, a.destino_rotulo,
                  d.situacao, d.visto_em, d.fazendo_em, d.feito_em, d.recolhido_ate, d.grau_max
             FROM cm_aviso_destinos d JOIN cm_avisos a ON a.id = d.aviso_id
            WHERE d.user_id = %s AND a.encerrado_em IS NULL
              AND (d.situacao <> 'FEITO' OR d.feito_em >= %s)
         ORDER BY a.criado_em, a.id""",
        (int(user_id), CM._iso(CM._dt(agora) - timedelta(days=dias_feitos))))
    saida: dict[str, list[dict]] = {ESPERANDO: [], FAZENDO: [], FEITO: []}
    for linha in linhas:
        item = dict(linha)
        if item["situacao"] == ESPERANDO:
            item["grau"] = grau(item["urgencia"], item["criado_em"], agora, item["recolhido_ate"])
            item["recolhido"] = bool(item["recolhido_ate"] and CM._dt(agora) < CM._dt(item["recolhido_ate"]))
            item["sobe_em"] = proximo_grau_em(item["urgencia"], item["criado_em"], agora)
        else:
            item["grau"] = 0
        saida[item["situacao"]].append(item)
    saida[FEITO].reverse()
    return saida


def insistencia(con, user_id: int, *, agora: str) -> dict:
    """O que a tela mostra agora: o cartão (o mais antigo no grau 3) e a faixa."""
    esperando = da_pessoa(con, user_id, agora=agora)[ESPERANDO]
    cartoes = [a for a in esperando if a["grau"] == CARTAO]
    faixas = [a for a in esperando if a["grau"] == FAIXA]
    return {
        "esperando": len(esperando),
        "grau": max((a["grau"] for a in esperando), default=0),
        "cartao": cartoes[0] if cartoes else None,
        "cartoes": len(cartoes),
        "faixa": faixas[0] if faixas else None,
        "faixas": len(faixas),
        "ids": [a["id"] for a in esperando if a["grau"] >= FAIXA],
    }


def lista_da_gestao(con, *, limite: int = 100) -> list[dict]:
    return banco(con).ler(
        """SELECT a.*,
                  COUNT(d.user_id) AS total,
                  COUNT(*) FILTER (WHERE d.situacao = 'ESPERANDO') AS esperando,
                  COUNT(*) FILTER (WHERE d.situacao = 'FAZENDO') AS fazendo,
                  COUNT(*) FILTER (WHERE d.situacao = 'FEITO') AS feitos,
                  COUNT(*) FILTER (WHERE d.visto_em IS NOT NULL) AS viram
             FROM cm_avisos a LEFT JOIN cm_aviso_destinos d ON d.aviso_id = a.id
         GROUP BY a.id ORDER BY a.encerrado_em IS NOT NULL, a.id DESC LIMIT %s""", (int(limite),))


def detalhe(con, aviso_id: int, *, agora: str) -> dict | None:
    bd = banco(con)
    a = bd.um("SELECT * FROM cm_avisos WHERE id=%s", (int(aviso_id),))
    if not a:
        return None
    destinos = bd.ler(
        """SELECT d.*, u.full_name AS nome, u.role AS papel
             FROM cm_aviso_destinos d JOIN users u ON u.id = d.user_id
            WHERE d.aviso_id = %s ORDER BY lower(u.full_name)""", (int(aviso_id),))
    for d in destinos:
        d["grau_agora"] = (grau(a["urgencia"], a["criado_em"], agora, d["recolhido_ate"])
                           if d["situacao"] == ESPERANDO and not a["encerrado_em"] else 0)
    eventos = bd.ler("SELECT * FROM cm_aviso_eventos WHERE aviso_id=%s ORDER BY id", (int(aviso_id),))
    return {"aviso": a, "destinos": destinos, "eventos": eventos}
