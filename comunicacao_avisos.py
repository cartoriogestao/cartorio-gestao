"""OS AVISOS DA GERÊNCIA — insistem na tela, em três graus, até «estou fazendo» (T028).

    «comunicacoes que ficam (harmonicamente) insistentes na tela ate o escrevente
     clicar que esta fazendo, com grau de progressividade em quanto espaco ocupa,
     com o maior grau entra uma mensagem completa no canto direito superior que
     ate permita a continuidade do trabalho mas apareça de forma insistente e que
     compele o escrevente a fazer o que for pedido»       — o titular, 28/11/2026

OS GRAUS (plano aprovado pelo titular em 28/11/2026)
    1 SINAL   o botão «Comunicação» da coluna da direita ganha contador e cor.
    2 FAIXA   uma linha no alto da área de trabalho, sem botão de fechar.
    3 CARTÃO  o aviso inteiro no canto superior direito; a tela continua
              clicável e digitável (não é modal, não escurece, não toma o foco).

    O grau sai do TEMPO DESDE O ENVIO e da urgência que quem mandou escolheu
    (`URGENCIAS`): a ideia é a do GoAlert (target/goalert, `escalation.Step`,
    passos com atraso em minutos, e o reconhecimento — «ack» — para a escala).
    Aqui o reconhecimento é «estou fazendo»; o «feito» vem depois e é opcional.

    «Recolher por 5 min» desce o cartão à faixa por cinco minutos — para terminar
    o ato que está na mão — e ele volta sozinho. Cada recolhida fica gravada.
    Não há «fechar» (pinax-announcements: `DISMISSAL_NO`, o aviso que não se
    dispensa).

QUEM MANDA, QUEM RECEBE
    Manda: ADMIN, MANAGER e TI (o TI chega como ADMIN, `papeis.EQUIVALE`) — o
    «admin, manager, ti e gestor» do titular; «gestor», na casa, é o par
    ADMIN/MANAGER (`modelos_da_casa.QUEM_GRAVA_PAPEL_DO_GESTOR`).
    Recebe: toda a equipe ativa, um grupo (da comunicação) ou uma pessoa. A lista
    de quem recebe é fotografada no envio, como a escala do GoAlert: quem entra
    no grupo depois não recebe o aviso que já tinha saído.

A TRILHA
    `cm_aviso_eventos` só recebe linhas: CRIADA, VISTA, SUBIU_GRAU, RECOLHIDA,
    FAZENDO, FEITO, ENCERRADA. O envio, o «estou fazendo», o «feito» e o
    encerramento também vão para o `audit_logs`, na mesma transação.
"""
from __future__ import annotations

from datetime import datetime, timedelta
from typing import Any

from bd_nativo import banco
import comunicacao as CM

NORMAL, URGENTE, IMEDIATA = "NORMAL", "URGENTE", "IMEDIATA"

#: Urgência -> (minutos até a FAIXA, minutos até o CARTÃO), contados do envio.
URGENCIAS: dict[str, tuple[int, int]] = {
    NORMAL: (15, 60),
    URGENTE: (0, 10),
    IMEDIATA: (0, 0),
}
ROTULO_DA_URGENCIA = {
    NORMAL: "Normal — sinal na coluna, faixa aos 15 min, cartão aos 60 min",
    URGENTE: "Urgente — faixa na hora, cartão aos 10 min",
    IMEDIATA: "Imediata — cartão na hora",
}
NOME_DA_URGENCIA = {NORMAL: "Normal", URGENTE: "Urgente", IMEDIATA: "Imediata"}

SINAL, FAIXA, CARTAO = 1, 2, 3
NOME_DO_GRAU = {0: "—", SINAL: "Sinal", FAIXA: "Faixa", CARTAO: "Cartão"}
MINUTOS_RECOLHIDO = 5

ESPERANDO, FAZENDO, FEITO = "ESPERANDO", "FAZENDO", "FEITO"
ROTULO_DA_SITUACAO = {ESPERANDO: "Esperando", FAZENDO: "Fazendo", FEITO: "Feito"}

TODOS, DESTINO_GRUPO, DESTINO_PESSOA = "TODOS", "GRUPO", "PESSOA"

#: Quem cria aviso (papel efetivo). Quem confere sem criar: + AUDITOR.
CRIAM = ("ADMIN", "MANAGER")
ACOMPANHAM = ("ADMIN", "MANAGER", "AUDITOR")
TITULO_MAXIMO = 120
TEXTO_MAXIMO = 3000

ESQUEMA = (
    """CREATE TABLE IF NOT EXISTS cm_avisos (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        titulo TEXT NOT NULL,
        texto TEXT NOT NULL DEFAULT '',
        urgencia TEXT NOT NULL CHECK (urgencia IN ('NORMAL','URGENTE','IMEDIATA')),
        destino_tipo TEXT NOT NULL CHECK (destino_tipo IN ('TODOS','GRUPO','PESSOA')),
        destino_ref bigint,
        destino_rotulo TEXT NOT NULL DEFAULT '',
        criado_por bigint NOT NULL REFERENCES users(id),
        criado_por_nome TEXT NOT NULL DEFAULT '',
        criado_em TEXT NOT NULL,
        encerrado_em TEXT,
        encerrado_por bigint REFERENCES users(id),
        encerrado_por_nome TEXT
    )""",
    """CREATE TABLE IF NOT EXISTS cm_aviso_destinos (
        aviso_id bigint NOT NULL REFERENCES cm_avisos(id),
        user_id bigint NOT NULL REFERENCES users(id),
        situacao TEXT NOT NULL DEFAULT 'ESPERANDO'
            CHECK (situacao IN ('ESPERANDO','FAZENDO','FEITO')),
        visto_em TEXT,
        fazendo_em TEXT,
        feito_em TEXT,
        grau_max INTEGER NOT NULL DEFAULT 0,
        recolhido_ate TEXT,
        recolhidas INTEGER NOT NULL DEFAULT 0,
        PRIMARY KEY (aviso_id, user_id)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_cm_aviso_destinos_user ON cm_aviso_destinos(user_id, situacao)",
    """CREATE TABLE IF NOT EXISTS cm_aviso_eventos (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        aviso_id bigint NOT NULL REFERENCES cm_avisos(id),
        user_id bigint REFERENCES users(id),
        evento TEXT NOT NULL CHECK (evento IN
            ('CRIADA','VISTA','SUBIU_GRAU','RECOLHIDA','FAZENDO','FEITO','ENCERRADA')),
        grau INTEGER,
        em TEXT NOT NULL,
        por_nome TEXT NOT NULL DEFAULT ''
    )""",
    "CREATE INDEX IF NOT EXISTS idx_cm_aviso_eventos_aviso ON cm_aviso_eventos(aviso_id, id)",
)


def init_avisos_schema(con) -> None:
    bd = banco(con)
    for comando in ESQUEMA:
        bd.escrever(comando)


# ------------------------------------------------------------------ a regra

def grau(urgencia: str, enviado_em: str | datetime, agora: str | datetime,
         recolhido_ate: str | datetime | None = None) -> int:
    """O grau de um aviso que ainda espera «estou fazendo». Só calcula.

    Sobe com o tempo e nunca desce — salvo o cartão recolhido, que fica faixa
    até `recolhido_ate` e volta sozinho.
    """
    faixa, cartao = URGENCIAS.get(urgencia, URGENCIAS[NORMAL])
    passados = (CM._dt(agora) - CM._dt(enviado_em)).total_seconds()
    if passados >= cartao * 60:
        g = CARTAO
    elif passados >= faixa * 60:
        g = FAIXA
    else:
        g = SINAL
    fim = CM._dt(recolhido_ate) if recolhido_ate else None
    if g == CARTAO and fim and CM._dt(agora) < fim:
        g = FAIXA
    return g


def proximo_grau_em(urgencia: str, enviado_em: str, agora: str) -> str | None:
    """Quando o aviso sobe de grau (para a tela dizer «vira cartão às 10:12»)."""
    faixa, cartao = URGENCIAS.get(urgencia, URGENCIAS[NORMAL])
    inicio, ag = CM._dt(enviado_em), CM._dt(agora)
    for minutos in (faixa, cartao):
        quando = inicio + timedelta(minutes=minutos)
        if quando > ag:
            return CM._iso(quando)
    return None


def _nome(bd, user_id: int) -> str:
    return str(bd.valor("SELECT full_name FROM users WHERE id=%s", (int(user_id),)) or "")


def _evento(bd, aviso_id: int, user_id: int | None, evento: str, agora: str,
            grau_: int | None = None) -> None:
    bd.escrever(
        """INSERT INTO cm_aviso_eventos (aviso_id, user_id, evento, grau, em, por_nome)
           VALUES (%s, %s, %s, %s, %s, %s)""",
        (int(aviso_id), user_id, evento, grau_, agora, _nome(bd, user_id) if user_id else ""))


def destinatarios(con, destino_tipo: str, destino_ref: Any, *, de: int) -> tuple[list[int], str]:
    """Quem recebe, e o rótulo que a tela mostra («Toda a equipe», «Grupo RI»...)."""
    bd = banco(con)
    if destino_tipo == TODOS:
        ids = [int(p["id"]) for p in CM.pessoas(con, exceto=de)]
        return ids, "Toda a equipe"
    if not str(destino_ref or "").strip().isdigit():
        raise CM.ComunicacaoErro("Escolha o grupo ou a pessoa.")
    ref = int(destino_ref)
    if destino_tipo == DESTINO_GRUPO:
        g = bd.um("SELECT id, nome FROM cm_conversas WHERE id=%s AND tipo='GRUPO' "
                  "AND arquivada_em IS NULL", (ref,))
        if not g:
            raise CM.ComunicacaoErro("Grupo não encontrado.")
        ids = [int(m["id"]) for m in CM.membros(con, ref)
               if int(m["active"] or 0) and int(m["id"]) != int(de)]
        return ids, f"Grupo {g['nome']}"
    if destino_tipo == DESTINO_PESSOA:
        p = CM.pessoa(con, ref)
        if not p or not int(p.get("active") or 0):
            raise CM.ComunicacaoErro("Esta pessoa não está ativa no sistema.")
        if int(p["id"]) == int(de):
            raise CM.ComunicacaoErro("O aviso é para outra pessoa, não para você.")
        return [int(p["id"])], p["nome"]
    raise CM.ComunicacaoErro("Escolha para quem vai o aviso.")


def criar(con, *, titulo: str, texto: str, urgencia: str, destino_tipo: str,
          destino_ref: Any, por: int, papel: str | None, agora: str,
          ip: str | None = None) -> int:
    """Envia o aviso. Recusa quem não é ADMIN/MANAGER/TI. ESCREVE."""
    if papel not in CRIAM:
        raise PermissionError("Só administrador, gerente e TI mandam aviso.")
    bd = banco(con)
    titulo = CM._texto_limpo(titulo, TITULO_MAXIMO).replace("\n", " ")
    if not titulo:
        raise CM.ComunicacaoErro("Dê um título ao aviso — é o que aparece na faixa.")
    texto = CM._texto_limpo(texto, TEXTO_MAXIMO)
    if urgencia not in URGENCIAS:
        raise CM.ComunicacaoErro("Escolha a urgência.")
    ids, rotulo = destinatarios(con, destino_tipo, destino_ref, de=por)
    if not ids:
        raise CM.ComunicacaoErro("Não há ninguém ativo para receber este aviso.")
    aid = int(bd.escrever(
        """INSERT INTO cm_avisos (titulo, texto, urgencia, destino_tipo, destino_ref,
                                  destino_rotulo, criado_por, criado_por_nome, criado_em)
           VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s) RETURNING id""",
        (titulo, texto, urgencia, destino_tipo,
         int(destino_ref) if str(destino_ref or "").strip().isdigit() else None,
         rotulo, int(por), _nome(bd, por), agora))[0]["id"])
    for uid in ids:
        bd.escrever("INSERT INTO cm_aviso_destinos (aviso_id, user_id) VALUES (%s, %s)", (aid, uid))
    _evento(bd, aid, int(por), "CRIADA", agora)
    CM.auditar(bd, user_id=int(por), acao="COMUNICACAO_AVISO_ENVIADO", entidade="cm_avisos",
               entidade_id=aid, detalhes={"titulo": titulo, "urgencia": urgencia,
                                          "destino": rotulo, "destinatarios": ids},
               agora=agora, ip=ip)
    return aid


def _destino(bd, aviso_id: int, user_id: int, *, travar: bool = False) -> dict:
    """A linha desta pessoa no aviso. `travar` a segura até o fim da transação: dois
    cliques juntos em «Estou fazendo» esperam um pelo outro e o segundo já vê o feito."""
    sql = """SELECT d.*, a.urgencia, a.criado_em, a.encerrado_em, a.titulo
               FROM cm_aviso_destinos d JOIN cm_avisos a ON a.id = d.aviso_id
              WHERE d.aviso_id = %s AND d.user_id = %s"""
    if travar:
        linhas = bd.escrever(sql + " FOR UPDATE OF d", (int(aviso_id), int(user_id)))
        d = linhas[0] if linhas else None
    else:
        d = bd.um(sql, (int(aviso_id), int(user_id)))
    if not d:
        raise CM.SemAcesso("Este aviso não é para você.")
    return d


def registrar_visto(con, user_id: int, avisos_ids: list[Any], *, agora: str) -> int:
    """O script diz «mostrei estes avisos». Grava a 1ª vista e cada subida de grau.

    O grau gravado é o que o SERVIDOR calcula agora — o do cliente não conta.
    Devolve quantos eventos gravou. ESCREVE.
    """
    bd = banco(con)
    gravados = 0
    for aid in {int(a) for a in avisos_ids if str(a).strip().isdigit()}:
        try:
            d = _destino(bd, aid, user_id, travar=True)
        except CM.SemAcesso:
            continue
        if d["encerrado_em"] or d["situacao"] != ESPERANDO:
            continue
        g = grau(d["urgencia"], d["criado_em"], agora, d["recolhido_ate"])
        if not d["visto_em"]:
            bd.escrever("UPDATE cm_aviso_destinos SET visto_em=%s WHERE aviso_id=%s AND user_id=%s",
                        (agora, aid, int(user_id)))
            _evento(bd, aid, int(user_id), "VISTA", agora, g)
            gravados += 1
        if g > int(d["grau_max"] or 0):
            bd.escrever("UPDATE cm_aviso_destinos SET grau_max=%s WHERE aviso_id=%s AND user_id=%s",
                        (g, aid, int(user_id)))
            _evento(bd, aid, int(user_id), "SUBIU_GRAU", agora, g)
            gravados += 1
    return gravados


def marcar_vista_aberta(con, aviso_id: int, user_id: int, *, agora: str) -> None:
    """Abrir o aviso na gaveta também é ver (sem mexer no grau)."""
    bd = banco(con)
    d = _destino(bd, aviso_id, user_id, travar=True)
    if not d["visto_em"]:
        bd.escrever("UPDATE cm_aviso_destinos SET visto_em=%s WHERE aviso_id=%s AND user_id=%s",
                    (agora, int(aviso_id), int(user_id)))
        _evento(bd, int(aviso_id), int(user_id), "VISTA", agora, None)


def marcar(con, aviso_id: int, user_id: int, situacao: str, *, agora: str,
           ip: str | None = None) -> bool:
    """«Estou fazendo» (FAZENDO) ou «Feito» (FEITO). Devolve se mudou algo. ESCREVE.

    Repetir não grava de novo; não se volta atrás; aviso encerrado não muda.
    «Feito» direto, sem passar por «fazendo», vale: grava os dois momentos.
    """
    if situacao not in (FAZENDO, FEITO):
        raise CM.ComunicacaoErro("Situação desconhecida.")
    bd = banco(con)
    d = _destino(bd, aviso_id, user_id, travar=True)
    if d["encerrado_em"]:
        raise CM.ComunicacaoErro("Este aviso foi encerrado por quem mandou.")
    ordem = {ESPERANDO: 0, FAZENDO: 1, FEITO: 2}
    if ordem[d["situacao"]] >= ordem[situacao]:
        return False
    if not d["visto_em"]:
        bd.escrever("UPDATE cm_aviso_destinos SET visto_em=%s WHERE aviso_id=%s AND user_id=%s",
                    (agora, int(aviso_id), int(user_id)))
    if situacao == FAZENDO or not d["fazendo_em"]:
        bd.escrever("""UPDATE cm_aviso_destinos SET situacao='FAZENDO', fazendo_em=%s
                        WHERE aviso_id=%s AND user_id=%s""", (agora, int(aviso_id), int(user_id)))
        _evento(bd, int(aviso_id), int(user_id), "FAZENDO", agora)
    if situacao == FEITO:
        bd.escrever("""UPDATE cm_aviso_destinos SET situacao='FEITO', feito_em=%s
                        WHERE aviso_id=%s AND user_id=%s""", (agora, int(aviso_id), int(user_id)))
        _evento(bd, int(aviso_id), int(user_id), "FEITO", agora)
    CM.auditar(bd, user_id=int(user_id), acao=f"COMUNICACAO_AVISO_{situacao}",
               entidade="cm_avisos", entidade_id=int(aviso_id),
               detalhes={"titulo": d["titulo"]}, agora=agora, ip=ip)
    return True


def recolher(con, aviso_id: int, user_id: int, *, agora: str) -> str:
    """Desce o cartão à faixa por 5 min. Só o cartão se recolhe. ESCREVE."""
    bd = banco(con)
    d = _destino(bd, aviso_id, user_id, travar=True)
    if d["encerrado_em"] or d["situacao"] != ESPERANDO:
        raise CM.ComunicacaoErro("Este aviso não está mais esperando você.")
    if grau(d["urgencia"], d["criado_em"], agora, d["recolhido_ate"]) != CARTAO:
        raise CM.ComunicacaoErro("Só o cartão se recolhe.")
    ate = CM._iso(CM._dt(agora) + timedelta(minutes=MINUTOS_RECOLHIDO))
    bd.escrever("""UPDATE cm_aviso_destinos SET recolhido_ate=%s, recolhidas = recolhidas + 1
                    WHERE aviso_id=%s AND user_id=%s""", (ate, int(aviso_id), int(user_id)))
    _evento(bd, int(aviso_id), int(user_id), "RECOLHIDA", agora, FAIXA)
    return ate


def encerrar(con, aviso_id: int, *, por: int, papel: str | None, agora: str,
             ip: str | None = None) -> None:
    """Some para todos; o histórico fica. ADMIN encerra qualquer um; MANAGER, os seus."""
    bd = banco(con)
    a = bd.um("SELECT * FROM cm_avisos WHERE id=%s", (int(aviso_id),))
    if not a:
        raise CM.SemAcesso("Aviso não encontrado.")
    if papel not in CRIAM or (papel != "ADMIN" and int(a["criado_por"]) != int(por)):
        raise PermissionError("Só quem mandou o aviso, ou um administrador, o encerra.")
    if a["encerrado_em"]:
        return
    bd.escrever("""UPDATE cm_avisos SET encerrado_em=%s, encerrado_por=%s, encerrado_por_nome=%s
                    WHERE id=%s""", (agora, int(por), _nome(bd, por), int(aviso_id)))
    _evento(bd, int(aviso_id), int(por), "ENCERRADA", agora)
    CM.auditar(bd, user_id=int(por), acao="COMUNICACAO_AVISO_ENCERRADO", entidade="cm_avisos",
               entidade_id=int(aviso_id), detalhes={"titulo": a["titulo"]}, agora=agora, ip=ip)


