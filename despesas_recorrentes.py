"""AS DESPESAS RECORRENTES — o que a serventia paga todo mês, cadastrado uma vez.

POR QUE EXISTE (28/10/2026)
    Pedido do oficial: «preciso poder cadastrar despesas recorrentes no
    sistema e o sistema me avisa todo mês para pagar elas. As que é só Pix,
    já deixa carregado pendente de confirmação».

AS DUAS ESPÉCIES, E A RAZÃO DA DIFERENÇA
    - **Pix por chave, de valor fixo** (aluguel, salário, honorário): a chave
      e o valor não mudam de um mês para o outro. O sistema CARREGA a despesa
      do mês sozinho, e ela nasce AGUARDANDO a autorização do oficial — que é
      a «confirmação» do pedido. Nada se paga sem ela: a autorização continua
      sendo do ADMIN (`despesas.autorizar`).
    - **Todo o resto** (boleto, conta de luz, guia, Pix copia e cola, pago em
      dinheiro): o código de pagamento MUDA todo mês e só chega com a fatura.
      Inventar o código seria pagar o mês errado; então o sistema AVISA, e o
      botão abre a despesa já preenchida, faltando colar o código.

    O que liga a despesa do mês à recorrente é (origem RECORRENTE, chave
    «<id>:<AAAA-MM>») — o mesmo índice único das guias do robô. A segunda
    rodada do mês acha a primeira, e o mês não entra duas vezes.

QUANDO O MÊS «ABRE»
    `antecedencia_dias` antes do vencimento. Só o mês corrente e o seguinte
    são olhados: uma recorrente cadastrada hoje não despeja meses passados, e
    o mês que passou sem ser pago continua avisando até o fim dele.

O AVISO (decisão do oficial, 28/10/2026, «não precisa me avisar cada
detalhe»): nada de e-mail por recorrente. O aviso é a faixa na tela das
despesas e o achado do processo DESPESAS_RECORRENTES, que entra no resumo do
dia da automação.

PostgreSQL nativo, pelo `bd_nativo`. Dinheiro em centavos.
"""
from __future__ import annotations

import calendar
from datetime import date, datetime, timedelta
from typing import Any, Mapping

import despesas as DP
from bd_nativo import banco
from caixa_schema import reais

ORIGEM = "RECORRENTE"
#: As formas que o sistema carrega sozinho. Só a chave Pix não muda de mês.
CARREGA_SOZINHO = (DP.PIX_CHAVE,)
ANTECEDENCIA_PADRAO = 7

SCHEMA: tuple[tuple[str, str], ...] = (
    ("dp_recorrentes", """
        CREATE TABLE IF NOT EXISTS dp_recorrentes (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ativa integer NOT NULL DEFAULT 1,
            descricao TEXT NOT NULL,
            categoria TEXT NOT NULL,
            beneficiario_nome TEXT NOT NULL,
            beneficiario_documento TEXT NOT NULL DEFAULT '',
            forma TEXT NOT NULL,
            chave_pix TEXT NOT NULL DEFAULT '',
            valor bigint,
            dia_vencimento integer NOT NULL CHECK (dia_vencimento BETWEEN 1 AND 31),
            antecedencia_dias integer NOT NULL DEFAULT 7,
            documento_especie TEXT NOT NULL,
            primeiro_mes TEXT NOT NULL,
            ultimo_mes TEXT NOT NULL DEFAULT '',
            criada_em TEXT NOT NULL,
            criada_por TEXT NOT NULL,
            atualizada_em TEXT,
            atualizada_por TEXT,
            encerrada_em TEXT,
            encerrada_por TEXT
        )"""),
)


def init_recorrentes_schema(con) -> None:
    """Cria a tabela que faltar. Idempotente."""
    bd = banco(con)
    for nome, comando in SCHEMA:
        if not bd.tem_tabela(nome):
            bd.escrever(comando)


# ------------------------------------------------------------- auxiliares

def mes(d: date) -> str:
    return f"{d.year:04d}-{d.month:02d}"


def _proximo_mes(competencia: str) -> str:
    ano, m = int(competencia[:4]), int(competencia[5:7])
    return f"{ano + (m == 12):04d}-{(m % 12) + 1:02d}"


def vencimento_do_mes(r: Mapping[str, Any], competencia: str) -> date:
    """O dia de vencimento naquele mês. Dia 31 em fevereiro é o último dia dele."""
    ano, m = int(competencia[:4]), int(competencia[5:7])
    return date(ano, m, min(int(r["dia_vencimento"]), calendar.monthrange(ano, m)[1]))


def chave_do_mes(recorrente_id: int, competencia: str) -> str:
    return f"{int(recorrente_id)}:{competencia}"


def _mes_valido(texto: Any, rotulo: str, *, vazio_ok: bool = False) -> str:
    texto = str(texto or "").strip()[:7]
    if not texto and vazio_ok:
        return ""
    try:
        date.fromisoformat(texto + "-01")
    except ValueError as erro:
        raise DP.DespesaError(f"{rotulo}: informe o mês como AAAA-MM.") from erro
    return texto


def conferir(dados: Mapping[str, Any]) -> dict:
    """A recorrente como ela se grava. Só calcula. Recusa o que não daria despesa.

    A conferência é a de `despesas.cadastrar`, para a recorrente não guardar o
    que a despesa do mês recusaria depois — no dia do vencimento, sem ninguém
    olhando.
    """
    categoria = str(dados.get("categoria") or "")
    if categoria not in DP.CATEGORIAS:
        raise DP.DespesaError("Escolha a categoria da despesa.")
    descricao = DP._texto(dados.get("descricao"))
    if len(descricao) < DP.MINIMO_DA_DESCRICAO:
        raise DP.DespesaError("Descreva a despesa em detalhe (art. 190, II, b do CN-MA): o "
                              "que é e a que se refere.")
    nome = DP._texto(dados.get("beneficiario_nome"), 150)
    if not nome:
        raise DP.DespesaError("Informe o favorecido (quem recebe o pagamento).")
    documento = DP.digitos(dados.get("beneficiario_documento"))
    if documento and DP.cpf_cnpj.documento_valido(documento) is not True:
        raise DP.DespesaError("O CPF/CNPJ do favorecido não confere.")
    forma = str(dados.get("forma") or "")
    if forma not in DP.FORMAS:
        raise DP.DespesaError("Escolha a forma de pagamento.")
    chave = DP._texto(dados.get("chave_pix"), 77) if forma == DP.PIX_CHAVE else ""
    valor = int(dados.get("valor") or 0)
    if forma in CARREGA_SOZINHO:
        if not chave:
            raise DP.DespesaError("Informe a chave Pix do favorecido: é com ela que a despesa "
                                  "do mês se carrega sozinha.")
        if valor <= 0:
            raise DP.DespesaError("O Pix recorrente precisa do valor fixo do mês. Se o valor "
                                  "muda todo mês, cadastre como «Pix copia e cola» ou boleto, "
                                  "e o sistema só avisa.")
    elif valor < 0:
        raise DP.DespesaError("O valor não pode ser negativo.")
    try:
        dia = int(dados.get("dia_vencimento") or 0)
        antecedencia = int(dados.get("antecedencia_dias") if dados.get("antecedencia_dias")
                           not in (None, "") else ANTECEDENCIA_PADRAO)
    except (TypeError, ValueError) as erro:
        raise DP.DespesaError("O dia do vencimento e a antecedência são números.") from erro
    if not 1 <= dia <= 31:
        raise DP.DespesaError("O dia do vencimento vai de 1 a 31.")
    if not 0 <= antecedencia <= 25:
        raise DP.DespesaError("A antecedência do aviso vai de 0 a 25 dias.")
    especie = DP._texto(dados.get("documento_especie"), 80)
    if not especie:
        raise DP.DespesaError("Informe a espécie do documento que comprova a despesa (nota "
                              "fiscal, recibo, contrato, fatura…) — art. 190, II, c do CN-MA.")
    primeiro = _mes_valido(dados.get("primeiro_mes"), "Primeiro mês")
    ultimo = _mes_valido(dados.get("ultimo_mes"), "Último mês", vazio_ok=True)
    if ultimo and ultimo < primeiro:
        raise DP.DespesaError("O último mês vem antes do primeiro.")
    return {"descricao": descricao, "categoria": categoria, "beneficiario_nome": nome,
            "beneficiario_documento": documento, "forma": forma, "chave_pix": chave,
            "valor": valor or None, "dia_vencimento": dia, "antecedencia_dias": antecedencia,
            "documento_especie": especie, "primeiro_mes": primeiro, "ultimo_mes": ultimo}


# ------------------------------------------------------- cadastrar e mudar

CAMPOS = ("descricao", "categoria", "beneficiario_nome", "beneficiario_documento", "forma",
          "chave_pix", "valor", "dia_vencimento", "antecedencia_dias", "documento_especie",
          "primeiro_mes", "ultimo_mes")


def cadastrar(con, dados: Mapping[str, Any], *, por: str, agora: datetime) -> int:
    """Grava a recorrente. ESCREVE. Não gera despesa nenhuma — quem gera é `gerar`."""
    r = conferir(dados)
    novo = banco(con).escrever(
        f"""INSERT INTO dp_recorrentes ({", ".join(CAMPOS)}, criada_em, criada_por)
            VALUES ({", ".join(["%s"] * (len(CAMPOS) + 2))}) RETURNING id""",
        (*[r[c] for c in CAMPOS], DP._carimbo(agora), DP._texto(por, 120) or "?"))
    return int(novo[0]["id"])


def alterar(con, recorrente_id: int, dados: Mapping[str, Any], *, por: str,
            agora: datetime) -> None:
    """Muda a recorrente. ESCREVE. Vale dos próximos meses em diante.

    A despesa do mês que já foi carregada NÃO muda: ela é linha de
    `dp_despesas`, com a sua própria autorização — mudar o valor dela por
    trás seria pagar o que o oficial não autorizou.
    """
    r = conferir(dados)
    bd = banco(con)
    if not bd.um("SELECT id FROM dp_recorrentes WHERE id = %s", (int(recorrente_id),)):
        raise DP.DespesaError("Recorrente não encontrada.")
    sets = ", ".join(f"{c} = %s" for c in CAMPOS)
    bd.escrever(f"UPDATE dp_recorrentes SET {sets}, atualizada_em = %s, atualizada_por = %s "
                f"WHERE id = %s",
                (*[r[c] for c in CAMPOS], DP._carimbo(agora), DP._texto(por, 120) or "?",
                 int(recorrente_id)))


def encerrar(con, recorrente_id: int, *, por: str, agora: datetime) -> None:
    """Para de avisar e de carregar. ESCREVE. Não apaga: o histórico fica."""
    bd = banco(con)
    bd.escrever("""UPDATE dp_recorrentes SET ativa = 0, encerrada_em = %s, encerrada_por = %s
                    WHERE id = %s AND ativa = 1""",
                (DP._carimbo(agora), DP._texto(por, 120) or "?", int(recorrente_id)))


def reativar(con, recorrente_id: int) -> None:
    banco(con).escrever("UPDATE dp_recorrentes SET ativa = 1, encerrada_em = NULL, "
                        "encerrada_por = NULL WHERE id = %s", (int(recorrente_id),))


def recorrente(con, recorrente_id: int) -> dict | None:
    return banco(con).um("SELECT * FROM dp_recorrentes WHERE id = %s", (int(recorrente_id),))


def lista(con) -> list[dict]:
    return banco(con).ler("SELECT * FROM dp_recorrentes ORDER BY ativa DESC, dia_vencimento, id")


# ------------------------------------------------------- o mês que abriu

def meses_abertos(r: Mapping[str, Any], hoje: date) -> list[tuple[str, date]]:
    """Os meses em que esta recorrente já devia ter a despesa. Só calcula.

    O mês corrente e o seguinte, os dois dentro da vigência, e só quando
    `hoje` já passou de (vencimento − antecedência).

    O MÊS QUE JÁ VENCIA QUANDO A RECORRENTE FOI CADASTRADA NÃO ABRE. Quem
    cadastra no dia 28 o aluguel que vence no dia 5 já pagou o deste mês, por
    fora — carregá-lo seria pedir para pagar duas vezes.
    """
    try:
        desde = date.fromisoformat(str(r.get("criada_em") or "")[:10])
    except ValueError:
        desde = None
    saida = []
    for competencia in (mes(hoje), _proximo_mes(mes(hoje))):
        if competencia < r["primeiro_mes"] or (r["ultimo_mes"] and competencia > r["ultimo_mes"]):
            continue
        venc = vencimento_do_mes(r, competencia)
        if desde and venc < desde:
            continue
        if hoje >= venc - timedelta(days=int(r["antecedencia_dias"] or 0)):
            saida.append((competencia, venc))
    return saida


def do_mes(con, hoje: date) -> list[dict]:
    """O que abriu e ainda não tem despesa — cada linha com o que falta. Só LÊ."""
    bd = banco(con)
    feitas = {r["chave_origem"] for r in bd.ler(
        "SELECT chave_origem FROM dp_despesas WHERE origem = %s", (ORIGEM,))}
    saida = []
    for r in bd.ler("SELECT * FROM dp_recorrentes WHERE ativa = 1 ORDER BY dia_vencimento, id"):
        for competencia, venc in meses_abertos(r, hoje):
            if chave_do_mes(r["id"], competencia) in feitas:
                continue
            saida.append({**r, "competencia": competencia, "vencimento": venc.isoformat(),
                          "carrega_sozinho": r["forma"] in CARREGA_SOZINHO and bool(r["valor"]),
                          "atrasada": venc < hoje})
    return saida


def descricao_do_mes(r: Mapping[str, Any], competencia: str) -> str:
    return f"{r['descricao']} — {competencia[5:7]}/{competencia[:4]}"


def gerar(con, *, hoje: date, agora: datetime, por: str) -> list[int]:
    """Carrega as despesas do mês das recorrentes por Pix. ESCREVE. Devolve os ids.

    Elas nascem AGUARDANDO a autorização do oficial (`despesas.cadastrar`),
    que é a confirmação. As outras formas não se carregam: ficam no aviso.
    """
    novas = []
    for linha in do_mes(con, hoje):
        if not linha["carrega_sozinho"]:
            continue
        novas.append(DP.cadastrar(
            con, agora=agora, por=por, origem=ORIGEM,
            chave_origem=chave_do_mes(linha["id"], linha["competencia"]),
            beneficiario_nome=linha["beneficiario_nome"],
            beneficiario_documento=linha["beneficiario_documento"],
            valor_centavos=int(linha["valor"]), vencimento=linha["vencimento"],
            forma=linha["forma"], codigo=linha["chave_pix"],
            descricao=descricao_do_mes(linha, linha["competencia"]),
            categoria=linha["categoria"], documento_especie=linha["documento_especie"]))
    return novas


def para_o_formulario(r: Mapping[str, Any], competencia: str) -> dict:
    """A despesa do mês, preenchida, para o balcão só colar o código. Só calcula."""
    return {"recorrente_id": r["id"], "competencia": competencia,
            "categoria": r["categoria"], "descricao": descricao_do_mes(r, competencia),
            "beneficiario_nome": r["beneficiario_nome"],
            "beneficiario_documento": r["beneficiario_documento"],
            "valor": reais(int(r["valor"])) if r["valor"] else "",
            "vencimento": vencimento_do_mes(r, competencia).isoformat(),
            "forma": r["forma"], "codigo": r["chave_pix"],
            "documento_especie": r["documento_especie"]}


def origem_do_formulario(con, recorrente_id: Any, competencia: Any) -> tuple[str, str | None]:
    """A origem e a chave da despesa cadastrada pela tela. Só LÊ.

    Vinda do botão de uma recorrente, ela leva a chave do mês — e é isso que
    tira o mês do aviso, e impede de cadastrá-lo duas vezes.
    """
    rid = str(recorrente_id or "").strip()
    comp = str(competencia or "").strip()[:7]
    if not rid.isdigit() or not comp:
        return "MANUAL", None
    _mes_valido(comp, "Mês")
    if not recorrente(con, int(rid)):
        raise DP.DespesaError("A recorrente deste formulário não existe mais.")
    return ORIGEM, chave_do_mes(int(rid), comp)
