"""Onde mora o que o Serviço de Pendências do e-Protocolo manda.

**DUAS TABELAS, PORQUE SÃO DUAS COISAS.** A notificação é um fato imutável: «tal
evento aconteceu a tal hora». O protocolo é o estado mais recente de um pedido,
e muda. Ligadas pelo `hash`, que é a chave de todas as rotas do serviço.

**O AMBIENTE FAZ PARTE DA CHAVE**, a lição da CENPROT: um hash de homologação não
pode ocupar o lugar de um de verdade.

**A CHAVE DA NOTIFICAÇÃO LEVA A DATA.** O manual diz para reconhecer o evento pelo
hash e pelo status, mas o mesmo status volta legitimamente no mesmo protocolo —
uma segunda nota de exigência, por exemplo. Sem a data a segunda seria descartada
como repetida, sem erro em lugar nenhum.

**OS ANEXOS NÃO MORAM AQUI.** O que fica é o detalhe que o serviço devolveu e o
arquivo estruturado, que traz causa da morte e dados de familiares: a leitura é
só de quem atende, e as telas não os escrevem em log. O PDF se busca na hora.
"""
from __future__ import annotations

import re

from bd_nativo import banco

SCHEMA = """
CREATE TABLE IF NOT EXISTS ep_notificacoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ambiente TEXT NOT NULL,
    hash TEXT NOT NULL,
    status TEXT NOT NULL,
    requirement_id bigint,
    cns TEXT,
    conteudo_json TEXT NOT NULL DEFAULT '{}',
    ocorrida_em TEXT NOT NULL,
    recebida_em TEXT NOT NULL,
    origem TEXT NOT NULL DEFAULT 'FILA',
    UNIQUE (ambiente, hash, status, ocorrida_em)
);

CREATE TABLE IF NOT EXISTS ep_protocolos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ambiente TEXT NOT NULL,
    hash TEXT NOT NULL,
    requirement_id bigint,
    numero TEXT,
    status TEXT,
    pagamento TEXT,
    servico TEXT,
    plataforma TEXT,
    tipo_registro TEXT,
    titular TEXT,
    detalhe_json TEXT,
    estruturado_json TEXT,
    tem_estruturado INTEGER NOT NULL DEFAULT 0,
    consulta_erro TEXT,
    consultado_em TEXT,
    primeiro_evento_em TEXT NOT NULL,
    ultimo_evento_em TEXT NOT NULL,
    novo_destino_cns TEXT,
    rascunho_id bigint,
    rascunho_em TEXT,
    rascunho_por TEXT,
    assento_id bigint REFERENCES rc_assentos(id),
    assento_em TEXT,
    assento_por TEXT,
    cumprimento_tentado_em TEXT,
    cumprimento_tentado_por TEXT,
    cumprido_em TEXT,
    cumprido_por TEXT,
    cumprimento_json TEXT,
    dispensado_em TEXT,
    dispensado_por TEXT,
    dispensado_motivo TEXT,
    UNIQUE (ambiente, hash)
);

CREATE INDEX IF NOT EXISTS idx_ep_notificacoes_hash ON ep_notificacoes (ambiente, hash);
CREATE INDEX IF NOT EXISTS idx_ep_protocolos_status ON ep_protocolos (ambiente, status);
"""


def init_eprotocolo_schema(con) -> None:
    """Cria as duas tabelas. Idempotente. Depois de `rc_assentos`, a quem aponta."""
    bd = banco(con)
    for comando in re.split(r";[ \t]*\n", re.sub(r"--[^\n]*", "", SCHEMA)):
        if comando.strip():
            bd.escrever(comando)
