"""As tabelas do gestor — o agente que confere a casa, cria e cobra as tarefas.

    «preciso que faça tudo, eu fiscalizo e reviso depois» — o oficial, 06/10/2026

AS TABELAS, E A PRIMEIRA É A QUE FALTAVA À CASA INTEIRA
    `ge_envios` guarda **o que saiu para cada Central**, com protocolo e recibo.
    Medido em 02/10/2026 na produção: nada no sistema dizia o que já tinha ido ao
    SIRC, à CENSEC, ao IBGE ou à DOI. Sem esse registro nenhuma conferência
    distingue «não foi mandado» de «foi mandado pelo portal» — e um agente que
    cobra prazo sem saber o que já foi cumprido cobra para sempre.

    `ge_achados` é a fila de revisão do oficial: cada coisa que a conferência
    acha, com a chave estável que a reconhece de um dia para o outro.

    `ge_execucoes` é o diário do próprio agente — quando rodou, o que achou, o
    que fechou e onde quebrou.

    `ge_responsaveis` diz quem responde por cada setor. Nasce **inferido** de
    quem lavrou os atos de cada setor, e o oficial troca depois: é o «revisa
    depois» aplicado à distribuição do serviço.

    `ge_conferencias_do_dia` (19/11/2026) guarda o «conferido hoje» da
    checklist de gestão (`gestor_checklist`): quem abriu cada tela da lista e
    quando. É um VISTO DE QUEM OLHOU, e não uma baixa — o achado só sai de
    `ge_achados` quando a conferência seguinte o fecha.

    `ge_retirados_da_gestao` (25/11/2026, T019) guarda o que o oficial ou o
    gerente tirou da checklist do dia ou dos projetos por não caber à gestão
    (`gestao_retirados`): a chave do item, o motivo, quem e quando — e, ao
    devolver, quem devolveu e quando. Não apaga nem resolve nada.

    `ge_rotina` e `ge_rotina_feitos` (26/11/2026) são a ROTINA DA SERVENTIA
    (`rotina_da_casa`): o que a TI e a administração fazem todo dia, semana,
    mês ou ano, escrito para quem não conhece o cartório, e o «feito» de cada
    vencimento. Elas apontam para `users` e por isso nascem à parte, em
    `init_rotina_schema`, depois dos usuários (`database.init_schema`): o
    `init_gestor_schema` roda também em banco de teste sem `users`.
"""
from __future__ import annotations

import re

from bd_nativo import banco

SCHEMA = """
CREATE TABLE IF NOT EXISTS ge_envios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    central TEXT NOT NULL,
    competencia TEXT,
    referencia TEXT,
    canal TEXT NOT NULL DEFAULT 'PORTAL',
    situacao TEXT NOT NULL DEFAULT 'ENVIADO',
    protocolo TEXT,
    recibo_caminho TEXT,
    quantos INTEGER,
    mensagem TEXT,
    enviado_em TEXT NOT NULL,
    registrado_em TEXT NOT NULL,
    registrado_por TEXT NOT NULL,
    origem TEXT NOT NULL DEFAULT 'BALCAO'
);
CREATE INDEX IF NOT EXISTS ix_ge_envios_central
    ON ge_envios (central, competencia, referencia);

CREATE TABLE IF NOT EXISTS ge_achados (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave TEXT NOT NULL UNIQUE,
    regra TEXT NOT NULL,
    gravidade TEXT NOT NULL,
    setor TEXT NOT NULL,
    titulo TEXT NOT NULL,
    detalhe TEXT,
    prazo TEXT,
    fundamento TEXT,
    primeiro_visto_em TEXT NOT NULL,
    ultimo_visto_em TEXT NOT NULL,
    resolvido_em TEXT,
    revisado_em TEXT,
    revisado_por TEXT,
    revisao TEXT
);
CREATE INDEX IF NOT EXISTS ix_ge_achados_abertos
    ON ge_achados (resolvido_em, regra);

CREATE TABLE IF NOT EXISTS ge_execucoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iniciada_em TEXT NOT NULL,
    terminada_em TEXT,
    hoje TEXT NOT NULL,
    achados INTEGER,
    novos INTEGER,
    resolvidos INTEGER,
    tarefas_criadas INTEGER,
    tarefas_fechadas INTEGER,
    tarefas_cobradas INTEGER,
    nao_mediu INTEGER,
    relatorio TEXT,
    erro TEXT
);

-- O LIVRO DE CARGAS DO ONR (gestor_cargas_ri, 09/10/2026): cada arquivo que o
-- agente pôs numa pasta do ONR, com o sha que permite achá-lo depois em
-- `Processados`, e cada rodada dele, com o que fez e onde quebrou.
CREATE TABLE IF NOT EXISTS ge_onr_cargas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal TEXT NOT NULL,              -- IMAGENS | PESSOAL | REAL
    tipo TEXT NOT NULL,               -- COMPLETA | INCREMENTAL | RODADA
    periodo_de TEXT,
    periodo_ate TEXT,
    arquivo TEXT,
    sha256 TEXT,
    quantos INTEGER,
    situacao TEXT NOT NULL,           -- PREPARADO | NA_PASTA | PROCESSADO | SUBSTITUIDO | OK | ERRO
    gerado_em TEXT NOT NULL,
    processado_em TEXT,
    detalhe TEXT
);
CREATE INDEX IF NOT EXISTS ix_ge_onr_cargas_canal
    ON ge_onr_cargas (canal, tipo, situacao);

-- O LIVRO DE CARGAS DO RCPN (gestor_cargas_rcpn, 09/10/2026): cada rodada do
-- agente, por carga, com os arquivos que deixou na pasta (nome, caminho e
-- sha), o que ficou de fora e por quê, e onde quebrou. É ele que a
-- conferência lê — o agente não registra envio: isso é da tela de cada carga.
CREATE TABLE IF NOT EXISTS ge_rcpn_cargas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal TEXT NOT NULL,              -- SIRC | CRC | FUNAI | OBITOS | IBGE
    tipo TEXT NOT NULL,               -- RODADA
    situacao TEXT NOT NULL,           -- OK | ERRO
    gerado_em TEXT NOT NULL,
    detalhe TEXT
);
CREATE INDEX IF NOT EXISTS ix_ge_rcpn_cargas_canal
    ON ge_rcpn_cargas (canal, tipo, id);

-- O QUE O PORTAL DO SELO DISSE DE CADA SELO (gestor_fiscal, 09/10/2026): a
-- consulta pública do TJMA, uma linha por selo, refeita enquanto o que ela diz
-- pode mudar (gratuidade em análise, cancelamento que só um lado tem). A
-- resposta inteira fica em `bruto`; as colunas são o que a conferência compara.
CREATE TABLE IF NOT EXISTS ge_portal_selos (
    numero TEXT PRIMARY KEY,
    consultado_em TEXT NOT NULL,
    situacao TEXT NOT NULL,           -- ACHADO | NAO_ACHADO | ERRO
    cancelado INTEGER,
    data_cancelado TEXT,
    isento INTEGER,
    motivo_isencao TEXT,
    analise TEXT,                     -- DEFERIDA | INDEFERIDA | EM_ANALISE | CANCELADA | NULL (não isento)
    motivo_indeferimento TEXT,
    prazo_recurso TEXT,
    codigo_ato TEXT,
    valor_ato double precision,
    emolumento double precision,
    valor_selo double precision,
    escrevente TEXT,
    data_selo TEXT,
    erro TEXT,
    bruto TEXT
);

-- O «CONFERIDO HOJE» DA CHECKLIST DE GESTÃO (gestor_checklist, 19/11/2026):
-- uma linha por item e por dia; o primeiro que confere fica, e o segundo
-- clique do mesmo dia só é avisado de quem já conferiu.
CREATE TABLE IF NOT EXISTS ge_conferencias_do_dia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item TEXT NOT NULL,
    dia TEXT NOT NULL,
    conferido_em TEXT NOT NULL,
    conferido_por TEXT NOT NULL,
    usuario_id INTEGER,
    UNIQUE (item, dia)
);

-- O QUE NÃO CABE À GESTÃO (gestao_retirados, 25/11/2026, T019): a marca que
-- tira um achado da checklist do dia (chave = `ge_achados.chave`) ou um projeto
-- da lista dos projetos (chave = `dev_projetos.id`). Uma linha por retirada; a
-- que vale é a sem `devolvido_em`. Devolver preenche as colunas de devolução,
-- e a linha fica.
CREATE TABLE IF NOT EXISTS ge_retirados_da_gestao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tela TEXT NOT NULL,               -- CHECKLIST | PROJETOS
    chave TEXT NOT NULL,
    motivo_codigo TEXT,               -- ESCREVENTE | TI | FORA | OUTRO | NULL
    motivo TEXT NOT NULL,
    retirado_em TEXT NOT NULL,
    retirado_por TEXT NOT NULL,
    retirado_por_id INTEGER,
    devolvido_em TEXT,
    devolvido_por TEXT,
    devolvido_por_id INTEGER
);
CREATE INDEX IF NOT EXISTS ix_ge_retirados_da_gestao_chave
    ON ge_retirados_da_gestao (tela, chave);

CREATE TABLE IF NOT EXISTS ge_responsaveis (
    setor TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL,
    origem TEXT NOT NULL DEFAULT 'INFERIDO',
    definido_em TEXT NOT NULL,
    definido_por TEXT NOT NULL,
    substituto_id INTEGER,
    rodizio INTEGER NOT NULL DEFAULT 0
);
"""

#: Colunas que chegaram depois da tabela — o banco que já a tem ganha por ALTER.
#: `rodizio=1`: titular e substituto se revezam tarefa a tarefa (ordem do
#: oficial em 06/10/2026 para o RCPN: «distribuindo entre Elisa e Debora;
#: quando uma for responsável, a outra fica como substituta»).
_COLUNAS_TARDIAS = (
    ("ge_responsaveis", "substituto_id", "INTEGER"),
    ("ge_responsaveis", "rodizio", "INTEGER NOT NULL DEFAULT 0"),
)


#: A ROTINA DA SERVENTIA (`rotina_da_casa`, 26/11/2026). Só acréscimo: duas
#: tabelas novas. `ge_rotina` é o cadastro (o código é a chave da carga em
#: lote); `ge_rotina_feitos` guarda um «feito» por item e por vencimento — o
#: primeiro fica, como no «conferido hoje». A prova em arquivo vai em
#: `attachments` (entity_type 'GE_ROTINA_FEITO', entity_id = o feito).
SCHEMA_ROTINA = """
CREATE TABLE IF NOT EXISTS ge_rotina (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE,
    area TEXT NOT NULL,               -- um código de conformidade.AREAS, ou TI
    titulo TEXT NOT NULL,
    para_que TEXT NOT NULL DEFAULT '',
    como_fazer TEXT NOT NULL,         -- um passo por linha
    pronto_quando TEXT NOT NULL DEFAULT '',
    se_der_errado TEXT NOT NULL DEFAULT '',
    prova TEXT NOT NULL DEFAULT '',
    onde_endpoint TEXT,
    onde_url TEXT,
    base_legal TEXT NOT NULL DEFAULT '',
    periodicidade TEXT NOT NULL CHECK (periodicidade IN
        ('DIARIA', 'SEMANAL', 'QUINZENAL', 'MENSAL', 'TRIMESTRAL', 'SEMESTRAL', 'ANUAL')),
    dias_semana TEXT,                 -- '1,3' = segunda e quarta (ISO 1..7)
    dias_mes TEXT,                    -- '5,20'
    dia_util INTEGER,                 -- 5 = 5º dia útil; -1 = último dia útil
    meses TEXT,                       -- '1,4,7,10'
    horario TEXT,                     -- 'até 09:00'
    responsavel_id bigint REFERENCES users(id),
    suplente_id bigint REFERENCES users(id),
    prioridade INTEGER NOT NULL DEFAULT 2   -- 1 alta, 2 normal, 3 baixa
        CONSTRAINT ge_rotina_prioridade_ck CHECK (prioridade BETWEEN 1 AND 3),
    ordem INTEGER NOT NULL DEFAULT 100,
    ativo INTEGER NOT NULL DEFAULT 1 CONSTRAINT ge_rotina_ativo_ck CHECK (ativo IN (0, 1)),
    motivo_desativacao TEXT,
    vale_desde TEXT,                  -- AAAA-MM-DD: o cadastro ou a reativação
    criado_em TEXT NOT NULL,
    criado_por TEXT NOT NULL,
    atualizado_em TEXT,
    atualizado_por TEXT
);
CREATE INDEX IF NOT EXISTS ix_ge_rotina_area ON ge_rotina (ativo, area);

CREATE TABLE IF NOT EXISTS ge_rotina_feitos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rotina_id bigint NOT NULL REFERENCES ge_rotina(id),
    referencia TEXT NOT NULL,         -- AAAA-MM-DD: a data NOMINAL do vencimento
    prazo TEXT,                       -- AAAA-MM-DD: a nominal levada ao dia útil
    com_atraso INTEGER NOT NULL DEFAULT 0
        CONSTRAINT ge_rotina_feitos_com_atraso_ck CHECK (com_atraso IN (0, 1)),
    feito_em TEXT NOT NULL,
    feito_por TEXT NOT NULL,
    usuario_id bigint CONSTRAINT ge_rotina_feitos_usuario_fk REFERENCES users(id),
    resultado TEXT NOT NULL CHECK (resultado IN ('OK', 'COM_PENDENCIA', 'NAO_SE_APLICA')),
    observacao TEXT NOT NULL DEFAULT '',
    UNIQUE (rotina_id, referencia)
);
"""

#: As colunas da rotina que chegaram depois da tabela (26/11/2026, revisão): o
#: banco que já tem a tabela ganha por ALTER, e o `vale_desde` vazio vira o dia
#: do cadastro. Nada sai nem muda de nome.
_COLUNAS_TARDIAS_DA_ROTINA = (
    ("ge_rotina", "vale_desde", "TEXT"),
    ("ge_rotina_feitos", "prazo", "TEXT"),
    ("ge_rotina_feitos", "com_atraso", "INTEGER NOT NULL DEFAULT 0"),
)

#: As travas da rotina que o banco guarda, pelo nome: no banco novo vêm no
#: CREATE TABLE; no que já tinha a tabela, entram por ALTER (NOT VALID: a linha
#: antiga não impede a subida, e a nova já é conferida).
_RESTRICOES_DA_ROTINA = (
    ("ge_rotina", "ge_rotina_prioridade_ck", "CHECK (prioridade BETWEEN 1 AND 3)"),
    ("ge_rotina", "ge_rotina_ativo_ck", "CHECK (ativo IN (0, 1))"),
    ("ge_rotina_feitos", "ge_rotina_feitos_com_atraso_ck", "CHECK (com_atraso IN (0, 1))"),
    ("ge_rotina_feitos", "ge_rotina_feitos_usuario_fk",
     "FOREIGN KEY (usuario_id) REFERENCES users(id)"),
)


def _rodar(bd, schema: str) -> None:
    for comando in re.split(r";[ \t]*\n", schema):
        if re.sub(r"--[^\n]*", "", comando).strip():
            bd.escrever(comando)


def init_gestor_schema(con) -> None:
    bd = banco(con)
    _rodar(bd, SCHEMA)
    for tabela, coluna, tipo in _COLUNAS_TARDIAS:
        if not bd.tem_coluna(tabela, coluna):
            bd.escrever(f"ALTER TABLE {tabela} ADD COLUMN {coluna} {tipo}")


def init_rotina_schema(con) -> None:
    """As tabelas da rotina da serventia. Apontam para `users`: vêm depois dele."""
    bd = banco(con)
    _rodar(bd, SCHEMA_ROTINA)
    for tabela, coluna, tipo in _COLUNAS_TARDIAS_DA_ROTINA:
        if not bd.tem_coluna(tabela, coluna):
            bd.escrever(f"ALTER TABLE {tabela} ADD COLUMN {coluna} {tipo}")
    bd.escrever("UPDATE ge_rotina SET vale_desde = substr(criado_em, 1, 10) "
                "WHERE vale_desde IS NULL")
    for tabela, nome, definicao in _RESTRICOES_DA_ROTINA:
        if not bd.valor("SELECT 1 FROM pg_constraint WHERE conname = %s "
                        "AND conrelid = to_regclass(%s)", (nome, tabela)):
            bd.escrever(f"ALTER TABLE {tabela} ADD CONSTRAINT {nome} {definicao} NOT VALID")
