"""O REGISTRO DO USO DE IA — o que alimenta o relatório anual à COGEX.

POR QUE EXISTE (LF01, 19/10/2026)
    A serventia é do Maranhão. O Código de Normas do Foro Extrajudicial do MA
    (Provimento COGEX 28/2026, arts. 167–179) permite IA só nos usos do
    art. 171, pede critérios auditáveis (art. 176) e um relatório anual à
    COGEX (art. 170, § 4º) com sistemas e finalidades, medidas de segurança,
    incidentes ou falhas e ações de mitigação. **Relatório sem registro é
    relatório de memória** — e memória não se audita. Até aqui o sistema
    citava os artigos e não guardava nada do uso.

    A base normativa é um RESUMO de terceiro (data de corte 25/08/2026), e
    não o texto oficial: toda tela que nasce daqui diz isso
    (`ia_catalogo.AVISO_DO_TEXTO_OFICIAL`).

O QUE SE GUARDA, E O QUE NÃO SE GUARDA
    `ia_uso` guarda UMA linha por chamada a um provedor: quando, de onde,
    para quê, quem, qual provedor e modelo, quantos tokens e como terminou.
    **NUNCA o texto que foi ou que voltou** — nem a pergunta, nem a resposta,
    nem o trecho do ato. A referência é `tabela:id`, que aponta para o que já
    está no banco, e o erro é um RESUMO de forma fixa (`HTTP 429`, `sem
    chave`), e não a mensagem do provedor, que pode trazer de volta um pedaço
    do que subiu. É a LGPD na forma de coluna: o banco vai no backup, e o
    backup sai da serventia.

QUEM GRAVA
    Os dois transportes — `agente_provedores.conversar` e
    `robo_llm.chamar_provedor` —, e mais ninguém. Gravar no transporte, e não
    em cada chamador, é o que impede um chamador novo de usar IA sem deixar
    rastro: ele pode esquecer a finalidade, mas não o registro.

    A GRAVAÇÃO VAI NUMA CONEXÃO PRÓPRIA, CURTA, E NUNCA DERRUBA A CHAMADA. O
    transporte não recebe `con` de propósito (ver `agente_provedores`), e o
    uso tem de ficar registrado mesmo quando quem chamou volta atrás. Se o
    banco não responder, a linha vai para o log do sistema e a chamada segue
    — a mesma troca da auditoria (`Database.log`): entre perder o registro e
    perder o atendimento, a serventia precisa do atendimento.
"""
from __future__ import annotations

import logging
import re
import unicodedata
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Any

import banco_pg
from bd_nativo import banco

LOG = logging.getLogger("cartorio.ia")

OK, ERRO, RECUSADO = "ok", "erro", "recusado"
RESULTADOS = (OK, ERRO, RECUSADO)

# A ESPERA PELA TRAVA, CURTA DE PROPÓSITO — a mesma régua da linha de
# auditoria (`Database.log`). O registro não pode fazer o balcão esperar os
# quinze segundos de uma gravação de verdade; passou disso, vai para o log.
ESPERA_MS = 800

# O TAMANHO DE CADA CAMPO DE TEXTO. Não é economia de disco: um campo sem
# limite é o lugar onde, um dia, alguém passa o texto inteiro do ato.
LIMITE = 120

# TABELA NOVA, UM COMANDO POR LINHA, E CADA UM SÓ SE O OBJETO FALTA — o
# `to_regclass` acha tabela e índice. Rodar o `CREATE INDEX` só quando a
# tabela falta faria uma tabela já existente nunca ganhar o índice novo.
SCHEMA: tuple[tuple[str, str], ...] = (
    ("ia_uso", """
        CREATE TABLE IF NOT EXISTS ia_uso (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            quando TEXT NOT NULL,
            modulo TEXT NOT NULL DEFAULT '',
            finalidade TEXT NOT NULL DEFAULT '',
            provedor TEXT NOT NULL DEFAULT '',
            modelo TEXT NOT NULL DEFAULT '',
            usuario TEXT NOT NULL DEFAULT '',
            atribuicao TEXT NOT NULL DEFAULT '',
            referencia TEXT NOT NULL DEFAULT '',
            mascarado boolean,
            tokens_entrada bigint NOT NULL DEFAULT 0,
            tokens_saida bigint NOT NULL DEFAULT 0,
            resultado TEXT NOT NULL
                CHECK (resultado IN ('ok', 'erro', 'recusado')),
            erro TEXT NOT NULL DEFAULT ''
        )"""),
    ("ix_ia_uso_quando",
     "CREATE INDEX IF NOT EXISTS ix_ia_uso_quando ON ia_uso (quando, id)"),
    ("ia_incidentes", """
        CREATE TABLE IF NOT EXISTS ia_incidentes (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            data TEXT NOT NULL,
            sistema TEXT NOT NULL DEFAULT '',
            o_que TEXT NOT NULL,
            impacto TEXT NOT NULL DEFAULT '',
            causa TEXT NOT NULL DEFAULT '',
            mitigacao TEXT NOT NULL DEFAULT '',
            comunicado_a TEXT NOT NULL DEFAULT '',
            registrado_por TEXT NOT NULL DEFAULT '',
            registrado_em TEXT NOT NULL
        )"""),
    ("ix_ia_incidentes_data",
     "CREATE INDEX IF NOT EXISTS ix_ia_incidentes_data ON ia_incidentes (data, id)"),
    ("ia_fornecedores", """
        CREATE TABLE IF NOT EXISTS ia_fornecedores (
            provedor TEXT PRIMARY KEY,
            empresa TEXT NOT NULL DEFAULT '',
            pais_processa TEXT NOT NULL DEFAULT '',
            pais_armazena TEXT NOT NULL DEFAULT '',
            retencao TEXT NOT NULL DEFAULT '',
            retencao_prazo TEXT NOT NULL DEFAULT '',
            treinamento TEXT NOT NULL DEFAULT '',
            iso27001 TEXT NOT NULL DEFAULT '',
            contrato TEXT NOT NULL DEFAULT '',
            atualizado_por TEXT NOT NULL DEFAULT '',
            atualizado_em TEXT NOT NULL DEFAULT ''
        )"""),
)


def init_ia_schema(con) -> None:
    """Cria as três tabelas e os índices que faltarem. Idempotente."""
    bd = banco(con)
    for nome, comando in SCHEMA:
        if not bd.tem_tabela(nome):
            bd.escrever(comando)


def _agora() -> str:
    """A hora do registro, calculada no Python (regra da casa)."""
    return datetime.now().replace(microsecond=0).isoformat()   # noqa: DTZ005


def _curto(valor: Any, limite: int = LIMITE) -> str:
    return " ".join(str(valor or "").split())[:limite]


# ----------------------------------------------------------------- o registro


def registrar(pasta_de_dados: Any, *, modulo: str = "", finalidade: str = "",
              provedor: str = "", modelo: str = "", usuario: str = "",
              atribuicao: str = "", referencia: str = "",
              mascarado: bool | None = None, tokens_entrada: int = 0,
              tokens_saida: int = 0, resultado: str = OK,
              erro: str = "") -> bool:
    """Grava UMA chamada em `ia_uso`. **ESCREVE, e NUNCA levanta.**

    O banco é o da instalação, ao lado de quem tem as chaves:
    `<pasta de dados>/cartorio_gestao.sqlite3` — o mesmo caminho que o
    `create_app` abre. Conexão própria, espera curta e confirmação na hora: o
    registro não entra na transação de quem chamou, e não fica preso a ela.

    Devolve se gravou. `False` não é erro de quem chamou: a linha foi para o
    log do sistema, com tudo menos o conteúdo — que nunca chega aqui.
    """
    campos = {
        "quando": _agora(), "modulo": _curto(modulo), "finalidade": _curto(finalidade),
        "provedor": _curto(provedor), "modelo": _curto(modelo),
        "usuario": _curto(usuario), "atribuicao": _curto(atribuicao),
        "referencia": _curto(referencia),
        "mascarado": None if mascarado is None else bool(mascarado),
        "tokens_entrada": max(0, int(tokens_entrada or 0)),
        "tokens_saida": max(0, int(tokens_saida or 0)),
        "resultado": resultado if resultado in RESULTADOS else ERRO,
        "erro": _curto(erro),
    }
    try:
        if pasta_de_dados in (None, ""):
            raise ValueError("quem chamou não disse a pasta de dados")
        if not banco_pg.ativo():
            # SEM O POSTGRESQL não há onde gravar: o módulo é nativo, e abrir
            # o caminho pelo sqlite3 criaria um banco vazio ao lado das chaves.
            raise RuntimeError("o PostgreSQL não está ligado (CG_PG_DSN)")
        caminho = Path(pasta_de_dados) / banco_pg.NOME_DO_BANCO_PRINCIPAL
        con = banco_pg.conectar(caminho)
        try:
            bd = banco(con)
            bd.ler(f"SET lock_timeout = '{int(ESPERA_MS)}ms'")
            if not bd.tem_tabela("ia_uso"):
                init_ia_schema(con)
            bd.escrever(
                """INSERT INTO ia_uso (quando, modulo, finalidade, provedor, modelo,
                       usuario, atribuicao, referencia, mascarado, tokens_entrada,
                       tokens_saida, resultado, erro)
                   VALUES (%(quando)s, %(modulo)s, %(finalidade)s, %(provedor)s,
                       %(modelo)s, %(usuario)s, %(atribuicao)s, %(referencia)s,
                       %(mascarado)s, %(tokens_entrada)s, %(tokens_saida)s,
                       %(resultado)s, %(erro)s)""", campos)
            con.commit()
        finally:
            con.close()
        return True
    except Exception as falha:  # noqa: BLE001 — o registro não derruba a chamada
        LOG.error("USO DE IA NAO REGISTRADO (%s: %s): quando=%s modulo=%s "
                  "finalidade=%s provedor=%s modelo=%s referencia=%s "
                  "resultado=%s erro=%s", type(falha).__name__,
                  _curto(falha, 200), campos["quando"], campos["modulo"],
                  campos["finalidade"], campos["provedor"], campos["modelo"],
                  campos["referencia"], campos["resultado"], campos["erro"])
        return False


# ------------------------------------------------------- o teto do dia (LX13)


def usos_do_dia(con, finalidade: str, dia: str) -> int:
    """Quantas chamadas daquela finalidade o registro tem no dia (AAAA-MM-DD).

    **SÓ LÊ** — é chamada por tela GET e POST antes da rede, e banco sem a
    tabela conta zero. Conta o que saiu ou pode ter saído (`ok` e `erro`, que
    inclui o prazo esgotado com o pedido já enviado); o `recusado` (sem chave,
    provedor desconhecido) não subiu nada e não conta.
    """
    bd = banco(con)
    if not bd.tem_tabela("ia_uso"):
        return 0
    seguinte = (date.fromisoformat(dia[:10]) + timedelta(days=1)).isoformat()
    return int(bd.valor(
        """SELECT count(*) AS n FROM ia_uso
            WHERE finalidade = %s AND quando >= %s AND quando < %s
              AND resultado <> %s""", (finalidade, dia[:10], seguinte, RECUSADO)) or 0)


def passou_do_teto(con, finalidade: str, *, agora: str | None = None) -> str | None:
    """A frase de recusa quando a finalidade já gastou o teto do dia, ou None.

    O TETO É DO CATÁLOGO (`ia_catalogo.CHAMADAS_POR_DIA`), e quem chama o
    transporte confere ANTES da rede: o registro só conta o que já foi, e o
    que se quer é que a chamada de número 401 não saia. Finalidade sem teto
    diário no catálogo (o teto dela é por rodada ou por ato, no módulo) passa.
    SÓ LÊ.
    """
    import ia_catalogo as CAT
    teto = CAT.teto_diario(finalidade)
    if teto is None:
        return None
    feitos = usos_do_dia(con, finalidade, (agora or _agora())[:10])
    if feitos < teto:
        return None
    return (f"O teto de uso de IA de hoje para «{CAT.nome_da_finalidade(finalidade)}» "
            f"já foi atingido ({feitos} de {teto} chamadas ao provedor). Nada foi "
            "enviado. O teto volta amanhã; se o dia pede mais, fale com o "
            "administrador — o número está no catálogo de IA (ia_catalogo).")


# ------------------------------------------------------------ o que se lê


def _limites_do_ano(ano: int) -> tuple[str, str]:
    return f"{int(ano):04d}-01-01", f"{int(ano) + 1:04d}-01-01"


def uso_do_ano(con, ano: int) -> list[dict]:
    """As chamadas do ano, somadas por mês, finalidade, provedor e resultado.

    **SÓ LÊ.** Banco em que a tabela ainda não existe devolve lista vazia — a
    tela é GET, e GET não cria tabela.
    """
    bd = banco(con)
    if not bd.tem_tabela("ia_uso"):
        return []
    inicio, fim = _limites_do_ano(ano)
    linhas = bd.ler(
        """SELECT left(quando, 7) AS mes, finalidade, provedor, resultado,
                  count(*) AS chamadas,
                  coalesce(sum(tokens_entrada), 0)::bigint AS entrada,
                  coalesce(sum(tokens_saida), 0)::bigint AS saida,
                  count(*) FILTER (WHERE mascarado IS TRUE) AS mascaradas,
                  count(*) FILTER (WHERE mascarado IS FALSE) AS sem_mascara
             FROM ia_uso
            WHERE quando >= %s AND quando < %s
            GROUP BY left(quando, 7), finalidade, provedor, resultado
            ORDER BY mes, finalidade, provedor, resultado""", (inicio, fim))
    return [{**l, "chamadas": int(l["chamadas"]), "entrada": int(l["entrada"]),
             "saida": int(l["saida"]), "mascaradas": int(l["mascaradas"]),
             "sem_mascara": int(l["sem_mascara"])} for l in linhas]


def falhas_do_ano(con, ano: int) -> list[dict]:
    """As chamadas que não terminaram em `ok`, agrupadas pelo resumo. SÓ LÊ."""
    bd = banco(con)
    if not bd.tem_tabela("ia_uso"):
        return []
    inicio, fim = _limites_do_ano(ano)
    linhas = bd.ler(
        """SELECT finalidade, provedor, resultado, erro, count(*) AS vezes,
                  min(quando) AS primeira, max(quando) AS ultima
             FROM ia_uso
            WHERE quando >= %s AND quando < %s AND resultado <> 'ok'
            GROUP BY finalidade, provedor, resultado, erro
            ORDER BY count(*) DESC, finalidade, provedor, resultado, erro""",
        (inicio, fim))
    return [{**l, "vezes": int(l["vezes"])} for l in linhas]


def primeiro_registro(con) -> str | None:
    """Quando o registro começou. SÓ LÊ.

    O relatório o diz em voz alta: antes desta data não há contagem, e mês
    sem linha antes dela não é mês sem uso.
    """
    bd = banco(con)
    if not bd.tem_tabela("ia_uso"):
        return None
    return bd.valor("SELECT min(quando) AS primeiro FROM ia_uso")


def provedores_usados(con, ano: int) -> list[str]:
    """Os provedores que receberam ao menos um pedido no ano. SÓ LÊ."""
    bd = banco(con)
    if not bd.tem_tabela("ia_uso"):
        return []
    inicio, fim = _limites_do_ano(ano)
    return [l["provedor"] for l in bd.ler(
        """SELECT DISTINCT provedor FROM ia_uso
            WHERE quando >= %s AND quando < %s AND provedor <> ''
            ORDER BY provedor""", (inicio, fim))]


# ---------------------------------------------------------- os incidentes

CAMPOS_DO_INCIDENTE = ("data", "sistema", "o_que", "impacto", "causa",
                       "mitigacao", "comunicado_a")


class IncidenteError(ValueError):
    """O incidente não pode ser gravado como veio; a mensagem diz por quê."""


def registrar_incidente(con, *, registrado_por: str, agora: str,
                        **campos: Any) -> int:
    """Grava um incidente ou falha. **ESCREVE** na transação de quem chama.

    O que se escreve aqui vai para o relatório à COGEX, e por isso o texto
    passa pela mesma barreira de dado de pessoa da Ajuda antes de gravar: CPF,
    e-mail, telefone e documento viram marca. Incidente se descreve pelo fato,
    e não pela pessoa.
    """
    import ajuda_privacidade as PRIV
    import ia_catalogo as CAT

    dados = {c: " ".join(str(campos.get(c) or "").split()) for c in CAMPOS_DO_INCIDENTE}
    # O SISTEMA É UM CÓDIGO DO CATÁLOGO, ou vazio («outro / vários»).
    if CAT.entrada(dados["sistema"]) is None:
        dados["sistema"] = ""
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", dados["data"]):
        raise IncidenteError("Informe a data do incidente (dia, mês e ano).")
    if not dados["o_que"]:
        raise IncidenteError("Descreva o que aconteceu.")
    for campo in CAMPOS_DO_INCIDENTE[2:]:
        try:
            dados[campo] = PRIV.sanitizar_para_modelo(dados[campo], nomes_livres=False)
        except PRIV.PrivacidadeError as recusa:
            raise IncidenteError(
                f"O texto ainda tem dado de pessoa ({recusa}). Descreva o fato "
                f"sem nome, CPF, e-mail ou telefone.") from recusa
        dados[campo] = dados[campo][:2000]
    bd = banco(con)
    init_ia_schema(con)
    return int(bd.escrever(
        """INSERT INTO ia_incidentes (data, sistema, o_que, impacto, causa,
               mitigacao, comunicado_a, registrado_por, registrado_em)
           VALUES (%(data)s, %(sistema)s, %(o_que)s, %(impacto)s, %(causa)s,
               %(mitigacao)s, %(comunicado_a)s, %(registrado_por)s, %(agora)s)
           RETURNING id""",
        {**dados, "registrado_por": _curto(registrado_por), "agora": agora})[0]["id"])


def incidentes(con, ano: int | None = None) -> list[dict]:
    """Os incidentes, do ano pedido ou todos, em ordem de data. SÓ LÊ."""
    bd = banco(con)
    if not bd.tem_tabela("ia_incidentes"):
        return []
    if ano is None:
        return bd.ler("SELECT * FROM ia_incidentes ORDER BY data DESC, id DESC")
    inicio, fim = _limites_do_ano(ano)
    return bd.ler("""SELECT * FROM ia_incidentes WHERE data >= %s AND data < %s
                      ORDER BY data, id""", (inicio, fim))


# -------------------------------------------------- os dados do fornecedor
#
# É CONFIGURAÇÃO QUE O OFICIAL PREENCHE, e não opinião do sistema. O relatório
# compara o que foi preenchido com o requisito do MA e mostra a diferença como
# PENDÊNCIA A CONFERIR — quem decide se o uso é conforme é o oficial.

CAMPOS_DO_FORNECEDOR = ("empresa", "pais_processa", "pais_armazena", "retencao",
                        "retencao_prazo", "treinamento", "iso27001", "contrato")
SIM, NAO, NAO_SEI = "sim", "nao", "nao_sei"
RESPOSTAS = {SIM: "sim", NAO: "não", NAO_SEI: "não sei"}
# A RETENÇÃO TAMBÉM É ESCOLHA FECHADA: «guarda?» é o que o requisito pergunta
# («banco no servidor da serventia»); o prazo vai ao lado, em texto livre.
NAO_GUARDA, GUARDA = "nao_guarda", "guarda"
RETENCOES = {NAO_GUARDA: "não guarda o que recebe", GUARDA: "guarda o que recebe",
             NAO_SEI: "não sei"}


def gravar_fornecedor(con, provedor: str, campos: dict, *, por: str,
                      agora: str) -> None:
    """Grava os dados de um fornecedor. **ESCREVE** na transação de quem chama."""
    dados = {c: _curto(campos.get(c), 300) for c in CAMPOS_DO_FORNECEDOR}
    for campo, validos in (("treinamento", RESPOSTAS), ("iso27001", RESPOSTAS),
                           ("retencao", RETENCOES)):
        if dados[campo] not in validos:
            dados[campo] = ""
    init_ia_schema(con)
    banco(con).escrever(
        """INSERT INTO ia_fornecedores (provedor, empresa, pais_processa,
               pais_armazena, retencao, retencao_prazo, treinamento, iso27001,
               contrato, atualizado_por, atualizado_em)
           VALUES (%(provedor)s, %(empresa)s, %(pais_processa)s, %(pais_armazena)s,
               %(retencao)s, %(retencao_prazo)s, %(treinamento)s, %(iso27001)s,
               %(contrato)s, %(por)s, %(agora)s)
           ON CONFLICT (provedor) DO UPDATE SET
               empresa = excluded.empresa, pais_processa = excluded.pais_processa,
               pais_armazena = excluded.pais_armazena, retencao = excluded.retencao,
               retencao_prazo = excluded.retencao_prazo,
               treinamento = excluded.treinamento, iso27001 = excluded.iso27001,
               contrato = excluded.contrato, atualizado_por = excluded.atualizado_por,
               atualizado_em = excluded.atualizado_em""",
        {**dados, "provedor": _curto(provedor, 40), "por": _curto(por), "agora": agora})


def fornecedores(con) -> dict[str, dict]:
    """Os dados gravados, por provedor. SÓ LÊ."""
    bd = banco(con)
    if not bd.tem_tabela("ia_fornecedores"):
        return {}
    return {l["provedor"]: l for l in bd.ler(
        "SELECT * FROM ia_fornecedores ORDER BY provedor")}


def _e_brasil(pais: str) -> bool:
    texto = unicodedata.normalize("NFKD", pais or "").encode("ascii", "ignore")
    return texto.decode().strip().lower() in {"brasil", "brazil", "br"}


def pendencias(dados: dict | None) -> list[str]:
    """O que contraria o requisito do MA, ou não foi informado. SÓ CALCULA.

    O requisito, pelo resumo: solução desenvolvida ou armazenada no Brasil,
    banco no servidor da serventia, ISO 27001. **Não decide** se o uso é
    conforme — lista o que o oficial tem de olhar.
    """
    d = dados or {}
    saida: list[str] = []
    if not any(str(d.get(c) or "").strip() for c in CAMPOS_DO_FORNECEDOR):
        return ["Dados do fornecedor não preenchidos — sem eles não há como "
                "conferir o requisito do MA."]
    for campo, rotulo in (("pais_processa", "processa"), ("pais_armazena", "armazena")):
        pais = str(d.get(campo) or "").strip()
        if not pais:
            saida.append(f"País onde {rotulo} os dados: não informado.")
        elif not _e_brasil(pais):
            saida.append(f"{rotulo.capitalize()} os dados fora do Brasil ({pais}) — "
                         "o requisito do MA fala em solução desenvolvida ou "
                         "armazenada no Brasil.")
    retencao = d.get("retencao") or ""
    if retencao != NAO_GUARDA:
        prazo = str(d.get("retencao_prazo") or "").strip()
        quanto = f" ({prazo})" if prazo else ""
        saida.append(
            f"Retenção pelo fornecedor: {RETENCOES.get(retencao, 'não informada')}"
            f"{quanto} — o requisito do MA pede o banco no servidor da serventia.")
    if (d.get("iso27001") or "") != SIM:
        saida.append(f"ISO 27001: {RESPOSTAS.get(d.get('iso27001') or '', 'não informado')} "
                     "— o requisito do MA pede a certificação.")
    return saida
