"""O Livro de Visitas e Correições — art. 188, I, e art. 189 do Código de Normas do MA.

POR QUE EXISTE (LG08, 19/10/2026)
    «São obrigatórios, em todas as serventias notariais e de registro, os
    seguintes livros administrativos: I - Livro de Visitas e Correições» (art.
    188). «O Livro de Visitas e Inspeções (Correições) será escriturado
    eletronicamente e ficará sob a guarda e responsabilidade do(a)
    delegatário(a) de cada serventia» (art. 189).

    Medido no código em 19/10/2026: o livro NÃO existia. A tela «Inspeções»
    (`inspections`) importa um relatório de inspeção e o transforma em tarefas
    — é o plano de ação do que a inspeção mandou fazer, e não o registro de que
    a autoridade esteve aqui, quando, com que natureza e o que determinou. As
    duas coisas se ligam: o lançamento pode apontar para a inspeção do plano de
    ação (`inspecao_id`), e é por isso que a ligação existe.

ELETRÔNICO, E POR ISSO NÃO SE EDITA
    Livro de papel não tem borracha; livro eletrônico também não pode ter. O
    lançamento não se altera nem se apaga. Erro se conserta por RETIFICAÇÃO:
    um lançamento novo, numerado na sequência, que aponta para o que corrige e
    diz por quê — o original continua no livro, marcado. É a mesma regra da
    retificação circunstanciada do Diário Auxiliar (art. 206) e da corrigenda
    do ato notarial (art. 795, § 7º).

O NÚMERO DE ORDEM
    Contínuo e sem buraco: nasce na gravação, debaixo de `bd.travar`, e é a
    ordem em que o livro foi escriturado — não a data da visita, que pode ser
    lançada depois (a visita de sexta registrada na segunda).

O § 1º
    «A escrituração do Livro de Visitas e Correições é dispensável, desde que
    os eventos estejam devidamente registrados em sistema próprio da
    Corregedoria». A tela diz isso; quem decide se a casa usa o livro é o
    oficial.

PostgreSQL nativo, pelo `bd_nativo` (MANUAL_DA_CONVERSAO). Data e hora se
calculam no Python (regra da casa).
"""
from __future__ import annotations

import re
from datetime import date
from typing import Any

from bd_nativo import banco

NATUREZAS: dict[str, str] = {
    "CORREICAO_ORDINARIA": "Correição ordinária",
    "CORREICAO_EXTRAORDINARIA": "Correição extraordinária",
    "INSPECAO": "Inspeção",
    "VISITA": "Visita",
    "OUTRA": "Outra (descrever no termo)",
}

# A frase do motivo da retificação tem a régua da casa (`caixa_protocolo`):
# «erro» não explica nada a quem ler o livro na próxima correição.
MINIMO_DO_TEXTO = 10
LIMITE = 200
LIMITE_DO_TERMO = 20_000

TRAVA = "lv_visitas.numero"


class VisitaError(ValueError):
    """Impedimento de regra, com a frase pronta para a tela."""


# ---------------------------------------------------------------- esquema
#
# Um comando por objeto, cada um só se o objeto falta (`to_regclass` acha
# tabela e índice — o padrão de `apostila` e `ia_uso`). Sem FK para
# `inspections`: o vínculo é informativo, e o plano de ação pode ser
# reimportado sem levar o livro junto.
SCHEMA: tuple[tuple[str, str], ...] = (
    ("lv_visitas", """
        CREATE TABLE IF NOT EXISTS lv_visitas (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            numero bigint NOT NULL,
            data TEXT NOT NULL,
            natureza TEXT NOT NULL CHECK (natureza IN (
                'CORREICAO_ORDINARIA', 'CORREICAO_EXTRAORDINARIA',
                'INSPECAO', 'VISITA', 'OUTRA')),
            autoridade TEXT NOT NULL,
            autoridade_nome TEXT NOT NULL DEFAULT '',
            processo TEXT NOT NULL DEFAULT '',
            termo TEXT NOT NULL,
            determinacoes TEXT NOT NULL DEFAULT '',
            prazo TEXT NOT NULL DEFAULT '',
            inspecao_id bigint,
            retifica_id bigint REFERENCES lv_visitas (id),
            motivo_retificacao TEXT NOT NULL DEFAULT '',
            lancado_em TEXT NOT NULL,
            lancado_por TEXT NOT NULL
        )"""),
    ("ux_lv_visitas_numero",
     "CREATE UNIQUE INDEX IF NOT EXISTS ux_lv_visitas_numero ON lv_visitas (numero)"),
    # Um lançamento só se retifica uma vez: a segunda correção retifica a
    # primeira, e o livro conta a história em fila, e não em leque.
    ("ux_lv_visitas_retifica",
     "CREATE UNIQUE INDEX IF NOT EXISTS ux_lv_visitas_retifica "
     "ON lv_visitas (retifica_id) WHERE retifica_id IS NOT NULL"),
)


def init_livro_visitas_schema(con) -> None:
    """Cria a tabela e os índices que faltarem. Idempotente."""
    bd = banco(con)
    for nome, comando in SCHEMA:
        if not bd.tem_tabela(nome):
            bd.escrever(comando)


# ------------------------------------------------------------- auxiliares


def _texto(valor: Any, limite: int = LIMITE) -> str:
    return " ".join(str(valor or "").split())[:limite]


def _id(valor: Any) -> int | None:
    """O id que veio do formulário, ou None. Só dígito ASCII e no tamanho do
    bigint: `str.isdigit()` aceita «²», e o `int()` que vem depois estoura
    (500 em vez de ignorar o campo — ressalva da revisão do LG08)."""
    texto = str(valor or "").strip()
    return int(texto) if re.fullmatch(r"[0-9]{1,18}", texto) else None


def _termo(valor: Any, limite: int = LIMITE_DO_TERMO) -> str:
    """O texto longo guarda as quebras de linha: o termo de correição tem
    itens, e itens colados numa linha só não se leem."""
    linhas = [" ".join(x.split()) for x in str(valor or "").splitlines()]
    return "\n".join(linhas).strip()[:limite]


def _dia(valor: Any, *, campo: str, hoje: str, obrigatorio: bool = True,
         futuro: bool = False) -> str:
    texto = str(valor or "").strip()[:10]
    if not texto:
        if obrigatorio:
            raise VisitaError(f"Informe {campo}.")
        return ""
    try:
        dia = date.fromisoformat(texto)
    except ValueError as erro:
        raise VisitaError(f"{campo.capitalize()} não é uma data válida.") from erro
    if not futuro and dia.isoformat() > hoje:
        raise VisitaError(
            f"{campo.capitalize()} está no futuro: o livro registra visita que "
            f"já aconteceu.")
    return dia.isoformat()


# ---------------------------------------------------------------- escrita


def lancar(con, *, hoje: str, agora: str, por: str, data: Any, natureza: Any,
           autoridade: Any, termo: Any, autoridade_nome: Any = "",
           processo: Any = "", determinacoes: Any = "", prazo: Any = "",
           inspecao_id: Any = None, retifica_id: Any = None,
           motivo_retificacao: Any = "") -> dict:
    """Escritura um lançamento no livro e devolve número e id. ESCREVE.

    Roda na transação do chamador. A trava vem ANTES de ler o maior número:
    dois lançamentos ao mesmo tempo serializam, e o segundo lê o número que o
    primeiro gravou (`trava-antes-da-lista`).
    """
    natureza = str(natureza or "").strip().upper()
    if natureza not in NATUREZAS:
        raise VisitaError("Escolha a natureza: correição, inspeção ou visita.")
    autoridade = _texto(autoridade)
    if not autoridade:
        raise VisitaError(
            "Informe a autoridade (o cargo ou órgão — por exemplo, juiz "
            "corregedor permanente da comarca).")
    termo = _termo(termo)
    if len(termo) < MINIMO_DO_TEXTO:
        raise VisitaError(
            "Escreva o termo: o que foi visto e o que a autoridade registrou. "
            "É ele que a próxima correição vai ler.")
    data = _dia(data, campo="a data da visita", hoje=hoje)
    prazo = _dia(prazo, campo="o prazo", hoje=hoje, obrigatorio=False, futuro=True)
    inspecao = _id(inspecao_id)
    alvo = _id(retifica_id)
    motivo = _texto(motivo_retificacao, 1000)

    bd = banco(con)
    bd.travar(TRAVA)
    if alvo is not None:
        original = bd.um("SELECT id, numero FROM lv_visitas WHERE id = %s", (alvo,))
        if not original:
            raise VisitaError("O lançamento a retificar não existe.")
        if bd.um("SELECT id FROM lv_visitas WHERE retifica_id = %s", (alvo,)):
            raise VisitaError(
                f"O lançamento nº {original['numero']} já foi retificado. "
                f"Retifique a retificação, para o livro contar a história em fila.")
        if len(motivo) < MINIMO_DO_TEXTO:
            raise VisitaError(
                f"Diga por que o lançamento nº {original['numero']} está sendo "
                f"retificado (pelo menos {MINIMO_DO_TEXTO} letras).")
    elif motivo:
        motivo = ""
    if inspecao is not None and bd.tem_tabela("inspections") and not bd.um(
            "SELECT id FROM inspections WHERE id = %s", (inspecao,)):
        raise VisitaError("A inspeção indicada não existe no plano de ação.")

    numero = int(bd.valor("SELECT COALESCE(MAX(numero), 0) AS n FROM lv_visitas") or 0) + 1
    novo = bd.escrever(
        """INSERT INTO lv_visitas (numero, data, natureza, autoridade, autoridade_nome,
               processo, termo, determinacoes, prazo, inspecao_id, retifica_id,
               motivo_retificacao, lancado_em, lancado_por)
           VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
           RETURNING id""",
        (numero, data, natureza, autoridade, _texto(autoridade_nome),
         _texto(processo), termo, _termo(determinacoes), prazo, inspecao, alvo,
         motivo, agora, _texto(por) or "?"))[0]["id"]
    return {"id": int(novo), "numero": numero, "retifica_id": alvo}


# ----------------------------------------------------------------- leitura


def lancamentos(con) -> list[dict]:
    """O livro inteiro, na ordem em que foi escriturado. Só LÊ.

    Cada linha diz se foi retificada e por qual: quem lê o lançamento antigo
    precisa saber, NA MESMA LINHA, que ele não vale mais como está.
    """
    bd = banco(con)
    linhas = bd.ler(
        """SELECT v.*, r.numero AS retificado_por_numero
             FROM lv_visitas v
             LEFT JOIN lv_visitas r ON r.retifica_id = v.id
            ORDER BY v.numero, v.id""")
    numero_de = {int(x["id"]): int(x["numero"]) for x in linhas}
    for x in linhas:
        x["natureza_nome"] = NATUREZAS.get(x["natureza"], x["natureza"])
        x["retifica_numero"] = numero_de.get(int(x["retifica_id"])) if x["retifica_id"] else None
    return linhas


def inspecoes_do_plano(con) -> list[dict]:
    """As inspeções do plano de ação, para o vínculo opcional. Só LÊ."""
    bd = banco(con)
    if not bd.tem_tabela("inspections"):
        return []
    return bd.ler("SELECT id, title, report_date FROM inspections ORDER BY id DESC")
