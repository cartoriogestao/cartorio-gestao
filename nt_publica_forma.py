def preco(con: Any, codigo_tj: Any, *, data: Any = None) -> dict | None:
    """Quanto custa, pela tabela do dia. `None` quando não há item. Só LÊ."""
    import ato_selado as AS
    codigo = _texto(codigo_tj)
    if not codigo:
        return None
    servico = AS.servico_do_codigo_tj(con, codigo)
    if not servico:
        return None
    try:
        conta = AS.calcular_custas(con, servico=int(servico["codigo"]),
                                   data=data)
    except AS.AtoError:
        return None
    return {"codigo_tj": codigo, "servico": int(servico["codigo"]),
            "descricao": servico.get("descricao"),
            "total": conta["total"],
            "total_centavos": conta["total_centavos"]}


# ------------------------------------------------------------------ emitir

def proximo_numero(con: Any, ano: int) -> int:
    """O número do exercício. A trava vem ANTES do MAX: dois balcões juntos
    leriam o mesmo maior e gravariam o mesmo número."""
    bd = banco(con)
    bd.travar("nt_publicas_formas.numero")
    maior = bd.valor(
        "SELECT MAX(numero) AS n FROM nt_publicas_formas WHERE ano = %s",
        (int(ano),))
    return int(maior or 0) + 1


def emitir(con: Any, *, documento_especie: Any, apresentante: Any,
           transcricao: Any, documento_descricao: Any = None,
           documento_expedidor: Any = None, apresentante_documento: Any = None,
           folhas: Any = 1, ressalvas: Any = None, codigo_tj: Any = None,
           hoje: str | None = None, agora: str | None = None,
           usuario: Any = None, usuario_funcao: Any = None,
           modelo: str | None = None) -> dict:
    """Numera, monta e congela o teor. ESCREVE, na transação de quem chama.

    NASCE SUSPENSA (`SUSPENSO_SELO`) e só vira `EMITIDA` quando o selo sai —
    o selo pede rede e não pode ir dentro desta transação. Se ele não sair, a
    pública forma continua suspensa, com o motivo, e não emitida sem selo.
    """
    especie = _texto(documento_especie)
    quem = _texto(apresentante)
    corpo = str(transcricao or "").strip()
    if not especie:
        raise PublicaFormaError("Diga que documento foi apresentado.")
    if not quem:
        raise PublicaFormaError("Informe quem apresentou o original.")
    if len(corpo) < 10:
        raise PublicaFormaError(
            "Transcreva o documento por inteiro — a pública forma reproduz o "
            "original, e não o resume.")
    doc = _digitos(apresentante_documento)
    if doc:
        import cpf_cnpj as CPFDOC
        if CPFDOC.documento_valido(doc) is False:
            raise PublicaFormaError(CPFDOC.mensagem_documento_invalido(doc))
    try:
        n_folhas = max(1, int(folhas or 1))
    except (TypeError, ValueError) as erro:
        raise PublicaFormaError("Folhas: informe um número.") from erro

    hoje = hoje or date.today().isoformat()
    agora = agora or datetime.now().isoformat(timespec="seconds")
    ano = int(str(hoje)[:4])
    numero = proximo_numero(con, ano)
    claros = {
        "numero": numero, "ano": ano, "documento_especie": especie,
        "documento_descricao": _texto(documento_descricao) or None,
        "documento_expedidor": _texto(documento_expedidor) or None,
        "apresentante": quem,
        "apresentante_documento": _texto(apresentante_documento) or None,
        "transcricao": corpo, "ressalvas": _texto(ressalvas) or None,
        "folhas": n_folhas,
    }
    if modelo is None:
        try:
            modelo = MODELOS.texto_do_papel(con, CHAVE_DO_PAPEL)
        except MODELOS.ModeloError as erro:
            raise PublicaFormaError(str(erro)) from erro
    try:
        teor = montar_teor(modelo=modelo, **claros)
    except Exception as erro:                              # noqa: BLE001
        raise PublicaFormaError(
            f"O modelo da pública forma não monta: {erro}") from erro
    impressao = hash_do_teor(numero, ano, teor, agora)
    novo = banco(con).escrever(
        """INSERT INTO nt_publicas_formas(numero, ano, data, documento_especie,
               documento_descricao, documento_expedidor, apresentante,
               apresentante_documento, transcricao, folhas, ressalvas, teor,
               hash_teor, codigo_tj, situacao, emitida_em, emitida_por,
               emitida_por_funcao)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,
                   'SUSPENSO_SELO',%s,%s,%s)
           RETURNING id""",
        (numero, ano, hoje, especie, claros["documento_descricao"],
         claros["documento_expedidor"], quem, doc or None, corpo, n_folhas,
         claros["ressalvas"], teor, impressao, _texto(codigo_tj) or None,
         agora, _texto(usuario) or None, _texto(usuario_funcao) or None))
    return {"id": int(novo[0]["id"]), "numero": numero, "ano": ano,
            "teor": teor, "hash": impressao}


def publica_forma(con: Any, pf_id: int) -> dict | None:
    return banco(con).um("SELECT * FROM nt_publicas_formas WHERE id = %s",
                         (int(pf_id),))


def listar(con: Any, limite: int = 50) -> list[dict]:
    return banco(con).ler(
        """SELECT * FROM nt_publicas_formas
            ORDER BY ano DESC, numero DESC, id DESC LIMIT %s""",
        (int(limite),))


def cancelar(con: Any, pf_id: int, *, motivo: Any, agora: str,
             usuario: Any) -> None:
    """Cancela; o teor fica. Papel com fé pública não se apaga."""
    if len(_texto(motivo)) < 10:
        raise PublicaFormaError(
            "Escreva o motivo do cancelamento (pelo menos dez letras).")
    feito = banco(con).escrever(
        """UPDATE nt_publicas_formas SET situacao = 'CANCELADA',
               motivo_cancelamento = %s, cancelada_em = %s, cancelada_por = %s
            WHERE id = %s AND situacao <> 'CANCELADA' RETURNING id""",
        (_texto(motivo), agora, _texto(usuario) or None, int(pf_id)))
    if not feito:
        raise PublicaFormaError("Pública forma não encontrada ou já cancelada.")


# -------------------------------------------------------------------- o selo

def envelope(*, codigo_tj: Any, escrevente: Any, versao_tabela: Any,
             apresentante: Any, apresentante_documento: Any = None) -> dict:
    """O corpo de `/selo/notas/publica-forma`. Só calcula.

    NA FORMA DO `AtosEmGeral` da certidão das Notas (`notas_certidao.
    envelope`), que vai pelo mesmo campo `dados` — ver o cabeçalho: o caminho
    nunca foi usado pela casa, e a forma se confere na homologação. O
    documento vai com onze zeros quando não há, como lá.
    """
    faltando = [o for o, v in (("o item da tabela de custas", codigo_tj),
                               ("o escrevente", escrevente),
                               ("a versão da tabela de custas", versao_tabela))
                if not _texto(v)]
    if faltando:
        raise PublicaFormaError(
            f"O selo da pública forma não sai sem {', '.join(faltando)}.")
    return {
        "ato": {"codigo": _texto(codigo_tj),
                "codigoTabelaCusta": _texto(versao_tabela)},
        "escrevente": _texto(escrevente),
        "partes": {"nomePartes": [],
                   "parteAto": [{"documento": _digitos(apresentante_documento)
                                 or "00000000000",
                                 "nome": _texto(apresentante)}]},
        "quantidade": 1,
    }


def selar(db, pasta_de_dados: Any, pf_id: int, *, escrevente: Any,
          data_da_tabela: Any, cns: Any, agora: str | None = None) -> dict:
    """Pede o selo e, se sair, emite. FALA COM A REDE, fora da transação.

    Devolve `{"selado", "numero" | "motivo"}`. **NUNCA ESTOURA**: a falha
    volta como motivo, a pública forma fica `SUSPENSO_SELO` com ele gravado, e
    a tela oferece selar de novo. A referência é a da pública forma — a mesma
    em toda tentativa —, e é dela que sai o SID que faz o aparelho devolver o
    selo já comprado em vez de vender outro.
    """
    import ato_selado as AS
    agora = agora or datetime.now().isoformat(timespec="seconds")
    with db.connect() as con:
        pf = publica_forma(con, pf_id)
    if not pf:
        return {"selado": False, "motivo": "Pública forma não encontrada."}
    if pf["situacao"] == "CANCELADA":
        return {"selado": False, "motivo": "A pública forma está cancelada."}
    if _texto(pf.get("selo")):
        return {"selado": True, "numero": pf["selo"], "ja_tinha": True}
    motivo = None
    resultado: dict = {}
    try:
        corpo = envelope(
            codigo_tj=pf.get("codigo_tj"), escrevente=escrevente,
            versao_tabela=AS.versao_da_tabela_de_custas(CAMINHO_DO_SELO,
                                                        data_da_tabela),
            apresentante=pf["apresentante"],
            apresentante_documento=pf.get("apresentante_documento"))
    except PublicaFormaError as erro:
        motivo = str(erro)
    else:
        resultado = AS.selar_o_ato_lavrado(
            db, pasta_de_dados, tabela="nt_publicas_formas", ato_id=int(pf_id),
            tipo="PUBLICA_FORMA", atribuicao="NOTAS", agora=agora, cns=cns,
            usuario=_texto(escrevente) or None, dados=corpo,
            caminho=CAMINHO_DO_SELO,
            referencia=f"nt_publicas_formas:{int(pf_id)}:{pf.get('codigo_tj')}:1")
        if not resultado.get("selado"):
            motivo = resultado.get("motivo") or "o selador não devolveu selo"
    with db.transaction() as con:
        if motivo:
            banco(con).escrever(
                """UPDATE nt_publicas_formas SET situacao = 'SUSPENSO_SELO',
                       motivo_suspensao = %s
                    WHERE id = %s AND situacao <> 'CANCELADA'""",
                (motivo, int(pf_id)))
        else:
            banco(con).escrever(
                """UPDATE nt_publicas_formas SET situacao = 'EMITIDA',
                       motivo_suspensao = NULL
                    WHERE id = %s AND situacao <> 'CANCELADA'""",
                (int(pf_id),))
    if motivo:
        return {"selado": False, "motivo": motivo}
    return {"selado": True, "numero": resultado.get("numero")}


