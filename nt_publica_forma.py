MARCA_DO_SELO = "@@SELO@@"


def papel_html(pf: dict, *, sv: dict) -> str:
    """O PAPEL da pública forma, em HTML: o teor congelado e a moldura. Só calcula.

    A MOLDURA NASCEU NA ROTA DO PAPEL (LD02, 21/10/2026): o lugar e a data da
    emissão, a linha de quem a expede, o rodapé com o número e a impressão
    digital do teor, e o carimbo do selo com o que ele declara (CN-MA arts.
    87, XVI, 130 e 131). Saiu da rota no LD07 (21/10/2026) para a matriz de
    requisitos (`tests/test_requisitos_notas.py`) medir o papel que sai, e não
    só o teor: até aqui ela lia o teor e acusava que faltavam o lugar, a data,
    quem expede e o selo — que estavam no papel, e não no teor. Os bytes do
    `.odt` são os de antes.

    A cancelada sai com a tarja. Quem decide se há papel (a suspensa não tem)
    é a rota.
    """
    from markupsafe import escape
    from ri_web import data_por_extenso
    try:
        emitida_extenso = data_por_extenso(
            date.fromisoformat(str(pf["emitida_em"])[:10]))
    except (TypeError, ValueError):
        emitida_extenso = data_por_extenso(date.today())
    emitida = str(pf["emitida_em"] or "")
    emitida_papel = (f"{emitida[8:10]}/{emitida[5:7]}/{emitida[:4]}"
                     + (f" às {emitida[11:19]}" if len(emitida) >= 19 else "")
                     if len(emitida) >= 10 else emitida)
    cancelada = ("<p align=\"center\"><b>PÚBLICA FORMA CANCELADA — "
                 f"{escape(pf.get('motivo_cancelamento') or '')}</b></p>"
                 if pf.get("situacao") == "CANCELADA" else "")
    return (f'{cancelada}{pf["teor"]}<p></p>'
            f'<p>{escape(sv.get("ri_cidade", ""))}-{escape(sv.get("ri_uf", ""))}, '
            f'{emitida_extenso}.</p><p></p>'
            '<p align="center">________________________________</p>'
            f'<p align="center">{escape(pf.get("emitida_por") or "")}</p>'
            f'<p align="center">{escape(pf.get("emitida_por_funcao") or "")}</p>'
            f'<p></p><p><font size="8">Pública forma n. {pf["numero"]}/'
            f'{pf["ano"]}, emitida em {emitida_papel}. Autenticidade: '
            f'{pf["hash_teor"]}</font></p>'
            f'<p>{MARCA_DO_SELO}</p>')


def hash_do_teor(numero: int, ano: int, teor: str, emitida_em: str) -> str:
    base = f"NOTAS|PUBLICA_FORMA|{numero}|{ano}|{emitida_em}|{teor}"
    return hashlib.sha256(base.encode("utf-8")).hexdigest()


