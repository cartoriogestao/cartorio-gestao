    @app.route("/notas/publica-forma/<int:pf_id>/odt")
    @login_required
    @roles_required(*QUEM_LE)
    def notas_publica_forma_odt(pf_id: int):
        """O PAPEL da pública forma, em PDF (ou .odt) — LD02, 21/10/2026. Só LÊ.

        ATÉ AQUI ELA SÓ TINHA A TELA DO SISTEMA, com o menu da casa: o teor
        congelado não traz a serventia, a data, o selo nem quem assina, e não
        havia como imprimi-la (CN-MA art. 131: o selo «deverá constar
        expressamente no corpo do ato físico»; arts. 849 a 851).

        A MOLDURA É A DA CERTIDÃO DAS NOTAS (`atribuicoes_web.
        notas_certidao_odt`): o cabeçalho da serventia, o teor congelado, o
        lugar e a data da emissão, a linha de quem a expede e o carimbo do selo
        com o que ele declara — refeita a cada impressão, como lá; o teor é o
        que se congelou com o hash.

        A SUSPENSA NÃO TEM PAPEL: sem selo a pública forma não foi emitida (a
        regra da casa desde 16/09/2026; CN-MA art. 130, § 2º), e imprimi-la
        poria no mundo o ato sem selo. A cancelada sai com a tarja, como a
        certidão cancelada.
        """
        import ato_selado as AS
        import impressao_web as IMPW
        import ri_odt as RODT
        from serventia import dados as dados_da_serventia
        with db.connect() as con:
            pf = publica_forma(con, pf_id)
            if not pf:
                abort(404)
            etiqueta = AS.etiqueta_do_ato(con, "nt_publicas_formas", pf_id,
                                          pf.get("selo") or "")
        if pf["situacao"] == "SUSPENSO_SELO" or not _texto(pf.get("selo")):
            flash("A pública forma está suspensa, sem selo: não há papel a "
                  "imprimir antes de o selo sair. Sele de novo nesta ficha.",
                  "danger")
            return redirect(url_for("notas_publica_forma_ver", pf_id=pf_id))
        s = dados_da_serventia(db.get_settings)
        # O papel é o de `papel_html` (LD07); o quadro do selo entra no lugar
        # da marca, colado como antes — os bytes do `.odt` não mudaram.
        antes_do_selo, _, depois_do_selo = papel_html(pf, sv=s).partition(
            f"<p>{MARCA_DO_SELO}</p>")
        frag_do_selo, imagens_do_selo = RODT.carimbo_da_certidao_odf(
            etiqueta, rotulo="SELO DA PÚBLICA FORMA")
        cab_odf, cab_imgs = RODT.cabecalho_certidao_completo_odf(s)
        todas = dict(cab_imgs or {})
        todas.update(imagens_do_selo or {})
        arquivo = RODT.gerar_odt(
            RODT.html_para_odf(antes_do_selo) + frag_do_selo
            + RODT.html_para_odf(depois_do_selo),
            titulo=f"Pública forma {pf['numero']}/{pf['ano']}",
            cabecalho_odf=cab_odf, imagens=todas or None,
            cabecalho_altura_min="2.0cm", cabecalho_margem_baixo="0.25cm",
            cabecalho_borda=False)
        audit("NT_PUBLICA_FORMA_ODT", "nt_publicas_formas", pf_id,
              {"numero": pf["numero"], "ano": pf["ano"]})
        return IMPW.resposta_do_papel(
            arquivo, nome=f"publica-forma-{pf['numero']}-{pf['ano']}",
            get_setting=db.get_setting,
            voltar_para=url_for("notas_publica_forma_ver", pf_id=pf_id))

