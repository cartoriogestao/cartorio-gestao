    @app.route("/notas/publica-forma/emitir", methods=["POST"])
    @login_required
    @roles_required(*QUEM_OPERA)
    def notas_publica_forma_emitir():
        """Numera e congela o teor; depois, fora da transação, o selo."""
        item = item_configurado(db.get_setting)
        if not item:
            flash("A pública forma não foi emitida: falta dizer qual item da "
                  "tabela do Tribunal a casa cobra nela, em Notas → Pública "
                  "forma → Configuração.", "danger")
            return redirect(url_for("notas_publica_forma"))
        try:
            with db.transaction() as con:
                r = emitir(con, documento_especie=_campo("documento_especie"),
                           documento_descricao=_campo("documento_descricao"),
                           documento_expedidor=_campo("documento_expedidor"),
                           apresentante=_campo("apresentante"),
                           apresentante_documento=_campo(
                               "apresentante_documento"),
                           transcricao=request.form.get("transcricao"),
                           folhas=_campo("folhas") or 1,
                           ressalvas=_campo("ressalvas"), codigo_tj=item,
                           usuario=usuario_nome(),
                           usuario_funcao=usuario_funcao())
        except PublicaFormaError as erro:
            flash(str(erro), "danger")
            return redirect(url_for("notas_publica_forma"))
        audit("NT_PUBLICA_FORMA_NUMERADA", "nt_publicas_formas", r["id"],
              {"numero": r["numero"], "ano": r["ano"], "hash": r["hash"],
               "item": item})
        resultado = _selar(r["id"])
        _avisar_do_selo({"id": r["id"], "numero": r["numero"], "ano": r["ano"]},
                        resultado, acao="emissao")
        return redirect(url_for("notas_publica_forma_ver", pf_id=r["id"]))

