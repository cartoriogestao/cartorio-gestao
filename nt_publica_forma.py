    def _campo(nome: str) -> str:
        return (request.form.get(nome) or "").strip()

    def _selar(pf_id: int) -> dict:
        import selo_robo as SR
        if not SR.pode_selar_automatico():
            return {"selado": False, "motivo": SR.recado_pendente_selo().strip()}
        return selar(db, Path(app.config["DATA_DIR"]), pf_id,
                     escrevente=usuario_nome(),
                     data_da_tabela=db.get_setting("selo_tabela_custas_em", ""),
                     cns=db.get_setting("ri_cns", ""))

    def _avisar_do_selo(pf: dict, r: dict, *, acao: str) -> None:
        if r.get("selado"):
            audit("NT_PUBLICA_FORMA_EMITIDA", "nt_publicas_formas", pf["id"],
                  {"numero": pf["numero"], "ano": pf["ano"],
                   "selo": r.get("numero"), "via": acao})
            flash(f"Pública forma n. {pf['numero']}/{pf['ano']} emitida. "
                  f"Selo {r.get('numero')}.", "success")
            return
        audit("NT_PUBLICA_FORMA_SUSPENSA_SELO_FALHOU", "nt_publicas_formas",
              pf["id"], {"numero": pf["numero"], "ano": pf["ano"],
                         "motivo": r.get("motivo"), "via": acao})
        flash(f"Pública forma n. {pf['numero']}/{pf['ano']} SUSPENSA: o selo "
              f"não saiu. Motivo: {r.get('motivo')}. Corrija e sele de novo "
              f"na ficha.", "danger")

