def _texto(valor: Any) -> str:
    return str(valor or "").strip()


def _digitos(valor: Any) -> str:
    return "".join(c for c in str(valor or "") if c.isdigit())


# ------------------------------------------------------------------- o teor

def montar_teor(*, modelo: str | None = None, **claros: Any) -> str:
    """O papel da pública forma. Só calcula.

    **A TRANSCRIÇÃO É TEXTO DO BALCÃO, e se escapa** — o papel é HTML. As
    quebras de linha do original viram `<br>`: transcrever «na íntegra» e
    juntar os parágrafos numa linha só seria transcrever outra coisa.
    """
    from jinja2.sandbox import SandboxedEnvironment
    from markupsafe import Markup, escape
    texto = modelo if modelo is not None else MODELOS.padrao_de(CHAVE_DO_PAPEL)
    contexto = dict(claros)
    linhas = str(contexto.get("transcricao") or "").splitlines()
    contexto["transcricao"] = Markup("<br>").join(escape(x) for x in linhas)
    papel = SandboxedEnvironment(autoescape=True).from_string(texto).render(
        **contexto)
    # O AJUSTE DA CASA SAI SEM O QUE EXECUTA (revisão de segurança de
    # 22/10/2026, A7): a tela da pública forma mostra o teor com `|safe`, e o
    # modelo é gravado na tela de Modelos. O padrão de fábrica sai como saía.
    return MODELOS.sem_o_que_executa(texto, papel)


def conferir_modelo(corpo: str) -> str:
    """O ajuste da casa monta? `""` quando sim; a frase do erro quando não.

    O boneco da tela de Modelos não tem os claros deste papel, e reprovaria
    todo ajuste (ou aprovaria `{{ inventado }}` como vazio). Aqui ele se monta
    com um caso de exemplo, pelo MESMO montador da emissão.
    """
    from jinja2 import StrictUndefined
    from jinja2.sandbox import SandboxedEnvironment
    try:
        SandboxedEnvironment(autoescape=True, undefined=StrictUndefined
                             ).from_string(corpo or "").render(
            **CLAROS_DE_EXEMPLO)
    except Exception as erro:                              # noqa: BLE001
        return f"O modelo da pública forma não monta: {erro}"
    return ""


