"""A PÚBLICA FORMA — a cópia que o tabelião transcreve à mão do original.

    «Pública forma e certidão reprográfica: emissão, selo, emolumento.»
                                                    — LG04, item 6, 19/10/2026

O QUE É, E POR QUE NÃO É AUTENTICAÇÃO
    A autenticação (13.18, `nt_autenticacoes`) confere uma CÓPIA REPROGRÁFICA
    com o original e põe o carimbo nela. A pública forma é outro ato: o
    tabelião TRANSCREVE por inteiro o documento apresentado e certifica que a
    transcrição está conforme — o papel que sai é dele, e não uma fotocópia.
    Lei 8.935/1994, art. 7º (o que compete ao tabelião de notas — conferir no
    texto oficial). O Código de Normas do MA (Prov. COGEX 28/2026, o texto que
    está na casa) **não tem a expressão «pública forma»** — procurada em
    19/10/2026, zero ocorrências. Por isso a ressalva de rasura e adulteração
    segue, por analogia, a da autenticação (art. 857, § 2º): constatada, o
    tabelião recusa, ou faz a pedido da parte e DESCREVE o que viu.

    A **certidão reprográfica** não é ato novo: é a autenticação de cópia
    reprográfica (13.18, a tela `/notas/autenticacao`) e a certidão das Notas
    extraída por meio reprográfico (art. 851, § 1º; `notas_certidao`, itens
    13.12.1 e 13.12.3). Este módulo não a repete — há teste que prova que as
    duas existem, selam e cobram o item certo.

O PRECEDENTE, MEDIDO
    O contrato do selador tem `/selo/notas/publica-forma` (esquema
    `PublicaForma`, no campo `dados`), e o E-Ofício tinha o ato 213 «Registro
    de Pública Forma de Documento» (`atribuicoes.ATOS`). **A casa nunca o
    selou**: o caminho não está em `atribuicoes.ITENS_DE_CUSTA_POR_CAMINHO`
    (24.849 selos medidos). O envelope sai, por isso, NA FORMA do `AtosEmGeral`
    que a certidão das Notas manda pelo mesmo campo `dados` — ato, escrevente,
    partes e quantidade —, e a forma se confere na homologação. Envelope
    errado não lavra nada: o selo recusado SUSPENDE a pública forma
    (`SUSPENSO_SELO`), que é a regra da casa desde 16/09/2026.

O EMOLUMENTO NÃO SE INVENTA
    A tabela ativa de 2026 (`tests/custas_reais.json`, 400 itens) **não tem
    item de pública forma** — procurado por «pública forma», «publica» e
    «transcri». Pôr um item aqui seria cobrar por palpite. O item é da casa:
    `settings[notas_publica_forma_item]`, gravado na tela de configuração por
    quem administra, conferido contra `cx_servicos` na hora de gravar. Sem ele
    a tela diz o que falta e o selo não sai — e a pública forma fica suspensa,
    e não emitida sem selo. Pergunta para o oficial: qual item ele usa.

O TEOR SE CONGELA
    O papel é `NOTAS_PUBLICA_FORMA` (modelos_padrao/notas), editável pela casa
    na tela de Modelos. O que sai na emissão é gravado em `teor`, com sha256:
    mudar o modelo amanhã não muda a pública forma de hoje.

PostgreSQL nativo, pelo `bd_nativo`.
"""
