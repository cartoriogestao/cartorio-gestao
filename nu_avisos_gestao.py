def _inteiro_entre(valor: Any, menor: int, maior: int, erro: str) -> int | None:
    if valor is None or str(valor).strip() == "":
        return None
    try:
        n = int(str(valor).strip())
    except ValueError as exc:
        raise AvisoGestaoError(erro) from exc
    if n < menor or n > maior:
        raise AvisoGestaoError(erro)
    return n


def _normalizar_barra(
    modo: str | None, dia: Any, papeis: Any, avisei_dias: Any
) -> dict[str, Any]:
    m = (modo or MODO_JANELA).strip().upper()
    if m not in MODOS:
        raise AvisoGestaoError("Modo de exibição inválido: janela ou barra fixa.")
    if papeis is None:
        lista = PAPEIS_PAGO_PADRAO.split(",")
    elif isinstance(papeis, str):
        lista = papeis.split(",")
    else:
        lista = list(papeis)
    marcados = {str(p).strip().upper() for p in lista if str(p).strip()}
    if marcados - set(PAPEIS_PAGO):
        raise AvisoGestaoError("Papel inválido para marcar pago.")
    if not marcados:
        if m == MODO_BARRA:
            raise AvisoGestaoError("Marque ao menos um papel que pode marcar «Pago».")
        marcados = set(PAPEIS_PAGO_PADRAO.split(","))
    dia_mes = _inteiro_entre(dia, 1, 31, "Dia do mês da barra: de 1 a 31.")
    dias_ocultos = _inteiro_entre(
        avisei_dias, 1, 31, "Dias ocultos pelo «avisei»: de 1 a 31."
    )
    return {
        "modo": m,
        # Na janela o dia do mês não vale nada; guardado, enganaria quem lê.
        "barra_dia_mes": dia_mes if m == MODO_BARRA else None,
        "barra_papeis": ",".join(p for p in PAPEIS_PAGO if p in marcados),
        "avisei_dias": dias_ocultos or 1,
    }


def papeis_do_aviso(aviso: dict) -> tuple[str, ...]:
    texto = aviso.get("barra_papeis") or PAPEIS_PAGO_PADRAO
    return tuple(p.strip().upper() for p in texto.split(",") if p.strip())


def criar_aviso_ferj(con) -> None:
    """Cria na subida a barra do FERJ/FERC — e só se ela ainda não existe.

    `ON CONFLICT (chave)`, e não «procura e insere»: dois processos subindo
    juntos (o servidor e o agendador) fariam duas barras iguais. Desativada
    pelo ADMIN, ela EXISTE — e continua desativada na subida seguinte.
    """
    agora = datetime.now().replace(microsecond=0).isoformat()
    banco(con).escrever(
        """INSERT INTO nu_avisos
           (titulo, corpo, ativo, prioridade, criado_em, atualizado_em, criado_por,
            modo, chave, barra_dia_mes, barra_papeis, avisei_dias)
           VALUES (%s, %s, 1, 0, %s, %s, %s, %s, %s, 1, %s, 1)
           ON CONFLICT (chave) DO NOTHING""",
        (FERJ_TITULO, FERJ_CORPO, agora, agora, "sistema", MODO_BARRA, CHAVE_FERJ,
         PAPEIS_PAGO_PADRAO),
    )


def ciclo_da_barra(aviso: dict, hoje: str) -> str | None:
    """O mês (AAAA-MM) em que a barra vale hoje, ou None se ainda não começou.

    Dia 31 num mês de 30 dias vira o último dia do mês: «a partir do dia 31»
    não pode significar «nunca em abril».
    """
    d = date.fromisoformat(hoje[:10])
    dia = aviso.get("barra_dia_mes")
    if dia is not None:
        inicio = min(int(dia), calendar.monthrange(d.year, d.month)[1])
        if d.day < inicio:
            return None
    return d.strftime("%Y-%m")


def barras_para_usuario(
    con: sqlite3.Connection,
    user_id: int,
    *,
    hoje: str | None = None,
    papel: str | None = None,
) -> list[dict[str, Any]]:
    """As barras fixas que este usuário vê hoje, a do FERJ/FERC primeiro.

    Só LÊ: roda em toda tela, e GET não abre escrita (regra da casa). A
    barra mensal some com a baixa DO MÊS; a que não se repete, com qualquer
    baixa. O «avisei» só esconde a do FERJ, só deste usuário, e só até
    `oculto_ate` — no dia seguinte ela volta, se o mês ainda não foi pago.
    """
    h = hoje or date.today().isoformat()
    bd = banco(con)
    avisos = [
        a for a in bd.ler(
            """SELECT * FROM nu_avisos WHERE ativo=1 AND modo=%s
               ORDER BY (chave IS NULL), prioridade DESC, id""",
            (MODO_BARRA,),
        )
        if vigente(a, h)
    ]
    if not avisos:
        return []
    pagos = bd.ler(
        """SELECT b.aviso_id, b.mes_ref FROM nu_aviso_baixa b
           JOIN nu_avisos a ON a.id = b.aviso_id
           WHERE a.ativo=1 AND a.modo=%s ORDER BY b.id""",
        (MODO_BARRA,),
    )
    meses_pagos = {(int(p["aviso_id"]), p["mes_ref"]) for p in pagos}
    algum_pago = {int(p["aviso_id"]) for p in pagos}
    ocultos = {
        (int(o["aviso_id"]), o["mes_ref"])
        for o in bd.ler(
            """SELECT aviso_id, mes_ref FROM nu_aviso_avisei
               WHERE user_id=%s AND oculto_ate > %s ORDER BY id""",
            (user_id, h),
        )
    }
    pode = (papel or "").upper()
    out: list[dict[str, Any]] = []
    for a in avisos:
        aid = int(a["id"])
        ciclo = ciclo_da_barra(a, h)
        if ciclo is None:
            continue
        mensal = a.get("barra_dia_mes") is not None
        if (aid, ciclo) in meses_pagos or (not mensal and aid in algum_pago):
            continue
        aceita_avisei = a.get("chave") == CHAVE_FERJ
        if aceita_avisei and (aid, ciclo) in ocultos:
            continue
        item = dict(a)
        item.update(
            mes_ref=ciclo,
            mes_rotulo=f"{ciclo[5:7]}/{ciclo[:4]}",
            pode_marcar_pago=pode in papeis_do_aviso(a),
            aceita_avisei=aceita_avisei,
            hoje=h,
        )
        out.append(item)
    return out


