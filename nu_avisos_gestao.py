def _barra_valendo(bd, aviso_id: int, h: str) -> tuple[dict, str]:
    aviso = bd.um("SELECT * FROM nu_avisos WHERE id=%s", (aviso_id,))
    if not aviso:
        raise AvisoGestaoError("Aviso não encontrado.")
    if aviso.get("modo") != MODO_BARRA:
        raise AvisoGestaoError("Este aviso não é barra fixa.")
    ciclo = ciclo_da_barra(aviso, h)
    if not int(aviso["ativo"]) or ciclo is None:
        raise AvisoGestaoError("Esta barra não está valendo hoje.")
    return aviso, ciclo


def marcar_pago(
    con: sqlite3.Connection,
    aviso_id: int,
    *,
    user_id: int,
    papel: str | None,
    data_pagamento: str | None,
    guia: str | None,
    agora: str,
    hoje: str | None = None,
    ip: str | None = None,
) -> str:
    """Dá a baixa do mês e devolve o mês de referência (AAAA-MM).

    O papel é o do AVISO (`barra_papeis`), e não o da rota: o oficial pode
    querer que o balcão também dê baixa num aviso, e não no do FERJ. Duas
    pessoas clicando juntas: a `UNIQUE (aviso_id, mes_ref)` deixa a primeira
    gravar e a segunda ouve quem já marcou — sem duas linhas no audit_logs.
    """
    h = hoje or data_local(agora)
    bd = banco(con)
    aviso, ciclo = _barra_valendo(bd, aviso_id, h)
    permitidos = papeis_do_aviso(aviso)
    if (papel or "").upper() not in permitidos:
        raise AvisoGestaoError(
            "Só " + "/".join(permitidos) + " marca esta barra como paga."
        )
    data_pg = _data_de_pagamento(data_pagamento, h)
    numero_guia = (guia or "").strip()[:60] or None
    if aviso.get("barra_dia_mes") is None:
        ja = bd.um(
            "SELECT mes_ref FROM nu_aviso_baixa WHERE aviso_id=%s ORDER BY id LIMIT 1",
            (aviso_id,),
        )
        if ja:
            raise AvisoGestaoError("Esta barra já foi marcada paga.")
    pessoa = _quem(bd, user_id)
    nova = bd.escrever(
        """INSERT INTO nu_aviso_baixa
           (aviso_id, mes_ref, data_pagamento, guia, user_id, usuario_nome, marcado_em)
           VALUES (%s, %s, %s, %s, %s, %s, %s)
           ON CONFLICT (aviso_id, mes_ref) DO NOTHING
           RETURNING id""",
        (aviso_id, ciclo, data_pg, numero_guia, user_id, pessoa["full_name"], agora),
    )
    if not nova:
        quem = bd.um(
            """SELECT usuario_nome, marcado_em FROM nu_aviso_baixa
               WHERE aviso_id=%s AND mes_ref=%s""",
            (aviso_id, ciclo),
        ) or {}
        raise AvisoGestaoError(
            f"O mês {ciclo[5:7]}/{ciclo[:4]} já foi marcado pago por "
            f"{quem.get('usuario_nome') or 'outro usuário'} em "
            f"{(quem.get('marcado_em') or '')[:10]}."
        )
    _auditar(
        bd, user_id=user_id, username=pessoa["username"], acao="NU_AVISO_PAGO",
        aviso_id=aviso_id, agora=agora, ip=ip,
        detalhes={"mes_referencia": ciclo, "data_pagamento": data_pg,
                  "guia": numero_guia, "titulo": aviso["titulo"]},
    )
    return ciclo


def registrar_avisei(
    con: sqlite3.Connection,
    aviso_id: int,
    *,
    user_id: int,
    palavra: str | None,
    agora: str,
    hoje: str | None = None,
    ip: str | None = None,
) -> str:
    """Oculta a barra do FERJ/FERC para ESTE usuário e devolve até quando.

    Digitar, e não clicar: foi a exigência do oficial — o clique vira reflexo,
    como virou o X da janela. Cada «avisei» é uma linha nova (o mesmo
    escrevente pode avisar de novo amanhã) e uma linha no audit_logs.
    """
    if (palavra or "").strip().casefold() != PALAVRA_AVISEI:
        raise AvisoGestaoError(
            "Para ocultar a barra, digite a palavra «avisei» no campo dela."
        )
    h = hoje or data_local(agora)
    bd = banco(con)
    aviso, ciclo = _barra_valendo(bd, aviso_id, h)
    if aviso.get("chave") != CHAVE_FERJ:
        raise AvisoGestaoError("Só a barra do FERJ/FERC se oculta com «avisei».")
    dias = int(aviso.get("avisei_dias") or 1)
    oculto_ate = (date.fromisoformat(h[:10]) + timedelta(days=dias)).isoformat()
    pessoa = _quem(bd, user_id)
    bd.escrever(
        """INSERT INTO nu_aviso_avisei
           (aviso_id, user_id, usuario_nome, mes_ref, avisado_em, oculto_ate)
           VALUES (%s, %s, %s, %s, %s, %s)""",
        (aviso_id, user_id, pessoa["full_name"], ciclo, agora, oculto_ate),
    )
    _auditar(
        bd, user_id=user_id, username=pessoa["username"], acao="NU_AVISO_AVISEI",
        aviso_id=aviso_id, agora=agora, ip=ip,
        detalhes={"mes_referencia": ciclo, "oculto_ate": oculto_ate},
    )
    return oculto_ate


def _mes_antes(mes: str, n: int = 1) -> str:
    total = int(mes[:4]) * 12 + int(mes[5:7]) - 1 - n
    return f"{total // 12:04d}-{total % 12 + 1:02d}"


def historico_barras(
    con: sqlite3.Connection, *, hoje: str | None = None, meses: int = 12
) -> list[dict[str, Any]]:
    """Quem marcou pago em cada mês, e quem disse «avisei» — para o ADMIN.

    O mês sem baixa também entra (com `baixa` vazia), para a barra mensal
    ativa: a lista que só mostrasse os pagos esconderia justamente o mês em
    que ninguém pagou.
    """
    h = hoje or date.today().isoformat()
    desde = _mes_antes(h[:7], max(1, meses) - 1)
    bd = banco(con)
    avisos = bd.ler(
        """SELECT id, titulo, criado_em, ativo, modo, barra_dia_mes
           FROM nu_avisos ORDER BY (chave IS NULL), id"""
    )
    baixas = bd.ler(
        """SELECT aviso_id, mes_ref, data_pagamento, guia, usuario_nome, marcado_em
           FROM nu_aviso_baixa WHERE mes_ref >= %s ORDER BY mes_ref DESC, id""",
        (desde,),
    )
    avisos_ditos = bd.ler(
        """SELECT aviso_id, mes_ref, usuario_nome, avisado_em, oculto_ate
           FROM nu_aviso_avisei WHERE mes_ref >= %s
           ORDER BY mes_ref DESC, avisado_em, id""",
        (desde,),
    )
    posicao = {int(a["id"]): i for i, a in enumerate(avisos)}
    titulos = {int(a["id"]): a["titulo"] for a in avisos}
    linhas: dict[tuple[str, int], dict[str, Any]] = {}

    def linha(mes: str, aid: int) -> dict[str, Any]:
        if (mes, aid) not in linhas:
            linhas[(mes, aid)] = {
                "mes_ref": mes,
                "mes_rotulo": f"{mes[5:7]}/{mes[:4]}",
                "aviso_id": aid,
                "titulo": titulos.get(aid, f"Aviso {aid}"),
                "baixa": None,
                "avisei": [],
            }
        return linhas[(mes, aid)]

    for a in avisos:
        if a["modo"] != MODO_BARRA or a["barra_dia_mes"] is None or not int(a["ativo"]):
            continue
        inicio = max(desde, (a["criado_em"] or h)[:7])
        mes = h[:7] if ciclo_da_barra(a, h) else _mes_antes(h[:7])
        while mes >= inicio:
            linha(mes, int(a["id"]))
            mes = _mes_antes(mes)
    for b in baixas:
        linha(b["mes_ref"], int(b["aviso_id"]))["baixa"] = b
    for v in avisos_ditos:
        linha(v["mes_ref"], int(v["aviso_id"]))["avisei"].append(v)
    saida = sorted(linhas.values(), key=lambda x: posicao.get(x["aviso_id"], len(posicao)))
    saida.sort(key=lambda x: x["mes_ref"], reverse=True)
    return saida
