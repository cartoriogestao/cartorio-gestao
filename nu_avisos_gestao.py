def remover(con: sqlite3.Connection, aviso_id: int) -> None:
    aviso = obter(con, aviso_id)
    if not aviso:
        raise AvisoGestaoError("Aviso nÃ£o encontrado.")
    if aviso.get("chave"):
        # O aviso do sistema renasce na próxima subida, e levaria junto a
        # lista de quem pagou cada mês. Desligar é desmarcar «Ativo».
        raise AvisoGestaoError(
            "Este aviso é do sistema e não se remove: desmarque «Ativo» para desligá-lo."
        )
    bd = banco(con)
    bd.escrever("DELETE FROM nu_aviso_dispensa WHERE aviso_id=%s", (aviso_id,))
    bd.escrever("DELETE FROM nu_aviso_avisei WHERE aviso_id=%s", (aviso_id,))
    bd.escrever("DELETE FROM nu_aviso_baixa WHERE aviso_id=%s", (aviso_id,))
    bd.escrever("DELETE FROM nu_avisos WHERE id=%s", (aviso_id,))
def listar_ativos_vigentes(con: sqlite3.Connection, *, hoje: str | None = None) -> list[dict]:
    """Os avisos de JANELA — a barra fixa tem o seu caminho (`barras_para_usuario`).

    Sem o filtro do modo, a barra do FERJ entraria também na janela e na
    contagem N, e ganharia lá um «Dispensar hoje» que a barra não tem.
    """
    h = hoje or date.today().isoformat()
    linhas = banco(con).ler(
        """SELECT * FROM nu_avisos WHERE ativo=1 AND modo=%s
           ORDER BY prioridade DESC, id ASC""",
        (MODO_JANELA,),
    )
    return [r for r in linhas if vigente(r, h)]
def ids_dispensados_hoje(
    con: sqlite3.Connection, user_id: int, *, hoje: str | None = None
) -> set[int]:
    h = hoje or date.today().isoformat()
    rows = banco(con).ler(
        """SELECT aviso_id FROM nu_aviso_dispensa
           WHERE user_id=%s AND data_local=%s""",
        (user_id, h),
    )
    return {int(r["aviso_id"]) for r in rows}
def pendentes_para_usuario(
    con: sqlite3.Connection,
    user_id: int,
    *,
    hoje: str | None = None,
    dispensados: set[int] | None = None,
) -> list[dict[str, Any]]:
    h = hoje or date.today().isoformat()
    if dispensados is None:
        dispensados = ids_dispensados_hoje(con, user_id, hoje=h)
    out: list[dict[str, Any]] = []
    for row in listar_ativos_vigentes(con, hoje=h):
        if eh_prioritario(row):
            out.append(dict(row))
            continue
        if int(row["id"]) in dispensados:
            continue
        out.append(dict(row))
    return out
