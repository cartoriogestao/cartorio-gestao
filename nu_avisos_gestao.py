def atualizar(
    con: sqlite3.Connection,
    aviso_id: int,
    *,
    titulo: str,
    corpo: str,
    ativo: bool,
    prioridade: int,
    vigencia_inicio: str | None,
    vigencia_fim: str | None,
    agora: str,
    recorrente: bool = False,
    recorrencia_dia_semana: int | None = None,
    recorrencia_dias: int | None = None,
    recorrencia_hora: str | None = None,
    modo: str | None = None,
    barra_dia_mes: int | str | None = None,
    barra_papeis: Any = None,
    avisei_dias: int | str | None = None,
    manter_barra: bool = True,
) -> None:
    """Grava a edição. Os campos da barra fixa vazios MANTÊM o que já está.

    `manter_barra=True` (o padrão) é para quem chama sem saber da barra — os
    chamadores de antes do LX17 —, e sem isto a primeira edição de título
    trocaria a barra do FERJ por janela. A tela passa `manter_barra=False` e
    manda os quatro campos, porque ali a caixa de papéis desmarcada é escolha.
    """
    atual = obter(con, aviso_id)
    if not atual:
        raise AvisoGestaoError("Aviso nÃ£o encontrado.")
    if manter_barra:
        modo = modo or atual.get("modo")
        barra_dia_mes = barra_dia_mes if barra_dia_mes is not None else atual.get("barra_dia_mes")
        barra_papeis = barra_papeis if barra_papeis is not None else atual.get("barra_papeis")
        avisei_dias = avisei_dias if avisei_dias is not None else atual.get("avisei_dias")
    barra = _normalizar_barra(modo or MODO_JANELA, barra_dia_mes, barra_papeis, avisei_dias)
    if atual.get("chave") == CHAVE_FERJ and (
        barra["modo"] != MODO_BARRA or barra["barra_dia_mes"] is None
    ):
        # O pedido do oficial é este: o FERJ/FERC é barra fixa MENSAL. Voltar
        # para a janela é voltar ao aviso que ele disse que ninguém lê.
        raise AvisoGestaoError(
            "O aviso do FERJ/FERC é sempre barra fixa mensal: informe o dia do mês."
        )
    titulo = (titulo or "").strip()
    corpo = (corpo or "").strip()
    if not titulo:
        raise AvisoGestaoError("Informe o tÃ­tulo do aviso.")
    if not corpo:
        raise AvisoGestaoError("Informe o texto do aviso.")
    if recorrencia_dias is not None:
        _raw_dias = recorrencia_dias
    elif recorrencia_dia_semana is not None:
        _raw_dias = 1 << int(recorrencia_dia_semana)
    else:
        _raw_dias = None
    rec, dia, dias_mask, hhmm = _normalizar_recorrencia(
        recorrente, _raw_dias, recorrencia_hora,
    )
    banco(con).escrever(
        """UPDATE nu_avisos SET titulo=%s, corpo=%s, ativo=%s, prioridade=%s,
           vigencia_inicio=%s, vigencia_fim=%s, atualizado_em=%s,
           recorrente=%s, recorrencia_dia_semana=%s, recorrencia_dias=%s, recorrencia_hora=%s,
           modo=%s, barra_dia_mes=%s, barra_papeis=%s, avisei_dias=%s
           WHERE id=%s""",
        (
            titulo,
            corpo,
            1 if ativo else 0,
            int(prioridade),
            vigencia_inicio or None,
            vigencia_fim or None,
            agora,
            rec,
            dia,
            dias_mask,
            hhmm,
            barra["modo"],
            barra["barra_dia_mes"],
            barra["barra_papeis"],
            barra["avisei_dias"],
            aviso_id,
        ),
    )
