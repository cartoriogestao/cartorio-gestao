def _data_de_pagamento(texto: str | None, hoje: str) -> str:
    t = (texto or "").strip()
    try:
        d = date.fromisoformat(t[:10]) if len(t) >= 10 else None
    except ValueError:
        d = None
    if d is None:
        raise AvisoGestaoError("Informe a data do pagamento.")
    if d > date.fromisoformat(hoje[:10]):
        raise AvisoGestaoError("A data do pagamento não pode ser futura.")
    return d.isoformat()


