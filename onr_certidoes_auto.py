def init_schema(con) -> None:
    bd = banco(con)
    bd.escrever(SCHEMA)
    for coluna, tipo in MIGRACOES:
        if not bd.tem_coluna("onr_cert_auto", coluna):
            bd.escrever(f"ALTER TABLE onr_cert_auto ADD COLUMN {coluna} {tipo}")


