def _codigo(valor: Any) -> str:
    return str(valor or "").strip().lower()


def finalidade_do_pedido(protocolo: str) -> str:
    """A finalidade que a certidão leva — e a marca que amarra a certidão ao
    pedido (`ato_selado.e_certidao_paga_no_onr`)."""
    import ato_selado as AS
    return f"{AS.PREFIXO_DA_FINALIDADE_ONR}{str(protocolo or '').strip()}"


def pessoa_do_pedido(dados: dict) -> str:
    """O que buscar primeiro: o documento, ou o nome. Ver `partes_da_pessoa`."""
    doc, nome = partes_da_pessoa(dados)
    return doc or nome


def partes_da_pessoa(dados: dict) -> tuple[str, str]:
    """O que buscar no Indicador Pessoal: o CPF/CNPJ do bloco PESSOA, ou o nome.

    O BLOCO `CERTIDAO/PESSOA` NUNCA FOI MEDIDO (25/10/2026): nenhuma cópia
    guardou os 97 pedidos de 11/10, e a produção não tem nenhum. Lê-se pelo
    nome do campo; o que não se reconhecer devolve vazio — e o pedido vai para
    A_MAO, em vez de buscar a pessoa errada. Devolve (documento, nome)."""
    doc = nome = ""
    for chave, valor in (dados or {}).items():
        k = str(chave).upper()
        if "PESSOA" not in k:
            continue
        texto = str(valor or "").strip()
        if not texto:
            continue
        digitos = re.sub(r"\D", "", texto)
        if re.search(r"CPF|CNPJ|DOCUMENTO|CIC", k) and len(digitos) in (11, 14):
            doc = doc or digitos
        elif re.search(r"NOME", k):
            nome = nome or texto
    return doc, nome


def grupos_do_pedido(con, dados: dict) -> list[dict]:
    """As pessoas do Indicador Pessoal que o pedido pode ser — pela régua LARGA:
    o documento E o nome, somados (revisão do Agente RI, 25/10/2026). A mesma
    pessoa costuma estar com CPF num cadastro e só com o nome noutro, e a busca
    só pelo CPF não acha o segundo: a negativa sairia sobre quem tem imóvel."""
    import ri_certidao_negativa as RINEG
    doc, nome = partes_da_pessoa(dados)
    vistos: dict[str, dict] = {}
    for termo in (doc, nome):
        if termo:
            for g in RINEG.buscar_por_pessoa(con, termo):
                vistos.setdefault(str(g["chave"]), g)
    return list(vistos.values())


def conferir_negativa_do_pedido(con, dados: dict) -> None:
    """A negativa do pedido por pessoa só sai se NEM o documento NEM o nome
    acharem alguém. Só LÊ; recusa com a frase pronta."""
    if not partes_da_pessoa(dados)[1]:
        raise AutoError(
            "O pedido traz só o documento: a negativa não sai sem buscar também pelo "
            "nome (a maioria das partes do acervo não tem documento cadastrado). "
            "Faça à mão.")
    achados = grupos_do_pedido(con, dados)
    if achados:
        raise AutoError(
            f"A busca pelo documento e pelo nome do pedido achou {len(achados)} "
            "cadastro(s) — não se emite negativa. Confira e emita a positiva, "
            "marcando as matrículas, ou faça à mão.")


def motivo_sem_selo_pago_no_onr(pedido: dict, *, ligado: bool = True) -> str | None:
    """Por que o selo pago no ONR não cobriria este pedido — ou None. Só calcula.

    A régua é a de `ato_selado.e_certidao_paga_no_onr`, dita antes de emitir:
    «o pedido chega no protocolo para darmos orçamento; depois volta pro
    cliente, ele paga e recebemos o encaminhamento» (o oficial, 25/10/2026).

    `ligado` é o ajuste do oficial (`ato_selado.selo_pago_no_onr_ligado`),
    desligado de fábrica (26/10/2026, M5): desligado, nenhum pedido pago é
    preparado para a aprovação — vai à mão, pela trava normal do selo."""
    import ato_selado as AS
    if not ligado:
        return ("o selo pago no ONR está DESLIGADO (só o oficial liga, depois de medir o "
                "primeiro pedido pago de verdade): a certidão segue a trava normal do selo "
                "pago — faça pela tela de sempre")
    if not AS.cobranca_integral_do_pedido_onr(pedido.get("dados_json")):
        return ("a cobrança do pedido não é INTEGRAL (prefeitura ou isenção): o selo "
                "pago no ONR não vale para ela — o oficial decide como selar")
    if not pedido.get("custas_em"):
        return ("o pedido chegou pago sem o orçamento desta casa (as custas não foram "
                "informadas por aqui): o selo pago no ONR não vale sem ele")
    return None


def sugerir(con, pedido: dict) -> dict:
    """O que o robô propõe para o pedido: via, tipo do RI, ou o motivo de ir à
    mão. Só LÊ."""
    import ri_certidao_negativa as RINEG
    dados = json.loads(pedido.get("dados_json") or "{}")
    por = _codigo(pedido.get("pesquisa_por"))
    tipo_onr = _codigo(pedido.get("tipo_certidao"))
    if por in PESQUISA_POR_MATRICULA:
        if not pedido.get("matricula_id"):
            return {"via": "MATRICULA", "tipo_ri": None, "etapa": A_MAO,
                    "motivo": f"a matrícula {pedido.get('matricula_numero') or '(sem número)'} "
                              "não está no sistema"}
        if tipo_onr in TIPOS_ONR_DE_ONUS:
            return {"via": "MATRICULA", "tipo_ri": "ONUS", "etapa": A_REVISAR, "motivo": None}
        tipo_ri = TIPO_RI_POR_TIPO_ONR.get(tipo_onr)
        if not tipo_ri:
            return {"via": "MATRICULA", "tipo_ri": None, "etapa": A_MAO,
                    "motivo": f"o tipo de certidão do ONR ({tipo_onr or 'vazio'}) não tem "
                              "equivalente automático"}
        return {"via": "MATRICULA", "tipo_ri": tipo_ri, "etapa": A_REVISAR, "motivo": None}
    if por in PESQUISA_POR_PESSOA:
        if tipo_onr not in ("1", "propriedade / negativa de propriedade"):
            return {"via": "PESSOA", "tipo_ri": None, "etapa": A_MAO,
                    "motivo": "pedido por pessoa de um tipo que não é propriedade/negativa"}
        busca = pessoa_do_pedido(dados)
        if not busca:
            return {"via": "PESSOA", "tipo_ri": None, "etapa": A_MAO,
                    "motivo": "o pedido não traz nome nem CPF/CNPJ que o sistema reconheça"}
        # A RÉGUA LARGA: documento E nome; e a positiva vale se houver QUALQUER
        # candidata, inclusive de outro cadastro com o mesmo nome — negativa
        # errada sobre quem tem imóvel é o erro que não se desfaz.
        achados = grupos_do_pedido(con, dados)
        if not achados and not partes_da_pessoa(dados)[1]:
            return {"via": "PESSOA", "tipo_ri": None, "etapa": A_MAO, "pessoa_busca": busca,
                    "motivo": "o pedido traz só o documento e a busca por ele não achou ninguém: "
                              "sem o nome, a negativa não é segura (a maioria das partes do "
                              "acervo não tem documento)"}
        if not achados:
            return {"via": "PESSOA", "tipo_ri": RINEG.TIPO, "etapa": A_REVISAR,
                    "motivo": None, "pessoa_busca": busca}
        donos = [g for g in achados if RINEG.candidatas_da_positiva(con, g["chave"])]
        if donos:
            return {"via": "PESSOA", "tipo_ri": RINEG.TIPO_POSITIVA, "etapa": A_REVISAR,
                    "motivo": None, "pessoa_busca": busca}
        return {"via": "PESSOA", "tipo_ri": None, "etapa": A_MAO, "pessoa_busca": busca,
                "motivo": "a pessoa aparece nos livros, mas não é dona de matrícula aberta: "
                          "nem a negativa nem a positiva servem sem decidir à mão"}
    return {"via": "OUTRO", "tipo_ri": None, "etapa": A_MAO,
            "motivo": f"pesquisa por «{pedido.get('pesquisa_por') or 'vazio'}» não tem caminho automático"}


def custas_pela_tabela(con, tipo_ri: str | None, folhas: int = 1) -> str | None:
    """O valor da certidão pela tabela do dia, em reais («123.06»). Só LÊ.

    É a certidão de UMA folha: a de mais folhas cobra o item da folha
    acrescida, e o número de folhas só se sabe na emissão. Sem preço, None."""
    import ato_selado as AS
    if not tipo_ri or not banco(con).tem_tabela("cx_servicos"):
        return None
    try:
        itens = AS.itens_da_certidao_do_ri(tipo_ri, max(1, int(folhas)))
    except AS.AtoError:
        return None
    total = 0
    for codigo, quantidade in itens:
        servico = AS.servico_do_codigo_tj(con, codigo)
        if not servico:
            return None
        try:
            conta = AS.calcular_custas(con, servico=servico["codigo"])
        except AS.AtoError:
            return None
        total += int(conta["total_devido_centavos"]) * int(quantidade)
    return f"{total // 100}.{total % 100:02d}"


# ---------------------------------------------------------------- a fila

def preparo(con, pedido_id: int) -> dict | None:
    linha = banco(con).um("SELECT * FROM onr_cert_auto WHERE pedido_id=%s", (int(pedido_id),))
    return dict(linha) if linha else None


def fila(con, *, etapas: tuple = ()) -> list[dict]:
    """Os pedidos com o que a automação sabe deles. Só LÊ."""
    onde, params = "", []
    if etapas:
        onde = "WHERE a.etapa IN (" + ",".join(["%s"] * len(etapas)) + ")"
        params = list(etapas)
    return [dict(r) for r in banco(con).ler(
        f"""SELECT a.*, p.protocolo, p.tipo_certidao, p.pesquisa_por, p.status_onr,
                   p.solicitante, p.matricula_numero, p.matricula_id, p.valor,
                   p.data_pedido, p.situacao AS situacao_pedido
              FROM onr_cert_auto a JOIN onr_cert_pedidos p ON p.id = a.pedido_id
              {onde}
             ORDER BY p.data_pedido, a.id""", params)]


def contar(con) -> dict[str, int]:
    return {r["etapa"]: int(r["n"]) for r in banco(con).ler(
        "SELECT etapa, COUNT(*) AS n FROM onr_cert_auto GROUP BY etapa")}


def _gravar(bd, pedido_id: int, agora: str, **campos) -> None:
    sets = ", ".join(f"{c}=%s" for c in campos)
    bd.escrever(f"UPDATE onr_cert_auto SET {sets}, atualizado_em=%s WHERE pedido_id=%s",
                (*campos.values(), agora, int(pedido_id)))


def sincronizar(con, ambiente: str, agora: str) -> dict:
    """Põe cada pedido aberto do ONR na etapa certa, pelo status dele. ESCREVE.

    Não mexe no que alguém já fez (EMITINDO em diante). O status «pago» é a
    mesma régua da trava do selo (`ato_selado.status_onr_e_pago`)."""
    import ato_selado as AS
    import onr_certidoes as OC
    init_schema(con)
    bd = banco(con)
    contas = {"novos": 0, "mudaram": 0}
    ligado = AS.selo_pago_no_onr_ligado(con)
    for p in bd.ler("SELECT * FROM onr_cert_pedidos WHERE ambiente=%s ORDER BY id", (ambiente,)):
        p = dict(p)
        atual = preparo(con, p["id"])
        status = _codigo(p.get("status_onr"))
        fechado = (status in OC.STATUS_FECHADOS_NO_ONR
                   or p.get("situacao") in ("RESPONDIDO", "DEVOLVIDO", "FECHADO_NO_ONR"))
        if atual is None:
            if fechado:
                continue                       # histórico, e não trabalho
            bd.escrever("INSERT INTO onr_cert_auto(pedido_id, etapa, criado_em, atualizado_em) "
                        "VALUES (%s,%s,%s,%s)", (p["id"], A_REVISAR, agora, agora))
            atual = preparo(con, p["id"])
            contas["novos"] += 1
        etapa = atual["etapa"]
        if etapa in (RESPONDIDO, FECHADO):
            continue
        if fechado and etapa not in (EMITINDO, A_ASSINAR):
            nova = RESPONDIDO if p.get("situacao") == "RESPONDIDO" else FECHADO
            _gravar(bd, p["id"], agora, etapa=nova)
            contas["mudaram"] += 1
            continue
        if etapa in EM_ANDAMENTO:
            continue
        if status in ("10", "informar valor dos emolumentos"):
            if etapa not in (CUSTAS_A_APROVAR, CUSTAS_APROVADAS):
                sug = sugerir(con, p)
                _gravar(bd, p["id"], agora, etapa=CUSTAS_A_APROVAR, via=sug["via"],
                        tipo_ri=sug["tipo_ri"], motivo=sug["motivo"],
                        pessoa_busca=sug.get("pessoa_busca"),
                        custas_calculadas=custas_pela_tabela(con, sug["tipo_ri"]))
                contas["mudaram"] += 1
            continue
        if status in ("11", "aguardando pagamento"):
            if etapa != AGUARDANDO_PAGAMENTO:
                _gravar(bd, p["id"], agora, etapa=AGUARDANDO_PAGAMENTO)
                contas["mudaram"] += 1
            continue
        if AS.status_onr_e_pago(status):
            if etapa in (A_REVISAR, A_MAO, ERRO) and atual.get("via"):
                continue                       # já preparado; não refaz a decisão
            sug = sugerir(con, p)
            barra = motivo_sem_selo_pago_no_onr(p, ligado=ligado)
            if barra and sug["etapa"] == A_REVISAR:
                sug = sug | {"etapa": A_MAO, "motivo": barra}
            _gravar(bd, p["id"], agora, etapa=sug["etapa"], via=sug["via"],
                    tipo_ri=sug["tipo_ri"], motivo=sug["motivo"],
                    pessoa_busca=sug.get("pessoa_busca"))
            contas["mudaram"] += 1
    return contas


