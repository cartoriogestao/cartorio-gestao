"""As certidões do RI pedidas pelo ONR, no automático — o robô prepara, o
escrevente aprova, o robô assina e envia.

    «o agente 4 vezes por dia [...] entra e olha se tem pedidos pendentes e
     prepara a certidao para envio, que poderia ficar numa area do sistema com
     aviso no painel. dai o escrevente verifica o resumo do pedido e a
     certidao emitida dentro do sistema e aprova o envio, nisso proxima vez
     que o script rodar ele ja mandar a certidao pro cliente»
                                                    — o oficial, 25/10/2026

AS DECISÕES DELE (25/10/2026)
    - o selo é gasto NA APROVAÇÃO: o robô prepara o rascunho, e o pedido
      recusado não gasta selo;
    - assina o A3 do OFICIAL, com o PIN no cofre da senha-mestra;
    - entram os pedidos por MATRÍCULA e por PESSOA (positiva = «relação dos
      imóveis atuais»; negativa quando nada consta);
    - o robô roda às 8h, 11h, 14h e 17h, em dias úteis;
    - pedido em «Informar valor dos emolumentos»: o robô calcula pela tabela,
      o escrevente aprova, o robô informa ao ONR;
    - a trava do selo pago aceita a certidão paga no ONR (`ato_selado.
      FORMA_CENTRAL_ONR`), estreita.

QUEM FAZ O QUÊ — E POR QUE A EMISSÃO NÃO É DO ROBÔ
    O despachante (`rodada`, fora do servidor) faz o que é rede e papel:
    busca os pedidos, prepara (etapa, tipo sugerido, custas), informa as
    custas aprovadas, assina com o A3 pelo serviço local e envia/finaliza.

    A EMISSÃO É O CLIQUE «APROVAR» DO ESCREVENTE, no servidor vivo
    (`onr_certidoes_auto_web`), pela MESMA rota do balcão — e não uma cópia
    dela. Desenho revisado com o Agente RI em 25/10/2026: abrir um app novo no
    despachante rodaria as recuperações que escrevem (a sessão do agente que
    estiver aberta viraria INTERROMPIDA) e pularia o `before_request`; e uma
    emissão às 14h no nome de quem não clicou mentiria na auditoria.

ESTE MÓDULO NÃO FALA COM A REDE NEM EMITE
    Ele decide e registra. A rede (WSOficio, serviço A3) está em `rodada` e
    nas rotas, sempre fora de `db.transaction()`.
"""
