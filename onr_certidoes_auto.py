def aprovar_custas(con, pedido_id: int, valor: str, *, usuario: str, agora: str) -> str:
    """O escrevente aprova o valor que o robô vai informar ao ONR. ESCREVE."""
    import onr_certidoes as OC
    a = preparo(con, pedido_id)
