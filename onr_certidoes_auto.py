def _antes(a: str, b: str, minutos: int) -> bool:
    try:
        return datetime.fromisoformat(str(a)[:19]) + timedelta(minutes=minutos) < \
            datetime.fromisoformat(str(b)[:19])
    except ValueError:
        return True


def marcar_emitindo(con, pedido_id: int, *, user_id: int, nome: str, status_onr: str,
                    formulario: dict, agora: str) -> dict:
    """A aprovação do escrevente, antes de despachar a emissão. ESCREVE.

    Transação CURTA, que se fecha antes do despacho (a rota de emissão trava
    `ri_certidoes.numero` noutra conexão). Depois do commit, a guarda contra o
    segundo clique é o próprio EMITINDO."""
    import ato_selado as AS
    bd = banco(con)
    bd.travar(f"onr_cert_auto:{int(pedido_id)}")
    a = preparo(con, pedido_id)
    if not a:
        raise AutoError("Este pedido ainda não foi preparado pela automação.")
    if a.get("certidao_id"):
        n = bd.um("SELECT numero, ano FROM ri_certidoes WHERE id=%s", (a["certidao_id"],))
        raise AutoError(f"Este pedido já tem a certidão nº {n['numero']}/{n['ano']}." if n
                        else "Este pedido já tem certidão.")
    if a["etapa"] == EMITINDO and not _antes(a.get("emitindo_desde"), agora,
                                             EMITINDO_VENCE_EM_MINUTOS):
        raise AutoError("A emissão deste pedido está em andamento (outro clique). Espere "
                        "alguns minutos e abra o pedido de novo.")
    if a["etapa"] not in (A_REVISAR, EMITINDO):
        raise AutoError(f"Este pedido está em «{NOME_DA_ETAPA.get(a['etapa'], a['etapa'])}» "
                        "e não pode ser aprovado agora.")
    if not AS.status_onr_e_pago(status_onr):
        raise AutoError(f"O ONR diz que este pedido está «{status_onr or 'sem status'}» — "
                        "a certidão só sai com o pedido pago (Em aberto, Processando ou "
                        "Pendente de resposta). Nada foi emitido.")
    p = dict(banco(con).um("SELECT * FROM onr_cert_pedidos WHERE id=%s", (int(pedido_id),)))
    barra = motivo_sem_selo_pago_no_onr(p, ligado=AS.selo_pago_no_onr_ligado(con))
    if barra:
        raise AutoError(f"Não dá para emitir por aqui: {barra}. Nada foi emitido.")
    marca = finalidade_do_pedido(p["protocolo"])
    _gravar(bd, pedido_id, agora, etapa=EMITINDO, aprovado_por_user_id=int(user_id),
            aprovado_por_nome=nome, aprovado_em=agora, status_onr_conferido=status_onr,
            status_conferido_em=agora, finalidade_marca=marca, emitindo_desde=agora,
            formulario_json=json.dumps(formulario, ensure_ascii=False, default=str), erro=None)
    return {"marca": marca, "emitindo_desde": agora}


