"""Onde mora o painel de conformidade do ONR — o declarado, a prova informada e as pendências.

RI010, 23/11/2026. O Painel ADPF 743 do ONR não aparece no login da serventia:
o que a casa sabe dele é o que alguém DIGITA aqui, de uma tela do Ofício
Eletrônico ou da Circular da Corregedoria. Por isso há três tabelas, e nenhuma
guarda número que o sistema tenha inventado:

  * `onr_declaracoes`  — o que a serventia declarou ao ONR (ou o que o painel
    mostra dela), **digitado**, com a data em que foi lido, de onde e por quem.
    Só se acrescenta: corrigir é lançar de novo (vale o último) ou anular.
  * `onr_provas_informadas` — a importação que o titular fez no portal do ONR
    («Envio de Indicador Real», IPS, CSL2...) e que o sistema não vê sozinho:
    quantas, em que situação o ONR a pôs (Processando, Importado, Não
    importado), o protocolo e quem informou. Só **Importado** conta como prova.
  * `onr_pendencias` — o que falta fazer, com responsável, prazo, protocolo do
    ONR e comprovante (anexo `ONR_PENDENCIA`).

NADA AQUI ENVIA AO ONR. O painel não entra no portal e não chama a API.
"""
from __future__ import annotations

import re

from bd_nativo import banco

SCHEMA = """
CREATE TABLE IF NOT EXISTS onr_declaracoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obrigacao TEXT NOT NULL,                 -- PROV143 | PROV195 | ITN003
    coluna TEXT NOT NULL,                    -- ver onr_conformidade.COLUNAS
    valor INTEGER NOT NULL,                  -- número; nas perguntas Sim/Não, 1 ou 0
    lido_em TEXT NOT NULL,                   -- a data em que o número foi lido na tela de origem
    origem TEXT NOT NULL,                    -- de que tela ou documento ele saiu
    observacao TEXT,
    lancado_em TEXT NOT NULL,
    lancado_por TEXT NOT NULL,
    anulado_em TEXT,
    anulado_por TEXT,
    anulado_motivo TEXT
);
CREATE INDEX IF NOT EXISTS ix_onr_declaracoes_coluna
    ON onr_declaracoes(obrigacao, coluna, id);

CREATE TABLE IF NOT EXISTS onr_provas_informadas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obrigacao TEXT NOT NULL,
    coluna TEXT NOT NULL,
    quantos INTEGER NOT NULL,
    situacao TEXT NOT NULL,                  -- PROCESSANDO | IMPORTADO | NAO_IMPORTADO
    visto_em TEXT NOT NULL,                  -- a data em que a situação foi vista no portal
    protocolo_onr TEXT,
    descricao TEXT,
    lancado_em TEXT NOT NULL,
    lancado_por TEXT NOT NULL,
    anulado_em TEXT,
    anulado_por TEXT,
    anulado_motivo TEXT
);
CREATE INDEX IF NOT EXISTS ix_onr_provas_coluna
    ON onr_provas_informadas(obrigacao, coluna, situacao);

CREATE TABLE IF NOT EXISTS onr_pendencias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obrigacao TEXT NOT NULL,
    coluna TEXT,
    titulo TEXT NOT NULL,
    responsavel TEXT,
    prazo TEXT,
    protocolo_onr TEXT,
    observacao TEXT,
    situacao TEXT NOT NULL DEFAULT 'ABERTA', -- ABERTA | CONCLUIDA | CANCELADA
    criada_em TEXT NOT NULL,
    criada_por TEXT NOT NULL,
    encerrada_em TEXT,
    encerrada_por TEXT,
    encerrada_motivo TEXT
);
CREATE INDEX IF NOT EXISTS ix_onr_pendencias_situacao
    ON onr_pendencias(situacao, obrigacao);
"""


def init_onr_conformidade_schema(con) -> None:
    """Cria as três tabelas do painel. Idempotente."""
    bd = banco(con)
    # os comentários saem ANTES de separar, como em `ri_onr_central_schema`.
    for comando in re.split(r";[ \t]*\n", re.sub(r"--[^\n]*", "", SCHEMA)):
        if comando.strip():
            bd.escrever(comando)
