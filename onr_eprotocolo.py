"""O e-Protocolo do Registro de Imóveis pelo ONR — a ENTRADA dos títulos (RI013, P1).

    «pode abrir a P1 do e-Protocolo também»          — o oficial, 24/11/2026

NÃO É O E-PROTOCOLO DO REGISTRO CIVIL
    `eprotocolo.py`, `eprotocolo_api.py` e `eprotocolo_web.py` são o e-Protocolo
    da CRC (Unidade Interligada e e-Óbito), outro produto, com outra central.
    Este é o do ONR: o serviço `eprotocolo.asmx` do WSOficio (manual 4.43, cap.
    3.10), por onde chegam os títulos que o apresentante remete ao RI.

O QUE ESTA ETAPA FAZ — E SÓ ISSO
    Lê. `ListPedidosAC` traz a lista; para cada contrato novo e ainda aberto,
    `GetPedidoAC_V8` traz a ficha e `ListAnexosAC` os anexos. Tudo fica gravado
    em tabela própria, com o XML da ficha CONGELADO (o trecho exato que o ONR
    mandou, com o SHA-256) e os campos achatados em `dados_json`, no molde de
    `onr_cert_pedidos`. **Nada se prenota, nada se emite, nada se sela e nada se
    escreve no ONR**: os `Set*` do serviço estão em `onr_wsoficio.CAMPOS` desde
    a RI013 B0 (25/11/2026), mas presos em `ESPERAM_O_PODE_DO_TITULAR` — a
    sessão os recusa — e este módulo não os monta.

A ORDEM É A DA REMESSA (CNN 326)
    A fila sai por `DataRemessa`, e o desempate é o `IDContrato` — o manual dá
    a data no formato aaaa-mm-dd, sem hora (3.10.22, p. 116). Se a primeira
    leitura real trouxer a hora, a ordem passa a ser exata sem mudar nada aqui;
    se não trouxer, dois títulos remetidos no mesmo dia ficam na ordem do
    número do contrato, que é A CONFERIR com o ONR.

A PRIORIDADE VALE PELA HORA DA PRENOTAÇÃO — decisão do titular, 24/11/2026
    («vale a hora da prenotacao»). Entre o título de balcão e o eletrônico, tem
    prioridade o que foi PRENOTADO primeiro, e não o que foi remetido primeiro.
    A ordem da remessa continua valendo ENTRE os títulos eletrônicos: é a ordem
    em que se prenotam (CNN 326). Por isso o aviso de contraditório não compara
    a prenotação nem o balcão com a data da remessa — compararia a coisa errada
    —, e só os títulos eletrônicos entre si se comparam pela remessa. A regra
    vai escrita para a P2 em `REGRA_DE_PRIORIDADE`.

OS AVISOS SE CALCULAM NA HORA; NÃO SE GRAVAM
    Prenotação aberta ou título de balcão sobre a mesma matrícula (o controle de
    contraditórios do CNN 326, por enquanto só aviso), outro título do
    e-Protocolo sobre a mesma matrícula, constrição, mandado, gratuidade e
    averbação de CDA. A prenotação de amanhã muda a resposta de hoje: por isso
    é uma lente sobre as tabelas onde a prenotação e o balcão já moram, e não
    uma coluna que envelheceria.

A REDE NUNCA ACONTECE DENTRO DE `db.transaction()`
    `ler` chama o ONR e, a cada resposta, abre uma transação curta para gravar
    o que veio. Uma ficha que falha não leva as outras.
"""
