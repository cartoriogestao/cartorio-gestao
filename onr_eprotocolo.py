def resumo_do_painel(con, *, agora: datetime, amb: str | None = None,
                     processo_ligado: bool = False, no_expediente: bool = True) -> dict:
    """O aviso do painel: quantos esperam prenotação, quantos têm aviso de
    contraditório e o horário da última leitura bem-sucedida."""
    init_schema(con)
    lista = fila_com_alertas(con, amb=amb)
    a_prenotar = [p for p in lista if p["situacao"] == "A_PRENOTAR"]
    contraditorios = [p for p in a_prenotar
                      if any(a["nivel"] == "perigo" for a in p["alertas"])]
    boa = ultima_leitura(con, amb)
    qualquer = ultima_leitura(con, amb, boa=False)
    minutos = None
    if boa and boa.get("terminada_em"):
        try:
            minutos = int((agora - datetime.fromisoformat(str(boa["terminada_em"])[:19]))
                          .total_seconds() // 60)
        except ValueError:
            minutos = None
    atrasada = bool(processo_ligado and no_expediente
                    and (minutos is None or minutos > MINUTOS_SEM_LEITURA_PARA_AVISAR))
    return {"a_prenotar": len(a_prenotar), "contraditorios": len(contraditorios),
            "abertos": len(lista), "ultima_boa": boa, "ultima": qualquer,
            "minutos_desde_a_boa": minutos, "atrasada": atrasada,
            "ultima_falhou": bool(qualquer and qualquer["situacao"] == "ERRO"),
            "processo_ligado": processo_ligado}


def processo_ligado(con) -> bool:
    """O processo da central está ligado? (`au_processos.ativo`). Sem a tabela, não."""
    bd = banco(con)
    if not bd.tem_tabela("au_processos"):
        return False
    return bool(bd.valor("SELECT ativo FROM au_processos WHERE codigo=%s", (CODIGO_DO_PROCESSO,)))


