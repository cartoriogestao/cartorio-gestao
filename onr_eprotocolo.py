def fila(con, *, todos: bool = False, amb: str | None = None) -> list[dict]:
    """Os pedidos NA ORDEM DA REMESSA (CNN 326). Sem a ficha, a data da
    solicitação faz as vezes da remessa até a ficha chegar."""
    init_schema(con)
    filtros, args = [], []
    if not todos:
        filtros.append("situacao IN ('A_PRENOTAR','EM_ANDAMENTO')")
    if amb:
        filtros.append("ambiente=%s")
        args.append(amb)
    onde = f"WHERE {' AND '.join(filtros)}" if filtros else ""
    linhas = banco(con).ler(
        f"SELECT * FROM onr_ep_pedidos {onde} ORDER BY "
        "COALESCE(NULLIF(data_remessa,''), NULLIF(data_solicitacao,''), recebido_em), "
        "id_contrato, id", tuple(args))
    return [dict(x) for x in linhas]


