class Gravador:
    """O transporte do WSOficio com memória: guarda o texto da última resposta
    de cada método, para congelar o XML exatamente como o ONR o mandou."""

    def __init__(self, transporte=None):
        self._transporte = transporte or WS._transporte_da_casa
        self.ultima: dict[str, str] = {}
        self.metodos: list[str] = []

    def __call__(self, url: str, corpo: bytes, acao: str) -> tuple[int, str]:
        metodo = acao.rsplit("/", 1)[-1]
        self.metodos.append(metodo)
        status, texto = self._transporte(url, corpo, acao)
        self.ultima[metodo] = texto
        return status, texto


def abrir_leitura(con, amb: str, origem: str, agora: str) -> int:
    init_schema(con)
    r = banco(con).escrever("INSERT INTO onr_ep_leituras(ambiente, origem, iniciada_em) "
                            "VALUES (%s,%s,%s) RETURNING id", (amb, origem, agora))
    return int(r[0]["id"])


def fechar_leitura(con, leitura_id: int, situacao: str, agora: str, *, listados=0, novos=0,
                   atualizados=0, fichas=0, erro: str | None = None) -> None:
    banco(con).escrever(
        "UPDATE onr_ep_leituras SET situacao=%s, terminada_em=%s, listados=%s, novos=%s, "
        "atualizados=%s, fichas=%s, erro=%s WHERE id=%s",
        (situacao, agora, listados, novos, atualizados, fichas,
         (str(erro)[:800] if erro else None), int(leitura_id)))


def ler(db, amb: str, *, hoje: date, agora: Callable[[], str], origem: str = ORIGEM_ROBO,
        dias: int = 30, fichas_por_leitura: int = 25, paginas_no_maximo: int = 20,
        pasta=None, transporte=None, certificado: dict | None = None) -> dict:
    """Uma leitura inteira do e-Protocolo: lista, fichas novas, anexos. SÓ LÊ.

    `db` tem `transaction()`; a rede acontece entre as transações. Cada chamada
    custa um login (o ONR devolve 1 token, medido em 09/10/2026), e por isso a
    leitura limita as fichas que pede: o que sobrar vem na próxima."""
    dias = max(1, min(180, int(dias or 30)))
    with db.transaction() as con:
        leitura_id = abrir_leitura(con, amb, origem, agora())
    gravador = Gravador(transporte)
    numeros = {"listados": 0, "novos": 0, "atualizados": 0, "fichas": 0}
    falhas: list[str] = []
    try:
        sessao = WS.Sessao(ambiente=amb, pasta=pasta, transporte=gravador,
                           certificado=certificado)
        de, ate = (hoje - timedelta(days=dias)).isoformat(), hoje.isoformat()
        pendentes: list[tuple[int, dict, str]] = []
        pagina, paginas = 1, 1
        while pagina <= min(paginas, paginas_no_maximo):
            sessao.pedidos_do_eprotocolo(de=de, ate=ate, pagina=pagina)
            itens, paginas = itens_da_lista(gravador.ultima["ListPedidosAC"])
            with db.transaction() as con:
                for item in itens:
                    r = guardar_da_lista(con, amb, item, agora())
                    numeros["listados"] += 1
                    numeros["novos"] += 1 if r["novo"] else 0
                    numeros["atualizados"] += 1 if r["mudou"] else 0
                    if r["ficha"] or r["anexos"]:
                        pendentes.append((r["pedido_id"], r, item["protocolo"]))
            pagina += 1
    except (WS.WSOficioError, EProtocoloRIError, ValueError, OSError) as erro:
        motivo = f"{type(erro).__name__}: {erro}"
        with db.transaction() as con:
            fechar_leitura(con, leitura_id, "ERRO", agora(), erro=motivo, **numeros)
        return {"situacao": "ERRO", "erro": motivo, "leitura_id": leitura_id, "falhas": [],
                "sobraram": 0, **numeros}
    sobraram = max(0, len(pendentes) - fichas_por_leitura)
    for pedido_id, r, protocolo in pendentes[:fichas_por_leitura]:
        id_contrato = _id_contrato(db, pedido_id)
        try:
            if r["ficha"]:
                sessao.pedido_do_eprotocolo(id_contrato)
                xml_ficha = resultado_cru(gravador.ultima["GetPedidoAC_V8"], "GetPedidoAC_V8")
                with db.transaction() as con:
                    guardar_ficha(con, pedido_id, xml_ficha, agora())
                numeros["fichas"] += 1
            sessao.anexos_do_eprotocolo(id_contrato)
            with db.transaction() as con:
                guardar_anexos(con, pedido_id, gravador.ultima["ListAnexosAC"], agora())
        except (WS.WSOficioError, EProtocoloRIError, ValueError, OSError) as erro:
            motivo = f"{type(erro).__name__}: {erro}"[:400]
            falhas.append(f"{protocolo or id_contrato}: {motivo}")
            with db.transaction() as con:
                anotar_erro_da_ficha(con, pedido_id, motivo, agora())
    situacao = "PARCIAL" if falhas else "OK"
    with db.transaction() as con:
        fechar_leitura(con, leitura_id, situacao, agora(),
                       erro=" | ".join(falhas) if falhas else None, **numeros)
    return {"situacao": situacao, "leitura_id": leitura_id, "falhas": falhas,
            "sobraram": sobraram, "metodos": list(gravador.metodos), **numeros}


def _id_contrato(db, pedido_id: int) -> int:
    with db.transaction() as con:
        return int(banco(con).valor("SELECT id_contrato FROM onr_ep_pedidos WHERE id=%s",
                                    (int(pedido_id),)))


def ultima_leitura(con, amb: str | None = None, *, boa: bool = True) -> dict | None:
    init_schema(con)
