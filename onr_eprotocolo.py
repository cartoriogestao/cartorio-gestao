_CITA_MATRICULA = re.compile(r"matr[íi]cula\s*(?:n[º°o.]*\s*)?([\d][\d.]*)", re.I)


def _citadas(*textos: Any) -> set[str]:
    return {RIDOM.normalizar_numero_matricula(m) for t in textos
            for m in _CITA_MATRICULA.findall(str(t or ""))}


def _numero_da_prenotacao(texto: Any) -> int | None:
    digitos = re.sub(r"\D", "", str(texto or ""))
    return int(digitos) if digitos else None


def _quando(remessa: str, outra: str) -> str:
    if not remessa or not outra:
        return ""
    return " (antes da remessa)" if outra[:10] < remessa[:10] else (
        " (no dia da remessa)" if outra[:10] == remessa[:10] else " (depois da remessa)")


def _br(data_texto: Any) -> str:
    d = str(data_texto or "")[:10]
    return f"{d[8:10]}/{d[5:7]}/{d[0:4]}" if re.fullmatch(r"\d{4}-\d{2}-\d{2}", d) else d


def alertas(con, p: dict, ims: list[dict] | None = None) -> list[dict]:
    """O que o escrevente precisa ver antes de prenotar. SÓ LÊ, e na hora.

    `nivel`: «perigo» (contraditório — CNN 326), «atencao» (constrição,
    mandado, gratuidade, CDA) e «info» (o que falta para ligar ao acervo)."""
    bd = banco(con)
    ims = imoveis(con, p["id"]) if ims is None else ims
    saida: list[dict] = []
    aberto = p.get("situacao") in ABERTAS
    remessa = p.get("data_remessa") or p.get("data_solicitacao") or ""
    propria = _numero_da_prenotacao(p.get("prenotacao_numero"))
    numeros = {im["matricula_numero"] for im in ims if im.get("matricula_numero")}
    ids = {int(im["matricula_id"]) for im in ims if im.get("matricula_id")}
    if aberto and (numeros or ids):
        tem = bd.tem_tabela
        if tem("ri_protocolos"):
            for pr in bd.ler(
                    "SELECT id, numero, data_prenotacao, matricula_id, matricula_numero, natureza_titulo "
                    "FROM ri_protocolos WHERE situacao IN ('ABERTO','DEVOLVIDO') "
                    "AND (matricula_id IS NOT NULL OR matricula_numero IS NOT NULL) "
                    "ORDER BY numero, id"):
                alvo = ((pr["matricula_id"] is not None and int(pr["matricula_id"]) in ids)
                        or RIDOM.normalizar_numero_matricula(pr["matricula_numero"]) in numeros)
                if not alvo:
                    continue
                if propria is not None and pr["numero"] == propria:
                    continue          # é a prenotação deste mesmo título
                # PELA HORA DA PRENOTAÇÃO (decisão de 24/11/2026): a que já está
                # prenotada vem antes do título que ainda não foi; se os dois já
                # foram, vale o número menor do Livro 1.
                if propria is not None and pr["numero"] is not None and pr["numero"] > propria:
                    quem = "prenotada DEPOIS deste título: a prioridade é deste"
                else:
                    quem = "já prenotada: pela hora da prenotação, ela tem prioridade sobre este título"
                saida.append({"tipo": "CONTRADITORIO_PRENOTACAO", "nivel": "perigo",
                              "protocolo_id": pr["id"],
                              "texto": f"Prenotação nº {pr['numero']} aberta sobre a mesma "
                                       f"matrícula, de {_br(pr['data_prenotacao'])}"
                                       f"{' — ' + pr['natureza_titulo'] if pr['natureza_titulo'] else ''}"
                                       f", {quem}."})
        if tem("cx_protocolos"):
            for cx in bd.ler(
                    "SELECT id, numero, data_abertura, ri_matricula_id, assunto, observacao "
                    "FROM cx_protocolos WHERE atribuicao='RI' AND situacao='ABERTO' "
                    "AND ri_protocolo_id IS NULL ORDER BY id"):
                ligado = cx["ri_matricula_id"] is not None and int(cx["ri_matricula_id"]) in ids
                citado = bool(_citadas(cx["assunto"], cx["observacao"]) & numeros)
                if not (ligado or citado):
                    continue
                como = "sobre a mesma matrícula" if ligado else "que cita o número da matrícula"
                ja = ("este título já está prenotado e tem a prioridade"
                      if propria is not None else
                      "nenhum dos dois está prenotado: a prioridade será do que for prenotado primeiro")
                saida.append({"tipo": "CONTRADITORIO_BALCAO", "nivel": "perigo",
                              "texto": f"Título de balcão no protocolo geral nº {cx['numero']}, "
                                       f"de {_br(cx['data_abertura'])}, ainda sem prenotação, "
                                       f"{como}. Pela hora da prenotação, {ja}."})
        if numeros:
            marcas = ",".join(["%s"] * len(numeros))
            for o in bd.ler(
                    f"SELECT DISTINCT p.id, p.protocolo, p.data_remessa, p.data_solicitacao "
                    f"FROM onr_ep_pedidos p JOIN onr_ep_imoveis i ON i.pedido_id = p.id "
                    f"WHERE p.id <> %s AND p.ambiente = %s "
                    f"AND p.situacao IN ('A_PRENOTAR','EM_ANDAMENTO') "
                    f"AND i.matricula_numero IN ({marcas}) ORDER BY p.id",
                    (int(p["id"]), p["ambiente"], *sorted(numeros))):
                outra = o["data_remessa"] or o["data_solicitacao"] or ""
                saida.append({"tipo": "CONTRADITORIO_ELETRONICO", "nivel": "perigo",
                              "pedido_id": o["id"],
                              "texto": f"Outro título do e-Protocolo ({o['protocolo'] or 'sem protocolo'}), "
                                       f"remetido em {_br(outra)}{_quando(remessa, outra)}, "
                                       "sobre a mesma matrícula. Entre os eletrônicos, a "
                                       "prenotação segue a ordem da remessa (CNN 326)."})
    if p.get("constricao_tipo") or p.get("constricao_processo"):
        detalhe = ", ".join(x for x in (
            p.get("constricao_tipo"),
            f"processo {p['constricao_processo']}" if p.get("constricao_processo") else "",
            p.get("constricao_vara"),
            f"valor {p['constricao_valor']}" if p.get("constricao_valor") else "") if x)
        saida.append({"tipo": "CONSTRICAO", "nivel": "atencao",
                      "texto": f"Pedido de constrição: {detalhe}."})
    if p.get("url_mandado"):
        saida.append({"tipo": "MANDADO", "nivel": "atencao",
                      "texto": "Veio com mandado judicial (arquivo no ONR)."})
    if (p.get("tipo_isencao") == 1 or p.get("tipo_cobranca") == 3
            or p.get("url_gratuidade")):
        fund = f" Fundamento: {p['fundamento_legal']}." if p.get("fundamento_legal") else ""
        saida.append({"tipo": "GRATUIDADE", "nivel": "atencao",
                      "texto": "Pedido com gratuidade ("
                               f"{WS.TIPO_COBRANCA_EPROTOCOLO.get(p.get('tipo_cobranca'), 'cobrança')}"
                               f"; {WS.TIPO_ISENCAO_EPROTOCOLO.get(p.get('tipo_isencao'), 'isenção a conferir')})."
                               + fund})
    if p.get("tem_cda"):
        saida.append({"tipo": "CDA", "nivel": "atencao",
                      "texto": "Pedido de averbação de CDA (dívida ativa)."})
    if p.get("ficha_lida") and aberto:
        if not ims:
            saida.append({"tipo": "SEM_IMOVEL", "nivel": "info",
                          "texto": "A ficha não indica matrícula: o controle de contraditórios "
                                   "não tem por onde conferir."})
        for im in ims:
            if im.get("matricula_numero") and not im.get("matricula_id"):
                saida.append({"tipo": "MATRICULA_FORA_DO_ACERVO", "nivel": "info",
                              "texto": f"A matrícula {im['matricula_texto']} não foi achada no "
                                       "acervo deste sistema."})
    if p.get("id_status") is not None and p["id_status"] not in WS.STATUS_EPROTOCOLO:
        saida.append({"tipo": "STATUS_DESCONHECIDO", "nivel": "info",
                      "texto": f"Status {p['id_status']} não está no manual 4.43."})
    return saida


def fila_com_alertas(con, *, todos: bool = False, amb: str | None = None) -> list[dict]:
    lista = fila(con, todos=todos, amb=amb)
    posicao = 0
    for p in lista:
        p["imoveis"] = imoveis(con, p["id"])
        p["alertas"] = alertas(con, p, p["imoveis"])
        if p["situacao"] == "A_PRENOTAR":
            posicao += 1
            p["posicao"] = posicao
    return lista


