def rodada(ctx) -> dict:
    """O processo RI_ONR_EPROTOCOLO: uma leitura. Nada além disso."""
    import automacao_processos as PROC
    import automacao_schema as SCH
    amb = ambiente(ctx.setting)
    sit = WS.situacao(amb, pasta=ctx.pasta_dados)
    if not (sit["tem_chave"] and sit["id_parceiro"] and sit["cpf"] and sit["email"]):
        return PROC._sem_credencial("WSOfício (ID do parceiro, chave, CPF e e-mail)",
                                    "Registro de Imóveis → Certidões do ONR")

    def agora() -> str:
        return datetime.now().replace(microsecond=0).isoformat()

    par = getattr(ctx, "parametros", None) or {}
    r = ler(ctx.db, amb, hoje=ctx.hoje, agora=agora, origem=ORIGEM_ROBO,
            dias=int(par.get("dias", 30) or 30),
            fichas_por_leitura=max(1, min(100, int(par.get("fichas_por_leitura", 25) or 25))),
            pasta=ctx.pasta_dados)
    if r["situacao"] == "ERRO":
        return PROC._nao_mediu("os títulos do e-Protocolo do ONR", r["erro"])
    with ctx.db.connect() as con:
        lista = fila_com_alertas(con, amb=amb)
    a_prenotar = [p for p in lista if p["situacao"] == "A_PRENOTAR"]
    perigo = [p for p in a_prenotar if any(a["nivel"] == "perigo" for a in p["alertas"])]
    partes = [f"{r['listados']} na lista do ONR, {r['novos']} novo(s), {r['fichas']} ficha(s) lida(s)"]
    if a_prenotar:
        partes.append(f"{len(a_prenotar)} esperando prenotação")
    if perigo:
        partes.append(f"{len(perigo)} com possível contraditório (CNN 326)")
    if r["sobraram"]:
        partes.append(f"{r['sobraram']} ficha(s) ficaram para a próxima rodada")
    if r["falhas"]:
        partes.append("falhas: " + " | ".join(r["falhas"]))
    relato = ("e-Protocolo do RI: " + "; ".join(partes) + ".")[:1500]
    achados = [{"protocolo": p["protocolo"], "posicao": p.get("posicao"),
                "remessa": p.get("data_remessa"),
                "alertas": [a["tipo"] for a in p["alertas"]]} for p in a_prenotar]
    acoes = [{"acao": "leu o e-Protocolo do ONR", "leitura_id": r["leitura_id"],
              "listados": r["listados"], "novos": r["novos"], "fichas": r["fichas"]}]
    if r["falhas"]:
        return PROC.resultado(SCH.ERRO, relato, achados, acoes)
    if a_prenotar:
        return PROC.resultado(SCH.AVISO, relato, achados, acoes)
    return PROC.resultado(SCH.OK, relato, achados, acoes)
