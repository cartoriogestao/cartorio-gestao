"""A prenotação, com um clique do escrevente, do título que chegou pelo e-Protocolo
do ONR (RI013, etapa P2a, 25/11/2026).

O QUE ESTA ETAPA FAZ — E O QUE NÃO FAZ
    Leva o título da fila do e-Protocolo (P1) à MESMA tela e à MESMA rota da
    prenotação de balcão (`/registro-imoveis/protocolo`), com o formulário já
    preenchido. Não há um segundo jeito de criar prenotação: o número, a data,
    o prazo, o protocolo geral, o andamento e o selo saem do caminho de sempre.
    **Nada se envia ao ONR.** O aviso da prenotação ao ONR (`SetPrenotacaoAC`)
    é da P2b; esta etapa grava o vínculo e só MOSTRA o que a P2b vai mandar.

A ORDEM É A DA REMESSA (CNN 326), E PULAR PEDE MOTIVO ESCRITO
    O botão «Prenotar este título» só fica ativo no título eletrônico mais
    antigo ainda não prenotado. Prenotar outro antes dele exige um motivo
    escrito, que fica em `onr_ep_pulos` e vai para a auditoria. A rota da
    prenotação confere a ordem DE NOVO ao gravar: a tela pode estar velha.

A PRIORIDADE VALE PELA HORA DA PRENOTAÇÃO — decisão do titular, 24/11/2026
    (`onr_eprotocolo.REGRA_DE_PRIORIDADE`). Por isso a fila diz há quanto tempo
    o mais antigo espera: entre o balcão e o eletrônico, a demora custa a
    prioridade do título que chegou pela Central.

O SELO É O DE SEMPRE
    O mesmo da prenotação de balcão (`/selo/imovel/prenotacao`). O selo «pago
    na Central» da prenotação eletrônica depende de confirmação no TJMA e fica
    para a P2b.

NENHUMA FUNÇÃO DAQUI FALA COM A REDE.
"""
from __future__ import annotations

import json
from datetime import datetime
from typing import Any

import onr_eprotocolo as EP
import onr_wsoficio as WS
from bd_nativo import banco

#: A origem gravada em `ri_protocolos.origem`; `origem_chave` leva o IDContrato.
ORIGEM = "ONR_EPROTOCOLO"
ROTULO_DA_ORIGEM = "e-Protocolo ONR"
#: Motivo de pulo curto demais não diz nada a quem audita.
MOTIVO_MINIMO = 10

SCHEMA = """
CREATE UNIQUE INDEX IF NOT EXISTS ux_onr_ep_pedidos_prenotacao
    ON onr_ep_pedidos(prenotacao_id) WHERE prenotacao_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS onr_ep_pulos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id bigint NOT NULL REFERENCES onr_ep_pedidos(id),
    pulados_json TEXT NOT NULL DEFAULT '[]',
    motivo TEXT NOT NULL,
    quem_id bigint,
    quem_nome TEXT,
    em TEXT NOT NULL,
    protocolo_id bigint,
    usado_em TEXT
);
CREATE INDEX IF NOT EXISTS ix_onr_ep_pulos_pedido ON onr_ep_pulos(pedido_id);
"""


class PrenotacaoEletronicaError(EP.EProtocoloRIError):
    """Recusa com frase de balcão. Nada foi prenotado e nenhum número se gastou."""


def init_schema(con) -> None:
    """As colunas do vínculo vêm de `EP.init_schema` (`COLUNAS_DA_P2A`)."""
    EP.init_schema(con)
    banco(con).escrever(SCHEMA)


# ------------------------------------------------------------ a fila e a ordem

def esperando(con, amb: str | None = None) -> list[dict]:
    """Os que esperam prenotação, NA ORDEM DA REMESSA (a de `EP.fila`)."""
    init_schema(con)
    return [p for p in EP.fila(con, amb=amb)
            if p["situacao"] == "A_PRENOTAR" and not p.get("prenotacao_id")]


def a_frente(con, p: dict) -> list[dict]:
    """Os títulos eletrônicos que esperam ANTES deste (vazio: é a vez dele)."""
    fila = esperando(con, p.get("ambiente"))
    ids = [x["id"] for x in fila]
    if p["id"] not in ids:
        return []
    return fila[:ids.index(p["id"])]


def espera(con, *, agora: datetime, amb: str | None = None) -> dict:
    """Quantos esperam e há quanto tempo o mais antigo chegou aqui."""
    fila = esperando(con, amb)
    mais_antigo = fila[0] if fila else None
    return {"quantos": len(fila), "mais_antigo": mais_antigo,
            "texto": EP.ha_quanto_tempo(mais_antigo["recebido_em"], agora) if mais_antigo else ""}


# ------------------------------------------------------------ pular a ordem

def registrar_pulo(con, pedido_id: int, motivo: str, *, quem_id: int | None,
                   quem_nome: str | None, agora: str) -> dict:
    """Grava o pulo da ordem, com o motivo. ESCREVE (e a rota audita).

    Recusa o motivo vazio ou curto, o título que já é o primeiro (não há o que
    pular) e o que não espera prenotação."""
    init_schema(con)
    p = EP.pedido(con, pedido_id)
    if p["situacao"] != "A_PRENOTAR" or p.get("prenotacao_id"):
        raise PrenotacaoEletronicaError("Este título não espera prenotação.")
    texto = " ".join(str(motivo or "").split())
    if len(texto) < MOTIVO_MINIMO:
        raise PrenotacaoEletronicaError(
            "Para prenotar fora da ordem da remessa, escreva o motivo "
            f"(pelo menos {MOTIVO_MINIMO} letras). Ele vai para a auditoria.")
    pulados = a_frente(con, p)
    if not pulados:
        raise PrenotacaoEletronicaError(
            "Este título já é o primeiro da fila: não há o que pular.")
    ids = [int(x["id"]) for x in pulados]
    novo = banco(con).escrever(
        "INSERT INTO onr_ep_pulos(pedido_id, pulados_json, motivo, quem_id, quem_nome, em) "
        "VALUES (%s,%s,%s,%s,%s,%s) RETURNING id",
        (int(pedido_id), json.dumps(ids), texto, quem_id, quem_nome, agora))
    return {"pulo_id": int(novo[0]["id"]), "pedido_id": int(pedido_id), "motivo": texto,
            "pulados": ids,
            "pulados_protocolos": [x.get("protocolo") or str(x["id_contrato"]) for x in pulados]}


def pulo_valido(con, pulo_id: Any, pedido_id: int) -> dict | None:
    """O pulo ainda não usado DESTE título (outro título não aproveita)."""
    try:
        pid = int(str(pulo_id).strip())
    except (TypeError, ValueError):
        return None
    row = banco(con).um("SELECT * FROM onr_ep_pulos WHERE id=%s AND pedido_id=%s "
                        "AND protocolo_id IS NULL", (pid, int(pedido_id)))
    return dict(row) if row else None


# ------------------------------------------------------------ conferir e preencher

def conferir(con, pedido_id: Any, *, pulo_id: Any = None) -> dict:
    """O título pode ser prenotado AGORA? Devolve o pedido, ou recusa.

    Confere: existe, espera prenotação, a ficha foi lida e é a vez dele — ou
    há um pulo com motivo, deste título, ainda não usado."""
    init_schema(con)
    try:
        pid = int(str(pedido_id).strip())
    except (TypeError, ValueError) as erro:
        raise PrenotacaoEletronicaError(
            "Não achei o título do e-Protocolo. Nada foi prenotado.") from erro
    try:
        p = EP.pedido(con, pid)
    except EP.EProtocoloRIError as erro:
        raise PrenotacaoEletronicaError(
            "Não achei o título do e-Protocolo. Nada foi prenotado.") from erro
    if p.get("prenotacao_id"):
        raise PrenotacaoEletronicaError(
            "Este título do e-Protocolo já foi prenotado. Nada foi prenotado de novo.")
    if p["situacao"] != "A_PRENOTAR":
        raise PrenotacaoEletronicaError(
            "Este título do e-Protocolo não espera prenotação (o ONR diz que ele está "
            f"«{EP.rotulo_do_status(p.get('id_status')) or p['situacao']}»). Nada foi prenotado.")
    if not p.get("ficha_lida"):
        raise PrenotacaoEletronicaError(
            "A ficha deste título ainda não veio do ONR: espere a próxima leitura. "
            "Nada foi prenotado.")
    antes = a_frente(con, p)
    p["pulo"] = None
    if antes:
        pulo = pulo_valido(con, pulo_id, pid)
        if not pulo:
            primeiro = antes[0]
            raise PrenotacaoEletronicaError(
                f"Há {len(antes)} título(s) do e-Protocolo remetido(s) antes deste — o "
                f"primeiro é o {primeiro.get('protocolo') or primeiro['id_contrato']}. "
                "Entre os eletrônicos, prenota-se na ordem da remessa (CNN 326); para "
                "pular, escreva o motivo na fila. Nada foi prenotado.")
        p["pulo"] = pulo
    p["a_frente"] = antes
    return p


def _rotulo_servico(p: dict) -> str:
    return (EP.rotulo_do_tipo_servico(p.get("tipo_servico"))
            or EP.rotulo_do_tipo_servico(p.get("id_tipo_servico")) or "")


def _partes(p: dict) -> list[dict]:
    dados = p.get("dados") or {}
    bases = sorted({k[:-len("/Nome")] for k in dados
                    if k.startswith("Partes/") and k.endswith("/Nome")},
                   key=lambda b: int(b.split("/")[1]) if b.split("/")[1].isdigit() else 0)
    return [{"nome": dados.get(f"{b}/Nome", ""), "documento": dados.get(f"{b}/CPFCNPJ", ""),
             "qualidade": dados.get(f"{b}/Qualidade", "")} for b in bases]


def _contato(p: dict, *nomes: str) -> str:
    dados = p.get("dados") or {}
    for n in nomes:
        v = str(dados.get(f"DadosApresentante/{n}") or "").strip()
        if v:
            return v
    return ""


def ficha_para_prenotar(con, p: dict) -> dict:
    """O que o formulário da prenotação recebe já preenchido. SÓ LÊ.

    `campos` são os nomes do formulário do balcão; o resto é o que a tela
    mostra ao lado (as partes, os anexos, o valor, o IDContrato, os avisos)."""
    servico = _rotulo_servico(p)
    documento = WS.TIPO_DOCUMENTO_EPROTOCOLO.get(EP._inteiro(p.get("tipo_documento")), "")
    ims = p.get("imoveis") or EP.imoveis(con, p["id"])
    partes = _partes(p)
    anexos = p.get("anexos") or EP.anexos(con, p["id"])
    protocolo = p.get("protocolo") or ""
    natureza = " — ".join(x for x in (servico, documento) if x)
    primeiro = next((im for im in ims if im.get("matricula_numero")), None)
    nomes_dos_anexos = ", ".join(a.get("nome") or str(a["id_anexo"]) for a in anexos
                                 if a.get("grupo") == "CONTRATO")
    quem = "; ".join(f"{x['nome']} ({x['qualidade'].lower()})" if x["qualidade"] else x["nome"]
                     for x in partes if x["nome"])
    onde = "; ".join(f"matrícula {im['matricula_texto']}" + (f", {im['endereco']}" if im.get("endereco") else "")
                     for im in ims if im.get("matricula_texto"))
    objeto = ". ".join(x for x in (
        f"Título remetido pelo e-Protocolo do ONR, protocolo {protocolo or '—'} "
        f"(IDContrato {p['id_contrato']})",
        f"Partes: {quem}" if quem else "",
        f"Imóvel: {onde}" if onde else "") if x) + "."
    tel = _contato(p, "Telefone", "NumeroTelefone")
    ddd = _contato(p, "DDDTelefone", "DDD")
    campos = {
        "apresentante": p.get("apresentante_nome") or p.get("solicitante") or p.get("instituicao") or "",
        "apresentante_documento": p.get("apresentante_documento") or "",
        "natureza_titulo": natureza,
        "matricula_numero": primeiro["matricula_numero"] if primeiro else "",
        "objeto": objeto,
        "documento_descricao": (f"Título eletrônico (e-Protocolo ONR {protocolo})"
                                + (f": {nomes_dos_anexos}" if nomes_dos_anexos else "")),
        "anotacao": f"{ROTULO_DA_ORIGEM} — protocolo {protocolo or '—'}, IDContrato {p['id_contrato']}",
        "telefone": f"({ddd}) {tel}" if ddd and tel else tel,
        "email": _contato(p, "Email", "EMail"),
    }
    return {
        "pedido_id": int(p["id"]),
        "id_contrato": int(p["id_contrato"]),
        "protocolo": protocolo,
        "ambiente": p.get("ambiente"),
        "data_remessa": p.get("data_remessa") or "",
        "recebido_em": p.get("recebido_em") or "",
        "servico": servico,
        "valor": p.get("valor_servico") or "",
        "cobranca": WS.TIPO_COBRANCA_EPROTOCOLO.get(p.get("tipo_cobranca"), ""),
        "imoveis": [{"texto": im.get("matricula_texto") or "", "numero": im.get("matricula_numero") or "",
                     "matricula_id": im.get("matricula_id"), "endereco": im.get("endereco") or ""}
                    for im in ims],
        "partes": partes,
        "anexos": anexos,
        "alertas": EP.alertas(con, p, ims),
        "pulo": p.get("pulo"),
        "a_frente": len(p.get("a_frente") or []),
        "campos": campos,
    }


# ------------------------------------------------------------ o vínculo

def vincular(con, pedido_id: int, protocolo_id: int, *, quem_id: int | None,
             quem_nome: str | None, agora: str, pulo_id: int | None = None) -> None:
    """Liga o título à prenotação criada. ESCREVE, e TEM de ir na mesma
    transação do INSERT da prenotação: se outro escrevente prenotou o mesmo
    título no meio do caminho, a exceção desfaz a prenotação inteira."""
    bd = banco(con)
    feitas = bd.escrever(
        "UPDATE onr_ep_pedidos SET prenotacao_id=%s, prenotado_por=%s, prenotado_por_nome=%s, "
        "prenotado_em=%s, pulo_id=%s, situacao='EM_ANDAMENTO', atualizado_em=%s "
        "WHERE id=%s AND prenotacao_id IS NULL AND situacao='A_PRENOTAR' RETURNING id",
        (int(protocolo_id), quem_id, quem_nome, agora, pulo_id, agora, int(pedido_id)))
    if not feitas:
        raise PrenotacaoEletronicaError(
            "Este título do e-Protocolo foi prenotado por outra pessoa enquanto a tela "
            "estava aberta. Nada foi prenotado.")
    if pulo_id is not None:
        bd.escrever("UPDATE onr_ep_pulos SET protocolo_id=%s, usado_em=%s WHERE id=%s",
                    (int(protocolo_id), agora, int(pulo_id)))


def para_o_onr(con, p: dict) -> dict | None:
    """O que a P2b vai mandar pelo `SetPrenotacaoAC` — a P2a SÓ MOSTRA.

    Campos do contrato (B0): IDContrato, NumeroPrenotacao, DataPrenotacao,
    DataVencimento, Senha. A casa não tem senha de consulta da prenotação:
    fica em branco até a P2b decidir."""
    if not p.get("prenotacao_id"):
        return None
    row = banco(con).um("SELECT id, numero, livro, data_prenotacao, hora, data_limite, origem, "
                        "origem_chave, situacao FROM ri_protocolos WHERE id=%s",
                        (int(p["prenotacao_id"]),))
    if not row:
        return None
    return {"protocolo_id": int(row["id"]), "IDContrato": int(p["id_contrato"]),
            "NumeroPrenotacao": str(row["numero"]), "DataPrenotacao": row["data_prenotacao"],
            "hora": row["hora"], "DataVencimento": row["data_limite"] or "", "Senha": "",
            "livro": row["livro"], "situacao": row["situacao"], "origem": row["origem"],
            "origem_chave": row["origem_chave"], "enviado": False}
