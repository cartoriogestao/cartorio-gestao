"""A e-Intimação do RI pelo ONR — a LEITURA dos pedidos (A005, a etapa que faltava ao RI013).

    «vamos fazer [...] para o item sair de vez» — o oficial, 27/11/2026, sobre
    a ROT-RI-02 da Rotina da serventia, que ficou só com as intimações porque o
    sistema não as lia.

O QUE É
    O serviço `intimacoes.asmx` do WSOfício (manual 4.43, cap. 3.11): os pedidos
    de intimação (alienação fiduciária) que o credor remete a esta serventia
    pelo ONR. O transporte é o da PR #531 (RI013 B0): `Sessao.status_da_intimacao`
    (`ListStatusIN`) e `Sessao.pedidos_da_intimacao` (`ListPedidosIN`).

O QUE ESTA ETAPA FAZ — E SÓ ISSO
    Lê. A tabela de status do serviço e a lista dos pedidos dos últimos dias,
    gravadas em tabela própria (`onr_in_status`, `onr_in_pedidos`), com cada
    leitura registrada (`onr_in_leituras`). **Nada se responde ao ONR**: as
    mensagens, as custas e os cancelamentos continuam presos em
    `onr_wsoficio.ESPERAM_O_PODE_DO_TITULAR`. Não abre a ficha (`GetDetalhesIN`)
    nem lista mensagens: a lista basta para saber se o pedido está parado, e
    ler mensagem pode marcá-la como lida do lado de lá.

«PARADO» DEPENDE DE UMA TABELA QUE SÓ O ONR TEM
    O status do PEDIDO de intimação não está no manual: vem de `ListStatusIN`.
    Por isso a regra mora em configuração (`CHAVE_STATUS_PARADOS`, os IDStatus em
    que a vez é da casa) e a tela mostra a tabela lida, com o que conta. Enquanto
    ninguém marcar, vale a SUGESTÃO pelo nome do status (`sugerir_parados`):
    aberto, novo, recebido, reaberto, aguardando o cartório. A tela diz que é
    sugestão, e o titular confere na primeira leitura.
    «Desde quando» é a `DataStatus` (o pedido entrou no status atual), senão a
    `DataPedido`.

QUEM COBRA
    Ninguém daqui. A cobrança é a da A005 (`onr_pedidos_avisos`, fonte
    INTIMACAO): aviso simples no 1º dia útil, faixa vermelha do 2º em diante,
    na tela da responsável pelos pedidos do ONR. Por isso a rodada deste
    processo fica OK com pedido parado (AVISO abriria tarefa para o admin).

A REDE NUNCA ACONTECE DENTRO DE `db.transaction()`.
"""
from __future__ import annotations

import re
import unicodedata
from datetime import date, datetime, timedelta
from typing import Any, Callable

import onr_wsoficio as WS
from bd_nativo import banco

CODIGO_DO_PROCESSO = "RI_ONR_INTIMACOES"
CHAVE_DO_AMBIENTE = "onr_intimacoes_ambiente"
#: Os IDStatus (separados por vírgula) em que a vez é da casa. Vazio: a sugestão.
CHAVE_STATUS_PARADOS = "onr_intimacoes_status_parados"
ORIGEM_ROBO, ORIGEM_TELA = "ROBO", "TELA"
LEITURA_BOA = ("OK",)
#: Uma leitura boa mais velha que isto não mede: a fonte fica «não medida».
HORAS_PARA_A_LEITURA_VALER = 26

SCHEMA = """
CREATE TABLE IF NOT EXISTS onr_in_status (
    ambiente TEXT NOT NULL,
    id_status INTEGER NOT NULL,
    nome TEXT NOT NULL,
    visto_em TEXT NOT NULL,
    PRIMARY KEY (ambiente, id_status)
);

CREATE TABLE IF NOT EXISTS onr_in_pedidos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ambiente TEXT NOT NULL,
    id_pedido bigint NOT NULL,
    protocolo TEXT NOT NULL DEFAULT '',
    solicitante TEXT,
    id_status INTEGER,
    data_pedido TEXT,
    data_status TEXT,
    recebido_em TEXT NOT NULL,
    status_em TEXT,
    atualizado_em TEXT NOT NULL,
    UNIQUE (ambiente, id_pedido)
);
CREATE INDEX IF NOT EXISTS ix_onr_in_pedidos_status ON onr_in_pedidos (ambiente, id_status);

CREATE TABLE IF NOT EXISTS onr_in_leituras (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ambiente TEXT NOT NULL,
    origem TEXT NOT NULL,
    iniciada_em TEXT NOT NULL,
    terminada_em TEXT,
    situacao TEXT NOT NULL DEFAULT 'RODANDO',
    listados INTEGER NOT NULL DEFAULT 0,
    novos INTEGER NOT NULL DEFAULT 0,
    mudaram INTEGER NOT NULL DEFAULT 0,
    erro TEXT
);
"""


class IntimacaoOnrError(ValueError):
    """Recusa com frase de balcão."""


def init_schema(con) -> None:
    banco(con).escrever(SCHEMA)


def ambiente(leitor: Callable[..., Any]) -> str:
    """Produção de fábrica, como o e-Protocolo: a credencial que existe é a de produção."""
    valor = str(leitor(CHAVE_DO_AMBIENTE, WS.PRODUCAO) or WS.PRODUCAO).strip().upper()
    return valor if valor in WS.BASE else WS.PRODUCAO


def _texto(v: Any) -> str:
    return "" if v is None else str(v).strip()


def _iso(v: Any) -> str | None:
    """A data do ONR em ISO (aaaa-mm-dd[Thh:mm:ss]); o que não for data → None."""
    d = WS.ler_data_do_onr(v) if not isinstance(v, (date, datetime)) else v
    if isinstance(d, datetime):
        return d.replace(microsecond=0).isoformat()
    if isinstance(d, date):
        return d.isoformat()
    return None


# ------------------------------------------------------------ o que conta como parado


def _sem_acento(t: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFD", t.lower())
                   if unicodedata.category(c) != "Mn")


#: A sugestão pelo nome: a vez é da casa. O que fala de pagamento, de devedor,
#: de cancelado, de concluído ou de devolvido não entra.
_NOME_PARADO = re.compile(r"\b(em aberto|aberto|novo|nova|recebid[oa]|reaberto|"
                          r"aguardando (o )?(cartorio|serventia|registro)|pendente (do|no) cartorio)\b")
_NOME_DE_FORA = re.compile(r"(pag|devedor|cancel|conclu|finaliz|devolv|arquiv|desist|intimad)")


def sugerir_parados(status: list[dict]) -> set[int]:
    """Os IDStatus cujo NOME diz que a vez é da casa. Só a sugestão: o titular confere."""
    saida = set()
    for s in status:
        nome = _sem_acento(_texto(s.get("nome")))
        if _NOME_PARADO.search(nome) and not _NOME_DE_FORA.search(nome):
            saida.add(int(s["id_status"]))
    return saida


def status_lidos(con, amb: str) -> list[dict]:
    bd = banco(con)
    if not bd.tem_tabela("onr_in_status"):
        return []
    return [dict(r) for r in bd.ler(
        "SELECT id_status, nome, visto_em FROM onr_in_status WHERE ambiente=%s ORDER BY id_status",
        (amb,))]


def regra_dos_parados(con, amb: str, leitor: Callable[..., Any]) -> dict:
    """Quais IDStatus contam como parados, e de onde veio a regra. Só LÊ.

    {ids: set, de_onde: CONFIGURADO|SUGESTAO|SEM_TABELA, status: [...]}"""
    status = status_lidos(con, amb)
    bruto = _texto(leitor(CHAVE_STATUS_PARADOS, ""))
    if bruto:
        ids = {int(x) for x in re.findall(r"-?\d+", bruto)}
        return {"ids": ids, "de_onde": "CONFIGURADO", "status": status}
    if not status:
        return {"ids": set(), "de_onde": "SEM_TABELA", "status": status}
    return {"ids": sugerir_parados(status), "de_onde": "SUGESTAO", "status": status}


def guardar_regra(valores: list[Any], status: list[dict]) -> str:
    """Os IDStatus marcados na tela → o valor da configuração. Só confere.

    Recusa código que a tabela lida não tem: marcar o que o ONR não usa seria
    medir nada achando que mede."""
    conhecidos = {int(s["id_status"]) for s in status}
    ids = set()
    for v in valores:
        t = _texto(v)
        if not re.fullmatch(r"-?\d+", t):
            raise IntimacaoOnrError("Marque os status pela lista.")
        if int(t) not in conhecidos:
            raise IntimacaoOnrError(f"O status {t} não está na tabela lida do ONR.")
        ids.add(int(t))
    if not ids:
        raise IntimacaoOnrError("Marque ao menos um status, ou volte à sugestão.")
    return ",".join(str(i) for i in sorted(ids))


# ------------------------------------------------------------------ gravar


def abrir_leitura(con, amb: str, origem: str, agora: str) -> int:
    init_schema(con)
    return int(banco(con).escrever(
        "INSERT INTO onr_in_leituras (ambiente, origem, iniciada_em) VALUES (%s,%s,%s) RETURNING id",
        (amb, origem, agora))[0]["id"])


def fechar_leitura(con, leitura_id: int, situacao: str, agora: str, *, erro: str | None = None,
                   listados: int = 0, novos: int = 0, mudaram: int = 0) -> None:
    banco(con).escrever(
        "UPDATE onr_in_leituras SET situacao=%s, terminada_em=%s, erro=%s, listados=%s, "
        "novos=%s, mudaram=%s WHERE id=%s",
        (situacao, agora, (erro or None) and erro[:600], listados, novos, mudaram, leitura_id))


def guardar_status(con, amb: str, status: list[dict], agora: str) -> int:
    """A tabela de status do ONR, como veio. Status que sumiu da tabela fica (histórico)."""
    bd = banco(con)
    n = 0
    for s in status:
        if s.get("IDStatus") is None:
            continue
        bd.escrever(
            """INSERT INTO onr_in_status (ambiente, id_status, nome, visto_em) VALUES (%s,%s,%s,%s)
               ON CONFLICT (ambiente, id_status) DO UPDATE SET nome=EXCLUDED.nome,
                   visto_em=EXCLUDED.visto_em""",
            (amb, int(s["IDStatus"]), _texto(s.get("NomeStatus"))[:200] or f"status {s['IDStatus']}",
             agora))
        n += 1
    return n


def guardar_pedido(con, amb: str, p: dict, agora: str) -> dict:
    """Um pedido da lista: novo entra; o que já estava muda só o que o ONR mudou."""
    if p.get("IDPedido") is None:
        raise IntimacaoOnrError("O ONR mandou um pedido de intimação sem IDPedido.")
    bd = banco(con)
    ident = int(p["IDPedido"])
    campos = (_texto(p.get("Protocolo"))[:120], _texto(p.get("Solicitante"))[:200] or None,
              p.get("IDStatus"), _iso(p.get("DataPedido")), _iso(p.get("DataStatus")))
    r = bd.um("SELECT id, id_status FROM onr_in_pedidos WHERE ambiente=%s AND id_pedido=%s",
              (amb, ident))
    if r is None:
        bd.escrever(
            """INSERT INTO onr_in_pedidos (ambiente, id_pedido, protocolo, solicitante, id_status,
                   data_pedido, data_status, recebido_em, status_em, atualizado_em)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
            (amb, ident, *campos, agora, agora, agora))
        return {"novo": True, "mudou": False}
    mudou = r["id_status"] != campos[2]
    bd.escrever(
        """UPDATE onr_in_pedidos SET protocolo=%s, solicitante=%s, id_status=%s, data_pedido=%s,
               data_status=%s, atualizado_em=%s,
               status_em=CASE WHEN %s THEN %s ELSE status_em END
           WHERE id=%s""",
        (*campos, agora, mudou, agora, r["id"]))
    return {"novo": False, "mudou": mudou}


# ------------------------------------------------------------------ ler (a rede)


def ler(db, amb: str, *, hoje: date, agora: Callable[[], str], origem: str = ORIGEM_ROBO,
        dias: int = 90, paginas_no_maximo: int = 20, pasta=None, sessao=None) -> dict:
    """Uma leitura: a tabela de status e a lista dos pedidos. SÓ LÊ o ONR.

    `sessao` é para o teste (um objeto com `status_da_intimacao` e
    `pedidos_da_intimacao`); sem ela, a sessão do WSOfício da casa."""
    dias = max(1, min(365, int(dias or 90)))
    with db.transaction() as con:
        leitura_id = abrir_leitura(con, amb, origem, agora())
    numeros = {"listados": 0, "novos": 0, "mudaram": 0}
    try:
        sessao = sessao or WS.Sessao(ambiente=amb, pasta=pasta)
        status = sessao.status_da_intimacao()
        with db.transaction() as con:
            guardar_status(con, amb, status, agora())
        de, ate = (hoje - timedelta(days=dias)).isoformat(), hoje.isoformat()
        pagina, paginas = 1, 1
        while pagina <= min(paginas, paginas_no_maximo):
            r = sessao.pedidos_da_intimacao(de=de, ate=ate, pagina=pagina)
            paginas = int(r.get("qtde_paginas") or 1)
            with db.transaction() as con:
                for p in r.get("pedidos") or []:
                    g = guardar_pedido(con, amb, p, agora())
                    numeros["listados"] += 1
                    numeros["novos"] += 1 if g["novo"] else 0
                    numeros["mudaram"] += 1 if g["mudou"] else 0
            pagina += 1
    except (WS.WSOficioError, IntimacaoOnrError, ValueError, OSError) as erro:
        motivo = f"{type(erro).__name__}: {erro}"
        with db.transaction() as con:
            fechar_leitura(con, leitura_id, "ERRO", agora(), erro=motivo, **numeros)
        return {"situacao": "ERRO", "erro": motivo, "leitura_id": leitura_id, **numeros}
    with db.transaction() as con:
        fechar_leitura(con, leitura_id, "OK", agora(), **numeros)
    return {"situacao": "OK", "leitura_id": leitura_id, **numeros}


def ultima_leitura(con, amb: str, *, boa: bool = True) -> dict | None:
    bd = banco(con)
    if not bd.tem_tabela("onr_in_leituras"):
        return None
    filtro = " AND situacao='OK'" if boa else ""
    r = bd.um(f"SELECT * FROM onr_in_leituras WHERE ambiente=%s AND terminada_em IS NOT NULL{filtro} "
              "ORDER BY id DESC LIMIT 1", (amb,))
    return dict(r) if r else None


# ------------------------------------------------------------------ o que os outros leem


def parados(con, amb: str, leitor: Callable[..., Any], *, agora: datetime) -> list[dict] | None:
    """Os pedidos de intimação em que a vez é da casa. Só LÊ.

    None quando a fonte não se mede: nunca houve leitura boa, a última é velha
    (`HORAS_PARA_A_LEITURA_VALER`), ou ninguém sabe quais status contam (a
    tabela de status ainda não veio)."""
    boa = ultima_leitura(con, amb)
    if boa is None:
        return None
    try:
        quando = datetime.fromisoformat(str(boa["terminada_em"])[:19])
    except ValueError:
        return None
    if agora - quando > timedelta(hours=HORAS_PARA_A_LEITURA_VALER):
        return None
    regra = regra_dos_parados(con, amb, leitor)
    if not regra["ids"]:
        return None
    nomes = {int(s["id_status"]): s["nome"] for s in regra["status"]}
    bd = banco(con)
    marcas = ", ".join(["%s"] * len(regra["ids"]))
    saida = []
    for p in bd.ler(f"SELECT * FROM onr_in_pedidos WHERE ambiente=%s AND id_status IN ({marcas}) "
                    "ORDER BY COALESCE(data_status, data_pedido, recebido_em), id",
                    (amb, *sorted(regra["ids"]))):
        saida.append({**dict(p), "nome_status": nomes.get(p["id_status"], f"status {p['id_status']}"),
                      "desde": p["data_status"] or p["data_pedido"] or p["recebido_em"]})
    return saida


def quadro(con, amb: str, leitor: Callable[..., Any]) -> dict:
    """A tela: os pedidos, a tabela de status com o que conta, as leituras. Só LÊ."""
    bd = banco(con)
    regra = regra_dos_parados(con, amb, leitor)
    nomes = {int(s["id_status"]): s["nome"] for s in regra["status"]}
    pedidos = []
    if bd.tem_tabela("onr_in_pedidos"):
        pedidos = [{**dict(p), "nome_status": nomes.get(p["id_status"], f"status {p['id_status']}"),
                    "parado": p["id_status"] in regra["ids"]}
                   for p in bd.ler("SELECT * FROM onr_in_pedidos WHERE ambiente=%s "
                                   "ORDER BY COALESCE(data_status, data_pedido) DESC, id DESC "
                                   "LIMIT 300", (amb,))]
    return {"pedidos": pedidos, "regra": regra, "ultima_boa": ultima_leitura(con, amb),
            "ultima": ultima_leitura(con, amb, boa=False)}


def pedido(con, pedido_id: int) -> dict:
    bd = banco(con)
    r = bd.um("SELECT * FROM onr_in_pedidos WHERE id=%s", (int(pedido_id),)) \
        if bd.tem_tabela("onr_in_pedidos") else None
    if r is None:
        raise IntimacaoOnrError("Pedido de intimação não encontrado.")
    return dict(r)


