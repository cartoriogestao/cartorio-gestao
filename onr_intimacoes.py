def rodada_das_intimacoes(ctx) -> dict:
    """O processo RI_ONR_INTIMACOES: uma leitura. OK mesmo com pedido parado —
    a cobrança é da escrevente, pelos avisos da A005."""
    import automacao_processos as PROC
    import automacao_schema as SCH
    amb = ambiente(ctx.setting)
    sit = WS.situacao(amb, pasta=ctx.pasta_dados)
    if not (sit["tem_chave"] and sit["id_parceiro"] and sit["cpf"] and sit["email"]):
        return PROC._sem_credencial("WSOfício (ID do parceiro, chave, CPF e e-mail)",
                                    "Registro de Imóveis → Certidões do ONR")

    def agora() -> str:
        return datetime.now().replace(microsecond=0).isoformat()

    par = getattr(ctx, "parametros", None) or {}
    r = ler(ctx.db, amb, hoje=ctx.hoje, agora=agora, origem=ORIGEM_ROBO,
            dias=int(par.get("dias", 90) or 90), pasta=ctx.pasta_dados)
    if r["situacao"] == "ERRO":
        return PROC._nao_mediu("os pedidos de e-Intimação do ONR", r["erro"])
    with ctx.db.connect() as con:
        regra = regra_dos_parados(con, amb, ctx.setting)
        lista = parados(con, amb, ctx.setting, agora=ctx.agora) or []
    relato = (f"e-Intimação do RI: {r['listados']} pedido(s) na lista do ONR, {r['novos']} novo(s), "
              f"{r['mudaram']} mudaram de status; {len(lista)} com a vez da casa"
              + (" (status pela SUGESTÃO do nome; confira na tela)" if regra["de_onde"] == "SUGESTAO"
                 else "") + ".")
    acoes = [{"acao": "leu a e-Intimação do ONR", "leitura_id": r["leitura_id"],
              "listados": r["listados"], "novos": r["novos"]}]
    return PROC.resultado(SCH.OK, relato, [{"parados": len(lista), "regra": regra["de_onde"]}], acoes)
