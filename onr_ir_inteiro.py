"""O ARQUIVO INTEIRO DO INDICADOR REAL, por botão, em qualquer serventia.

    «as outras serventias que baixarem o programa precisam do botao»
                                                      — o oficial, 30/10/2026

O QUE ISTO SUBSTITUI
    O script `FERRAMENTAS/gerar_indicador_real_xml.py`, de 10 e 11/10/2026, que lia o banco antigo e
    trazia escritas nele as decisões de uma serventia: as fichas que ficam fora, os donos informados e
    a regra para o que a ficha não diz. Aqui elas viram dado, e cada serventia edita as suas na tela.
    Instalação nova nasce sem nenhuma ficha fora e sem nenhum dono informado.

O QUE SAI, E O QUE NÃO MUDA
    Sai todo imóvel ativo. A ordem do preenchimento é a de `onr_indicador_xml.completar_ficha`: o que a
    FICHA diz, depois o que o TEXTO da ficha diz, depois a REGRA desta serventia. **NENHUMA FICHA É
    ALTERADA, E NADA É ENVIADO:** a ficha completada e os donos vão só para o arquivo.

O CORPO É O MESMO DA API
    Quem monta cada indicador é `ri_onr_central.montar_indicador`, e quem veste em XML é
    `onr_indicador_xml`. Duas montagens divergiriam no primeiro conserto.

O MESMO NÚMERO EM DUAS FICHAS ATIVAS sairia duas vezes no índice. Vai a que tem mais partes, e a outra
aparece na lista das repetidas, como o script fazia em 11/10/2026.
"""
from __future__ import annotations

import csv
import io
import re
import zipfile
from typing import Any, Mapping

import cpf_cnpj as CC
import onr_api as API
import onr_endereco_do_teor as ENDERECO
import onr_indicador_xml as XML
import ri_onr_central as ONR
from bd_nativo import banco

SCHEMA = """
CREATE TABLE IF NOT EXISTS onr_ir_fichas_fora (
    numero TEXT PRIMARY KEY,
    motivo TEXT NOT NULL,
    por TEXT NOT NULL,
    em TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS onr_ir_donos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero TEXT NOT NULL,
    nome TEXT NOT NULL,
    documento TEXT,
    de_onde TEXT NOT NULL,
    por TEXT NOT NULL,
    em TEXT NOT NULL,
    UNIQUE (numero, nome)
);
"""

# A regra para o que nem a ficha nem o texto dizem. O padrão só vale enquanto a serventia não escrever
# a dela, e nenhum deles fala de uma serventia em particular.
#   chave em `settings`, campo que `completar_ficha` lê, rótulo na tela, padrão
REGRAS = (
    ("onr_ir_rural_padrao", "rural_padrao", "A ficha não diz se é rural ou urbana", "R"),
    ("onr_ir_numero", "numero", "A ficha não traz o número", ENDERECO.NUMERO_SEM_NUMERO),
    ("onr_ir_bairro_rural", "bairro_rural", "Imóvel rural sem bairro", ENDERECO.BAIRRO_RURAL),
    ("onr_ir_bairro_urbano", "bairro_urbano", "Imóvel urbano sem bairro", XML.BAIRRO_URBANO_SEM_NOME),
    ("onr_ir_logradouro_rural", "logradouro_rural", "Imóvel rural sem logradouro", XML.LOGRADOURO_RURAL_SEM_NOME),
    ("onr_ir_logradouro_urbano", "logradouro_urbano", "Imóvel urbano sem logradouro", XML.LOGRADOURO_URBANO_SEM_NOME),
    ("onr_ir_tipo_rural", "tipo_rural", "Tipo do imóvel rural, se a ficha não diz", XML.TIPO_RURAL),
    ("onr_ir_tipo_urbano", "tipo_urbano", "Tipo do imóvel urbano, se a ficha não diz", XML.TIPO_URBANO),
)
MENOR_MOTIVO = 10


class RegraError(ValueError):
    """O que não se pode gravar, com a frase pronta para o balcão."""


def init_schema(con) -> None:
    banco(con).escrever(SCHEMA)


def _texto(v: Any) -> str:
    return "" if v is None else str(v).strip()


def _digitos(v: Any) -> str:
    return "".join(c for c in _texto(v) if c.isdigit())


def _sem_marcas(texto: str) -> str:
    return re.sub(r"\*\*", "", texto or "")


# ------------------------------------------------------------ as regras


def regras_na_tela(settings: Mapping[str, Any]) -> list[dict]:
    return [{"chave": chave, "rotulo": rotulo, "padrao": padrao,
             "valor": _texto(settings.get(chave)) or padrao}
            for chave, _campo, rotulo, padrao in REGRAS]


def padrao_do_arquivo(settings: Mapping[str, Any]) -> dict:
    """O que `completar_ficha` lê: o que a casa guarda, mais a regra desta serventia."""
    padrao = ENDERECO.padrao_da_casa(dict(settings))
    for chave, campo, _rotulo, inicial in REGRAS:
        padrao[campo] = _texto(settings.get(chave)) or inicial
    return padrao


def conferir_regras(campos: Mapping[str, Any]) -> dict[str, str]:
    """As regras a gravar. Recusa o que o ONR recusaria depois, em cada ficha do arquivo."""
    saida: dict[str, str] = {}
    for chave, campo, rotulo, inicial in REGRAS:
        valor = _texto(campos.get(chave)) or inicial
        if len(valor) > 100:
            raise RegraError(f"«{rotulo}»: use até 100 letras.")
        if campo == "rural_padrao" and valor not in ("R", "U"):
            raise RegraError(f"«{rotulo}»: escolha rural ou urbano.")
        if campo.startswith("logradouro_") and ONR.partir_logradouro(valor)["tipo_codigo"] is None:
            raise RegraError(f"«{rotulo}»: o ONR exige que o logradouro comece por um tipo que ele "
                             f"conheça, como «Rua» ou «Fazenda». «{valor}» não começa.")
        if campo.startswith("tipo_") and API.sem_acento(valor) not in API.CODIGO_DO_IMOVEL:
            raise RegraError(f"«{rotulo}»: o tipo tem de ser um dos dez que o ONR aceita.")
        saida[chave] = valor
    return saida


def tipos_do_onr() -> list[str]:
    return sorted(API.TIPOS_DE_IMOVEL.values())


# ------------------------------------------------------------ o que a serventia decidiu


def _existe_a_ficha(con, numero: str) -> bool:
    return bool(banco(con).um(
        "SELECT 1 AS tem FROM ri_matriculas WHERE regexp_replace(numero, '[^0-9]', '', 'g') = %s LIMIT 1",
        (numero,)))


def fichas_fora(con) -> list[dict]:
    return banco(con).ler("SELECT numero, motivo, por, em FROM onr_ir_fichas_fora "
                          "ORDER BY length(numero), numero")


def donos_informados(con) -> list[dict]:
    return banco(con).ler("SELECT id, numero, nome, documento, de_onde, por, em FROM onr_ir_donos "
                          "ORDER BY length(numero), numero, id")


def por_fora(con, numero: Any, motivo: Any, *, por: str, agora: str) -> str:
    """Tira uma ficha do arquivo. Exige o motivo: quem ler o arquivo depois vai perguntar por quê."""
    n, m = _digitos(numero), _texto(motivo)
    if not n or not _existe_a_ficha(con, n):
        raise RegraError(f"Não há matrícula com o número «{_texto(numero)}».")
    if len(m) < MENOR_MOTIVO:
        raise RegraError(f"Escreva o motivo, com pelo menos {MENOR_MOTIVO} letras.")
    banco(con).escrever(
        """INSERT INTO onr_ir_fichas_fora (numero, motivo, por, em) VALUES (%s, %s, %s, %s)
           ON CONFLICT (numero) DO UPDATE SET motivo = EXCLUDED.motivo, por = EXCLUDED.por, em = EXCLUDED.em""",
        (n, m, por, agora))
    return n


def trazer_de_volta(con, numero: str) -> None:
    banco(con).escrever("DELETE FROM onr_ir_fichas_fora WHERE numero = %s", (numero,))


def informar_dono(con, numero: Any, nome: Any, documento: Any, de_onde: Any, *, por: str, agora: str) -> str:
    """Um dono que a ficha não traz. Vale para o arquivo, e não muda a ficha."""
    n, quem, origem = _digitos(numero), _texto(nome), _texto(de_onde)
    doc = CC.so_digitos(documento)
    if not n or not _existe_a_ficha(con, n):
        raise RegraError(f"Não há matrícula com o número «{_texto(numero)}».")
    if not quem:
        raise RegraError("Escreva o nome do proprietário.")
    if doc and CC.documento_valido(doc) is not True:
        raise RegraError(CC.mensagem_documento_invalido(doc))
    if len(origem) < MENOR_MOTIVO:
        raise RegraError(f"Diga de onde veio a informação, com pelo menos {MENOR_MOTIVO} letras.")
    banco(con).escrever(
        """INSERT INTO onr_ir_donos (numero, nome, documento, de_onde, por, em) VALUES (%s, %s, %s, %s, %s, %s)
           ON CONFLICT (numero, nome) DO UPDATE SET documento = EXCLUDED.documento,
               de_onde = EXCLUDED.de_onde, por = EXCLUDED.por, em = EXCLUDED.em""",
        (n, quem, doc or None, origem, por, agora))
    return n


def tirar_dono(con, dono_id: int) -> None:
    banco(con).escrever("DELETE FROM onr_ir_donos WHERE id = %s", (int(dono_id),))


# ------------------------------------------------------------ o cálculo


def calcular(con, *, settings: Mapping[str, Any], cns: Any) -> dict:
    """O que vai no arquivo, o que fica de fora e de onde veio cada coisa. SÓ LÊ."""
    from gestor_cargas_ri import NUMERO_DE_FICHA_ARQUIVADA
    bd = banco(con)
    padrao = padrao_do_arquivo(settings)
    fora_dela = {x["numero"]: x["motivo"] for x in fichas_fora(con)}
    informados: dict[str, list[dict]] = {}
    for d in donos_informados(con):
        informados.setdefault(d["numero"], []).append(d)

    saida: dict[str, Any] = {"corpos": [], "fora": [], "donos": [], "sem_dono": [], "repetidas": [],
                             "preenchido": [], "arquivadas": 0}
    ids, vistas = [], {}
    for x in bd.ler("""SELECT m.id, m.numero,
                              (SELECT COUNT(*) FROM ri_partes p WHERE p.matricula_id = m.id) AS partes
                         FROM ri_matriculas m WHERE COALESCE(m.encerrada, 0) = 0
                        ORDER BY partes DESC, m.id"""):
        if x["numero"] in vistas:
            saida["repetidas"].append({"numero": _texto(x["numero"]), "id_fora": x["id"],
                                       "id_que_vai": vistas[x["numero"]]})
            continue
        vistas[x["numero"]] = x["id"]
        ids.append(x["id"])

    for mid in sorted(ids):
        m = dict(bd.um("SELECT * FROM ri_matriculas WHERE id = %s", (mid,)))
        dig = _digitos(m.get("numero"))
        if not dig:
            saida["fora"].append({"id": mid, "numero": _texto(m.get("numero")), "motivo": "A ficha não tem número."})
            continue
        if int(dig) >= NUMERO_DE_FICHA_ARQUIVADA:
            saida["arquivadas"] += 1
            continue
        if dig in fora_dela:
            saida["fora"].append({"id": mid, "numero": dig, "motivo": "Decisão desta serventia: " + fora_dela[dig]})
            continue
        proposta = None
        if _texto(m.get("teor")):
            # A LEITURA DO TEXTO É AJUDA, E NÃO DERRUBA O ARQUIVO: sem ela, valem a ficha e a regra.
            try:
                proposta = ENDERECO.propor(m, settings=dict(settings), padrao=padrao)
            except Exception:                              # noqa: BLE001
                proposta = None
        ficha, origem = XML.completar_ficha(m, proposta, padrao)
        saida["preenchido"] += [{"numero": dig, "campo": c, "de_onde": de, "valor": _texto(ficha.get(c))}
                                for c, de in origem.items()]
        partes = [dict(p) for p in bd.ler("SELECT * FROM ri_partes WHERE matricula_id = %s ORDER BY id", (mid,))]
        nomes = {_texto(p.get("nome")) for p in partes}
        for d in informados.get(dig, []):
            if d["nome"] not in nomes:
                partes.append({"nome": d["nome"], "documento_numero": d["documento"], "papel": "proprietario",
                               "proprietario": 1, "proprietario_ativo": 1, "qualificacao": "ABERTURA · informado"})
                saida["donos"].append({"numero": dig, "nome": d["nome"], "de_onde": d["de_onde"]})
        atos = {int(a["id"]): (_texto(a["tipo"]).upper(), int(a["numero"] or 0))
                for a in bd.ler("SELECT id, tipo, numero FROM ri_atos WHERE matricula_id = %s", (mid,))}
        donos, de_onde = XML.donos_presumidos(partes, atos)
        if de_onde and de_onde != "ficha":
            saida["donos"] += [{"numero": dig, "nome": _texto(p.get("nome")), "de_onde": de_onde} for p in donos]
        elif not donos:
            saida["sem_dono"].append(dig)
        # A FICHA QUE NÃO SE MONTA NÃO DERRUBA AS OUTRAS.
        try:
            r = ONR.montar_indicador(con, mid, cns=cns, ficha=ficha, donos=donos)
        except Exception as erro:                          # noqa: BLE001
            saida["fora"].append({"id": mid, "numero": dig, "motivo": f"Não deu para montar: {erro}"})
            continue
        if r["impedem"]:
            saida["fora"].append({"id": mid, "numero": dig, "motivo": _sem_marcas(" | ".join(r["impedem"]))})
            continue
        corpo = r["corpo"]
        corpo["atos"] = [a for a in (corpo.get("atos") or []) if XML.ato_entra(a)]
        saida["corpos"].append(corpo)
    return saida


def _csv(cabecalho: list[str], linhas: list[list[Any]]) -> bytes:
    f = io.StringIO(newline="")
    w = csv.writer(f, delimiter=";")
    w.writerow(cabecalho)
    w.writerows(linhas)
    return f.getvalue().encode("utf-8-sig")


def pacote(r: Mapping[str, Any], *, data: str) -> tuple[bytes, list[str]]:
    """O .zip: o XML, em partes se passar do limite do ONR, e os relatórios. Devolve os nomes dos XML."""
    base = f"IndicadorReal_COMPLETO_{data}"
    corpos = list(r["corpos"])
    limite = XML.LIMITE_POR_ARQUIVO
    arquivos: list[tuple[str, bytes]] = []
    nomes_xml: list[str] = []
    for i in range(0, max(len(corpos), 1), limite):
        sufixo = "" if len(corpos) <= limite else f"_{i // limite + 1}"
        nome = f"{base}{sufixo}.XML"
        nomes_xml.append(nome)
        arquivos.append((nome, XML.arquivo_xml(corpos[i:i + limite]).encode("utf-8")))
    arquivos += [
        (f"{base}_fora.csv", _csv(["matricula", "motivo"], [[x["numero"], x["motivo"]] for x in r["fora"]])),
        (f"{base}_donos.csv", _csv(["matricula", "proprietario", "de_onde"],
                                   [[x["numero"], x["nome"], x["de_onde"]] for x in r["donos"]])),
        (f"{base}_sem_dono.csv", _csv(["matricula"], [[x] for x in r["sem_dono"]])),
        (f"{base}_repetidas.csv", _csv(["matricula", "id_fora", "id_que_vai"],
                                       [[x["numero"], x["id_fora"], x["id_que_vai"]] for x in r["repetidas"]])),
        (f"{base}_preenchido.csv", _csv(["matricula", "campo", "de_onde", "valor"],
                                        [[x["numero"], x["campo"], x["de_onde"], x["valor"]] for x in r["preenchido"]])),
    ]
    saida = io.BytesIO()
    with zipfile.ZipFile(saida, "w", zipfile.ZIP_DEFLATED) as z:
        for nome, conteudo in arquivos:
            z.writestr(nome, conteudo)
    return saida.getvalue(), nomes_xml
