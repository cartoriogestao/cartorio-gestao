def lotes(con, limite: int = 100) -> list[dict]:
    return banco(con).ler(
        """SELECT id, arquivo, sha256, bytes, registros, recusadas, filtros, situacao, gerado_por, gerado_em
             FROM onr_ir_lotes ORDER BY id DESC LIMIT %s""", (int(limite),))


def eventos(con, lote_ids: list[int]) -> dict[int, list[dict]]:
    saida: dict[int, list[dict]] = {}
    if lote_ids:
        for e in banco(con).ler("SELECT * FROM onr_ir_lote_eventos WHERE lote_id = ANY(%s) ORDER BY id", (lote_ids,)):
            saida.setdefault(e["lote_id"], []).append(e)
    return saida


def entregues(con) -> int:
    """Quantas matrículas o portal disse «Importado». É o único número de entrega desta tela."""
    return int(banco(con).valor(
        """SELECT COUNT(DISTINCT i.numero) FROM onr_ir_lote_itens i
             JOIN onr_ir_lotes l ON l.id = i.lote_id WHERE l.situacao = %s""", (IMPORTADO,)) or 0)


def arquivo_do_lote(con, lote_id: int) -> tuple[str, bytes] | None:
    """O arquivo como foi gerado. Devolve `None` se o conteúdo não bate mais com o hash gravado."""
    x = banco(con).um("SELECT arquivo, sha256, conteudo FROM onr_ir_lotes WHERE id = %s", (int(lote_id),))
    if not x:
        return None
    conteudo = x["conteudo"].encode("utf-8")
    if J.sha256(conteudo) != x["sha256"]:
        raise LoteError("O arquivo gravado não confere com o hash do lote. Não o importe.")
    return x["arquivo"], conteudo


def recusadas_csv(con, lote_id: int) -> tuple[str, bytes] | None:
    x = banco(con).um("SELECT arquivo, lista_recusadas FROM onr_ir_lotes WHERE id = %s", (int(lote_id),))
    if not x:
        return None
    f = io.StringIO(newline="")
    w = csv_seguro.escritor(f)
    w.writerow(["matricula", "classe", "motivo"])
    for item in json.loads(x["lista_recusadas"]):
        w.writerow([item["numero"], NOME_DA_CLASSE.get(item["classe"], item["classe"]), " | ".join(item["motivos"])])
    return x["arquivo"].replace(".json", "_recusadas.csv"), f.getvalue().encode("utf-8-sig")
