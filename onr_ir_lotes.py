def registrar_resultado(con, lote_id: int, para: str, *, visto_em: Any, observacao: Any, por: str, agora: str) -> None:
    """Anota o que o oficial viu no portal. **Só `IMPORTADO` conta como entregue.**"""
    bd = banco(con)
    bd.travar("onr_ir_lotes")
    lote = bd.um("SELECT id, situacao FROM onr_ir_lotes WHERE id = %s FOR UPDATE", (int(lote_id),))
    if not lote:
        raise LoteError("Lote não encontrado.")
    de = lote["situacao"]
    if para not in TRANSICOES.get(de, set()):
        raise LoteError(f"Um lote «{NOME_DA_SITUACAO.get(de, de)}» não passa para "
                        f"«{NOME_DA_SITUACAO.get(para, para)}».")
    nota, visto = _texto(observacao), _texto(visto_em)
    if de in (IMPORTADO, NAO_IMPORTADO) and len(nota) < MENOR_OBSERVACAO:
        raise LoteError(f"Para mudar um resultado já registrado, escreva o motivo, com pelo menos {MENOR_OBSERVACAO} letras.")
    if para == DESCARTADO:
        if len(nota) < MENOR_OBSERVACAO:
            raise LoteError(f"Diga por que o lote foi descartado, com pelo menos {MENOR_OBSERVACAO} letras.")
    else:
        try:
            dia = date.fromisoformat(visto)
        except ValueError:
            raise LoteError("Informe a data em que o portal mostrou este resultado.") from None
        if dia.isoformat() > agora[:10]:
            raise LoteError("A data do resultado não pode estar no futuro.")
    bd.escrever("UPDATE onr_ir_lotes SET situacao = %s WHERE id = %s", (para, int(lote_id)))
    bd.escrever("INSERT INTO onr_ir_lote_eventos (lote_id, de, para, visto_em, observacao, por, em) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s)", (int(lote_id), de, para, visto or None, nota or None, por, agora))


