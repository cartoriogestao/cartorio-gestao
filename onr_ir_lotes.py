#: PROPOSITALMENTE LARGA: pega também «a matrícula supra foi unificada». Errar para mais só manda a
#: ficha para a conferência de uma pessoa, e errar para menos publicaria imóvel que já não existe.
_CITA_ENCERRAMENTO = re.compile(
    r"matr[ií]cula\s+(?:\S+\s+){0,4}?(?:encerrad|unificad|esgotad)"
    r"|encerramento\s+d[ae]\s+matr[ií]cula"
    r"|encerrad[ao]\s+(?:a\s+)?(?:presente\s+|esta\s+)matr[ií]cula"
    r"|unifica[cç][aã]o\s*/\s*encerramento", re.I)
_MARCA_HTML = re.compile(r"<[^>]+>")
#: Quem veio destas frases de `propor` veio do padrão da casa, e não do que o livro escreve.
_FRASES_DA_REGRA = ("padrão", "sem número", "imóvel rural", "a ficha não", "cep de ", "coluna", "já estava", "unidade")
_CAMPOS_DO_TEOR = ("logradouro", "numero_predial", "bairro", "cidade", "cep", "rural_urbano", "tipo_imovel")


class LoteError(ValueError):
    """O que não se pode fazer, com a frase pronta para a tela."""


def init_schema(con) -> None:
    banco(con).escrever(SCHEMA)


def _texto(v: Any) -> str:
    return "" if v is None else str(v).strip()


def _so_digitos(v: Any) -> str:
    return re.sub(r"\D", "", _texto(v))


# ------------------------------------------------------------ a classe de uma ficha


def _veio_do_texto(frase: Any) -> bool:
    return not _texto(frase).lower().startswith(_FRASES_DA_REGRA)


def ficha_com_o_teor(m: Mapping[str, Any], proposta: Mapping[str, Any], casa: J.Serventia) -> dict:
    """A ficha com os brancos que o TEXTO preenche. O que `propor` tirou do padrão não entra."""
    saida = dict(m)
    campos, de_onde = proposta.get("campos") or {}, proposta.get("de_onde") or {}
    for c in _CAMPOS_DO_TEOR:
        if not _texto(saida.get(c)) and _texto(campos.get(c)) and _veio_do_texto(de_onde.get(c)):
            saida[c] = campos[c]
    # A VIA INTEIRA TEM DE ESTAR ESCRITA. `propor` lê «denominada "Riacho Fundo"» e põe «Área» à frente:
    # o nome é do livro, o tipo é da casa. Medido na réplica em 25/11/2026: 515 fichas entravam assim
    # como «completa pelo teor». Com o tipo da casa, a ficha é REGRA.
    if not _texto(m.get("logradouro")) and _texto(saida.get("logradouro")) \
            and not _diz_no_teor(m.get("teor"), saida.get("logradouro")):
        saida["logradouro"] = ""
    # O município da serventia já diz a UF: não é palpite, é a mesma informação.
    if not _texto(saida.get("uf")) and J.chave(saida.get("cidade")) in casa.municipios:
        saida["uf"] = casa.uf
    return saida


def _comparavel(texto: Any) -> str:
    """Só letras e números, entre espaços: é assim que um nome se procura dentro do teor."""
    limpo = re.sub(r"[^a-z0-9 ]", " ", J.chave(_MARCA_HTML.sub(" ", _texto(texto))))
    return " " + " ".join(limpo.split()) + " "


def _diz_no_teor(teor: Any, trecho: Any) -> bool:
    procurado = _comparavel(trecho)
    return bool(procurado.strip()) and procurado in _comparavel(teor)


def ficha_sem_padrao(m: Mapping[str, Any], padrao: Mapping[str, Any]) -> dict:
    """A ficha sem os valores da regra da casa que já foram gravados nela.

    MEDIDO EM 23/11/2026: nas fichas que pareciam completas, quase todas tinham número «0» e o CEP
    geral do município. São a regra da casa, só que dentro da ficha, e por isso esperam a mesma
    decisão do titular. Os dois campos são opcionais no manual: em branco não afirmam nada.
    """
    s = dict(m)
    if re.fullmatch(r"0+|s\s*/?\s*n", J.chave(s.get("numero_predial"))):
        s["numero_predial"] = ""
    gerais = {_so_digitos(v) for v in (padrao.get("ceps") or {}).values()} | {_so_digitos(padrao.get("cep"))}
    if _so_digitos(s.get("cep")) in gerais - {""}:
        s["cep"] = ""
    bairros = {J.chave(padrao.get("bairro_rural")), J.chave(padrao.get("bairro_urbano"))} - {""}
    if J.chave(s.get("bairro")) in bairros and not _diz_no_teor(s.get("teor"), s.get("bairro")):
        s["bairro"] = ""
    return s


def _pessoa(motivos: list[str]) -> dict:
    return {"classe": PESSOA, "registro": None, "motivos": motivos}


def avaliar(m: Mapping[str, Any], casa: J.Serventia, settings: Mapping[str, Any], padrao: Mapping[str, Any],
            *, aceitar_regra: bool = False) -> dict:
    """A classe da ficha e o registro que ela daria. SÓ CALCULA.

    Sem `aceitar_regra`, o registro sai sem os valores da regra da casa, mesmo os gravados na ficha.
    """
    if _texto(m.get("situacao")).upper() not in ("ATIVA", "ATIVO"):
        return _pessoa([f"A situação da ficha («{_texto(m.get('situacao'))}») não é de matrícula ativa. Confira."])
    if _CITA_ENCERRAMENTO.search(_MARCA_HTML.sub(" ", _texto(m.get("teor")))):
        return _pessoa(["O teor cita encerramento ou unificação da matrícula. Confira antes de enviar."])

    proposta = None
    if _texto(m.get("teor")):
        # A LEITURA DO TEXTO É AJUDA: se ela falhar, a ficha continua valendo pelo que diz.
        try:
            proposta = ENDERECO.propor(dict(m), settings=dict(settings), padrao=dict(padrao))
        except Exception:                                  # noqa: BLE001
            proposta = None
    if proposta and proposta.get("divergente"):
        return _pessoa(["O teor contradiz a ficha em urbano ou rural."])
    if proposta:
        # `propor` só conhece as cidades do mapa de CEPs. A da própria serventia não é «de fora».
        citada = re.match(r"padrão \(a ficha diz «(.+?)»", _texto((proposta.get("de_onde") or {}).get("cidade")))
        if citada and J.chave(citada.group(1)) not in casa.municipios:
            return _pessoa(["O teor cita um município que não é desta serventia. Confira onde fica o imóvel."])

    # «CONDOMINIO» no complemento da matrícula pode ser matrícula-mãe, que no manual é outro código.
    if "condominio" in J.chave(m.get("complemento")):
        return _pessoa(["A ficha está marcada como condomínio. Confira se é matrícula-mãe (REGISTRO_TIPO 2)."])
    if _texto(m.get("teor")) and _texto(m.get("logradouro")):
        _tipo, nome_via = J.partir_logradouro(m.get("logradouro"))
        if _tipo is not None and not _diz_no_teor(m.get("teor"), nome_via):
            return _pessoa([f"O logradouro da ficha («{_texto(m.get('logradouro'))}») não aparece no teor. Confira no livro."])

    base = dict(m) if aceitar_regra else ficha_sem_padrao(m, padrao)
    registro, motivos = J.montar_registro(base, casa)
    if registro and all(_texto(m.get(c)) for c in ("numero_predial", "bairro", "cep")):
        return {"classe": PRONTA, "registro": registro, "motivos": []}
    if proposta is None:
        return _pessoa(motivos or ["A ficha não tem teor para completar o que falta."])
    if proposta.get("confianca") == "baixa":
        return _pessoa(["A leitura do teor é fraca, e a ficha não traz o que falta."])

    do_teor, motivos_teor = J.montar_registro(ficha_com_o_teor(base, proposta, casa), casa)
    if do_teor:
        return {"classe": TEOR, "registro": do_teor, "motivos": []}
    completa, _origem = XML.completar_ficha(dict(m), proposta, dict(padrao))
    da_regra, motivos_regra = J.montar_registro(completa, casa)
    if da_regra:
        return {"classe": REGRA, "registro": da_regra, "motivos": motivos_teor}
    return _pessoa(motivos_regra)


# ------------------------------------------------------------ conferir


def _faixa(valor: Any, rotulo: str) -> int | None:
    bruto = _texto(valor)
    if not bruto:
        return None
    if not bruto.isdigit():
        raise LoteError(f"«{rotulo}» tem de ser o número da matrícula, só com dígitos.")
    return int(bruto)


def filtros_de(campos: Mapping[str, Any], classes: Iterable[str] | None = None) -> dict:
    """Os filtros da tela, conferidos. Tudo o que alarga o arquivo nasce desligado."""
    de, ate = _faixa(campos.get("de"), "Da matrícula"), _faixa(campos.get("ate"), "Até a matrícula")
    if de is not None and ate is not None and de > ate:
        raise LoteError("A faixa está invertida: o primeiro número é maior que o último.")
    escolhidas = [c for c in (classes if classes is not None else [PRONTA]) if c in (PRONTA, TEOR, REGRA)]
    aceitar_regra = str(campos.get("aceitar_regra") or "") == "1"
    if REGRA in escolhidas and not aceitar_regra:
        raise LoteError("A classe «regra da casa» só vai com a opção de aceitar a regra marcada.")
    if not escolhidas:
        raise LoteError("Escolha ao menos uma classe.")
    bruto_limite = _texto(campos.get("limite")) or str(LOTE_PADRAO)
    if not bruto_limite.isdigit() or not 1 <= int(bruto_limite) <= LOTE_MAXIMO:
        raise LoteError(f"O tamanho do lote vai de 1 a {LOTE_MAXIMO}.")
    return {"de": de, "ate": ate, "classes": escolhidas, "limite": int(bruto_limite),
            "incluir_acervo": str(campos.get("incluir_acervo") or "") == "1", "aceitar_regra": aceitar_regra}


def _em_lote_vivo(con) -> dict[str, int]:
    return {x["numero"]: x["lote_id"] for x in banco(con).ler(
        """SELECT i.numero, MAX(i.lote_id) AS lote_id FROM onr_ir_lote_itens i
             JOIN onr_ir_lotes l ON l.id = i.lote_id
            WHERE l.situacao = ANY(%s) GROUP BY i.numero""", (list(SITUACOES_VIVAS),))}


def conferir(con, *, settings: Mapping[str, Any], filtros: Mapping[str, Any]) -> dict:
    """O que iria no arquivo e o que fica de fora, com o motivo. SÓ LÊ."""
    from gestor_cargas_ri import NUMERO_DE_FICHA_ARQUIVADA
    casa, faltam = J.serventia_de(settings)
    if casa is None:
        raise LoteError("Falta na configuração: " + "; ".join(faltam) + ".")
    padrao = INTEIRO.padrao_do_arquivo(settings)
    vivos = _em_lote_vivo(con)
    fichas = banco(con).ler("SELECT * FROM ri_matriculas WHERE COALESCE(encerrada, 0) = 0")
    vezes = Counter(_texto(m.get("numero")) for m in fichas)
    fichas.sort(key=lambda m: (int(re.sub(r"\D", "", _texto(m.get("numero"))) or 0), m["id"]))

    r: dict[str, Any] = {"vao": [], "recusadas": [], "por_classe": Counter(), "fora_da_selecao": 0,
                         "para_o_proximo": 0, "na_faixa": 0, "acervo_de_fora": 0}
    for m in fichas:
        numero = _texto(m.get("numero"))
        n = int(numero) if numero.isdigit() else None
        if n is not None and n >= NUMERO_DE_FICHA_ARQUIVADA:
            continue
        if (filtros.get("de") is not None or filtros.get("ate") is not None) and n is None:
            continue
        if n is not None and ((filtros.get("de") is not None and n < filtros["de"])
                              or (filtros.get("ate") is not None and n > filtros["ate"])):
            continue
        r["na_faixa"] += 1
        a = avaliar(m, casa, settings, padrao, aceitar_regra=bool(filtros.get("aceitar_regra")))
        r["por_classe"][a["classe"]] += 1

        def recusa(motivos: list[str]) -> None:
            r["recusadas"].append({"id": m["id"], "numero": numero, "classe": a["classe"], "motivos": motivos})

        acervo = _texto(m.get("tipo_ficha")).upper() == "ACERVO"
        if vezes[numero] > 1:
            recusa([f"O número {numero} está em {vezes[numero]} fichas ativas. Confira qual vale."])
        elif numero in vivos:
            recusa([f"Já está no lote {vivos[numero]}. Registre o resultado dele ou descarte-o antes."])
        elif acervo and not filtros.get("incluir_acervo"):
            r["acervo_de_fora"] += 1
            recusa(["Ficha do acervo: fica de fora até o titular decidir subir o acervo."])
        elif a["classe"] == PESSOA:
            recusa(a["motivos"])
        elif a["classe"] == REGRA and not filtros.get("aceitar_regra"):
            recusa(["Depende da regra da casa, que está desligada: " + " ".join(a["motivos"])])
        elif a["classe"] not in filtros["classes"]:
            r["fora_da_selecao"] += 1
        elif len(r["vao"]) >= filtros["limite"]:
            r["para_o_proximo"] += 1
        else:
            r["vao"].append({"id": m["id"], "numero": numero, "classe": a["classe"], "registro": a["registro"]})
    r["por_classe"] = {c: r["por_classe"].get(c, 0) for c in CLASSES}
    r["casa"] = casa
    return r


# ------------------------------------------------------------ gerar


def _hash_registro(registro: Mapping[str, Any]) -> str:
    return J.sha256(json.dumps(registro, ensure_ascii=False, sort_keys=True).encode("utf-8"))


def gerar(con, *, settings: Mapping[str, Any], filtros: Mapping[str, Any], por: str, agora: str) -> dict:
    """Grava o lote e o arquivo. Roda dentro da transação de quem chama, e sob trava."""
    import ri_onr
    bd = banco(con)
    bd.travar("onr_ir_lotes")
    r = conferir(con, settings=settings, filtros=filtros)
    if not r["vao"]:
        raise LoteError("Nenhuma ficha passou com estes filtros. Veja a lista das recusadas.")
    casa = r["casa"]
    conteudo = ri_onr.gerar_indicador_real([x["registro"] for x in r["vao"]], casa)
    resumo_filtros = {k: filtros.get(k) for k in ("de", "ate", "classes", "limite", "incluir_acervo", "aceitar_regra")}
    lote_id = bd.valor(
        """INSERT INTO onr_ir_lotes (arquivo, sha256, bytes, registros, recusadas, filtros, lista_recusadas,
                                     conteudo, situacao, gerado_por, gerado_em)
           VALUES ('', %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) RETURNING id""",
        (J.sha256(conteudo), len(conteudo), len(r["vao"]), len(r["recusadas"]),
         json.dumps(resumo_filtros, ensure_ascii=False), json.dumps(r["recusadas"], ensure_ascii=False),
         conteudo.decode("utf-8"), GERADO, por, agora))
    arquivo = f"IndicadorReal_{casa.cns}_{_so_digitos(agora)[:14]}_L{lote_id}.json"
    bd.escrever("UPDATE onr_ir_lotes SET arquivo = %s WHERE id = %s", (arquivo, lote_id))
    for x in r["vao"]:
        bd.escrever(
            "INSERT INTO onr_ir_lote_itens (lote_id, numero, matricula_id, classe, sha256_registro) "
            "VALUES (%s, %s, %s, %s, %s)", (lote_id, x["numero"], x["id"], x["classe"], _hash_registro(x["registro"])))
    bd.escrever("INSERT INTO onr_ir_lote_eventos (lote_id, de, para, observacao, por, em) VALUES (%s, NULL, %s, %s, %s, %s)",
                (lote_id, GERADO, "Arquivo gerado. Nada foi enviado.", por, agora))
    return {"id": lote_id, "arquivo": arquivo, "sha256": J.sha256(conteudo), "registros": len(r["vao"]),
            "recusadas": len(r["recusadas"]), "para_o_proximo": r["para_o_proximo"]}


