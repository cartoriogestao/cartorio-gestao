def relatorio(con, *, de: str, ate: str, hoje: date | None = None) -> dict[str, Any]:
    """As manifestações RECEBIDAS no período, contadas. Sem identificação."""
    hoje = hoje or date.today()
    linhas = banco(con).ler(
        "SELECT tipo, canal, setor, situacao, prazo, recebida_em, respondida_em "
        "FROM ou_manifestacoes WHERE recebida_em >= %s AND recebida_em <= %s",
        (str(de)[:10], str(ate)[:10]))

    def _conta(campo: str, nomes: dict[str, str]) -> list[dict[str, Any]]:
        saida = []
        for chave, nome in nomes.items():
            n = sum(1 for x in linhas if x[campo] == chave)
            if n:
                saida.append({"chave": chave, "nome": nome, "total": n})
        return saida

    respondidas = [x for x in linhas if x["respondida_em"]]
    no_prazo = sum(1 for x in respondidas
                   if _data(x["respondida_em"]) and _data(x["prazo"])
                   and _data(x["respondida_em"]) <= _data(x["prazo"]))
    dias = [(_data(x["respondida_em"]) - _data(x["recebida_em"])).days for x in respondidas
            if _data(x["respondida_em"]) and _data(x["recebida_em"])]
    vencidas = sum(1 for x in linhas if x["situacao"] in EM_ABERTO
                   and _data(x["prazo"]) and _data(x["prazo"]) < hoje)
    return {
        "de": str(de)[:10], "ate": str(ate)[:10], "total": len(linhas),
        "por_tipo": _conta("tipo", TIPOS), "por_canal": _conta("canal", CANAIS),
        "por_setor": _conta("setor", SETORES), "por_situacao": _conta("situacao", SITUACOES),
        "respondidas": len(respondidas), "respondidas_no_prazo": no_prazo,
        "respondidas_fora_do_prazo": len(respondidas) - no_prazo,
        "media_dias_resposta": round(sum(dias) / len(dias), 1) if dias else None,
        "em_aberto": sum(1 for x in linhas if x["situacao"] in EM_ABERTO),
        "vencidas": vencidas,
    }


def numeros_do_painel(con, *, hoje: date | None = None) -> dict[str, Any]:
    """O quadro do painel: o que está aberto e vencido HOJE (de qualquer
    período), e o que chegou nos últimos 30 dias."""
    hoje = hoje or date.today()
    bd = banco(con)
    abertas = bd.ler("SELECT prazo FROM ou_manifestacoes "
                     "WHERE situacao IN ('ABERTA', 'EM_ANALISE')")
    inicio = (hoje - timedelta(days=30)).isoformat()
    recentes = bd.ler("SELECT tipo FROM ou_manifestacoes WHERE recebida_em >= %s", (inicio,))
    return {
        "abertas": len(abertas),
        "vencidas": sum(1 for x in abertas if _data(x["prazo"]) and _data(x["prazo"]) < hoje),
        "vencem_em_5_dias": sum(1 for x in abertas if _data(x["prazo"])
                                and hoje <= _data(x["prazo"]) <= hoje + timedelta(days=5)),
        "ultimos_30_dias": len(recentes),
        "reclamacoes_30_dias": sum(1 for x in recentes if x["tipo"] == "RECLAMACAO"),
        "elogios_30_dias": sum(1 for x in recentes if x["tipo"] == "ELOGIO"),
    }

