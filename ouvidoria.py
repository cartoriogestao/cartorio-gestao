"""A OUVIDORIA DA CASA — as manifestações de quem usa o serviço.

POR QUE EXISTE (26/10/2026)
    Medido no código em 26/10/2026: não havia registro de reclamação, sugestão,
    elogio, denúncia nem pedido de informação. O que existia com nome parecido
    era o inventário de LGPD e governança (`lgpd_items`), que guarda os itens de
    adequação da casa — e não o que o usuário veio dizer. O levantamento de
    lacunas de 17/10/2026 marcava «pesquisa de satisfação e ouvidoria» como
    PARCIAL só por causa da fila de senhas (`service_tickets`).

O QUE ELA FAZ
    - registra a manifestação, com tipo, canal de entrada, setor e responsável,
      e dá a ela um número próprio («OUV-2026/0001»), contínuo por ano;
    - calcula o PRAZO de resposta pelos dias da configuração;
    - abre uma TAREFA para o responsável (`source_type` = «OUVIDORIA»), pela
      régua da casa (`db.create_task`, que não deixa nascer tarefa repetida);
    - guarda o andamento (encaminhou, respondeu, encerrou) e a resposta;
    - conta por período, para o relatório e para o painel.

O PRAZO É DE 30 DIAS — DECISÃO DO OFICIAL EM 26/10/2026
    Procurado no repositório e na documentação da casa em 26/10/2026: nenhum
    texto do Código de Normas do MA nem do CNJ citado aqui fixa o prazo de
    resposta da ouvidoria de uma serventia. A pergunta foi ao oficial, e ele
    respondeu «30 dias». O número continua CONFIGURÁVEL
    (`ouvidoria_prazo_dias`), em dias corridos, e só o oficial o muda; a tela
    diz de onde vem o padrão.

OS DADOS DE QUEM SE MANIFESTA SÃO PROTEGIDOS
    - a manifestação pode ser ANÔNIMA: nenhum dado de identificação é gravado;
    - identificada, o nome, o documento e o contato não aparecem na lista nem
      na tarefa; na ficha, só o oficial, o gerente e o responsável os veem, e
      só depois de pedir — cada vez fica na auditoria;
    - na DENÚNCIA, a identificação e o relato ficam só com o oficial e o
      responsável: a tarefa diz que existe, não o que diz.

PostgreSQL nativo, pelo `bd_nativo`. Data e hora se calculam no Python.
"""
from __future__ import annotations

from datetime import date, timedelta
from typing import Any

from bd_nativo import banco

TIPOS: dict[str, str] = {
    "RECLAMACAO": "Reclamação",
    "SUGESTAO": "Sugestão",
    "ELOGIO": "Elogio",
    "DENUNCIA": "Denúncia",
    "INFORMACAO": "Pedido de informação",
}

CANAIS: dict[str, str] = {
    "BALCAO": "Balcão",
    "TELEFONE": "Telefone",
    "EMAIL": "E-mail",
    "WHATSAPP": "WhatsApp",
    "CARTA": "Carta",
}

#: O setor da manifestação. As atribuições da casa e a «Geral», para o que é
#: da serventia inteira (atendimento, instalações, horário).
SETORES: dict[str, str] = {
    "GERAL": "Geral (a serventia)",
    "RI": "Registro de Imóveis",
    "NOTAS": "Notas",
    "PROTESTO": "Protesto",
    "RCPN": "Registro Civil das Pessoas Naturais",
    "RTD": "Títulos e Documentos",
    "RCPJ": "Pessoas Jurídicas",
}

SITUACOES: dict[str, str] = {
    "ABERTA": "Aberta",
    "EM_ANALISE": "Em análise",
    "RESPONDIDA": "Respondida",
    "ENCERRADA": "Encerrada",
}
#: As que ainda pedem resposta — e são as que vencem.
EM_ABERTO = ("ABERTA", "EM_ANALISE")

#: Dias corridos. DECISÃO DO OFICIAL EM 26/10/2026 («30 dias»); ver o cabeçalho.
PRAZO_PADRAO_DIAS = 30
PRAZO_MINIMO_DIAS = 1
PRAZO_MAXIMO_DIAS = 180

CHAVE_PRAZO = "ouvidoria_prazo_dias"
CHAVE_RESPONSAVEL = "ouvidoria_responsavel_padrao"

SOURCE_TYPE = "OUVIDORIA"
TRAVA = "ou_manifestacoes.numero"

LIMITE_CURTO = 200
LIMITE_TEXTO = 10_000
MINIMO_DO_RELATO = 10
MINIMO_DA_RESPOSTA = 10

#: Quem vê a identificação sempre (além do responsável). Na denúncia, só o
#: ADMIN e o responsável.
VEEM_IDENTIFICACAO = ("ADMIN", "MANAGER")


class OuvidoriaError(ValueError):
    """Impedimento de regra, com a frase pronta para a tela."""


# ---------------------------------------------------------------- esquema
#
# Um comando por objeto, cada um só se o objeto falta (o padrão de
# `livro_visitas`). Sem chave estrangeira para `users` nem para `tasks`: o
# vínculo é informativo, e apagar um usuário não pode levar a manifestação.
SCHEMA: tuple[tuple[str, str], ...] = (
    ("ou_manifestacoes", """
        CREATE TABLE IF NOT EXISTS ou_manifestacoes (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ano integer NOT NULL,
            sequencia integer NOT NULL,
            numero TEXT NOT NULL,
            tipo TEXT NOT NULL CHECK (tipo IN (
                'RECLAMACAO', 'SUGESTAO', 'ELOGIO', 'DENUNCIA', 'INFORMACAO')),
            canal TEXT NOT NULL CHECK (canal IN (
                'BALCAO', 'TELEFONE', 'EMAIL', 'WHATSAPP', 'CARTA')),
            anonima integer NOT NULL DEFAULT 0,
            nome TEXT NOT NULL DEFAULT '',
            documento TEXT NOT NULL DEFAULT '',
            contato TEXT NOT NULL DEFAULT '',
            forma_resposta TEXT NOT NULL DEFAULT '',
            setor TEXT NOT NULL DEFAULT 'GERAL',
            responsavel_id bigint,
            assunto TEXT NOT NULL,
            relato TEXT NOT NULL,
            protocolo_ref TEXT NOT NULL DEFAULT '',
            recebida_em TEXT NOT NULL,
            prazo_dias integer NOT NULL,
            prazo TEXT NOT NULL,
            situacao TEXT NOT NULL DEFAULT 'ABERTA' CHECK (situacao IN (
                'ABERTA', 'EM_ANALISE', 'RESPONDIDA', 'ENCERRADA')),
            resposta TEXT NOT NULL DEFAULT '',
            respondida_em TEXT,
            respondida_por bigint,
            encerrada_em TEXT,
            tarefa_id bigint,
            criada_em TEXT NOT NULL,
            criada_por bigint,
            atualizada_em TEXT NOT NULL
        )"""),
    ("ux_ou_manifestacoes_numero",
     "CREATE UNIQUE INDEX IF NOT EXISTS ux_ou_manifestacoes_numero "
     "ON ou_manifestacoes (ano, sequencia)"),
    ("ix_ou_manifestacoes_recebida",
     "CREATE INDEX IF NOT EXISTS ix_ou_manifestacoes_recebida "
     "ON ou_manifestacoes (recebida_em, situacao)"),
    ("ou_andamentos", """
        CREATE TABLE IF NOT EXISTS ou_andamentos (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            manifestacao_id bigint NOT NULL REFERENCES ou_manifestacoes (id),
            ts TEXT NOT NULL,
            usuario_id bigint,
            acao TEXT NOT NULL,
            nota TEXT NOT NULL DEFAULT ''
        )"""),
    ("ix_ou_andamentos_manifestacao",
     "CREATE INDEX IF NOT EXISTS ix_ou_andamentos_manifestacao "
     "ON ou_andamentos (manifestacao_id, id)"),
)


def init_ouvidoria_schema(con) -> None:
    """Cria as tabelas e os índices que faltarem. Idempotente."""
    bd = banco(con)
    for nome, comando in SCHEMA:
        if not bd.tem_tabela(nome):
            bd.escrever(comando)
    # A PESQUISA DE SATISFAÇÃO mora no módulo dela, e nasce junto.
    import satisfacao
    satisfacao.init_satisfacao_schema(con)


# ------------------------------------------------------------- auxiliares


def _texto(valor: Any, limite: int = LIMITE_CURTO) -> str:
    return " ".join(str(valor or "").split())[:limite]


def _longo(valor: Any, limite: int = LIMITE_TEXTO) -> str:
    """Texto de várias linhas: tira só o espaço das pontas."""
    return str(valor or "").strip()[:limite]


def _data(valor: Any) -> date | None:
    try:
        return date.fromisoformat(str(valor or "")[:10])
    except ValueError:
        return None


def prazo_em_dias(get_setting) -> int:
    """Os dias corridos da configuração; fora da faixa, o padrão da casa."""
    try:
        dias = int(str(get_setting(CHAVE_PRAZO, "") or "").strip())
    except ValueError:
        return PRAZO_PADRAO_DIAS
    if PRAZO_MINIMO_DIAS <= dias <= PRAZO_MAXIMO_DIAS:
        return dias
    return PRAZO_PADRAO_DIAS


def validar_prazo(valor: Any) -> int:
    """O número que a tela de configuração mandou, ou a frase do porquê não."""
    try:
        dias = int(str(valor or "").strip())
    except ValueError:
        raise OuvidoriaError("Informe o prazo em dias, só com números.") from None
    if not PRAZO_MINIMO_DIAS <= dias <= PRAZO_MAXIMO_DIAS:
        raise OuvidoriaError(f"O prazo vai de {PRAZO_MINIMO_DIAS} a {PRAZO_MAXIMO_DIAS} dias.")
    return dias


def _andamento(con, manifestacao_id: int, acao: str, *, por: int | None,
               agora: str, nota: str = "") -> None:
    banco(con).escrever(
        "INSERT INTO ou_andamentos (manifestacao_id, ts, usuario_id, acao, nota) "
        "VALUES (%s, %s, %s, %s, %s)", (manifestacao_id, agora, por, acao, nota))


# ---------------------------------------------------------------- registro


def registrar(con, dados: dict[str, Any], *, por: int | None, agora: str,
              prazo_dias: int) -> dict[str, Any]:
    """Grava a manifestação e devolve `{id, numero, prazo}`.

    A tarefa NÃO nasce aqui: `db.create_task` abre a própria transação, e quem
    chama a cria depois do commit e a amarra com `amarrar_tarefa`."""
    tipo = _texto(dados.get("tipo")).upper()
    if tipo not in TIPOS:
        raise OuvidoriaError("Escolha o tipo da manifestação.")
    canal = _texto(dados.get("canal")).upper()
    if canal not in CANAIS:
        raise OuvidoriaError("Escolha por qual canal a manifestação chegou.")
    setor = _texto(dados.get("setor")).upper() or "GERAL"
    if setor not in SETORES:
        raise OuvidoriaError("Escolha o setor da manifestação.")
    assunto = _texto(dados.get("assunto"))
    if not assunto:
        raise OuvidoriaError("Escreva o assunto em poucas palavras.")
    relato = _longo(dados.get("relato"))
    if len(relato) < MINIMO_DO_RELATO:
        raise OuvidoriaError("Escreva o relato do que a pessoa disse — com as palavras dela, "
                             "o mais fiel possível.")
    try:
        responsavel = int(dados.get("responsavel_id") or 0) or None
    except (TypeError, ValueError):
        responsavel = None
    if responsavel is None:
        raise OuvidoriaError("Escolha quem vai responder à manifestação.")
    hoje = _data(agora) or date.today()
    recebida = _data(dados.get("recebida_em")) or hoje
    if recebida > hoje:
        raise OuvidoriaError("A data de recebimento não pode ser depois de hoje.")
    anonima = str(dados.get("anonima") or "").strip().lower() in ("1", "on", "sim", "true")
    # ANÔNIMA NÃO GRAVA IDENTIFICAÇÃO, nem que a tela a tenha mandado: o campo
    # preenchido por engano antes de marcar a caixa não pode ficar no banco.
    nome = "" if anonima else _texto(dados.get("nome"))
    documento = "" if anonima else _texto(dados.get("documento"), 40)
    contato = "" if anonima else _texto(dados.get("contato"))
    forma = "" if anonima else _texto(dados.get("forma_resposta"))
    prazo = recebida + timedelta(days=int(prazo_dias))

    bd = banco(con)
    bd.travar(TRAVA)
    seq = int(bd.valor("SELECT COALESCE(MAX(sequencia), 0) + 1 FROM ou_manifestacoes "
                       "WHERE ano = %s", (recebida.year,)))
    numero = f"OUV-{recebida.year}/{seq:04d}"
    novo = bd.escrever(
        """INSERT INTO ou_manifestacoes (ano, sequencia, numero, tipo, canal, anonima,
               nome, documento, contato, forma_resposta, setor, responsavel_id, assunto,
               relato, protocolo_ref, recebida_em, prazo_dias, prazo, situacao,
               criada_em, criada_por, atualizada_em)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,'ABERTA',%s,%s,%s)
           RETURNING id""",
        (recebida.year, seq, numero, tipo, canal, 1 if anonima else 0, nome, documento,
         contato, forma, setor, responsavel, assunto, relato,
         _texto(dados.get("protocolo_ref"), 40), recebida.isoformat(), int(prazo_dias),
         prazo.isoformat(), agora, por, agora))
    mid = int(novo[0]["id"])
    _andamento(con, mid, "REGISTRADA", por=por, agora=agora,
               nota=f"{TIPOS[tipo]} pelo canal {CANAIS[canal]}; prazo de {prazo_dias} dias.")
    return {"id": mid, "numero": numero, "prazo": prazo.isoformat()}


def dados_da_tarefa(m: dict[str, Any]) -> dict[str, Any]:
    """O que vai para `db.create_task`. SEM a identificação de quem se
    manifestou — a lista de tarefas é de todos. Na denúncia, nem o assunto."""
    if m["tipo"] == "DENUNCIA":
        titulo = f"[Ouvidoria] Responder à denúncia {m['numero']}"
        corpo = ("Denúncia recebida pela ouvidoria. O teor fica na ficha da manifestação, "
                 "com acesso restrito ao oficial e a você.")
    else:
        titulo = f"[Ouvidoria] Responder à manifestação {m['numero']}"
        corpo = f"{TIPOS[m['tipo']]} — assunto: {m['assunto']}."
    prazo = _data(m["prazo"])
    corpo += (f" Canal: {CANAIS[m['canal']]}. Prazo de resposta: "
              f"{prazo.strftime('%d/%m/%Y') if prazo else m['prazo']}. "
              f"Abra em /administrativo/ouvidoria/{m['id']} para ler e registrar a resposta.")
    return {
        "source_type": SOURCE_TYPE,
        "source_ref": f"OUVIDORIA:{m['id']}",
        "title": titulo,
        "description": corpo,
        "sector": m["setor"],
        "priority": "ALTA" if m["tipo"] in ("RECLAMACAO", "DENUNCIA") else "MEDIA",
        "assigned_user_id": m["responsavel_id"],
        "start_date": m["recebida_em"],
        "due_date": m["prazo"],
    }


def amarrar_tarefa(con, manifestacao_id: int, tarefa_id: int) -> None:
    banco(con).escrever("UPDATE ou_manifestacoes SET tarefa_id = %s WHERE id = %s",
                        (int(tarefa_id), int(manifestacao_id)))


# ---------------------------------------------------------------- leitura


def ler(con, manifestacao_id: int) -> dict[str, Any] | None:
    linha = banco(con).um(
        """SELECT m.*, u.full_name AS responsavel_nome, r.full_name AS respondida_por_nome
             FROM ou_manifestacoes m
             LEFT JOIN users u ON u.id = m.responsavel_id
             LEFT JOIN users r ON r.id = m.respondida_por
            WHERE m.id = %s""", (int(manifestacao_id),))
    return _com_nomes(linha) if linha else None


def andamentos(con, manifestacao_id: int) -> list[dict[str, Any]]:
    return banco(con).ler(
        """SELECT a.*, u.full_name AS usuario_nome FROM ou_andamentos a
             LEFT JOIN users u ON u.id = a.usuario_id
            WHERE a.manifestacao_id = %s ORDER BY a.id""", (int(manifestacao_id),))


def _com_nomes(m: dict[str, Any], hoje: date | None = None) -> dict[str, Any]:
    m = dict(m)
    m["tipo_nome"] = TIPOS.get(m["tipo"], m["tipo"])
    m["canal_nome"] = CANAIS.get(m["canal"], m["canal"])
    m["setor_nome"] = SETORES.get(m["setor"], m["setor"])
    m["situacao_nome"] = SITUACOES.get(m["situacao"], m["situacao"])
    hoje = hoje or date.today()
    prazo = _data(m.get("prazo"))
    m["vencida"] = bool(m["situacao"] in EM_ABERTO and prazo and prazo < hoje)
    respondida = _data(m.get("respondida_em"))
    m["no_prazo"] = (None if not respondida or not prazo else respondida <= prazo)
    return m


def listar(con, *, situacao: str = "", tipo: str = "", de: str = "", ate: str = "",
           limite: int = 500, hoje: date | None = None) -> list[dict[str, Any]]:
    """A lista da tela, sem nenhum dado de identificação (nem a coluna vem)."""
    conds, args = [], []
    if situacao == "EM_ABERTO":
        conds.append("m.situacao IN ('ABERTA', 'EM_ANALISE')")
    elif situacao in SITUACOES:
        conds.append("m.situacao = %s")
        args.append(situacao)
    if tipo in TIPOS:
        conds.append("m.tipo = %s")
        args.append(tipo)
    if _data(de):
        conds.append("m.recebida_em >= %s")
        args.append(str(de)[:10])
    if _data(ate):
        conds.append("m.recebida_em <= %s")
        args.append(str(ate)[:10])
    onde = ("WHERE " + " AND ".join(conds)) if conds else ""
    linhas = banco(con).ler(
        f"""SELECT m.id, m.numero, m.tipo, m.canal, m.anonima, m.setor, m.responsavel_id,
                   m.assunto, m.recebida_em, m.prazo, m.situacao, m.respondida_em,
                   m.tarefa_id, u.full_name AS responsavel_nome
              FROM ou_manifestacoes m LEFT JOIN users u ON u.id = m.responsavel_id
              {onde}
             ORDER BY m.recebida_em DESC, m.id DESC LIMIT %s""", (*args, int(limite)))
    return [_com_nomes(x, hoje) for x in linhas]


# --------------------------------------------------- quem vê o quê


def e_responsavel(m: dict[str, Any], usuario: dict[str, Any] | None) -> bool:
    return bool(usuario) and m.get("responsavel_id") is not None and \
        int(m["responsavel_id"]) == int(usuario["id"])


def ve_identificacao(m: dict[str, Any], usuario: dict[str, Any] | None) -> bool:
    """O nome, o documento e o contato: o oficial, o gerente e o responsável —
    na denúncia, só o oficial e o responsável. Anônima não tem o que ver."""
    if not usuario or m.get("anonima"):
        return False
    if e_responsavel(m, usuario):
        return True
    if m.get("tipo") == "DENUNCIA":
        return usuario["role"] == "ADMIN"
    return usuario["role"] in VEEM_IDENTIFICACAO


def ve_teor(m: dict[str, Any], usuario: dict[str, Any] | None) -> bool:
    """O relato e a resposta. Na denúncia, só quem vê a identificação dela e o
    gerente; nas outras, todo mundo que abre a ouvidoria."""
    if not usuario:
        return False
    if m.get("tipo") != "DENUNCIA":
        return True
    return e_responsavel(m, usuario) or usuario["role"] in VEEM_IDENTIFICACAO


def pode_tratar(m: dict[str, Any], usuario: dict[str, Any] | None) -> bool:
    """Responder, encaminhar, pôr em análise e encerrar."""
    if not usuario:
        return False
    return e_responsavel(m, usuario) or usuario["role"] in VEEM_IDENTIFICACAO


def para_a_tela(m: dict[str, Any], usuario: dict[str, Any] | None, *,
                mostrar_identificacao: bool = False) -> dict[str, Any]:
    """A ficha como a pessoa pode vê-la. O que ela não pode ver SAI do
    dicionário — não basta a tela não imprimir."""
    m = dict(m)
    m["pode_ver_identificacao"] = ve_identificacao(m, usuario)
    m["pode_ver_teor"] = ve_teor(m, usuario)
    m["pode_tratar"] = pode_tratar(m, usuario)
    m["identificacao_aberta"] = bool(mostrar_identificacao and m["pode_ver_identificacao"])
    if not m["identificacao_aberta"]:
        for campo in ("nome", "documento", "contato", "forma_resposta"):
            m[campo] = ""
    if not m["pode_ver_teor"]:
        m["relato"] = ""
        m["resposta"] = ""
        m["assunto"] = "(denúncia — teor reservado)"
    return m


def assunto_na_lista(m: dict[str, Any], usuario: dict[str, Any] | None) -> str:
    return m["assunto"] if ve_teor(m, usuario) else "(denúncia — teor reservado)"


# --------------------------------------------------------------- andamento


def _em_aberto(con, manifestacao_id: int) -> dict[str, Any]:
    bd = banco(con)
    bd._escrita()
    m = bd.um("SELECT * FROM ou_manifestacoes WHERE id = %s FOR UPDATE", (int(manifestacao_id),))
    if not m:
        raise OuvidoriaError("Manifestação não encontrada.")
    if m["situacao"] not in EM_ABERTO:
        raise OuvidoriaError("Esta manifestação já foi respondida ou encerrada.")
    return m


def em_analise(con, manifestacao_id: int, *, por: int | None, agora: str) -> None:
    m = _em_aberto(con, manifestacao_id)
    if m["situacao"] == "EM_ANALISE":
        return
    banco(con).escrever("UPDATE ou_manifestacoes SET situacao = 'EM_ANALISE', atualizada_em = %s "
                        "WHERE id = %s", (agora, m["id"]))
    _andamento(con, m["id"], "EM_ANALISE", por=por, agora=agora)


def encaminhar(con, manifestacao_id: int, novo_responsavel: int, *, motivo: str,
               por: int | None, agora: str) -> dict[str, Any]:
    """Troca quem responde. Devolve a linha de antes (a tarefa vai junto, por
    quem chama, pelo `db.update_task`)."""
    m = _em_aberto(con, manifestacao_id)
    if not novo_responsavel:
        raise OuvidoriaError("Escolha para quem encaminhar.")
    if m["responsavel_id"] and int(m["responsavel_id"]) == int(novo_responsavel):
        raise OuvidoriaError("A manifestação já está com essa pessoa.")
    banco(con).escrever("UPDATE ou_manifestacoes SET responsavel_id = %s, atualizada_em = %s "
                        "WHERE id = %s", (int(novo_responsavel), agora, m["id"]))
    _andamento(con, m["id"], "ENCAMINHADA", por=por, agora=agora, nota=_texto(motivo, 1000))
    return m


def responder(con, manifestacao_id: int, *, resposta: str, por: int | None,
              agora: str) -> dict[str, Any]:
    """Grava a resposta dada a quem se manifestou. A resposta é o texto que
    foi (ou vai) para a pessoa — não a nota interna."""
    m = _em_aberto(con, manifestacao_id)
    texto = _longo(resposta)
    if len(texto) < MINIMO_DA_RESPOSTA:
        raise OuvidoriaError("Escreva a resposta dada à pessoa.")
    banco(con).escrever(
        "UPDATE ou_manifestacoes SET situacao = 'RESPONDIDA', resposta = %s, respondida_em = %s, "
        "respondida_por = %s, atualizada_em = %s WHERE id = %s",
        (texto, agora, por, agora, m["id"]))
    prazo = _data(m["prazo"])
    dia = _data(agora)
    fora = bool(prazo and dia and dia > prazo)
    _andamento(con, m["id"], "RESPONDIDA", por=por, agora=agora,
               nota="Respondida depois do prazo." if fora else "Respondida no prazo.")
    return m


def encerrar(con, manifestacao_id: int, *, motivo: str, por: int | None,
             agora: str) -> dict[str, Any]:
    """Fecha sem resposta (ou depois dela). Precisa de motivo escrito."""
    bd = banco(con)
    bd._escrita()
    m = bd.um("SELECT * FROM ou_manifestacoes WHERE id = %s FOR UPDATE", (int(manifestacao_id),))
    if not m:
        raise OuvidoriaError("Manifestação não encontrada.")
    if m["situacao"] == "ENCERRADA":
        raise OuvidoriaError("Esta manifestação já está encerrada.")
    nota = _texto(motivo, 1000)
    if len(nota) < MINIMO_DO_RELATO:
        raise OuvidoriaError("Diga por que se encerra — quem ler depois precisa saber.")
    bd.escrever("UPDATE ou_manifestacoes SET situacao = 'ENCERRADA', encerrada_em = %s, "
                "atualizada_em = %s WHERE id = %s", (agora, agora, m["id"]))
    _andamento(con, m["id"], "ENCERRADA", por=por, agora=agora, nota=nota)
    return m


