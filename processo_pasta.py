def init_schema(con: Any) -> None:
    bd = banco(con)
    for comando in SCHEMA.split(";"):
        if comando.strip():
            bd.escrever(comando)


def _digitos(texto: Any) -> str:
    return re.sub(r"\D", "", str(texto or ""))


def resolver(con: Any, tabela: str, referencia: str) -> int:
    """Do que o escrevente digitou ao id da peça. Recusa o que não acha."""
    if tabela not in TIPOS:
        raise PastaError("Esse tipo de peça não pode entrar na pasta do processo.")
    ref = (referencia or "").strip()
    if not ref:
        raise PastaError(f"Informe {TIPOS[tabela]['ajuda']}.")
    d = _digitos(ref)
    bd = banco(con)
    linha = None
    if tabela == "expedientes":
        linha = bd.um("SELECT id FROM expedientes WHERE internal_protocol=%s ORDER BY id",
                      (ref.upper(),))
        if not linha and d and ref.isdigit():
            linha = bd.um("SELECT id FROM expedientes WHERE id=%s", (int(d),))
    elif tabela == "rc_assentos":
        if len(d) == 32:
            linha = bd.um("SELECT id FROM rc_assentos WHERE matricula=%s ORDER BY id", (d,))
        elif d and ref.isdigit():
            linha = bd.um("SELECT id FROM rc_assentos WHERE id=%s", (int(d),))
    elif tabela == "ri_matriculas":
        achadas = bd.ler("SELECT id FROM ri_matriculas WHERE numero=%s ORDER BY id", (ref,))
        if not achadas and d:
            achadas = bd.ler("SELECT id FROM ri_matriculas WHERE numero=%s ORDER BY id", (d,))
        if len(achadas) > 1:
            raise PastaError(f"Há {len(achadas)} fichas com o número {ref}; abra a ficha e "
                             "vincule pelo número interno.")
        linha = achadas[0] if achadas else None
    elif tabela == "ri_protocolos":
        if d:
            linha = bd.um("SELECT id FROM ri_protocolos WHERE numero=%s ORDER BY id", (int(d),))
    elif tabela == "cx_protocolos":
        linha = bd.um("SELECT id FROM cx_protocolos WHERE numero=%s ORDER BY id", (ref,))
    elif d and ref.isdigit():
        linha = bd.um(f"SELECT id FROM {tabela} WHERE id=%s", (int(d),))
    if not linha:
        raise PastaError(f"Não achei {TIPOS[tabela]['nome'].lower()} com «{ref}». "
                         f"Informe {TIPOS[tabela]['ajuda']}.")
    return int(linha["id"])


def vincular(con: Any, task_id: int, tabela: str, referencia: str, *,
             agora: str, por: int | None) -> int:
    """Põe a peça na pasta do processo. ESCREVE só o vínculo."""
    bd = banco(con)
    init_schema(bd)
    if not bd.um("SELECT 1 FROM tasks WHERE id=%s", (int(task_id),)):
        raise PastaError(f"Não achei o processo #{task_id}.")
    item = resolver(bd, tabela, referencia)
    if tabela == "expedientes" and bd.um(
            "SELECT 1 FROM tasks WHERE id=%s AND linked_expediente_id=%s", (int(task_id), item)):
        raise PastaError("Este expediente já é a origem do processo; ele já está na pasta.")
    if bd.um("SELECT 1 FROM pr_vinculos WHERE task_id=%s AND tabela=%s AND item_id=%s",
             (int(task_id), tabela, item)):
        raise PastaError("Esta peça já está na pasta do processo.")
    bd.escrever("INSERT INTO pr_vinculos(task_id, tabela, item_id, criado_em, criado_por) "
                "VALUES (%s,%s,%s,%s,%s)", (int(task_id), tabela, item, agora, por))
    bd.escrever("INSERT INTO task_history(task_id, ts, user_id, action, note) VALUES (%s,%s,%s,%s,%s)",
                (int(task_id), agora, por, "NOTA",
                 f"Na pasta do processo: {TIPOS[tabela]['nome'].lower()} {rotulo(bd, tabela, item)}."))
    return item


def desvincular(con: Any, task_id: int, vinculo_id: int, *, agora: str,
                por: int | None) -> None:
    """Tira a peça da pasta. A peça continua onde sempre esteve."""
    bd = banco(con)
    init_schema(bd)
    v = bd.um("SELECT tabela, item_id FROM pr_vinculos WHERE id=%s AND task_id=%s",
              (int(vinculo_id), int(task_id)))
    if not v:
        raise PastaError("Este vínculo não é deste processo.")
    bd.escrever("DELETE FROM pr_vinculos WHERE id=%s", (int(vinculo_id),))
    bd.escrever("INSERT INTO task_history(task_id, ts, user_id, action, note) VALUES (%s,%s,%s,%s,%s)",
                (int(task_id), agora, por, "NOTA",
                 f"Saiu da pasta do processo: {TIPOS[v['tabela']]['nome'].lower()} "
                 f"{rotulo(bd, v['tabela'], v['item_id'])}."))


def ato_lavrado_do_rascunho(con: Any, task_id: int, vinculo_id: int, *,
                            apagar_rascunho: bool, agora: str, por: int | None) -> None:
    """O ato do rascunho foi lavrado: o processo conclui, com a nota. ESCREVE.

    O rascunho aberto pela tela sai sozinho quando o ato grava
    (`rascunho_de_tela.saiu_com_o_ato`), e aqui ele já pode não existir. O processo
    não fecha sozinho: é quem lavrou que diz, aqui, numa ação só. E o ato que saiu
    de uma tela em branco só se sabe por esta palavra, que tira o rascunho também."""
    bd = banco(con)
    init_schema(bd)
    v = bd.um("SELECT tabela, item_id FROM pr_vinculos WHERE id=%s AND task_id=%s",
              (int(vinculo_id), int(task_id)))
    if not v or v["tabela"] != "rascunhos_de_tela":
        raise PastaError("Este vínculo não é um rascunho deste processo.")
    if apagar_rascunho:
        RASC.virou_ato(bd, int(v["item_id"]), endereco=None, agora=agora,
                       por=str(por or ""))
    bd.escrever("UPDATE tasks SET status='CONCLUIDA', completed_at=%s, completed_by=%s, updated_at=%s WHERE id=%s",
                (agora, por, agora, int(task_id)))
    bd.escrever("INSERT INTO task_history(task_id, ts, user_id, action, old_value, new_value, note) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s)",
                (int(task_id), agora, por, "ALTEROU_STATUS", None, "CONCLUIDA",
                 "O ato do rascunho foi lavrado." + (" Rascunho apagado." if apagar_rascunho else "")))


def rotulo(con: Any, tabela: str, item_id: int) -> str:
    """Como a peça se chama para quem lê."""
    q = {
        "expedientes": "SELECT internal_protocol, subject FROM expedientes WHERE id=%s",
        "rc_assentos": "SELECT especie, numero, livro_volume, nome FROM rc_assentos WHERE id=%s",
        "ri_matriculas": "SELECT numero, livro FROM ri_matriculas WHERE id=%s",
        "ri_protocolos": "SELECT numero, natureza_titulo FROM ri_protocolos WHERE id=%s",
        "cx_protocolos": "SELECT numero, interessado FROM cx_protocolos WHERE id=%s",
        "nt_atos": "SELECT tipo, livro, folha FROM nt_atos WHERE id=%s",
        "rg_registros": "SELECT atribuicao, numero, volume FROM rg_registros WHERE id=%s",
        "rascunhos_de_tela": "SELECT titulo, tela FROM rascunhos_de_tela WHERE id=%s",
        "rg_titulos": "SELECT numero, natureza, apresentante FROM rg_titulos WHERE id=%s",
    }[tabela]
    r = banco(con).um(q, (int(item_id),))
    if not r:
        return f"#{item_id} (não existe mais)"
    r = list(r.values())
    if tabela == "expedientes":
        return f"{r[0]} — {r[1] or ''}"
    if tabela == "rc_assentos":
        livro = f", livro {r[2]}" if r[2] else ""
        return f"{(r[0] or '').lower()} nº {r[1]}{livro} — {r[3] or ''}".strip(" —")
    if tabela == "ri_matriculas":
        return f"nº {r[0]}" + (f" (livro {r[1]})" if r[1] else "")
    if tabela == "ri_protocolos":
        return f"nº {r[0]}" + (f" — {r[1]}" if r[1] else "")
    if tabela == "cx_protocolos":
        return f"{r[0]}" + (f" — {r[1]}" if r[1] else "")
    if tabela == "nt_atos":
        return f"{r[0] or 'ato'} — livro {r[1] or '?'}, fl. {r[2] or '?'}"
    if tabela == "rg_registros":
        return f"{r[0]} nº {r[1]}" + (f", livro {r[2]}" if r[2] else "")
    if tabela == "rg_titulos":
        return f"protocolo nº {r[0] or '?'} — {r[1] or ''}" + (f", de {r[2]}" if r[2] else "")
    return f"#{item_id} — {r[0]}"


def processos_da_peca(con: Any, tabela: str, item_id: int) -> list[dict]:
    """O CAMINHO DE VOLTA: as tarefas em cuja pasta esta peça está. Só LÊ.

    «precisamos poder criar uma tarefa a partir do protocolo e precisamos poder
     linkar um protocolo a uma tarefa nova ou preexistente» — o oficial,
     26/10/2026. A pasta do processo já ligava a tarefa ao protocolo; faltava o
     protocolo saber das tarefas dele. O vínculo é o MESMO (`pr_vinculos`): uma
     ligação só, vista dos dois lados."""
    bd = banco(con)
    init_schema(bd)
    return [dict(r) for r in bd.ler(
        """SELECT v.id AS vinculo_id, t.id, t.title, t.status, t.due_date,
                  u.full_name AS responsavel
             FROM pr_vinculos v JOIN tasks t ON t.id = v.task_id
             LEFT JOIN users u ON u.id = t.assigned_user_id
            WHERE v.tabela = %s AND v.item_id = %s
            ORDER BY t.id DESC""", (tabela, int(item_id)))]


def tarefas_abertas(con: Any, *, limite: int = 300) -> list[dict]:
    """As tarefas que ainda andam, para escolher a quem ligar uma peça. Só LÊ."""
    import tarefa_processo as TP
    marcas = ",".join(["%s"] * len(TP.SITUACOES_ABERTAS))
    return [dict(r) for r in banco(con).ler(
        f"""SELECT id, title FROM tasks WHERE status IN ({marcas})
             ORDER BY id DESC LIMIT %s""", (*TP.SITUACOES_ABERTAS, int(limite)))]


def vinculos(con: Any, task_id: int) -> list[dict]:
    """As peças da pasta: a origem (o expediente de onde o processo nasceu) e
    as vinculadas à mão. Cada uma com o que precisa para virar link."""
    bd = banco(con)
    init_schema(bd)
    saida = []
    origem = bd.um("SELECT linked_expediente_id FROM tasks WHERE id=%s", (int(task_id),))
    if origem and origem["linked_expediente_id"]:
        saida.append({"id": None, "tabela": "expedientes",
                      "item_id": int(origem["linked_expediente_id"]), "origem": True})
    for r in bd.ler(
            "SELECT id, tabela, item_id FROM pr_vinculos WHERE task_id=%s ORDER BY id", (int(task_id),)):
        saida.append({"id": r["id"], "tabela": r["tabela"], "item_id": int(r["item_id"]),
                      "origem": False})
    for v in saida:
        t = TIPOS[v["tabela"]]
        v["nome"] = t["nome"]
        v["rotulo"] = rotulo(bd, v["tabela"], v["item_id"])
        v["endpoint"], v["arg"] = t["endpoint"], t["arg"]
        if v["tabela"] == "rascunhos_de_tela":
            r = bd.um("SELECT id, tela, chave FROM rascunhos_de_tela WHERE id=%s", (v["item_id"],))
            v["endpoint"] = r["tela"] if r else None
            v["rascunho"] = dict(r) if r else None
            virou = None if r else RASC.o_ato_do_rascunho(bd, v["item_id"])
            if virou:
                v["rotulo"] = f"#{v['item_id']} — já virou ato"
                v["ato_url"] = virou["endereco"]
        if v["tabela"] == "ri_protocolos":
            v["etapa"] = etapa_do_ri(bd, v["item_id"])
    return saida


def etapa_do_ri(con: Any, protocolo_id: int) -> str | None:
    """A etapa da prenotação, calculada pela régua do agente do RI
    (`ri_pedidos.etapa`) — uma régua só para o mesmo fato. Sem a tabela das
    qualificações (instalação antiga), devolve None em vez de inventar."""
    try:
        from datetime import date

        import ri_pedidos as RIP
        bd = banco(con)
        p = bd.um("SELECT * FROM ri_protocolos WHERE id=%s", (int(protocolo_id),))
        if not p:
            return None
        quals = RIP.qualificacoes_de(bd, protocolo_id)
        codigo = RIP.etapa(p, quals[-1] if quals else None, date.today().isoformat())
        return dict((c, nome) for c, nome, _ in RIP.ETAPAS).get(codigo, codigo)
    except (ImportError, sqlite3.Error):
        return None


def _todos_os_documentos(con: Any, task_id: int) -> list[dict]:
    """Os documentos do processo e de cada peça vinculada, com a marca de
    retirada quando houver. Só lê.

    `SELECT *` lido pela descrição do cursor, e não pela posição: as colunas da
    retirada (`retirado_em`, `retirado_motivo`, relato #135) nasceram depois, e
    banco que ainda não as tem continua respondendo — sem elas, nada foi
    retirado.
    """
    bd = banco(con)
    grupos = [("TASK", int(task_id), "anexado ao processo")]
    for v in vinculos(bd, task_id):
        for ent in TIPOS[v["tabela"]]["anexos"]:
            grupos.append((ent, v["item_id"], f"{v['nome'].lower()} {v['rotulo']}"))
    saida, vistos = [], set()
    for ent, eid, de_onde in grupos:
        for a in bd.ler("SELECT * FROM attachments "
                        "WHERE entity_type=%s AND entity_id=%s ORDER BY id", (ent, eid)):
            if a["id"] in vistos:
                continue
            vistos.add(a["id"])
            saida.append({"id": a["id"], "nome": a.get("original_name"),
                          "tamanho": a.get("size_bytes"), "em": a.get("uploaded_at"),
                          "de_onde": de_onde,
                          "retirado_em": a.get("retirado_em"),
                          "retirado_por": a.get("retirado_por"),
                          "retirado_motivo": a.get("retirado_motivo")})
    return saida


def documentos(con: Any, task_id: int) -> list[dict]:
    """Todos os documentos ATIVOS da pasta, de onde quer que estejam guardados:
    os do processo e os de cada peça vinculada. Só lê."""
    return [d for d in _todos_os_documentos(con, task_id) if not d["retirado_em"]]


def documentos_retirados(con: Any, task_id: int) -> list[dict]:
    """Os que foram retirados da peça com motivo — à parte, e não escondidos:
    documento que sustentou uma qualificação não some do rastro. Só lê."""
    return [d for d in _todos_os_documentos(con, task_id) if d["retirado_em"]]
