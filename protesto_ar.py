# -*- coding: utf-8 -*-
"""O AR DIGITAL DA INTIMAÇÃO — o aviso que vai pelos Correios, e o que volta.

O CAMINHO, do lado desta casa (LG06, 19/10/2026):

    1. o aviso de intimação é emitido como sempre (`protesto_aviso.emitir`) —
       o endereço congela nele;
    2. a POSTAGEM manda esse aviso aos Correios e guarda o número do objeto e
       o PRAZO-LIMITE da intimação, o mesmo que vai impresso no aviso
       (`protesto_aviso.prazo_limite`: três dias úteis da protocolização);
    3. o RETORNO traz o AR — entregue ou não, a data, quem recebeu e a imagem
       do canhoto assinado — e entra **pelo mesmo caminho da entrega feita pela
       mão da casa**: `protesto_aviso.registrar_entrega`. Entregue, lavra a
       intimação pessoal e anexa a imagem como comprovante; não entregue,
       deixa o aviso na fila «não entregues», que leva à Resolve e ao edital.

**A REGRA NÃO SE REPETE AQUI.** Quem lavra a intimação é `protesto`, quem
registra a tentativa e guarda o comprovante é `protesto_aviso`. Este módulo é o
correio: leva, traz, e diz o que trouxe. Escrever outra vez «entregue lavra a
intimação» seria a segunda versão de uma regra que já tem dono.

O TRÍDUO É O PRAZO DO AR. CN-MA (Prov. COGEX 28/2026), art. 921, § 2º: «Não
havendo devolução do AR pelos Correios dentro do tríduo legal, a intimação será
efetuada por pessoa vinculada ao próprio tabelionato.» Por isso a postagem
guarda o prazo-limite, e `sem_retorno` lista o AR que chegou ao último dia sem
voltar — é o alerta «AR não voltou» do painel do devedor. E o AR que volta
DEPOIS do prazo continua valendo como intimação; o que muda é a data do
protesto (art. 924: «somente será lavrado no primeiro dia útil subsequente»),
e a observação da postagem diz isso.

**NADA DISTO LIGA SOZINHO.** A integração nasce DESLIGADA
(`protesto_integracoes`); em homologação fala com o serviço falso e não lavra
nem anexa nada; em produção só fala com o transporte do contrato, que ainda não
existe. A chamada aos Correios acontece fora da transação, e o registro dela se
grava antes (a vaga) e depois (o número) — uma queda no meio deixa a tentativa
à vista como FALHOU, e não um aviso «postado» que não saiu.
"""
from __future__ import annotations

import json
import re
from typing import Any

import correios_api as CAPI
import protesto as PT
import protesto_aviso as AV
import protesto_integracoes as INTEG
from bd_nativo import banco
