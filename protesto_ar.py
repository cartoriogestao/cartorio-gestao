class ArError(ValueError):
    """Recusa de regra do AR, com a frase pronta para o balcão."""


# Quem entregou, na tentativa e no aviso. A grafia é a certa; o «CORREIROS» do
# cadastro do E-Ofício fica onde está (`protesto_aviso.ENTREGADORES`).
ENTREGADOR_CORREIOS = "CORREIOS"

SOLICITADA, POSTADA = "SOLICITADA", "POSTADA"
ENTREGUE, NAO_ENTREGUE = CAPI.ENTREGUE, CAPI.NAO_ENTREGUE
CONFERIR, FALHOU = "CONFERIR", "FALHOU"
SITUACOES: tuple[str, ...] = (SOLICITADA, POSTADA, ENTREGUE, NAO_ENTREGUE,
                              CONFERIR, FALHOU)
# A postagem viva: uma só por aviso e ambiente, e quem guarda isso é o índice
# único parcial, e não a conferência — dois cliques ao mesmo tempo passariam
# os dois na conferência.
SITUACOES_VIVAS: tuple[str, ...] = (SOLICITADA, POSTADA)

# O MOTIVO DOS CORREIOS NO CATÁLOGO DA CASA (`protesto_aviso.TODOS_OS_MOTIVOS`).
# É a tradução que faz o AR não entregue andar pela mesma fila do aviso que a
# casa não conseguiu entregar: «Ausente» (11) conta como tentativa; «Mudou-se»
# (1) vai direto ao edital, como no cadastro do E-Ofício.
#
#   `NUMERO_INEXISTENTE` vai para o 7, «Não existe o número indicado» — o texto
#   é o mesmo, palavra por palavra. O 7 está INATIVO no cadastro da casa (zero
#   usos, fora da lista da tela), e continua no catálogo justamente para ser
#   lido; ver «Dúvidas» no relatório do LG06.
MOTIVO_DA_CASA: dict[str, int] = {
    "AUSENTE": 11, "MUDOU_SE": 1, "ENDERECO_INSUFICIENTE": 9,
    "NUMERO_INEXISTENTE": 7, "RECUSADO": 3, "DESCONHECIDO": 8,
    "FALECIDO": 4, "NAO_PROCURADO": 13, "FORA_DA_AREA": 14,
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS pt_ar_postagens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- O AVISO QUE FOI PELO CORREIO, e o título dele. O aviso é o papel; a
    -- postagem é o caminho que ele fez.
    aviso_id bigint NOT NULL REFERENCES pt_avisos(id),
    titulo_id bigint NOT NULL REFERENCES pt_titulos(id),

    -- HOMOLOGACAO ou PRODUCAO, e quem respondeu. O de homologação nunca
    -- lavra, e a lista de produção não o mostra.
    ambiente TEXT NOT NULL,
    provedor TEXT NOT NULL,

    -- O NOSSO NÚMERO na postagem (aviso e tentativa) e o número do objeto
    -- que os Correios deram.
    identificador TEXT NOT NULL,
    codigo_objeto TEXT,
    situacao TEXT NOT NULL DEFAULT 'SOLICITADA',

    -- O PRAZO-LIMITE DA INTIMAÇÃO, congelado na postagem: é contra ele que
    -- se mede o AR que não voltou (CN-MA art. 921, § 2º).
    prazo_limite TEXT,
    destinatario_json TEXT NOT NULL DEFAULT '{}',
    -- O que os Correios cobraram, quando dizem (CN-MA art. 921, § 4º: a
    -- tarifa vai para o apresentante). NULL é «não informado», e não zero.
    tarifa_centavos bigint,

    solicitada_em TEXT NOT NULL,
    solicitada_por TEXT,
    postada_em TEXT,

    -- O RETORNO: quando chegou aqui, a data do AR, quem assinou e, se não
    -- entregou, o motivo dos Correios e o da casa.
    retorno_em TEXT,
    entrega_em TEXT,
    recebedor TEXT,
    motivo_correios TEXT,
    motivo INTEGER,
    -- A imagem do AR mora em `attachments`, como comprovante do AVISO
    -- (`protesto_aviso.ENTIDADE_DO_COMPROVANTE`); aqui fica só o número.
    anexo_id bigint,
    ato_id bigint REFERENCES pt_atos(id),
    observacao TEXT,
    resposta TEXT
);

CREATE INDEX IF NOT EXISTS ix_pt_ar_postagens_titulo
    ON pt_ar_postagens(titulo_id);
CREATE INDEX IF NOT EXISTS ix_pt_ar_postagens_situacao
    ON pt_ar_postagens(ambiente, situacao);
CREATE UNIQUE INDEX IF NOT EXISTS ux_pt_ar_postagens_objeto
    ON pt_ar_postagens(ambiente, codigo_objeto);
CREATE UNIQUE INDEX IF NOT EXISTS ux_pt_ar_postagens_viva
    ON pt_ar_postagens(aviso_id, ambiente)
    WHERE situacao IN ('SOLICITADA', 'POSTADA');
"""


def init_pt_ar_schema(con: Any) -> None:
    """Cria a tabela das postagens. Idempotente. Depois do Protesto."""
    bd = banco(con)
    for comando in re.sub(r"--[^\n]*", "", SCHEMA).split(";"):
        if comando.strip():
            bd.escrever(comando)


# ----------------------------------------------------------- a postagem


def _br(iso: Any) -> str:
    s = str(iso or "")[:10]
    return f"{s[8:10]}/{s[5:7]}/{s[:4]}" if len(s) == 10 and s[4] == "-" else s


def _destinatario(aviso: Any) -> dict:
    a = dict(aviso)
    return {"nome": a.get("devedor_nome"), "documento": a.get("devedor_documento"),
            "endereco": a.get("endereco"), "bairro": a.get("bairro"),
            "cep": a.get("cep"), "cidade": a.get("cidade"), "uf": a.get("uf")}


def _porque_nao(bd: Any, aviso: dict, titulo: dict | None) -> str:
    """Por que este aviso não pode ir pelo correio, ou vazio. SÓ LÊ."""
    if not titulo:
        return "o título do aviso não existe"
    if aviso.get("situacao") != "EMITIDO":
        return (f"o aviso está {str(aviso.get('situacao') or '').lower()} — só "
                f"vai pelo correio o aviso que ainda não teve desfecho")
    if titulo.get("situacao") not in AV.SITUACOES_QUE_ACEITAM_AVISO:
        return f"o título está {str(titulo.get('situacao') or '').lower()}"
    # SUSTADO NÃO SE INTIMA: a carta seria cobrança de quem o juiz mandou
    # parar (Lei 9.492/1997, art. 17) — a mesma régua da Resolve.
    if PT.sustacao_em_vigor(bd, int(titulo["id"])):
        return "o título está sustado por ordem judicial"
    try:
        CAPI.conferir_destinatario(_destinatario(aviso))
    except CAPI.CorreiosError as erro:
        return str(erro)
    if not AV.prazo_limite(bd, titulo):
        return ("o protocolo não diz a data da protocolização, e sem ela não "
                "há prazo-limite para medir o retorno do AR")
    return ""


def postaveis(con: Any, *, ambiente: str | None, limite: int = 200) -> list[dict]:
    """Os avisos emitidos que podem ir pelo correio — e os que não podem, com
    o motivo. SÓ LÊ.

    **O que não pode ir aparece, e não some**: a lista que esconde faz o
    balcão procurar o aviso e não achar (a lição da Resolve).
    """
    bd = banco(con)
    linhas = bd.ler(
        """SELECT a.*, t.numero_titulo, t.protocolo,
                  t.situacao AS situacao_do_titulo
             FROM pt_avisos a JOIN pt_titulos t ON t.id = a.titulo_id
            WHERE a.situacao = 'EMITIDO'
              AND NOT EXISTS (
                    SELECT 1 FROM pt_ar_postagens p
                     WHERE p.aviso_id = a.id AND p.ambiente = %s
                       AND p.situacao IN ('SOLICITADA', 'POSTADA'))
            ORDER BY a.id
            LIMIT %s""", (str(ambiente or ""), int(limite)))
    fora = []
    for linha in linhas:
        d = dict(linha)
        tit = PT.titulo(bd, int(d["titulo_id"]))
        d["porque_nao"] = _porque_nao(bd, d, tit)
        d["prazo_limite"] = AV.prazo_limite(bd, tit) if tit else None
        fora.append(d)
    return fora


def solicitar_postagem(db: Any, aviso_id: int, *, quem: str = "",
                       pasta: Any = None, transporte: Any = None,
                       cfg: dict | None = None) -> dict:
    """Manda o aviso pelo correio, com AR digital. **ESCREVE NOS CORREIOS.**

    RECEBE `db`, E A CHAMADA É FORA DA TRANSAÇÃO. São três passos: a vaga se
    grava (SOLICITADA, com o aviso preso), os Correios são chamados, e o número
    do objeto se grava depois. Se a chamada falhar, a vaga vira FALHOU — à
    vista, e liberando o aviso para outra tentativa.

    `transporte` e `cfg` existem para o teste; a tela não os passa, e então
    vale o que está ligado no Gestor.
    """
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.AR, pasta=pasta)
    ambiente, provedor = cfg["ambiente"], cfg["provedor"]
    INTEG.recusar_simulador_em_producao(ambiente, transporte)
    agora = db.now()

    with db.transaction() as con:
        bd = banco(con)
        aviso = AV._aviso_para_gravar(bd, aviso_id)
        if not aviso:
            raise ArError(f"Aviso {aviso_id} não encontrado.")
        tit = PT.titulo(bd, int(aviso["titulo_id"]))
        porque = _porque_nao(bd, dict(aviso), tit)
        if porque:
            raise ArError(
                f"O aviso {aviso['numero']}/{aviso['ano']} não vai pelo correio: "
                f"{porque}.")
        destinatario = CAPI.conferir_destinatario(_destinatario(aviso))
        prazo = AV.prazo_limite(bd, tit)
        n = int(bd.valor(
            "SELECT count(*) AS n FROM pt_ar_postagens WHERE aviso_id=%s",
            (int(aviso_id),)) or 0)
        identificador = f"AV{aviso['numero']}-{aviso['ano']}-{n + 1}"
        nova = bd.escrever(
            """INSERT INTO pt_ar_postagens(
                   aviso_id, titulo_id, ambiente, provedor, identificador,
                   situacao, prazo_limite, destinatario_json, solicitada_em,
                   solicitada_por)
               VALUES (%s,%s,%s,%s,%s,'SOLICITADA',%s,%s,%s,%s)
               ON CONFLICT (aviso_id, ambiente)
                   WHERE situacao IN ('SOLICITADA', 'POSTADA') DO NOTHING
               RETURNING id""",
            (int(aviso_id), int(aviso["titulo_id"]), ambiente, provedor,
             identificador, prazo, json.dumps(destinatario, ensure_ascii=False),
             agora, quem or None))
        if not nova:
            raise ArError(
                f"O aviso {aviso['numero']}/{aviso['ano']} já tem postagem em "
                f"andamento — uma carta por aviso.")
        postagem_id = int(nova[0]["id"])

    pedido = {"identificador": identificador, "destinatario": destinatario,
              "conteudo": f"Aviso de intimação {aviso['numero']}/{aviso['ano']}",
              "prazo_limite": prazo}
    try:
        r = transporte.postar(pedido)
    except Exception as erro:
        with db.transaction() as con:
            banco(con).escrever(
                """UPDATE pt_ar_postagens SET situacao='FALHOU', observacao=%s
                    WHERE id=%s AND situacao='SOLICITADA'""",
                (str(erro)[:500], postagem_id))
        if isinstance(erro, CAPI.CorreiosError):
            raise ArError(f"{erro} Nada foi postado; a tentativa ficou "
                          f"registrada como FALHOU.") from erro
        raise

    codigo = str((r or {}).get("codigo_objeto") or "").strip().upper()
    tarifa = (r or {}).get("tarifa_centavos")
    with db.transaction() as con:
        banco(con).escrever(
            """UPDATE pt_ar_postagens
                  SET situacao='POSTADA', codigo_objeto=%s, tarifa_centavos=%s,
                      postada_em=%s, resposta=%s
                WHERE id=%s AND situacao='SOLICITADA'""",
            (codigo or None, int(tarifa) if tarifa is not None else None,
             db.now(), json.dumps((r or {}).get("resposta") or {},
                                  ensure_ascii=False)[:4000], postagem_id))
    return {"postagem_id": postagem_id, "codigo_objeto": codigo,
            "ambiente": ambiente, "prazo_limite": prazo,
            "identificador": identificador, "aviso_id": int(aviso_id)}


# ------------------------------------------------------------- o retorno


def buscar_retornos(db: Any, *, quem: str = "", usuario_id: int | None = None,
                    pasta_de_arquivos: Any, pasta: Any = None,
                    transporte: Any = None, cfg: dict | None = None,
                    limite: int = 100) -> dict:
    """Pergunta aos Correios por cada AR que saiu e não voltou. LÊ LÁ, e o que
    voltou se registra aqui.

    **A FALHA APARECE, E NÃO VIRA ZERO**: objeto que não deu para consultar
    vai em `falhas`, e a tela diz quantos — um dia sem resposta não pode
    parecer um dia sem AR.
    """
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.AR, pasta=pasta)
    INTEG.recusar_simulador_em_producao(cfg["ambiente"], transporte)
    with db.connect() as con:
        fila = banco(con).ler(
            """SELECT id, codigo_objeto FROM pt_ar_postagens
                WHERE ambiente = %s AND provedor = %s AND situacao = 'POSTADA'
                  AND coalesce(codigo_objeto, '') <> ''
                ORDER BY postada_em, id LIMIT %s""",
            (cfg["ambiente"], cfg["provedor"], int(limite)))
    olhadas, voltaram, falhas = 0, [], []
    for item in fila:
        try:
            r = transporte.consultar(item["codigo_objeto"])
        except CAPI.CorreiosError as erro:
            falhas.append({"postagem_id": int(item["id"]), "porque": str(erro)})
            continue
        olhadas += 1
        if str((r or {}).get("estado") or "") not in (ENTREGUE, NAO_ENTREGUE):
            continue
        voltaram.append(registrar_retorno(
            db, int(item["id"]), r, quem=quem, usuario_id=usuario_id,
            pasta_de_arquivos=pasta_de_arquivos))
    return {"ambiente": cfg["ambiente"], "olhadas": olhadas,
            "voltaram": voltaram, "falhas": falhas}


def registrar_retorno(db: Any, postagem_id: int, retorno: dict, *,
                      quem: str = "", usuario_id: int | None = None,
                      pasta_de_arquivos: Any) -> dict:
    """Assenta o AR que voltou. ESCREVE — numa transação, ou em CONFERIR.

    **O QUE NÃO DÁ PARA ASSENTAR NÃO SE PERDE.** Título pago, sustado ou já
    encerrado, livro que falta, motivo que a casa não sabe traduzir: a
    transação volta atrás inteira (nada de intimação pela metade), e a
    postagem fica CONFERIR com a frase — é a lista de pendências da tela do AR.
    """
    agora = db.now()
    estado = str((retorno or {}).get("estado") or "").upper()
    data = str((retorno or {}).get("data") or "")[:10] or agora[:10]
    recebedor = str((retorno or {}).get("recebedor") or "").strip() or None
    motivo_correios = str((retorno or {}).get("motivo") or "").strip().upper()
    motivo = (MOTIVO_DA_CASA.get(motivo_correios) if estado == NAO_ENTREGUE
              else None)
    try:
        with db.transaction() as con:
            return _assentar(con, int(postagem_id), estado=estado, data=data,
                             recebedor=recebedor, motivo_correios=motivo_correios,
                             motivo=motivo, retorno=retorno or {}, agora=agora,
                             quem=quem, usuario_id=usuario_id,
                             pasta_de_arquivos=pasta_de_arquivos)
    except (ArError, AV.AvisoError, PT.ProtestoError, LivroError) as erro:
        with db.transaction() as con:
            bd = banco(con)
            bd._escrita()
            p = bd.um("SELECT situacao FROM pt_ar_postagens WHERE id=%s FOR UPDATE",
                      (int(postagem_id),))
            if p and p["situacao"] == POSTADA:
                bd.escrever(
                    """UPDATE pt_ar_postagens
                          SET situacao='CONFERIR', retorno_em=%s, entrega_em=%s,
                              recebedor=%s, motivo_correios=%s, motivo=%s,
                              observacao=%s
                        WHERE id=%s""",
                    (agora, data, recebedor, motivo_correios or None, motivo,
                     (f"O AR voltou {('entregue' if estado == ENTREGUE else 'não entregue')}"
                      f" e não foi assentado: {erro}")[:1000], int(postagem_id)))
        return {"postagem_id": int(postagem_id), "situacao": CONFERIR,
                "motivo": str(erro), "ato_id": None}


def _assentar(con: Any, postagem_id: int, *, estado: str, data: str,
              recebedor: str | None, motivo_correios: str, motivo: int | None,
              retorno: dict, agora: str, quem: str, usuario_id: int | None,
              pasta_de_arquivos: Any) -> dict:
    """O retorno, dentro da transação. A ORDEM DAS TRAVAS é a do resto do
    aviso: o aviso primeiro, depois a postagem, e o título por último (quem o
    prende é `protesto.lancar_intimacao`)."""
    if estado not in (ENTREGUE, NAO_ENTREGUE):
        raise ArError(f"O retorno não diz se o AR foi entregue: «{estado}».")
    bd = banco(con)
    p0 = bd.um("SELECT aviso_id FROM pt_ar_postagens WHERE id=%s",
               (postagem_id,))
    if not p0:
        raise ArError(f"Postagem {postagem_id} não encontrada.")
    aviso = AV._aviso_para_gravar(bd, int(p0["aviso_id"]))
    bd._escrita()
    p = bd.um("SELECT * FROM pt_ar_postagens WHERE id=%s FOR UPDATE",
              (postagem_id,))
    if p["situacao"] != POSTADA:
        # O SEGUNDO CLIQUE NÃO ASSENTA DUAS VEZES: quem chegou primeiro já
        # mudou a situação, e aqui só se devolve o que ficou.
        return {"postagem_id": postagem_id, "situacao": p["situacao"],
                "ato_id": p["ato_id"], "ja_estava": True}

    codigo = p["codigo_objeto"] or "?"
    obs = [f"AR digital dos Correios, objeto {codigo}"]
    if p["prazo_limite"] and data > str(p["prazo_limite"]):
        obs.append(f"o AR voltou com data posterior ao prazo-limite "
                   f"({_br(p['prazo_limite'])}); se a intimação vale, o "
                   f"protesto só se lavra no primeiro dia útil seguinte "
                   f"(CN-MA art. 924)")
    ato_id = anexo_id = None
    producao = p["ambiente"] == INTEG.PRODUCAO
    if not producao:
        obs.append("homologação: nada se lavra nem se anexa")
    elif aviso["situacao"] in ("EMITIDO", "NAO_ENTREGUE"):
        if estado == NAO_ENTREGUE and motivo is None:
            raise ArError(
                f"o motivo dos Correios «{motivo_correios or 'vazio'}» não tem "
                f"tradução no catálogo de não-entrega da casa")
        # O AR ENTREGUE LEVA A IMAGEM NO MESMO ATO (29/10/2026, ordem do
        # oficial: entrega só com o comprovante e com quem recebeu). Sem a
        # imagem ou sem o recebedor, `registrar_entrega` recusa — e a recusa
        # põe a postagem em CONFERIR, com a frase: o robô não afirma nada por
        # ninguém, e quem resolve é o balcão, na tela dos avisos.
        entregue = estado == ENTREGUE
        if entregue:
            # A TRAVA DA CENPROT TAMBÉM NO AR (integração de 29/10/2026). O
            # título que a Central dá por PAGO POR LIQUIDAÇÃO não se intima —
            # lá isso não se altera (o oficial, 29/10/2026, PR #105). Na ficha
            # a escrevente vence a trava afirmando; o AR é robô, e robô não
            # afirma: a recusa põe a postagem em CONFERIR, com a frase.
            import cenprot_conferencia as CCONF
            try:
                CCONF.trava_sem_rede(
                    con, int(aviso["titulo_id"]), "INTIMACAO", robo=True,
                    onde_afirmar=(
                        "O AR não afirma por ninguém: confira a CENPROT e, se "
                        "for o caso, registre a entrega deste aviso pela tela "
                        "«Avisos e editais», onde a afirmação se faz."))
            except CCONF.ConferenciaError as erro:
                raise ArError(str(erro)) from None
        imagem_da_entrega = retorno.get("imagem") if entregue else None
        r = AV.registrar_entrega(
            con, int(aviso["id"]), entregue=entregue, agora=agora,
            quando=data, entregador=ENTREGADOR_CORREIOS, motivo=motivo,
            recebido_por=recebedor, observacao="; ".join(obs), usuario=quem or None,
            comprovante_nome=((retorno.get("imagem_nome") or f"AR-{codigo}.png")
                              if imagem_da_entrega else None),
            comprovante_conteudo=imagem_da_entrega or None,
            pasta_de_arquivos=(pasta_de_arquivos if imagem_da_entrega
                               else None),
            usuario_id=usuario_id)
        ato_id = r["ato_id"]
        anexo_id = r.get("anexo_id")
    else:
        obs.append(f"o aviso já estava {str(aviso['situacao']).lower()} — o AR "
                   f"ficou registrado sem lavrar ato")

    imagem = retorno.get("imagem")
    if producao and imagem and anexo_id is None:
        agora_aviso = AV.ler(bd, int(aviso["id"]))
        if agora_aviso and agora_aviso["situacao"] in AV.SITUACOES_COM_COMPROVANTE:
            try:
                anexo_id = AV.guardar_comprovante(
                    con, int(aviso["id"]),
                    nome=retorno.get("imagem_nome") or f"AR-{codigo}.png",
                    conteudo=imagem, pasta_de_arquivos=pasta_de_arquivos,
                    agora=agora, usuario_id=usuario_id)["anexo_id"]
            except AV.AvisoError as erro:
                obs.append(f"a imagem do AR não foi anexada: {erro}")

    situacao = ENTREGUE if estado == ENTREGUE else NAO_ENTREGUE
    bd.escrever(
        """UPDATE pt_ar_postagens
              SET situacao=%s, retorno_em=%s, entrega_em=%s, recebedor=%s,
                  motivo_correios=%s, motivo=%s, anexo_id=%s, ato_id=%s,
                  observacao=%s
            WHERE id=%s""",
        (situacao, agora, data, recebedor, motivo_correios or None, motivo,
         anexo_id, ato_id, "; ".join(obs)[:1000], postagem_id))
    return {"postagem_id": postagem_id, "situacao": situacao, "ato_id": ato_id,
            "anexo_id": anexo_id, "aviso_id": int(aviso["id"]),
            "codigo_objeto": codigo}


def simular_retorno(db: Any, postagem_id: int, *, entregue: bool, data: str,
                    recebedor: str = "", motivo: str = "",
                    pasta: Any = None, transporte: Any = None,
                    cfg: dict | None = None) -> dict:
    """O carteiro da HOMOLOGAÇÃO: diz ao serviço falso como o AR voltou.

    **Só com o serviço falso e só em postagem de homologação** — em produção
    quem diz como o AR voltou são os Correios, e mais ninguém.
    """
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.AR, pasta=pasta)
    if cfg["modo"] != INTEG.HOMOLOGACAO or not INTEG.e_simulador(transporte):
        raise ArError("Simular o retorno do AR só existe na homologação, com o "
                      "serviço falso.")
    with db.connect() as con:
        p = banco(con).um("SELECT * FROM pt_ar_postagens WHERE id=%s",
                          (int(postagem_id),))
    if not p or p["ambiente"] != INTEG.HOMOLOGACAO or p["situacao"] != POSTADA:
        raise ArError("Só se simula o retorno de postagem de homologação que "
                      "ainda não voltou.")
    try:
        return transporte.simular_retorno(
            p["codigo_objeto"], entregue=entregue, data=data,
            recebedor=recebedor, motivo=motivo)
    except CAPI.CorreiosError as erro:
        raise ArError(str(erro)) from erro


