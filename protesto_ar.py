def postagens(con: Any, *, ambiente: str | None = None,
              limite: int = 200) -> list[dict]:
    """As postagens, da mais nova para a mais velha. SÓ LÊ."""
    onde, args = "", []
    if ambiente:
        onde, args = "WHERE p.ambiente = %s", [ambiente]
    return [dict(x) for x in banco(con).ler(
        f"""SELECT p.*, a.numero AS aviso_numero, a.ano AS aviso_ano,
                   a.devedor_nome, t.numero_titulo, t.protocolo,
                   t.situacao AS situacao_do_titulo
              FROM pt_ar_postagens p
              JOIN pt_avisos a ON a.id = p.aviso_id
              JOIN pt_titulos t ON t.id = p.titulo_id
              {onde}
             ORDER BY p.id DESC LIMIT %s""", [*args, int(limite)])]


def sem_retorno(con: Any, *, hoje: str, limite: int = 200) -> list[dict]:
    """O AR que chegou ao prazo-limite sem voltar — em PRODUÇÃO. SÓ LÊ.

    CN-MA art. 921, § 2º: sem a devolução dentro do tríduo, a intimação vai
    por pessoa da casa. **No próprio dia do prazo ele já aparece**: é o último
    dia em que o portador ainda chega a tempo.
    """
    return [dict(x) for x in banco(con).ler(
        """SELECT p.*, a.numero AS aviso_numero, a.ano AS aviso_ano,
                  a.devedor_nome, t.numero_titulo, t.protocolo
             FROM pt_ar_postagens p
             JOIN pt_avisos a ON a.id = p.aviso_id
             JOIN pt_titulos t ON t.id = p.titulo_id
            WHERE p.ambiente = %s AND p.situacao = 'POSTADA'
              AND p.prazo_limite IS NOT NULL AND p.prazo_limite <= %s
            ORDER BY p.prazo_limite, p.id LIMIT %s""",
        (INTEG.PRODUCAO, str(hoje)[:10], int(limite)))]


def do_titulo(con: Any, titulo_id: int) -> list[dict]:
    """As postagens de PRODUÇÃO de um título, na ordem. SÓ LÊ."""
    return [dict(x) for x in banco(con).ler(
        """SELECT * FROM pt_ar_postagens
            WHERE titulo_id = %s AND ambiente = %s ORDER BY id""",
        (int(titulo_id), INTEG.PRODUCAO))]


def contagens(con: Any, *, ambiente: str | None) -> dict:
    """Quantas postagens em cada situação, naquele ambiente. SÓ LÊ."""
    achado = {r["situacao"]: int(r["n"]) for r in banco(con).ler(
        """SELECT situacao, count(*) AS n FROM pt_ar_postagens
            WHERE ambiente = %s GROUP BY situacao ORDER BY situacao""",
        (str(ambiente or ""),))}
    return {s: achado.get(s, 0) for s in SITUACOES}
