# -*- coding: utf-8 -*-
"""O BOLETO DO DEVEDOR — emitir, cancelar e dar baixa pelo que o banco pagou.

O QUE O CÓDIGO DE NORMAS DIZ (Prov. COGEX 28/2026, art. 925):
    § 2º — o pagamento por meios eletrônicos, «dentre os quais boleto bancário,
           transferência bancária (DOC, TED, PIX ou outro meio equivalente)»;
    § 4º — «O prazo-limite para pagamento é o dia previsto para a lavratura do
           protesto»: é o VENCIMENTO do boleto, e ele sai da mesma conta que vai
           impressa no aviso (`protesto_aviso.prazo_limite`);
    § 5º — o custo do boleto que acompanha a intimação pode ser repassado ao
           devedor: é a tarifa do Gestor, que nasce zero;
    § 7º — os custos de cada forma de pagamento se apresentam ANTES: por isso o
           boleto guarda a composição (título, emolumentos e despesas, tarifa),
           e a tela a mostra.

A BAIXA AUTOMÁTICA, E ATÉ ONDE ELA VAI
    Buscar os pagamentos pergunta ao banco o que foi liquidado e, para cada
    liquidação, procura o boleto pelo nosso número. **Dá baixa sozinha só
    quando tudo bate**: boleto aberto, valor pago IGUAL ao do boleto, título
    numa situação que aceita pagamento e sem sustação. A baixa é o mesmo
    `protesto.lancar_pagamento` do balcão — forma BOLETO, com a identificação
    —, e por isso ocupa lugar no Livro de Registro de Pagamentos como qualquer
    outro (CN-MA art. 930).

    **O resto vira CONFERIR, e não decisão do programa**: valor diferente
    (pagamento parcial é do oficial — `protesto.lancar_pagamento` diz o mesmo),
    título que já foi pago no balcão ou desistido (o dinheiro entrou duas vezes
    e alguém tem de devolver), título sustado (art. 17, § 1º: só com
    autorização judicial), boleto cancelado que ainda assim foi pago, ou
    liquidação de boleto que a casa não conhece. Cada uma fica na lista de
    pendências com a frase, até alguém dizer o que fez.

    **Nada roda por relógio**: a busca é um botão, como o «perguntar o estado»
    da Resolve. E é idempotente — a liquidação já vista não se assenta de novo
    (índice único do evento do banco).

HOMOLOGAÇÃO NÃO DÁ BAIXA. O boleto do serviço falso «pago» fica PAGO na lista
de homologação, e o título não muda. Ver `protesto_integracoes`.

A CHAMADA AO BANCO É FORA DA TRANSAÇÃO, e a vaga se grava antes (PENDENTE):
uma queda no meio deixa a tentativa à vista, e não um boleto que o banco tem e
a casa não sabe.
"""
