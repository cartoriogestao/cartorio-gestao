class BoletoDominioError(ValueError):
    """Recusa de regra do boleto, com a frase pronta para o balcão."""


PENDENTE, EMITIDO, SEM_RESPOSTA = "PENDENTE", "EMITIDO", "SEM_RESPOSTA"
RECUSADO, PAGO, CONFERIR, CANCELADO = "RECUSADO", "PAGO", "CONFERIR", "CANCELADO"
SITUACOES: tuple[str, ...] = (PENDENTE, EMITIDO, SEM_RESPOSTA, RECUSADO, PAGO,
                              CONFERIR, CANCELADO)
# O boleto VIVO — um só por título e ambiente, e quem garante é o índice
# único parcial. `SEM_RESPOSTA` conta como vivo de propósito: o banco pode ter
# registrado, e um segundo boleto faria o devedor ver dois e pagar os dois.
SITUACOES_VIVAS: tuple[str, ...] = (PENDENTE, EMITIDO, SEM_RESPOSTA)

BAIXADO, SEM_BOLETO, ENSAIO = "BAIXADO", "SEM_BOLETO", "HOMOLOGACAO"

# Os títulos que aceitam boleto: os que esperam o prazo-limite. Recebido ainda
# não tem protocolo (e sem protocolo não há prazo); os outros já se resolveram.
SITUACOES_QUE_ACEITAM_BOLETO = ("APONTADO", "INTIMADO")

