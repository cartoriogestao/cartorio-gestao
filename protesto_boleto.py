def init_pt_boleto_schema(con: Any) -> None:
    """Cria as tabelas do boleto. Idempotente. Depois do Protesto."""
    bd = banco(con)
    for comando in re.sub(r"--[^\n]*", "", SCHEMA).split(";"):
        if comando.strip():
            bd.escrever(comando)


def _texto_em_reais(c: int) -> str:
    """`1310.45` — o texto que `caixa_schema.centavos` lê de volta sem susto.

    **Inteiro não serve**: `centavos(131045)` leria cento e trinta e um mil
    REAIS (inteiro pequeno é tomado como reais). Por isso o valor vai como
    texto com ponto.
    """
    c = int(c)
    return f"{c // 100}.{c % 100:02d}"


def _br(iso: Any) -> str:
    s = str(iso or "")[:10]
    return f"{s[8:10]}/{s[5:7]}/{s[:4]}" if len(s) == 10 and s[4] == "-" else s


def _pagador(bd: Any, titulo_id: int) -> dict | None:
    linha = bd.um(
        """SELECT nome, documento_numero, endereco, bairro, cep, cidade, uf
             FROM pt_devedores WHERE titulo_id=%s ORDER BY id LIMIT 1""",
        (int(titulo_id),))
    if not linha:
        return None
    return {"nome": linha["nome"], "documento": linha["documento_numero"],
            "endereco": linha["endereco"], "bairro": linha["bairro"],
            "cep": linha["cep"], "cidade": linha["cidade"], "uf": linha["uf"]}


def composicao(titulo: Any, *, emolumentos_centavos: int,
               tarifa_centavos: int) -> dict:
    """O que o devedor paga, parcela por parcela. Só calcula.

    O valor do título é o SALDO quando há (é o que o aviso cobra), senão o
    valor de face — a mesma escolha de `protesto_aviso.montar_teor_do_aviso`.
    """
    t = dict(titulo)
    do_titulo = int(t.get("saldo_centavos") or t.get("valor_centavos") or 0)
    emol, tarifa = int(emolumentos_centavos), int(tarifa_centavos)
    return {"valor_titulo_centavos": do_titulo, "emolumentos_centavos": emol,
            "tarifa_centavos": tarifa, "valor_centavos": do_titulo + emol + tarifa}


def _porque_nao(bd: Any, titulo: dict | None, *, hoje: str) -> str:
    """Por que este título não pode ter boleto agora, ou vazio. SÓ LÊ."""
    if not titulo:
        return "o título não existe"
    if titulo.get("situacao") not in SITUACOES_QUE_ACEITAM_BOLETO:
        return f"o título está {str(titulo.get('situacao') or '').lower()}"
    if PT.sustacao_em_vigor(bd, int(titulo["id"])):
        # Art. 17, § 1º: o sustado só se paga com autorização judicial —
        # boleto seria convite a pagar o que o juiz mandou parar.
        return "o título está sustado por ordem judicial"
    limite = AV.prazo_limite(bd, titulo)
    if not limite:
        return ("o protocolo não diz a data da protocolização, e sem ela não há "
                "prazo-limite — que é o vencimento do boleto")
    if limite < str(hoje)[:10]:
        return f"o prazo-limite para pagamento já passou ({_br(limite)})"
    return ""


def emitiveis(con: Any, *, hoje: str, ambiente: str | None,
              limite: int = 200) -> list[dict]:
    """Os títulos que esperam o prazo e ainda não têm boleto vivo, com o motivo
    de quem não pode ter. SÓ LÊ."""
    bd = banco(con)
    linhas = bd.ler(
        """SELECT t.*,
                  (SELECT d.nome FROM pt_devedores d WHERE d.titulo_id = t.id
                    ORDER BY d.id LIMIT 1) AS devedor_nome
             FROM pt_titulos t
            WHERE t.situacao IN ('APONTADO', 'INTIMADO')
              AND NOT EXISTS (
                    SELECT 1 FROM pt_boletos b
                     WHERE b.titulo_id = t.id AND b.ambiente = %s
                       AND b.situacao IN ('PENDENTE', 'EMITIDO', 'SEM_RESPOSTA'))
            ORDER BY t.id
            LIMIT %s""", (str(ambiente or ""), int(limite)))
    fora = []
    for linha in linhas:
        d = dict(linha)
        d["porque_nao"] = _porque_nao(bd, d, hoje=hoje)
        if not d["porque_nao"]:
            try:
                BAPI.conferir_pedido({"valor_centavos": 1, "vencimento": hoje,
                                      "pagador": _pagador(bd, int(d["id"])) or {}})
            except BAPI.BoletoError as erro:
                d["porque_nao"] = str(erro)
        d["prazo_limite"] = AV.prazo_limite(bd, d)
        fora.append(d)
    return fora


# --------------------------------------------------------------- emitir


def emitir(db: Any, titulo_id: int, *, emolumentos: Any, hoje: str,
           quem: str = "", pasta: Any = None, transporte: Any = None,
           cfg: dict | None = None) -> dict:
    """Registra o boleto do título no banco. **ESCREVE NO BANCO.**

    OS EMOLUMENTOS SÃO DE QUEM EMITE, e não deste módulo: é dinheiro que o
    devedor paga, e o valor derivado sem ninguém conferir é o engano que só
    aparece no balcão (a mesma regra de `resolve_intimacao.montar`). Zero se
    digita — não se presume.
    """
    if emolumentos is None or not str(emolumentos).strip():
        raise BoletoDominioError(
            "Informe os emolumentos e despesas que vão no boleto (zero, se for o "
            "caso, digitado) — o valor que o devedor paga não se presume.")
    emol = centavos(str(emolumentos))
    if emol < 0:
        raise BoletoDominioError("Os emolumentos não podem ser negativos.")
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.BOLETO, pasta=pasta)
    ambiente, provedor = cfg["ambiente"], cfg["provedor"]
    INTEG.recusar_simulador_em_producao(ambiente, transporte)
    agora = db.now()

    with db.transaction() as con:
        bd = banco(con)
        tit = PT.titulo_para_gravar(bd, titulo_id)
        porque = _porque_nao(bd, tit, hoje=hoje)
        if porque:
            raise BoletoDominioError(
                f"O título {(tit or {}).get('numero_titulo') or titulo_id} não "
                f"pode ter boleto agora: {porque}.")
        pagador = _pagador(bd, int(titulo_id)) or {}
        partes = composicao(tit, emolumentos_centavos=emol,
                            tarifa_centavos=int(cfg.get("tarifa_centavos") or 0))
        vencimento = AV.prazo_limite(bd, tit)
        pedido = {"valor_centavos": partes["valor_centavos"],
                  "vencimento": vencimento, "pagador": pagador}
        try:
            BAPI.conferir_pedido(pedido)
        except BAPI.BoletoError as erro:
            raise BoletoDominioError(str(erro)) from erro
        n = int(bd.valor("SELECT count(*) AS n FROM pt_boletos WHERE titulo_id=%s",
                         (int(titulo_id),)) or 0)
        identificador = f"PT{int(titulo_id)}-{n + 1}"
        nova = bd.escrever(
            """INSERT INTO pt_boletos(
                   titulo_id, ambiente, provedor, identificador, situacao,
                   valor_titulo_centavos, emolumentos_centavos, tarifa_centavos,
                   valor_centavos, vencimento, pagador_json, emitido_em,
                   emitido_por)
               VALUES (%s,%s,%s,%s,'PENDENTE',%s,%s,%s,%s,%s,%s,%s,%s)
               ON CONFLICT (titulo_id, ambiente)
                   WHERE situacao IN ('PENDENTE', 'EMITIDO', 'SEM_RESPOSTA')
                   DO NOTHING
               RETURNING id""",
            (int(titulo_id), ambiente, provedor, identificador,
             partes["valor_titulo_centavos"], partes["emolumentos_centavos"],
             partes["tarifa_centavos"], partes["valor_centavos"], vencimento,
             json.dumps(pagador, ensure_ascii=False), agora, quem or None))
        if not nova:
            raise BoletoDominioError(
                f"O título {tit['numero_titulo']} já tem boleto em aberto. "
                f"Cancele aquele antes de emitir outro — dois boletos vivos são "
                f"dois convites a pagar.")
        boleto_id = int(nova[0]["id"])

    pedido.update({"identificador": identificador,
                   "mensagem": (f"Protocolo {tit.get('protocolo') or '-'} — "
                                f"título {tit.get('numero_titulo') or '-'}. "
                                f"Pagável até {_br(vencimento)}.")})
    try:
        r = transporte.registrar(pedido)
    except BAPI.BoletoRecusado as erro:
        _marcar(db, boleto_id, RECUSADO, str(erro))
        raise BoletoDominioError(f"O banco recusou o boleto: {erro}") from erro
    except Exception as erro:
        # A RESPOSTA SE PERDEU: o banco pode ter registrado. Fica SEM_RESPOSTA
        # — vivo, bloqueando outro — até alguém conferir no banco.
        _marcar(db, boleto_id, SEM_RESPOSTA, str(erro))
        if isinstance(erro, BAPI.BoletoError):
            raise BoletoDominioError(
                f"Não deu para confirmar o registro no banco: {erro}. O boleto "
                f"ficou SEM RESPOSTA — use «Conferir no banco» antes de emitir "
                f"outro.") from erro
        raise
    _gravar_registro(db, boleto_id, r)
    return {"boleto_id": boleto_id, "ambiente": ambiente,
            "identificador": identificador, **partes, "vencimento": vencimento,
            "nosso_numero": (r or {}).get("nosso_numero")}


def _marcar(db: Any, boleto_id: int, situacao: str, porque: str) -> None:
    with db.transaction() as con:
        banco(con).escrever(
            """UPDATE pt_boletos SET situacao=%s, observacao=%s
                WHERE id=%s AND situacao IN ('PENDENTE', 'SEM_RESPOSTA')""",
            (situacao, str(porque)[:500], int(boleto_id)))


def _gravar_registro(db: Any, boleto_id: int, r: dict) -> None:
    r = r or {}
    with db.transaction() as con:
        banco(con).escrever(
            """UPDATE pt_boletos
                  SET situacao='EMITIDO', nosso_numero=%s, id_no_provedor=%s,
                      linha_digitavel=%s, codigo_barras=%s,
                      pix_copia_e_cola=%s, resposta=%s
                WHERE id=%s AND situacao IN ('PENDENTE', 'SEM_RESPOSTA')""",
            (str(r.get("nosso_numero") or "").strip() or None,
             r.get("id_no_provedor") or None, r.get("linha_digitavel") or None,
             r.get("codigo_barras") or None, r.get("pix_copia_e_cola") or None,
             json.dumps(r.get("resposta") or {}, ensure_ascii=False)[:4000],
             int(boleto_id)))


def conferir_no_banco(db: Any, boleto_id: int, *, pasta: Any = None,
                      transporte: Any = None, cfg: dict | None = None) -> dict:
    """O boleto SEM RESPOSTA: o banco o tem ou não? LÊ LÁ, e grava aqui.

    Pergunta pelo «seu número». Se o banco o tem, o boleto vira EMITIDO com o
    que ele devolveu; se não tem, vira RECUSADO, e o título pode ter outro.
    """
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.BOLETO, pasta=pasta)
    with db.connect() as con:
        b = banco(con).um("SELECT * FROM pt_boletos WHERE id=%s", (int(boleto_id),))
    if not b or b["situacao"] != SEM_RESPOSTA:
        raise BoletoDominioError("Só se confere no banco o boleto que ficou sem "
                                 "resposta.")
    if b["ambiente"] != cfg["ambiente"] or b["provedor"] != cfg["provedor"]:
        raise BoletoDominioError(
            "Este boleto foi pedido em outro ambiente ou a outro provedor do que "
            "está ligado agora — não se pergunta a quem não o recebeu.")
    try:
        achado = transporte.consultar(b["identificador"])
    except BAPI.BoletoError as erro:
        raise BoletoDominioError(f"O banco não respondeu: {erro}") from erro
    if achado:
        _gravar_registro(db, int(boleto_id), achado)
        return {"boleto_id": int(boleto_id), "situacao": EMITIDO}
    _marcar(db, int(boleto_id), RECUSADO,
            "conferido no banco: o boleto não foi registrado")
    return {"boleto_id": int(boleto_id), "situacao": RECUSADO}


# -------------------------------------------------------------- cancelar


def cancelar(db: Any, boleto_id: int, *, motivo: str, quem: str = "",
             pasta: Any = None, transporte: Any = None,
             cfg: dict | None = None) -> dict:
    """Pede ao banco a baixa do boleto aberto. **ESCREVE NO BANCO.**

    É o que se faz quando o título foi pago no balcão, desistido ou sustado:
    deixar o boleto vivo é deixar o devedor pagar duas vezes. O motivo é
    obrigatório — boleto que some sem porquê é o que a correição pergunta.
    """
    porque = " ".join(str(motivo or "").split())
    if len(porque) < 5:
        raise BoletoDominioError("Escreva o motivo do cancelamento do boleto.")
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.BOLETO, pasta=pasta)
    with db.connect() as con:
        b = banco(con).um("SELECT * FROM pt_boletos WHERE id=%s", (int(boleto_id),))
    if not b or b["situacao"] != EMITIDO:
        raise BoletoDominioError("Só se cancela boleto EMITIDO.")
    if b["ambiente"] != cfg["ambiente"] or b["provedor"] != cfg["provedor"]:
        raise BoletoDominioError(
            "Este boleto foi registrado em outro ambiente ou noutro provedor do "
            "que está ligado agora.")
    try:
        transporte.cancelar(b["nosso_numero"])
    except BAPI.BoletoError as erro:
        raise BoletoDominioError(f"O banco não deu baixa: {erro}") from erro
    agora = db.now()
    with db.transaction() as con:
        bd = banco(con)
        bd._escrita()
        atual = bd.um("SELECT situacao FROM pt_boletos WHERE id=%s FOR UPDATE",
                      (int(boleto_id),))
        if atual and atual["situacao"] == EMITIDO:
            bd.escrever(
                """UPDATE pt_boletos SET situacao='CANCELADO', cancelado_em=%s,
                          cancelado_por=%s, observacao=%s WHERE id=%s""",
                (agora, quem or None, porque[:500], int(boleto_id)))
    return {"boleto_id": int(boleto_id), "situacao": CANCELADO}


# ------------------------------------------------- os pagamentos do banco


def buscar_pagamentos(db: Any, *, sv: dict, data_extenso: str, hoje: str,
                      quem: str = "", pasta: Any = None, transporte: Any = None,
                      cfg: dict | None = None) -> dict:
    """Pergunta ao banco o que foi pago e dá baixa no que bate. LÊ LÁ, e lavra
    aqui o pagamento que bate por inteiro.

    O período começa no boleto vivo mais antigo do ambiente (e nunca mais de
    sessenta dias atrás): é o que pode ter sido pago. Sem boleto vivo, não se
    pergunta nada.
    """
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.BOLETO, pasta=pasta)
    INTEG.recusar_simulador_em_producao(cfg["ambiente"], transporte)
    with db.connect() as con:
        mais_antigo = banco(con).valor(
            """SELECT min(emitido_em) AS m FROM pt_boletos
                WHERE ambiente = %s AND provedor = %s
                  AND situacao IN ('EMITIDO', 'SEM_RESPOSTA')""",
            (cfg["ambiente"], cfg["provedor"]))
    if not mais_antigo:
        return {"ambiente": cfg["ambiente"], "perguntou": False, "vistas": 0,
                "baixadas": [], "conferir": [], "ja_vistas": 0}
    piso = (date.fromisoformat(str(hoje)[:10]) - timedelta(days=60)).isoformat()
    desde = max(str(mais_antigo)[:10], piso)
    try:
        lista = transporte.liquidacoes(desde, str(hoje)[:10])
    except BAPI.BoletoError as erro:
        raise BoletoDominioError(f"O banco não respondeu: {erro}") from erro

    baixadas, conferir, ja_vistas = [], [], 0
    for liq in lista or []:
        r = conciliar(db, liq, cfg=cfg, sv=sv, data_extenso=data_extenso,
                      quem=quem)
        if r["situacao"] == "JA_VISTA":
            ja_vistas += 1
        elif r["situacao"] in (BAIXADO, ENSAIO):
            baixadas.append(r)
        else:
            conferir.append(r)
    return {"ambiente": cfg["ambiente"], "perguntou": True,
            "vistas": len(lista or []), "baixadas": baixadas,
            "conferir": conferir, "ja_vistas": ja_vistas, "desde": desde}


def conciliar(db: Any, liquidacao: dict, *, cfg: dict, sv: dict,
              data_extenso: str, quem: str = "") -> dict:
    """Assenta UMA liquidação do banco. ESCREVE — baixa, ou pendência.

    Numa transação só: a liquidação, o pagamento lavrado e o boleto pago. Se
    o pagamento não puder ser lavrado, a transação volta inteira e a liquidação
    entra de novo, sozinha, como CONFERIR com a frase.
    """
    agora = db.now()
    liq = {"evento_id": str(liquidacao.get("evento_id") or "").strip(),
           "nosso_numero": str(liquidacao.get("nosso_numero") or "").strip(),
           "valor": int(liquidacao.get("valor_pago_centavos") or 0),
           "pago_em": str(liquidacao.get("pago_em") or "")[:10] or None,
           "creditado_em": str(liquidacao.get("creditado_em") or "")[:10] or None}
    if not liq["evento_id"]:
        raise BoletoDominioError("O banco devolveu liquidação sem identificação.")
    try:
        with db.transaction() as con:
            return _assentar(con, liq, cfg=cfg, sv=sv, data_extenso=data_extenso,
                             quem=quem, agora=agora)
    except (PT.ProtestoError, LivroError, BoletoDominioError) as erro:
        with db.transaction() as con:
            bd = banco(con)
            b = bd.um("""SELECT id FROM pt_boletos WHERE ambiente=%s AND provedor=%s
                           AND nosso_numero=%s""",
                      (cfg["ambiente"], cfg["provedor"], liq["nosso_numero"]))
            nova = _inserir_liquidacao(bd, liq, cfg=cfg, situacao=CONFERIR,
                                       motivo=str(erro), boleto_id=(b or {}).get("id"),
                                       agora=agora, quem=quem)
            if nova and b:
                bd._escrita()
                bd.um("SELECT id FROM pt_boletos WHERE id=%s FOR UPDATE", (b["id"],))
                bd.escrever(
                    """UPDATE pt_boletos SET situacao='CONFERIR', pago_em=%s,
                              valor_pago_centavos=%s, observacao=%s
                        WHERE id=%s AND situacao IN ('EMITIDO','SEM_RESPOSTA',
                                                     'CANCELADO')""",
                    (liq["pago_em"], liq["valor"], str(erro)[:500], b["id"]))
        return {"evento_id": liq["evento_id"], "situacao": CONFERIR if nova
                else "JA_VISTA", "motivo": str(erro)}


def _inserir_liquidacao(bd: Any, liq: dict, *, cfg: dict, situacao: str,
                        motivo: str | None, boleto_id: Any, agora: str,
                        quem: str, ato_id: Any = None) -> int | None:
    nova = bd.escrever(
        """INSERT INTO pt_boletos_liquidacoes(
               ambiente, provedor, evento_id, nosso_numero, boleto_id,
               valor_pago_centavos, pago_em, creditado_em, situacao, motivo,
               ato_id, recebida_em, recebida_por, resposta)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
           ON CONFLICT (ambiente, provedor, evento_id) DO NOTHING
           RETURNING id""",
        (cfg["ambiente"], cfg["provedor"], liq["evento_id"],
         liq["nosso_numero"] or None, boleto_id, liq["valor"], liq["pago_em"],
         liq["creditado_em"], situacao, (motivo or "")[:1000] or None, ato_id,
         agora, quem or None,
         json.dumps({k: liq[k] for k in sorted(liq)}, ensure_ascii=False)))
    return int(nova[0]["id"]) if nova else None


def _assentar(con: Any, liq: dict, *, cfg: dict, sv: dict, data_extenso: str,
              quem: str, agora: str) -> dict:
    """A liquidação, dentro da transação. AS TRAVAS NA ORDEM DA CASA: o título
    primeiro (como em `emitir` e em todo `lancar_*`), o boleto depois."""
    bd = banco(con)
    ja = bd.um("""SELECT id FROM pt_boletos_liquidacoes
                   WHERE ambiente=%s AND provedor=%s AND evento_id=%s""",
               (cfg["ambiente"], cfg["provedor"], liq["evento_id"]))
    if ja:
        return {"evento_id": liq["evento_id"], "situacao": "JA_VISTA"}
    b0 = bd.um("""SELECT id, titulo_id FROM pt_boletos
                   WHERE ambiente=%s AND provedor=%s AND nosso_numero=%s""",
               (cfg["ambiente"], cfg["provedor"], liq["nosso_numero"]))
    if not b0:
        nova = _inserir_liquidacao(
            bd, liq, cfg=cfg, situacao=SEM_BOLETO, boleto_id=None, agora=agora,
            quem=quem, motivo=(f"o banco pagou o nosso número "
                               f"{liq['nosso_numero'] or '(vazio)'}, que esta "
                               f"casa não emitiu (ou emitiu noutro ambiente)"))
        return {"evento_id": liq["evento_id"],
                "situacao": SEM_BOLETO if nova else "JA_VISTA"}

    tit = PT.titulo_para_gravar(bd, int(b0["titulo_id"]))
    bd._escrita()
    b = bd.um("SELECT * FROM pt_boletos WHERE id=%s FOR UPDATE", (b0["id"],))
    quando = _br(liq["pago_em"]) or "data não informada"

    if cfg["ambiente"] != INTEG.PRODUCAO:
        nova = _inserir_liquidacao(
            bd, liq, cfg=cfg, situacao=ENSAIO, boleto_id=b["id"], agora=agora,
            quem=quem, motivo="homologação: o título não muda")
        if nova:
            bd.escrever(
                """UPDATE pt_boletos SET situacao='PAGO', pago_em=%s,
                          valor_pago_centavos=%s
                    WHERE id=%s AND situacao IN ('EMITIDO', 'SEM_RESPOSTA')""",
                (liq["pago_em"], liq["valor"], b["id"]))
        return {"evento_id": liq["evento_id"], "boleto_id": int(b["id"]),
                "situacao": ENSAIO if nova else "JA_VISTA", "ato_id": None}

    if b["situacao"] not in (EMITIDO, SEM_RESPOSTA):
        raise BoletoDominioError(
            f"o boleto {b['nosso_numero']} estava {b['situacao']} e foi pago em "
            f"{quando} — confira e, se for o caso, devolva")
    if liq["valor"] != int(b["valor_centavos"]):
        raise BoletoDominioError(
            f"o banco pagou R$ {_texto_em_reais(liq['valor'])} e o boleto "
            f"{b['nosso_numero']} era de R$ {_texto_em_reais(b['valor_centavos'])}"
            f" — pagamento diferente do cobrado é decisão do oficial")
    if tit is None:
        raise BoletoDominioError("o título do boleto não existe mais")
    # A BAIXA É O PAGAMENTO DO BALCÃO, com a forma BOLETO. Quem recusa título
    # sustado, pago ou desistido é `lancar_pagamento` — e a recusa dele vira a
    # frase da pendência (o `except` de `conciliar`).
    lavrado = PT.lancar_pagamento(
        con, int(b["titulo_id"]), sv=sv, agora=agora, data_extenso=data_extenso,
        valor_pago=_texto_em_reais(b["valor_titulo_centavos"]),
        usuario=quem or None, origem="BOLETO", forma_pagamento="BOLETO",
        forma_identificacao=(f"boleto nosso número {b['nosso_numero']}, pago em "
                             f"{quando} (baixa pela liquidação do banco)"),
        emolumentos=_texto_em_reais(b["emolumentos_centavos"]))
    ato_id = int(lavrado["ato_id"])
    _inserir_liquidacao(bd, liq, cfg=cfg, situacao=BAIXADO, boleto_id=b["id"],
                        agora=agora, quem=quem, motivo=None, ato_id=ato_id)
    bd.escrever(
        """UPDATE pt_boletos SET situacao='PAGO', pago_em=%s,
                  valor_pago_centavos=%s, ato_id=%s WHERE id=%s""",
        (liq["pago_em"], liq["valor"], ato_id, b["id"]))
    return {"evento_id": liq["evento_id"], "boleto_id": int(b["id"]),
            "titulo_id": int(b["titulo_id"]), "situacao": BAIXADO,
            "ato_id": ato_id}


def simular_pagamento(db: Any, boleto_id: int, *, pago_em: str,
                      valor: Any = None, pasta: Any = None,
                      transporte: Any = None, cfg: dict | None = None) -> dict:
    """O devedor da HOMOLOGAÇÃO pagando — só com o serviço falso."""
    if transporte is None or cfg is None:
        with db.connect() as con:
            cfg, transporte = INTEG.transporte_em_uso(con, INTEG.BOLETO, pasta=pasta)
    if cfg["modo"] != INTEG.HOMOLOGACAO or not INTEG.e_simulador(transporte):
        raise BoletoDominioError("Simular pagamento só existe na homologação, com "
                                 "o serviço falso.")
    with db.connect() as con:
        b = banco(con).um("SELECT * FROM pt_boletos WHERE id=%s", (int(boleto_id),))
    if not b or b["ambiente"] != INTEG.HOMOLOGACAO or b["situacao"] != EMITIDO:
        raise BoletoDominioError("Só se simula o pagamento de boleto de "
                                 "homologação emitido.")
    v = (centavos(str(valor)) if valor is not None and str(valor).strip()
         else None)
    try:
        return transporte.simular_pagamento(b["nosso_numero"], pago_em=pago_em,
                                            valor_centavos=v)
    except BAPI.BoletoError as erro:
        raise BoletoDominioError(str(erro)) from erro


def resolver_pendencia(db: Any, liquidacao_id: int, *, conferencia: str,
                       quem: str = "") -> dict:
    """Fecha a pendência com o que foi feito, ESCRITO. ESCREVE.

    **Não lavra nada**: se a decisão é dar baixa, ela se lança na ficha do
    título (Pagamento), com selo e lugar no livro; se é devolver, a devolução
    é do caixa. Aqui fica o registro de que alguém olhou e do que decidiu.
    """
    texto = " ".join(str(conferencia or "").split())
    if len(texto) < 10:
        raise BoletoDominioError(
            "Escreva o que foi feito com este pagamento (pelo menos dez letras) "
            "— é o que a correição lê.")
    agora = db.now()
    with db.transaction() as con:
        bd = banco(con)
        bd._escrita()
        liq = bd.um("""SELECT * FROM pt_boletos_liquidacoes WHERE id=%s
                       FOR UPDATE""", (int(liquidacao_id),))
        if not liq or liq["situacao"] not in (CONFERIR, SEM_BOLETO):
            raise BoletoDominioError("Esta liquidação não está pendente.")
        if liq["conferida_em"]:
            raise BoletoDominioError("Esta pendência já foi resolvida.")
        bd.escrever(
            """UPDATE pt_boletos_liquidacoes
                  SET conferida_em=%s, conferida_por=%s, conferencia=%s
                WHERE id=%s""",
            (agora, quem or None, texto[:1000], int(liquidacao_id)))
    return {"liquidacao_id": int(liquidacao_id)}


