def boletos(con: Any, *, ambiente: str | None, limite: int = 200) -> list[dict]:
    """Os boletos daquele ambiente, do mais novo para o mais velho. SÓ LÊ."""
    return [dict(x) for x in banco(con).ler(
        """SELECT b.*, t.numero_titulo, t.protocolo, t.situacao AS situacao_do_titulo
             FROM pt_boletos b JOIN pt_titulos t ON t.id = b.titulo_id
            WHERE b.ambiente = %s
            ORDER BY b.id DESC LIMIT %s""", (str(ambiente or ""), int(limite)))]


def pendencias(con: Any, *, limite: int = 200) -> list[dict]:
    """O dinheiro que entrou e não deu baixa sozinho — em PRODUÇÃO. SÓ LÊ."""
    return [dict(x) for x in banco(con).ler(
        """SELECT l.*, b.titulo_id, t.numero_titulo, t.protocolo
             FROM pt_boletos_liquidacoes l
             LEFT JOIN pt_boletos b ON b.id = l.boleto_id
             LEFT JOIN pt_titulos t ON t.id = b.titulo_id
            WHERE l.ambiente = %s AND l.situacao IN ('CONFERIR', 'SEM_BOLETO')
              AND l.conferida_em IS NULL
            ORDER BY l.id LIMIT %s""", (INTEG.PRODUCAO, int(limite)))]


def boletos_do_titulo(con: Any, titulo_id: int) -> list[dict]:
    """Os boletos de PRODUÇÃO de um título. SÓ LÊ."""
    return [dict(x) for x in banco(con).ler(
        """SELECT * FROM pt_boletos WHERE titulo_id = %s AND ambiente = %s
            ORDER BY id""", (int(titulo_id), INTEG.PRODUCAO))]


