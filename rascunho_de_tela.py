"""Salvar o preenchimento de um formulário e continuar depois.

    «em todos os atos do cartório, durante o preenchimento, é preciso ter um
     campo para salvar o progresso e continuar depois»
        — o oficial, relato #36, 30/08/2026

POR QUE UM MECANISMO SÓ, E NÃO UM RASCUNHO POR TELA
    O pedido é «em todos os atos», e os atos desta casa são muitos: assento,
    escritura, protocolo, prenotação, habilitação, usucapião. Um rascunho
    escrito dentro de cada formulário daria seis implementações que divergem
    no primeiro conserto — e é o defeito que este projeto persegue.

    Aqui há **um** mecanismo: ele guarda o que foi digitado numa tela,
    identificado por qual tela é, e devolve isso quando ela reabrir. Não sabe
    nada sobre assento, escritura ou protocolo — e é justamente por não saber
    que serve aos seis.

POR QUE NÃO É `ri_rascunhos`, QUE JÁ EXISTE
    Aquele resolve outro problema, e resolve bem: ele guarda **um ato do RI**
    antes de virar ato, para se ver como a matrícula vai ler com ele dentro.
    Tem regra própria — o ato do RI toma número e entra na corrente de hash no
    instante em que nasce.

    Este aqui é mais humilde: guarda **o que foi digitado**, sem entender o que
    significa. Um serve ao Registro de Imóveis; o outro, ao balcão inteiro.

O QUE ELE NÃO FAZ, E POR QUÊ
    **Não lavra, não numera, não reserva nada.** Rascunho que consome número é
    ato disfarçado — e ato disfarçado aparece na correição como buraco na
    sequência. Aqui o número só nasce quando o ato nasce.

    **Não é fila de trabalho.** Quem lista o que ficou pela metade e cobra é
    `inacabados`, que mede atos que já existem. Rascunho é papel de anotação:
    pode ser abandonado sem que nada fique devendo.

QUANDO O ATO GRAVA, O RASCUNHO SAI DA LISTA — decisão do oficial, 31/10/2026
    Ele ficava na lista depois de lavrado, e alguém podia lavrar de novo a partir
    dele. Agora `saiu_com_o_ato` o apaga, com o dado do cliente dentro, e fica só a
    marca em `rascunhos_que_viraram_ato`. É ela que segura o mesmo registro de um
    arquivo fora da fila, e que leva ao ato quem volta pelo navegador.
"""
from __future__ import annotations

import json
import re
from typing import Any

from bd_nativo import banco

SCHEMA = """
-- O QUE FOI DIGITADO NUMA TELA, antes de virar ato.
--
-- `tela` e o endpoint (`rcpn_assento_novo`, `notas_ato_novo`...), e e por ele
-- que a tela reencontra o proprio rascunho. `chave` distingue rascunhos da
-- mesma tela — o numero do protocolo, o id da matricula —, e fica vazia
-- quando a tela e unica.
CREATE TABLE IF NOT EXISTS rascunhos_de_tela (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tela TEXT NOT NULL,
    chave TEXT NOT NULL DEFAULT '',

    -- O ROTULO QUE O ESCREVENTE VE. Sem ele a lista seria de endpoints, e
    -- ninguem reconhece o proprio trabalho por `rcpn_assento_novo`.
    titulo TEXT NOT NULL,

    -- O QUE FOI DIGITADO. JSON porque cada tela tem os seus campos, e uma
    -- coluna por campo daria uma tabela que muda a cada formulario novo.
    dados_json TEXT NOT NULL DEFAULT '{}',

    criado_em TEXT NOT NULL,
    criado_por TEXT,
    atualizado_em TEXT,
    atualizado_por TEXT
);

CREATE INDEX IF NOT EXISTS ix_rascunhos_tela
    ON rascunhos_de_tela(tela, chave);
CREATE INDEX IF NOT EXISTS ix_rascunhos_quando
    ON rascunhos_de_tela(atualizado_em DESC);

-- O RASCUNHO QUE VIROU ATO. A linha de cima se apaga, com o dado do cliente
-- dentro. Aqui fica so o que impede lavrar de novo: a chave, que segura o mesmo
-- registro de um arquivo fora da fila, e o endereco do ato, para onde vai quem
-- volta pelo navegador. Nao guarda titulo nem dados, de proposito.
CREATE TABLE IF NOT EXISTS rascunhos_que_viraram_ato (
    rascunho_id bigint PRIMARY KEY,
    tela TEXT NOT NULL,
    chave TEXT NOT NULL DEFAULT '',
    endereco TEXT,
    em TEXT NOT NULL,
    por TEXT
);

CREATE INDEX IF NOT EXISTS ix_rascunhos_ato_chave
    ON rascunhos_que_viraram_ato(chave);
"""

# OS CAMPOS QUE NUNCA ENTRAM NO RASCUNHO.
#
#   `csrf_token` e de uso unico: guardado, volta invalido e o formulario
#   recusa — o escrevente veria o proprio rascunho ser rejeitado sem entender.
#   `senha` e `password` nao se guardam em lugar nenhum, e muito menos num
#   papel de anotacao que fica no banco ate alguem apagar.
NAO_SE_GUARDA = ("csrf_token", "senha", "password", "pin", "certificado")

# QUANTOS DIAS UM RASCUNHO FICA ANTES DE VIRAR ENTULHO.
#
#   **Rascunho tem dado de cliente dentro** — nome, filiacao, endereco. Ele
#   existe para o escrevente voltar hoje ou amanha, e nao para virar um
#   arquivo paralelo de dados pessoais que ninguem sabe que tem. O prazo e
#   generoso e o descarte e explicito: `expirados()` mostra, e alguem apaga.
DIAS_ATE_ENVELHECER = 30

# OS CAMPOS REPETIDOS — 31/10/2026. O segundo devedor do Protesto e as outras
# partes do Livro 3 têm o mesmo `name` do primeiro, e o rascunho guardava só o
# primeiro valor: quem salvava dois devedores reabria com um.
#
#   QUEM LÊ `dados` CONTINUA LENDO UM DICIONÁRIO PLANO, com um texto por nome.
#   A lista inteira vai à parte, nesta chave, e só para o nome que veio mais de
#   uma vez. O sublinhado garante que ela não colide com campo de tela: o que
#   começa com `_` nunca entra em `dados`. `ler` a tira de lá, e por isso nenhum
#   leitor a vê; e rascunho antigo, que não a tem, abre como sempre abriu.
CHAVE_DOS_REPETIDOS = "_repetidos"

# A TELA QUE NÃO É ROTA. Averbar, anotar e retificar desenham o mesmo molde, e
# ele salva com este nome, que não vira endereço: é preciso saber de que
# assento é o lançamento. O endereço da tela é quem sabe, e ele fica na `chave`.
TELA_DO_LANCAMENTO = "rcpn_lancamento_novo"
_ENDERECO_DO_LANCAMENTO = re.compile(r"/rcpn/\d+/(?:averbar|anotar|retificar)")

# O CAMPO QUE LEVA O RASCUNHO ATÉ A GRAVAÇÃO. Onde o formulário grava no próprio
# endereço, o `?rascunho_id=` basta. O assento do civil passa pela conferência, cujos
# botões têm endereço fixo, e a matrícula nova do layout novo grava sem ele. Começa
# com sublinhado: nunca entra no que o rascunho guarda.
CAMPO_DO_RASCUNHO = "_rascunho_id_tela"


class RascunhoError(ValueError):
    """Erro de regra, em português de balcão."""


def init_rascunho_schema(con) -> None:
    """Cria a tabela. Idempotente."""
    bd = banco(con)
    for comando in SCHEMA.split(";"):
        sem_comentario = "\n".join(
            l for l in comando.splitlines() if not l.strip().startswith("--"))
        if sem_comentario.strip():
            bd.escrever(sem_comentario)


def _texto(v: Any) -> str:
    return "" if v is None else str(v).strip()


def limpar_campos(dados: dict) -> dict:
    """Tira o que não se guarda. Só calcula.

    **NÃO É ZELO GENÉRICO**: o `csrf_token` guardado volta inválido e faz o
    formulário recusar o próprio rascunho, e o escrevente não teria como
    entender por quê.
    """
    fora = {}
    for chave, valor in (dados or {}).items():
        nome = str(chave).lower()
        if any(proibido in nome for proibido in NAO_SE_GUARDA):
            continue
        fora[str(chave)] = valor
    return fora


def dados_do_envio(form) -> dict:
    """O que a tela mandou, na forma que `salvar` guarda. Só calcula.

    `form` é o formulário do Flask, e não um dicionário: é ele que sabe dos
    nomes repetidos. O campo que começa com `_` é do próprio rascunho.

    **EM `dados[nome]` FICA O PRIMEIRO VALOR PREENCHIDO**, e não o primeiro
    valor: é o que os leitores sempre receberam, quando o valor vazio nem
    chegava aqui. Na lista repetida o vazio fica, porque é a posição dele que
    diz de quem é cada valor: sem o documento vazio do primeiro devedor, o do
    segundo voltaria como se fosse do primeiro.
    """
    dados: dict = {}
    repetidos: dict = {}
    for nome in form.keys():
        if str(nome).startswith("_"):
            continue
        valores = form.getlist(nome)
        dados[nome] = next((v for v in valores if _texto(v)),
                           valores[0] if valores else "")
        if len(valores) > 1:
            repetidos[nome] = valores
    if repetidos:
        dados[CHAVE_DOS_REPETIDOS] = repetidos
    return dados


def salvar(con, *, tela: str, dados: dict, titulo: str,
           agora: str, chave: str = "", por: str = "",
           rascunho_id: int | None = None) -> dict:
    """Guarda o que foi digitado. ESCREVE.

    **NÃO EXIGE QUE O FORMULÁRIO ESTEJA VÁLIDO**, e essa é a razão de existir:
    o escrevente salva no meio, com metade dos campos e a outra metade errada,
    porque o cliente foi buscar um documento. Cobrar validade aqui seria
    exigir que ele terminasse para poder parar.

    Só recusa duas coisas: tela sem nome e rascunho vazio — este porque um
    registro sem nada dentro só serviria para confundir a lista.
    """
    tela = _texto(tela)
    if not tela:
        raise RascunhoError("O rascunho precisa saber de que tela ele é.")
    limpos = limpar_campos(dados)
    repetidos = limpar_campos(limpos.pop(CHAVE_DOS_REPETIDOS, None))
    if not any(_texto(v) for v in limpos.values()):
        raise RascunhoError(
            "Não havia nada preenchido para guardar. Escreva alguma coisa "
            "antes de salvar o rascunho.")
    titulo = _texto(titulo) or tela
    corpo = json.dumps(
        {**limpos, CHAVE_DOS_REPETIDOS: repetidos} if repetidos else limpos,
        ensure_ascii=False)
    # O RASCUNHO DO ASSENTO DO RCPN VOLTA COM A CONFERÊNCIA (11/10/2026). Não
    # recusa — rascunho é para guardar pela metade —, mas quem o monta (o
    # balcão, ou o robô que lê as digitalizações) fica sabendo na hora o que
    # a lavratura vai recusar, e não no balcão com o declarante na frente.
    conferencia: list[dict] = []
    if tela.startswith("rcpn_assento"):
        try:
            import rc_conferencia_dados as CONF
            conferencia = CONF.conferir(CONF.dados_do_formulario(
                limpos, data_ato=agora, assina_depois=True))
        except Exception:                               # noqa: BLE001
            conferencia = []

    if rascunho_id:
        bd = banco(con)
        existe = bd.um("SELECT id, tela FROM rascunhos_de_tela WHERE id=%s",
                       (int(rascunho_id),))
        if not existe:
            raise RascunhoError(f"Não achei o rascunho #{rascunho_id}.")
        if existe["tela"] != tela:
            raise RascunhoError(f"O rascunho #{rascunho_id} é de outra tela. "
                                "Nada foi guardado por cima dele.")
        bd.escrever(
            """UPDATE rascunhos_de_tela SET dados_json=%s, titulo=%s,
                   atualizado_em=%s, atualizado_por=%s WHERE id=%s""",
            (corpo, titulo, agora, por, int(rascunho_id)))
        return {"id": int(rascunho_id), "novo": False, "conferencia": conferencia}

    novo = banco(con).escrever(
        """INSERT INTO rascunhos_de_tela
               (tela, chave, titulo, dados_json, criado_em, criado_por,
                atualizado_em, atualizado_por)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
        (tela, _texto(chave), titulo, corpo, agora, por, agora, por))
    return {"id": int(novo[0]["id"]), "novo": True, "conferencia": conferencia}


def ler(con, rascunho_id: int) -> dict:
    """O rascunho e o que ele guarda. Só lê."""
    linha = banco(con).um("SELECT * FROM rascunhos_de_tela WHERE id=%s",
                          (int(rascunho_id),))
    if not linha:
        raise RascunhoError(f"Não achei o rascunho #{rascunho_id}.")
    d = dict(linha)
    d["dados"], d["repetidos"] = {}, {}
    try:
        guardado = json.loads(d.get("dados_json") or "{}")
    except (ValueError, TypeError):
        guardado = None
    if isinstance(guardado, dict):
        repetidos = guardado.pop(CHAVE_DOS_REPETIDOS, None)
        d["dados"] = guardado
        d["repetidos"] = repetidos if isinstance(repetidos, dict) else {}
    else:
        # DADO ILEGIVEL NAO DERRUBA A TELA. O rascunho abre vazio, e a tela
        # diz que ele nao pode ser lido — melhor que um erro de sistema em
        # cima de um papel de anotacao.
        d["ilegivel"] = True
    return d


def formulario(rascunho: dict):
    """O rascunho na forma de um formulário enviado. Só calcula.

    **É O MESMO OBJETO QUE O MOLDE RECEBE NA RECUSA DO SERVIDOR**, com `.get` e
    `.getlist`, e por isso cada tela só precisa saber voltar preenchida uma vez.
    """
    from werkzeug.datastructures import ImmutableMultiDict

    repetidos = rascunho.get("repetidos") or {}
    itens = []
    for nome, valor in (rascunho.get("dados") or {}).items():
        lista = repetidos.get(nome)
        for v in (lista if isinstance(lista, list) else [valor]):
            itens.append((nome, "" if v is None else str(v)))
    return ImmutableMultiDict(itens)


def para_a_tela(db, tela: str, de_outra_tela: str, chave: str | None = None):
    """O que a tela de ato mostra, e o rascunho aberto: `(form, rascunho_id)`. SÓ LÊ.

    A rota chama no começo, e usa os dois no molde. Foi escrita para não haver
    oito cópias da leitura que `rcpn_assento_novo`, `rcpn_habilitacao_nova` e
    `ri_nova_matricula` fazem, com as mesmas regras:

      - **quem preenche a tela é só o GET.** No POST, o que vale é o que a pessoa
        acabou de digitar, e o `form` é o do pedido. Sem rascunho, ele é o do
        pedido também: no GET vem vazio, e a tela sai como sempre saiu.
      - **rascunho de outra tela é recusado com aviso**, e `de_outra_tela` é a
        frase. A `chave`, quando vem, tem de ser a do rascunho também.
      - **o `rascunho_id` vai para a macro `salvar_rascunho`**, e salvar de novo
        atualiza o mesmo em vez de criar outro. Na recusa ele continua valendo,
        porque o endereço do formulário o carrega.
      - **o rascunho que já virou ato não reabre nem grava de novo**: quem volta a
        ele vai para o ato (`barrar_se_ja_virou_ato`).

    O corpo que a tela manda não ganha campo nenhum. Reabrir não grava nada.
    """
    from flask import flash, request

    barrar_se_ja_virou_ato(db)
    rascunho_id = request.args.get("rascunho_id", type=int)
    if not rascunho_id:
        return request.form, None
    abrindo = request.method == "GET"
    with db.connect() as con:
        try:
            r = ler(con, rascunho_id)
        except RascunhoError as erro:
            if abrindo:
                flash(str(erro), "danger")
            return request.form, None
    if r["tela"] != tela or (chave is not None and r.get("chave") != chave):
        if abrindo:
            flash(de_outra_tela, "danger")
        return request.form, None
    if not abrindo:
        return request.form, rascunho_id
    if r.get("ilegivel"):
        flash(f"Não consegui ler o que o rascunho #{rascunho_id} guardou. A tela "
              "abriu em branco, e ele continua na lista.", "danger")
        return request.form, None
    flash(f"Aberto do rascunho #{rascunho_id}. Confira os campos antes de gravar. "
          "Ele não é ato: não tomou número, não selou e não cobrou.", "info")
    return formulario(r), rascunho_id


def chave_da_tela(tela: str, volta: str, chave: Any = "") -> str:
    """A `chave` com que o rascunho se guarda. Só calcula.

    Só o lançamento do civil a calcula: o endereço de volta diz de que assento
    ele é, e se é averbação, anotação ou retificação.
    """
    if tela == TELA_DO_LANCAMENTO and _ENDERECO_DO_LANCAMENTO.fullmatch(volta or ""):
        return volta
    return _texto(chave)


def endereco_de_abrir(rascunho: dict, url_for) -> str | None:
    """Para onde o «abrir» da lista leva, ou `None`. Só calcula.

    `None` é a tela que não existe mais, ou que não sabe reabrir. A linha continua
    na lista, e pode ser apagada: ela só não promete o que não cumpre.
    """
    try:
        if rascunho["tela"] != TELA_DO_LANCAMENTO:
            return url_for(rascunho["tela"], rascunho_id=rascunho["id"])
    except Exception:                                   # noqa: BLE001
        return None
    chave = rascunho.get("chave") or ""
    if _ENDERECO_DO_LANCAMENTO.fullmatch(chave):
        return f"{chave}?rascunho_id={rascunho['id']}"
    return None


def listar(con, *, tela: str = "",
           limite: int = 200) -> list[dict]:
    """Os rascunhos guardados, do mais recente. Só lê."""
    onde, params = ["1=1"], []
    if _texto(tela):
        onde.append("tela = %s")
        params.append(_texto(tela))
    return banco(con).ler(
        f"""SELECT id, tela, chave, titulo, criado_em, criado_por,
                   atualizado_em, atualizado_por
              FROM rascunhos_de_tela WHERE {' AND '.join(onde)}
          ORDER BY COALESCE(atualizado_em, criado_em) DESC, id DESC LIMIT %s""",
        (*params, int(limite)))


def quantos(con, *, tela: str = "") -> int:
    return len(listar(con, tela=tela, limite=100000))


def apagar(con, rascunho_id: int) -> None:
    """Joga o rascunho fora. ESCREVE.

    **APAGAR RASCUNHO NÃO PEDE MOTIVO**, ao contrário de cancelar ato: ele
    nunca foi ato, não tomou número e não está em corrente nenhuma. Exigir
    justificativa para jogar fora um papel de anotação faria o escrevente
    deixar tudo acumulado.
    """
    banco(con).escrever("DELETE FROM rascunhos_de_tela WHERE id=%s",
                        (int(rascunho_id),))


def do_envio() -> int | None:
    """O rascunho de onde este envio saiu, ou `None`. Só calcula."""
    from flask import request

    return (request.form.get(CAMPO_DO_RASCUNHO, type=int)
            or request.args.get("rascunho_id", type=int))


def o_ato_do_rascunho(con, rascunho_id: int) -> dict | None:
    """A marca do rascunho que virou ato, ou `None`. Só lê."""
    linha = banco(con).um(
        "SELECT * FROM rascunhos_que_viraram_ato WHERE rascunho_id=%s",
        (int(rascunho_id),))
    return dict(linha) if linha else None


def chave_ja_recebida(con, chave: str) -> bool:
    """O registro desta chave já entrou: está na lista, ou já virou ato. Só lê.

    A fila de pré-cadastros pergunta aqui. Perguntar só à lista traria de volta, na
    importação seguinte, o registro que já foi lavrado.
    """
    bd = banco(con)
    return bool(
        (bd.tem_tabela("rascunhos_de_tela")
         and bd.um("SELECT 1 FROM rascunhos_de_tela WHERE chave = %s", (chave,)))
        or (bd.tem_tabela("rascunhos_que_viraram_ato")
            and bd.um("SELECT 1 FROM rascunhos_que_viraram_ato WHERE chave = %s",
                      (chave,))))


def virou_ato(con, rascunho_id: int, *, endereco: str | None, agora: str,
              por: str = "") -> None:
    """O rascunho virou ato: ele sai da lista, e fica só a marca. ESCREVE.

    **A marca não leva o título nem os dados.** O rascunho tem dado de cliente
    dentro, e esse dado agora mora no ato.
    """
    bd = banco(con)
    r = bd.um("SELECT tela, chave FROM rascunhos_de_tela WHERE id=%s",
              (int(rascunho_id),))
    if not r:
        return
    bd.escrever(
        """INSERT INTO rascunhos_que_viraram_ato
               (rascunho_id, tela, chave, endereco, em, por)
           VALUES (%s,%s,%s,%s,%s,%s)
           ON CONFLICT (rascunho_id) DO NOTHING""",
        (int(rascunho_id), r["tela"], r["chave"], endereco, agora, por))
    bd.escrever("DELETE FROM rascunhos_de_tela WHERE id=%s", (int(rascunho_id),))


def saiu_com_o_ato(db, audit, tela: str, endereco: str, por: str,
                   chave: str | None = None) -> None:
    """O ato deste envio ficou de pé: o rascunho sai da lista. ESCREVE.

    **A ROTA CHAMA DEPOIS DO SELO.** Onde o selo que falha desfaz o ato, o rascunho
    fica na lista, para corrigir e tentar de novo: é a única cópia do que foi digitado.

    Só sai o rascunho desta tela, e da mesma `chave` quando ela vem: o número no
    endereço pode ser o de outro. Fora da transação do ato, e **a falha aqui não
    derruba o ato**, que já está gravado: ela vira aviso.
    """
    from flask import flash

    rascunho_id = do_envio()
    if not rascunho_id:
        return
    try:
        with db.transaction() as con:
            r = banco(con).um("SELECT tela, chave FROM rascunhos_de_tela WHERE id=%s",
                              (rascunho_id,))
            if not r or r["tela"] != tela or (chave is not None and r["chave"] != chave):
                return
            virou_ato(con, rascunho_id, endereco=endereco, agora=db.now(), por=por)
    except Exception:                                   # noqa: BLE001
        flash(f"O ato foi gravado, mas o rascunho #{rascunho_id} continua na lista de "
              "Rascunhos. Apague-o lá, para ninguém lavrar de novo a partir dele.",
              "warning")
        return
    audit("RASCUNHO_VIROU_ATO", "rascunhos_de_tela", rascunho_id,
          {"tela": tela, "ato": endereco})
    flash(f"O rascunho #{rascunho_id} saiu da lista: o que ele guardava já está gravado.",
          "info")


def barrar_se_ja_virou_ato(db) -> None:
    """Quem volta a um rascunho que já virou ato vai para o ato. SÓ LÊ.

    **É O QUE IMPEDE LAVRAR DUAS VEZES PELO BOTÃO DE VOLTAR**, ou por uma segunda aba
    aberta no mesmo rascunho. O rascunho apagado à mão não tem marca, e não barra:
    jogar fora um papel não diz que o ato existe.
    """
    from flask import abort, flash, redirect, url_for

    rascunho_id = do_envio()
    if not rascunho_id:
        return
    with db.connect() as con:
        feito = o_ato_do_rascunho(con, rascunho_id)
    if feito:
        flash(f"O rascunho #{rascunho_id} já virou ato, e nada foi gravado de novo.",
              "warning")
        abort(redirect(feito.get("endereco") or url_for("rascunhos")))


def expirados(con, hoje: str,
              dias: int = DIAS_ATE_ENVELHECER) -> list[dict]:
    """Os rascunhos velhos demais. Só lê — **não apaga sozinho**.

    Apagar sozinho seria o sistema jogando fora trabalho de alguém sem
    avisar. A lista mostra; quem apaga é quem olha.
    """
    from datetime import date, timedelta

    def _dia(v: Any):
        try:
            return date.fromisoformat(_texto(v)[:10])
        except ValueError:
            return None

    limite = _dia(hoje)
    if not limite:
        raise RascunhoError("Preciso da data de hoje em aaaa-mm-dd.")
    corte = limite - timedelta(days=int(dias))
    fora = []
    for r in listar(con, limite=100000):
        quando = _dia(r.get("atualizado_em") or r.get("criado_em"))
        if quando and quando < corte:
            r["dias_parado"] = (limite - quando).days
            fora.append(r)
    return fora
