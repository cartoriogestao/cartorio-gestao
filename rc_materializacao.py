"""A materialização de certidão eletrônica vinda de OUTRA serventia — 26/10/2026.

    «assim como criamos o emissor de selo para certidão eletrônica de registro
     do cartório, preciso que o sistema emita selo para a materialização de
     certidão vinda de outros cartórios para entrega a clientes» — o oficial

O QUE É
    O cliente pede, pela CRC, a certidão de um registro que mora em outro
    cartório; a certidão chega eletrônica, e esta casa a imprime e a entrega
    no balcão. A impressão leva selo desta casa, e o selador tem caminho
    próprio para isso: `/selo/civil/certidao/materializacao`
    (`DadosSeloCertidaoMaterializacao`), que a casa nunca usou — zero dos
    26.130 selos do acervo.

O QUE O PEDIDO EXIGE, MEDIDO NO CONTRATO (`tests/selador_reais.json`)
    nomeCartorioExpedidor, cidadeCartorioExpedidor, estadoCartorioExpedidor,
    nomeFuncionarioExpedidor e valorEmolumentosCertidao são obrigatórios — é a
    certidão de LÁ que se descreve; `nomeParte` e `parte` são opcionais.
    `codigoAto` é o item 14.5.1 (certidão com uma folha) e o pagamento é no
    CAIXA desta casa, como qualquer ato: decisões do oficial em 26/10/2026.

POR QUE TABELA PRÓPRIA
    `rc_certidoes` exige o assento (`assento_id NOT NULL`), e o assento aqui
    não existe: ele está no livro do outro cartório. A chave do selo é
    `tabela` + `ato_id`, e o selo precisa de um ato daqui para se amarrar.

ESTE MÓDULO NÃO PEDE SELO: ele grava, cancela e monta o pedido. Quem fala com
o selador é a rota, fora da transação, pelo caminho de sempre.
"""
from __future__ import annotations

from typing import Any

from ato_selado import CAMINHO_MATERIALIZACAO as CAMINHO
from bd_nativo import banco

CODIGO_ATO = "14.5.1"
TABELA = "rc_materializacoes"

SCHEMA = """
CREATE TABLE IF NOT EXISTS rc_materializacoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_parte TEXT NOT NULL,               -- de quem é o registro
    requerente TEXT,                        -- quem pediu e recebe no balcão
    cartorio_nome TEXT NOT NULL,            -- quem expediu a certidão
    cartorio_cidade TEXT NOT NULL,
    cartorio_uf TEXT NOT NULL,
    funcionario_expedidor TEXT NOT NULL,    -- quem assinou lá
    valor_emolumentos_centavos INTEGER NOT NULL,  -- o que se cobrou lá
    especie TEXT,                           -- nascimento, casamento, óbito...
    matricula TEXT,                         -- os 32 dígitos, se vierem
    selo TEXT,
    cancelada_em TEXT,
    cancelada_por TEXT,
    cancelada_motivo TEXT,
    emitida_em TEXT NOT NULL,
    emitida_por TEXT
)
"""


class MaterializacaoError(ValueError):
    """Erro de regra da materialização, com a frase pronta para o balcão."""


def init_rc_materializacao_schema(con) -> None:
    """Cria a tabela. Idempotente."""
    banco(con).escrever(SCHEMA)


def centavos(valor: Any) -> int | None:
    """«12,34», «12.34», «R$ 1.234,56» → centavos. None se não for valor."""
    bruto = str(valor or "").replace("R$", "").strip()
    if not bruto:
        return None
    if "," in bruto:
        bruto = bruto.replace(".", "").replace(",", ".")
    try:
        numero = round(float(bruto) * 100)
    except ValueError:
        return None
    return int(numero) if numero >= 0 else None


def conferir(dados: dict) -> dict:
    """Confere o que a escrevente digitou e devolve limpo. Só calcula.

    Recusa o que o selador recusaria — obrigatórios do contrato — aqui, com
    a frase em português, e não na rede, com a frase do fornecedor."""
    limpo = {k: str(dados.get(k) or "").strip() for k in (
        "nome_parte", "requerente", "cartorio_nome", "cartorio_cidade",
        "cartorio_uf", "funcionario_expedidor", "especie", "matricula")}
    limpo["cartorio_uf"] = limpo["cartorio_uf"].upper()
    faltando = [rotulo for chave, rotulo in (
        ("nome_parte", "o nome de quem é o registro"),
        ("cartorio_nome", "o nome do cartório que expediu"),
        ("cartorio_cidade", "a cidade do cartório que expediu"),
        ("cartorio_uf", "a UF do cartório que expediu"),
        ("funcionario_expedidor", "quem expediu a certidão lá"))
        if not limpo[chave]]
    valor = centavos(dados.get("valor_emolumentos"))
    if valor is None:
        faltando.append("o valor dos emolumentos da certidão de origem")
    if faltando:
        raise MaterializacaoError(
            "Para o selo da materialização falta " + ", ".join(faltando) + ".")
    if len(limpo["cartorio_uf"]) != 2 or not limpo["cartorio_uf"].isalpha():
        raise MaterializacaoError("A UF do cartório que expediu tem duas letras (ex.: MA).")
    limpo["valor_emolumentos_centavos"] = valor
    return limpo


def registrar(con, dados: dict, *, agora: str, usuario: Any) -> int:
    """Grava a materialização (ainda sem selo) e devolve o id. ESCREVE."""
    d = conferir(dados)
    novo = banco(con).escrever(
        """INSERT INTO rc_materializacoes(nome_parte, requerente, cartorio_nome,
               cartorio_cidade, cartorio_uf, funcionario_expedidor,
               valor_emolumentos_centavos, especie, matricula, emitida_em,
               emitida_por)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
        (d["nome_parte"], d["requerente"] or None, d["cartorio_nome"],
         d["cartorio_cidade"], d["cartorio_uf"], d["funcionario_expedidor"],
         d["valor_emolumentos_centavos"], d["especie"] or None,
         d["matricula"] or None, agora, str(usuario or "") or None))
    return int(novo[0]["id"])


def cancelar(con, materializacao_id: int, *, motivo: str, agora: str,
             usuario: Any) -> None:
    """Marca a materialização cancelada (o selo não saiu). ESCREVE. Não apaga."""
    banco(con).escrever(
        """UPDATE rc_materializacoes
              SET cancelada_em=%s, cancelada_por=%s, cancelada_motivo=%s
            WHERE id=%s AND cancelada_em IS NULL""",
        (agora, str(usuario or "") or None, motivo, int(materializacao_id)))


def listar(con, limite: int = 50) -> list[dict]:
    return [dict(x) for x in banco(con).ler(
        "SELECT * FROM rc_materializacoes ORDER BY id DESC LIMIT %s",
        (int(limite),))]


def envelope(m: dict, *, escrevente: Any, versao_tabela: Any,
             isento: bool = False, motivo_isencao: Any = None) -> dict:
    """O pedido do selo, no schema `DadosSeloCertidaoMaterializacao`. Só calcula.

    `dadosSelo` é o do civil (`DadosRCPNSelo`: escrevente, versão da tabela e
    a marca de isento), e o isento vai como a casa o mandava no caminho geral:
    `isentoGratuito: "ISENTO"` mais o motivo. `parte` é `ParteAto` (nome, e o
    documento opcional). O valor da certidão de origem vai em reais, com
    ponto — a forma de número do contrato."""
    if not str(escrevente or "").strip() or not str(versao_tabela or "").strip():
        raise MaterializacaoError(
            "O selo da materialização não sai sem o escrevente e a versão da "
            "tabela de custas.")
    dados_selo: dict[str, Any] = {"escrevente": str(escrevente).strip(),
                                  "versaoTabelaDeCustas": str(versao_tabela).strip()}
    if isento:
        motivo = str(motivo_isencao or "").strip()
        if not motivo:
            raise MaterializacaoError(
                "Ato gratuito / isento precisa do motivo escrito — é ele que a "
                "conferência do Tribunal lê no selo.")
        dados_selo["isentoGratuito"] = "ISENTO"
        dados_selo["motivoIsentoGratuito"] = motivo.upper()
    nome = str(m["nome_parte"]).strip()
    return {
        "codigoAto": CODIGO_ATO,
        "dadosSelo": dados_selo,
        "nomeCartorioExpedidor": str(m["cartorio_nome"]).strip(),
        "cidadeCartorioExpedidor": str(m["cartorio_cidade"]).strip(),
        "estadoCartorioExpedidor": str(m["cartorio_uf"]).strip().upper(),
        "nomeFuncionarioExpedidor": str(m["funcionario_expedidor"]).strip(),
        "valorEmolumentosCertidao": round(int(m["valor_emolumentos_centavos"]) / 100, 2),
        "nomeParte": nome,
        "parte": {"nome": nome},
    }
