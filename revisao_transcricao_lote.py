def ver(con, lote_id: int) -> dict | None:
    """O lote com a lista do que foi visto: as fichas com GRAVE primeiro. SÓ LÊ."""
    bd = banco(con)
    if not bd.tem_tabela("ri_transcricao_lotes"):
        return None
    lote = bd.um("SELECT * FROM ri_transcricao_lotes WHERE id = %s", (int(lote_id),))
    if lote is None:
        return None
    lote = dict(lote)
    lote["situacao"] = _situacao_viva(lote)
    lote["filtro"] = json.loads(lote["filtro_json"] or "{}")
    contas = {r["situacao"]: int(r["n"]) for r in bd.ler(
        """SELECT situacao, count(*) AS n FROM ri_transcricao_lote_itens
            WHERE lote_id = %s GROUP BY situacao ORDER BY situacao""", (int(lote_id),))}
    itens = bd.ler(
        """SELECT i.id, i.ordem, i.matricula_id, i.paginas, i.situacao, i.tentativas,
                  i.revisao_id, i.motivo, m.numero, m.livro_norm AS livro,
                  COALESCE(r.graves, 0) AS graves, COALESCE(r.leves, 0) AS leves,
                  COALESCE(r.avisos, 0) AS avisos, r.situacao AS revisao_situacao
             FROM ri_transcricao_lote_itens i
             JOIN ri_matriculas m ON m.id = i.matricula_id
             LEFT JOIN ri_transcricao_revisoes r ON r.id = i.revisao_id
            WHERE i.lote_id = %s AND i.situacao <> 'A_FAZER'
         ORDER BY COALESCE(r.graves, 0) DESC, i.ordem, i.id LIMIT %s""",
        (int(lote_id), LINHAS_NA_TELA))
    vistos = []
    for i in itens:
        d = dict(i)
        d["primeira_grave"] = None
        if d["graves"] and d["revisao_id"]:
            r = RT.mostrar(bd, d["revisao_id"]) or {}
            d["graves_pendentes"] = r.get("graves_pendentes", 0)
            paginas = {p["n"]: p for p in r.get("lista_de_paginas") or []}
            for x in r.get("divergencias") or []:
                if x.get("gravidade") == "GRAVE" and x.get("pagina") in paginas:
                    d["primeira_grave"] = paginas[x["pagina"]]
                    break
        vistos.append(d)
    lote["contas"] = contas
    lote["a_fazer"] = contas.get("A_FAZER", 0)
    lote["itens"] = vistos
    return lote
