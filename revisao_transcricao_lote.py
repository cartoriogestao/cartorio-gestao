"""A REVISÃO DAS TRANSCRIÇÕES EM LOTE — os livros antigos, do mais velho para
o mais novo (LH11, pedido do oficial em 21/10/2026).

O QUE ENTRA NO LOTE
    As fichas TRANSCRITAS: com teor e com página escaneada para conferir
    (`ri_imagens` ou a digitalização oficial) — é o que `revisao_transcricao`
    sabe revisar. A escolha é por livro e período de abertura, ou «todos os
    transcritos sem revisão». A ORDEM É A DA NUMERAÇÃO: o número da matrícula
    é único na serventia e cresce com o tempo (os livros 2, 2-A … 2-S são
    volumes da mesma série — ver `ri_correcoes`), e por isso o mais baixo é o
    mais antigo. É por ele que se começa.

A RODADA TEM TETO, E O TETO É DA CASA
    Cada «começar» ou «continuar» é uma RODADA, com teto de páginas e de custo
    (`revisao_transcricao.configuracao`; o ADMIN muda em Configurações). Bateu
    o teto, o lote PAUSA e diz por quê — quem decide gastar mais é quem clica
    em continuar. A conta de custo é a estimativa pela tabela de preço da casa
    e pelos tokens que o provedor devolveu; quem cobra é o provedor.

PAUSAR E CONTINUAR
    Pausar não corta a ficha no meio: a linha de execução termina a que está
    lendo e para. Continuar retoma do primeiro item que falta — os itens moram
    em `ri_transcricao_lote_itens`, e a revisão de cada ficha, em
    `ri_transcricao_revisoes`: o que já foi lido não se paga de novo, nem
    dentro do lote nem fora dele (a certidão que pediu antes conta).
    O servidor reiniciado no meio deixa o lote «rodando» sem ninguém rodar: a
    batida (`batida_em`) velha o mostra como PARADO, e ele se continua.

A IA FORA DO AR: três fichas seguidas em erro pausam o lote, e a ficha que
errou volta para a fila (até a terceira tentativa) — a falha da rede não pode
virar uma lista de «revisado com erro».

NADA DO TEXTO NO LOG NEM NA AUDITORIA: o lote guarda ids, contagens e a
gravidade; o resultado de cada ficha mora na revisão dela.
"""
from __future__ import annotations

import json
import logging
import threading
from datetime import datetime
from pathlib import Path

import banco_pg
import revisao_transcricao as RT
from bd_nativo import Banco, banco

_LOG = logging.getLogger(__name__)

NOVO, RODANDO, PAUSANDO, PAUSADO, PARADO, TERMINADO = (
    "NOVO", "RODANDO", "PAUSANDO", "PAUSADO", "PARADO", "TERMINADO")
#: Sem batida há mais disto, o lote «rodando» é um lote parado. Uma ficha de
#: quarenta páginas são vinte chamadas de até dois minutos cada.
MINUTOS_SEM_BATIDA = 45
ERROS_SEGUIDOS_PARA_PAUSAR = 3
TENTATIVAS_POR_FICHA = 3
#: A tela do lote mostra até tantas fichas vistas — as com GRAVE vêm primeiro,
#: e são elas que se conferem; o resto está na ficha de cada uma.
LINHAS_NA_TELA = 500
USUARIO_DO_LOTE = "revisão em lote"

SCHEMA = (
    ("ri_transcricao_lotes", """
CREATE TABLE IF NOT EXISTS ri_transcricao_lotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filtro_json TEXT NOT NULL,
    situacao TEXT NOT NULL DEFAULT 'NOVO',
    criado_em TEXT NOT NULL,
    criado_por TEXT,
    teto_paginas bigint NOT NULL,
    teto_custo double precision NOT NULL,
    rodada bigint NOT NULL DEFAULT 0,
    rodada_paginas bigint NOT NULL DEFAULT 0,
    rodada_custo double precision NOT NULL DEFAULT 0,
    total_fichas bigint NOT NULL DEFAULT 0,
    total_paginas bigint NOT NULL DEFAULT 0,
    paginas_lidas bigint NOT NULL DEFAULT 0,
    custo double precision NOT NULL DEFAULT 0,
    erros_seguidos bigint NOT NULL DEFAULT 0,
    batida_em TEXT,
    terminado_em TEXT,
    mensagem TEXT
)"""),
    ("ri_transcricao_lote_itens", """
CREATE TABLE IF NOT EXISTS ri_transcricao_lote_itens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id bigint NOT NULL REFERENCES ri_transcricao_lotes(id),
    ordem bigint NOT NULL,
    matricula_id bigint NOT NULL,
    paginas bigint NOT NULL DEFAULT 0,
    situacao TEXT NOT NULL DEFAULT 'A_FAZER',   -- A_FAZER | FEITO | REAPROVEITADO | PULADO | ERRO
    tentativas bigint NOT NULL DEFAULT 0,
    revisao_id bigint,
    motivo TEXT,
    feito_em TEXT
)"""),
    ("ix_ri_transcricao_lote_itens_lote", """
CREATE INDEX IF NOT EXISTS ix_ri_transcricao_lote_itens_lote
    ON ri_transcricao_lote_itens (lote_id, situacao, ordem)"""),
)


class LoteError(ValueError):
    """Erro de regra, com a frase pronta para a tela."""


def init_schema(con) -> None:
    bd = banco(con)
    RT.init_schema(bd)
    for nome, comando in SCHEMA:
        if not bd.tem_tabela(nome):
            bd.escrever(comando)


def _agora() -> str:
    return datetime.now().isoformat(timespec="seconds")


# ------------------------------------------------------------------ a escolha

def livros(con) -> list[str]:
    """Os livros que têm ficha transcrita, para a tela escolher. SÓ LÊ."""
    return [r["livro"] for r in banco(con).ler(
        """SELECT DISTINCT livro_norm AS livro FROM ri_matriculas m
            WHERE COALESCE(m.teor, '') <> '' AND livro_norm IS NOT NULL
              AND (COALESCE(m.digi_path, '') <> ''
                   OR EXISTS (SELECT 1 FROM ri_imagens i WHERE i.matricula_id = m.id))
         ORDER BY livro_norm""")]


def candidatos(con, *, livro: str = "", de: str = "", ate: str = "",
               so_sem_revisao: bool = True) -> list[dict]:
    """As fichas transcritas da escolha, da mais antiga para a mais nova. SÓ LÊ.

    `paginas` é a conta do banco — uma linha de `ri_imagens` por página, e a
    digitalização oficial contada pelo arquivo —, que é o que a estimativa
    precisa antes de abrir qualquer imagem.

    A ORDEM LÊ ATÉ 18 ALGARISMOS do começo do número (LH12): o `bigint` vai
    até 19, e um número de matrícula digitado com 19 ou mais estourava a
    conversão e derrubava a lista inteira — a tela do lote e a prévia junto."""
    bd = banco(con)
    onde, params = [], []
    if livro:
        onde.append("m.livro_norm = %s")
        params.append(livro)
    if de:
        onde.append("m.data_abertura >= %s")
        params.append(de)
    if ate:
        onde.append("m.data_abertura <= %s")
        params.append(ate)
    if so_sem_revisao and bd.tem_tabela("ri_transcricao_revisoes"):
        onde.append("""NOT EXISTS (SELECT 1 FROM ri_transcricao_revisoes r
                                    WHERE r.matricula_id = m.id AND r.situacao = 'PRONTA')""")
    linhas = bd.ler(
        f"""SELECT m.id, m.numero, m.livro_norm AS livro, m.data_abertura, m.digi_path,
                   (SELECT count(*) FROM ri_imagens i WHERE i.matricula_id = m.id) AS imagens,
                   (SELECT count(*) FROM ri_atos a WHERE a.matricula_id = m.id
                       AND a.origem = 'EOFICIO') AS atos_do_acervo
              FROM ri_matriculas m
             WHERE COALESCE(m.teor, '') <> ''
               AND (COALESCE(m.digi_path, '') <> ''
                    OR EXISTS (SELECT 1 FROM ri_imagens i WHERE i.matricula_id = m.id))
               {''.join(' AND ' + o for o in onde)}
          ORDER BY COALESCE(substring(m.numero FROM '^[0-9]{{1,18}}')::bigint, 0), m.id""",
        params)
    saida = []
    for r in linhas:
        paginas = int(r["imagens"] or 0)
        if r["digi_path"] and Path(r["digi_path"]).is_file():
            try:
                paginas = RT._quadros(Path(r["digi_path"]))[1]
            except Exception:                    # noqa: BLE001 — a leitura conta de novo
                paginas = max(paginas, 1)
        saida.append({"matricula_id": int(r["id"]), "numero": r["numero"],
                      "livro": r["livro"], "data_abertura": r["data_abertura"],
                      "paginas": paginas, "atos_do_acervo": int(r["atos_do_acervo"] or 0)})
    return saida


def previa(con, filtro: dict) -> dict:
    """Quantas fichas, atos do acervo e páginas, e quanto custaria. SÓ LÊ."""
    lista = candidatos(con, **filtro)
    conta = RT.estimativa(con, [c["paginas"] for c in lista])
    conta["atos_do_acervo"] = sum(c["atos_do_acervo"] for c in lista)
    conta["primeiras"] = lista[:5]
    return conta


def _filtro(dados: dict) -> dict:
    return {"livro": str(dados.get("livro") or "").strip(),
            "de": str(dados.get("de") or "").strip()[:10],
            "ate": str(dados.get("ate") or "").strip()[:10],
            "so_sem_revisao": bool(dados.get("so_sem_revisao"))}


def criar(con, dados: dict, *, usuario: str = "") -> int:
    """Cria o lote com a lista de fichas, na ordem. ESCREVE. Não começa a ler."""
    bd = banco(con)
    init_schema(bd)
    filtro = _filtro(dados)
    lista = candidatos(bd, **filtro)
    if not lista:
        raise LoteError("Nenhuma ficha transcrita com página escaneada nesta escolha "
                        "(ou todas já foram revisadas).")
    cfg = RT.configuracao(bd)
    novo = bd.escrever(
        """INSERT INTO ri_transcricao_lotes (filtro_json, criado_em, criado_por,
               teto_paginas, teto_custo, total_fichas, total_paginas)
           VALUES (%s, %s, %s, %s, %s, %s, %s) RETURNING id""",
        (json.dumps(filtro), _agora(), usuario or None, cfg["teto_paginas"],
         cfg["teto_custo"], len(lista), sum(c["paginas"] for c in lista)))
    lote_id = int(novo[0]["id"])
    for ordem, c in enumerate(lista, start=1):
        bd.escrever("""INSERT INTO ri_transcricao_lote_itens (lote_id, ordem, matricula_id,
                           paginas) VALUES (%s, %s, %s, %s)""",
                    (lote_id, ordem, c["matricula_id"], c["paginas"]))
    return lote_id


# ------------------------------------------------------------------ começar e pausar

def _situacao_viva(lote: dict) -> str:
    if lote["situacao"] in (RODANDO, PAUSANDO) and lote.get("batida_em"):
        try:
            idade = (datetime.now() - datetime.fromisoformat(lote["batida_em"])
                     ).total_seconds()
        except ValueError:
            idade = 0
        if idade > MINUTOS_SEM_BATIDA * 60:
            return PARADO
    return lote["situacao"]


def comecar(con, lote_id: int) -> None:
    """Abre uma RODADA nova: zera a conta dela e lê o teto de hoje. ESCREVE.

    Um lote por vez na casa: dois lotes lendo juntos dobrariam o gasto sem que
    o teto de nenhum dos dois o visse. A trava vem antes da conferência — dois
    cliques em «continuar» não abrem duas rodadas."""
    bd = banco(con)
    init_schema(bd)
    bd.travar("ri_transcricao_lotes.rodada")
    lote = bd.um("SELECT * FROM ri_transcricao_lotes WHERE id = %s FOR UPDATE",
                 (int(lote_id),))
    if lote is None:
        raise LoteError("Lote não encontrado.")
    situacao = _situacao_viva(lote)
    if situacao in (RODANDO, PAUSANDO):
        raise LoteError("Este lote já está rodando.")
    if situacao == TERMINADO:
        raise LoteError("Este lote já terminou.")
    for outro in bd.ler("""SELECT id, situacao, batida_em FROM ri_transcricao_lotes
                            WHERE id <> %s AND situacao IN ('RODANDO', 'PAUSANDO')
                         ORDER BY id""", (int(lote_id),)):
        if _situacao_viva(outro) in (RODANDO, PAUSANDO):
            raise LoteError(f"O lote nº {outro['id']} está rodando. Pause-o (ou espere "
                            "terminar) antes de começar outro.")
    cfg = RT.configuracao(bd)
    bd.escrever(
        """UPDATE ri_transcricao_lotes
              SET situacao = 'RODANDO', rodada = rodada + 1, rodada_paginas = 0,
                  rodada_custo = 0, erros_seguidos = 0, teto_paginas = %s,
                  teto_custo = %s, batida_em = %s, mensagem = NULL
            WHERE id = %s""",
        (cfg["teto_paginas"], cfg["teto_custo"], _agora(), int(lote_id)))


def pausar(con, lote_id: int, *, usuario: str = "") -> str:
    """Pede a pausa. ESCREVE. A ficha que está sendo lida termina; o lote
    parado (servidor reiniciado) pausa na hora."""
    bd = banco(con)
    bd._escrita()
    lote = bd.um("SELECT * FROM ri_transcricao_lotes WHERE id = %s FOR UPDATE",
                 (int(lote_id),))
    if lote is None:
        raise LoteError("Lote não encontrado.")
    situacao = _situacao_viva(lote)
    if situacao == RODANDO:
        bd.escrever("UPDATE ri_transcricao_lotes SET situacao = 'PAUSANDO', mensagem = %s "
                    "WHERE id = %s", (f"Pausa pedida por {usuario or 'alguém'}; a ficha em "
                                      "leitura termina antes.", int(lote_id)))
        return PAUSANDO
    if situacao in (PARADO, PAUSANDO):
        bd.escrever("UPDATE ri_transcricao_lotes SET situacao = 'PAUSADO', mensagem = %s "
                    "WHERE id = %s", (f"Pausado por {usuario or 'alguém'}.", int(lote_id)))
        return PAUSADO
    raise LoteError("Este lote não está rodando.")


# ------------------------------------------------------------------ a rodada

def _lote_preso(bd, lote_id: int) -> dict | None:
    """A linha do lote, presa até o próximo commit — LH12, a ressalva 4 da
    revisão do LH11. `pausar` e `comecar` também a prendem: a rodada que leu
    o lote solto e gravou TERMINADO ou PAUSADO depois cobria a pausa pedida
    entre a leitura e a escrita. Presa, a pausa espera a decisão da rodada, e
    a rodada que chega depois da pausa a vê."""
    bd._escrita()
    return bd.um("SELECT * FROM ri_transcricao_lotes WHERE id = %s FOR UPDATE",
                 (int(lote_id),))


def _parar(bd, lote: dict, situacao: str, mensagem: str) -> bool:
    """TERMINADO ou PAUSADO pela rodada — só se a situação ainda for a lida
    (`lote`, de `_lote_preso`): a pausa pedida no meio não se cobre.

    DEVOLVE SE PAROU (LH15, a observação 5 da revisão do LH12). Com o lote
    lido sem a linha presa, a situação pode ter mudado desde a leitura; aí não
    se grava, e isso não fica calado: vai ao log (o lote e as duas situações,
    sem texto nenhum), e quem chama relê o lote em vez de dizer que ele
    parou."""
    feito = bd.escrever("""UPDATE ri_transcricao_lotes SET situacao = %s, mensagem = %s,
                                  batida_em = %s, terminado_em = %s
                            WHERE id = %s AND situacao = %s
                        RETURNING id""",
                        (situacao, mensagem, _agora(),
                         _agora() if situacao == TERMINADO else None, int(lote["id"]),
                         lote["situacao"]))
    if feito:
        return True
    agora = bd.valor("SELECT situacao FROM ri_transcricao_lotes WHERE id = %s",
                     (int(lote["id"]),))
    _LOG.warning("O lote %s da revisão das transcrições não ficou %s: a situação mudou "
                 "depois da leitura (lida %s, agora %s).", lote["id"], situacao,
                 lote["situacao"], agora)
    return False


def _custo_previsto(bd, paginas: int) -> float:
    media = RT.media_por_chamada(bd)
    return RT.chamadas_previstas(paginas) * RT.custo(
        RT.MODELO, round(media["entrada"]), round(media["saida"]))


def rodar(banco_caminho, pasta_dados: Path, raiz: Path, lote_id: int, *,
          conversar=None) -> str:
    """A rodada: uma ficha por vez, até o teto, a pausa ou o fim. Devolve a
    situação em que o lote ficou. FALA COM A REDE (por `revisao_transcricao.
    executar`), com conexão própria; cada ficha se confirma antes da seguinte,
    e nada fica preso enquanto a IA lê."""
    con = banco_pg.conectar(str(banco_caminho), timeout=30)
    try:
        bd = Banco(con)
        init_schema(bd)
        con.commit()
        # O LOTE QUE NÃO PAROU NÃO SE DIZ PARADO (LH15): `_parar` que não
        # gravou (a situação mudou depois da leitura) volta ao começo, e a
        # volta seguinte decide pelo que está na linha.
        while True:
            lote = _lote_preso(bd, lote_id)
            if lote is None:
                con.commit()
                return ""
            if lote["situacao"] == PAUSANDO:
                parou = _parar(bd, lote, PAUSADO, lote["mensagem"] or "Pausado.")
                con.commit()
                if parou:
                    return PAUSADO
                continue
            if lote["situacao"] != RODANDO:
                con.commit()                       # solta a linha
                return lote["situacao"]
            # A FICHA QUE FALHOU VAI PARA O FIM DA FILA (menos tentativas
            # primeiro): sem isto, a IA fora do ar faria a MESMA ficha ser tentada
            # três vezes seguidas e sair da fila como «erro», sem culpa dela.
            item = bd.um("""SELECT * FROM ri_transcricao_lote_itens
                             WHERE lote_id = %s AND situacao = 'A_FAZER'
                          ORDER BY tentativas, ordem, id LIMIT 1""", (int(lote_id),))
            if item is None:
                parou = _parar(bd, lote, TERMINADO, "Todas as fichas do lote foram vistas.")
                con.commit()
                if parou:
                    return TERMINADO
                continue
            paginas = int(item["paginas"] or 0)
            # O TETO DA RODADA SE CONFERE ANTES DA FICHA, e não depois: o que se
            # quer é que a ficha que passaria do teto não saia.
            if paginas > lote["teto_paginas"]:
                bd.escrever("""UPDATE ri_transcricao_lote_itens SET situacao = 'PULADO',
                                      motivo = %s, feito_em = %s WHERE id = %s""",
                            (f"{paginas} páginas, mais que o teto de "
                             f"{lote['teto_paginas']} da rodada: revise pela ficha",
                             _agora(), item["id"]))
                con.commit()
                continue
            if lote["rodada_paginas"] and (lote["rodada_paginas"] + paginas
                                           > lote["teto_paginas"]):
                parou = _parar(
                    bd, lote, PAUSADO,
                    f"Parou no teto de páginas da rodada ({lote['rodada_paginas']} de "
                    f"{lote['teto_paginas']}). Clique em continuar para outra rodada.")
                con.commit()
                if parou:
                    return PAUSADO
                continue
            if lote["rodada_custo"] and (lote["rodada_custo"] + _custo_previsto(bd, paginas)
                                         > lote["teto_custo"]):
                parou = _parar(
                    bd, lote, PAUSADO,
                    f"Parou no teto de custo da rodada (US$ {lote['rodada_custo']:.2f} "
                    f"de US$ {lote['teto_custo']:.2f}). Clique em continuar para outra "
                    "rodada.")
                con.commit()
                if parou:
                    return PAUSADO
                continue
            # A LINHA SE SOLTA ANTES DA FICHA: a leitura leva minutos, e a
            # pausa pedida durante ela não espera a IA.
            con.commit()
            _uma_ficha(bd, con, banco_caminho, pasta_dados, raiz, lote, item, conversar)
    finally:
        con.close()


def _uma_ficha(bd, con, banco_caminho, pasta_dados, raiz, lote, item, conversar) -> None:
    """Lê uma ficha e põe o resultado no item e na conta do lote."""
    revisao_id, nova = None, False
    try:
        revisao_id, nova = RT.pedir(bd, item["matricula_id"], raiz=raiz,
                                    usuario=USUARIO_DO_LOTE, origem="LOTE",
                                    lote_id=int(lote["id"]))
        con.commit()
    except RT.TranscricaoError as erro:
        # A FICHA QUE NÃO TEM O QUE REVISAR SAI DA FILA com o motivo (o teor
        # foi esvaziado depois de o lote nascer, a matrícula sumiu).
        con.rollback()
        bd.escrever("""UPDATE ri_transcricao_lote_itens SET situacao = 'PULADO', motivo = %s,
                              feito_em = %s WHERE id = %s""",
                    (str(erro)[:200], _agora(), item["id"]))
        con.commit()
        return
    except Exception as erro:                       # noqa: BLE001 — conta como falha
        con.rollback()
        r = {"situacao": RT.ERRO, "erro": type(erro).__name__}
    else:
        if nova:
            RT.executar(banco_caminho, pasta_dados, revisao_id, raiz=raiz,
                        conversar=conversar)
        r = RT.mostrar(bd, revisao_id) or {}
    gasto = float(r.get("custo") or 0) if nova else 0.0
    lidas = int(r.get("paginas_vistas") or 0) if nova else 0
    if r.get("situacao") == RT.ERRO:
        tentativas = int(item["tentativas"] or 0) + 1
        situacao_item = "ERRO" if tentativas >= TENTATIVAS_POR_FICHA else "A_FAZER"
        erros = int(lote["erros_seguidos"] or 0) + 1
    else:
        tentativas = int(item["tentativas"] or 0)
        situacao_item = "FEITO" if nova else "REAPROVEITADO"
        erros = 0
    bd.escrever("""UPDATE ri_transcricao_lote_itens
                      SET situacao = %s, tentativas = %s, revisao_id = %s, feito_em = %s,
                          motivo = %s
                    WHERE id = %s""",
                (situacao_item, tentativas, revisao_id, _agora(),
                 "a leitura falhou" if r.get("situacao") == RT.ERRO else None,
                 item["id"]))
    bd.escrever("""UPDATE ri_transcricao_lotes
                      SET rodada_paginas = rodada_paginas + %s, rodada_custo = rodada_custo + %s,
                          paginas_lidas = paginas_lidas + %s, custo = custo + %s,
                          erros_seguidos = %s, batida_em = %s
                    WHERE id = %s""",
                (lidas, gasto, lidas, gasto, erros, _agora(), int(lote["id"])))
    if erros >= ERROS_SEGUIDOS_PARA_PAUSAR:
        # A PAUSA DOS ERROS SÓ COBRE O LOTE QUE AINDA RODA (LH12). O lote se
        # leu no começo da ficha, e a linha se soltou durante a leitura: a
        # pausa pedida nesse meio tempo fica como foi pedida, e a volta
        # seguinte da rodada a fecha com a frase de quem pediu.
        agora = _lote_preso(bd, lote["id"])
        if agora is not None and agora["situacao"] == RODANDO:
            _parar(bd, agora, PAUSADO,
                   f"A IA não respondeu em {erros} fichas seguidas: o lote pausou. "
                   "Continue mais tarde — as fichas que falharam voltam para a fila.")
    con.commit()


