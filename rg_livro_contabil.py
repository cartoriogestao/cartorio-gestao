    @login_required
    @roles_required(*quem_le)
    def rcpj_rtd_livro_contabil_papel(livro_id: int, qual: str):
        """O termo congelado, ou a certidão. Só LÊ — o termo não se remonta."""
        if qual not in PAPEIS:
            abort(404)
        with db.connect() as con:
            try:
                linha = um(con, livro_id)
                if qual == "certidao":
                    texto = certidao(con, livro_id, sv(), hoje=hoje(),
                                     full_name=usuario_nome(),
                                     funcao=usuario_funcao())
                else:
                    texto = linha[f"termo_{qual}"]
            except LivroContabilError as erro:
                flash(str(erro), "danger")
                return redirect(url_for("rcpj_rtd_livro_contabil_ficha",
                                        livro_id=livro_id))
        if not texto:
            flash("O termo nasce na autenticação — este pedido ainda não foi "
                  "autenticado.", "warning")
            return redirect(url_for("rcpj_rtd_livro_contabil_ficha",
                                    livro_id=livro_id))
        # O SELO CONFERÍVEL NO PAPEL — LT05, 20/10/2026. O texto congelado
        # cita o número do selo (a certidão) ou nem isso (os termos, que se
        # congelam antes de o selo sair); o QR e o endereço da consulta (CN-MA,
        # art. 132) e o que o selo declara de emolumentos saem aqui, desenhados
        # na impressão, sem mexer no que foi congelado.
        import notas_selo as NSELO
        import selo_no_papel as SNPAPEL
        selo = _texto(linha.get("selo"))
        with db.connect() as con:
            texto_do_selo = _texto(banco(con).valor(
                "SELECT texto FROM sd_selos WHERE numero = %s ORDER BY id LIMIT 1",
                (selo,))) if selo else ""
        return render_template("rcpj_rtd_livro_contabil_papel.html",
                               texto=texto, l=linha, qual=qual,
                               marca=NSELO.marca_do_selo(selo),
                               consulta=SNPAPEL.link_de_consulta(selo, texto_do_selo),
                               valores=SNPAPEL.linha_de_valores(texto_do_selo))

