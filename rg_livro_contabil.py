def _data_extenso(iso: Any) -> str:
    from ri_web import data_por_extenso
    try:
        return data_por_extenso(date.fromisoformat(_texto(iso)[:10]))
    except ValueError:
        return _texto(iso)


def claros(linha: dict, serventia: dict, *, hoje: Any, full_name: Any,
           funcao: Any) -> dict:
    """Os claros dos três papéis, do que a autenticação guarda. Só calcula."""
    autenticado = _texto(linha.get("autenticado_em"))[:10]
    return {
        "tipo_livro": rotulo_do_livro(linha),
        "numero_livro": linha.get("numero_livro") or "",
        "pj_nome": linha.get("pj_nome") or "",
        "pj_cnpj": DOC.formatar_cnpj(linha.get("pj_cnpj")),
        "folhas": linha.get("folhas") or "",
        "folha_de": linha.get("folha_de") or "",
        "folha_ate": linha.get("folha_ate") or "",
        "forma": FORMAS.get(linha.get("forma") or "", ""),
        "numero": linha.get("numero") or "",
        "ano": linha.get("ano") or "",
        "selo": _texto(linha.get("selo")) or "(sem selo)",
        "data_autenticacao": (f"{autenticado[8:10]}/{autenticado[5:7]}/"
                              f"{autenticado[:4]}" if len(autenticado) == 10
                              else autenticado),
        "unit_name": serventia.get("unit_name") or "",
        "cns": serventia.get("ri_cns") or "",
        "cidade_uf": serventia.get("cidade_uf") or "",
        "data_extenso": _data_extenso(hoje),
        "full_name": _texto(full_name),
        "funcao": _texto(funcao),
    }


def conferir_modelo(corpo: str) -> str:
    """O ajuste da casa serve a um dos três papéis? O erro, ou ``""``."""
    return MODELOS.conferir_claros(corpo, CLAROS_DOS_PAPEIS)


def montar_papel(con: Any, chave: str, valores: dict) -> str:
    """O papel pelo modelo da casa (ajuste → padrão). Só LÊ.

    O modelo que não monta (claro inventado no ajuste) vira recusa de balcão,
    e não 500.
    """
    try:
        return MODELOS.textos(con).preencher(chave, **valores)
    except MODELOS.ModeloError as erro:
        raise LivroContabilError(str(erro)) from erro


def certidao(con: Any, livro_id: int, serventia: dict, *, hoje: Any,
             full_name: Any, funcao: Any) -> str:
    """A certidão da autenticação, montada do que ela congelou. Só LÊ.

    Só da AUTENTICADA: certificar a que está suspensa (sem selo) ou
    cancelada seria a certidão afirmando um ato que não se completou.
    """
    linha = um(con, livro_id)
    if linha["situacao"] != "AUTENTICADO":
        raise LivroContabilError(
            "Só se certifica a autenticação concluída, com selo. Esta está: "
            f"{SITUACOES.get(linha['situacao'], linha['situacao']).lower()}.")
    return montar_papel(con, PAPEL_CERTIDAO,
                        claros(linha, serventia, hoje=hoje,
                               full_name=full_name, funcao=funcao))


# ------------------------------------------------------- a autenticação


def item_configurado(get_setting) -> str:
    """O item da tabela do TJMA que a casa configurou, ou ``""``. Só LÊ."""
    return _texto(get_setting(CHAVE_DO_ITEM, ""))


def preco(con: Any, codigo_tj: Any, *, data: Any = None) -> dict | None:
    """O preço do item na tabela do dia, ou None se a tabela não o tem. Só LÊ."""
    servico = AS.servico_do_codigo_tj(con, _texto(codigo_tj))
    if not servico:
        return None
    try:
        conta = AS.calcular_custas(con, servico=int(servico["codigo"]),
                                   data=data)
    except AS.AtoError:
        return None
    from caixa_schema import reais
    return {"servico": int(servico["codigo"]), "descricao": servico["descricao"],
            "total_centavos": conta["total_centavos"],
            "total": reais(conta["total_centavos"]), "conta": conta}


def autenticar(con: Any, livro_id: int, *, codigo_tj: Any, serventia: dict,
               hoje: str, agora: str, usuario: Any, funcao: Any) -> dict:
    """Numera, congela os termos e deixa a autenticação à espera do selo. ESCREVE.

    A ORDEM DAS TRAVAS É A DO RESTO DA CASA: primeiro a do assunto (o número
    do controle), depois a linha (`FOR UPDATE`). Ao contrário, dois
    autenticadores podiam se esperar um ao outro.

    SEM ITEM CONFIGURADO NÃO NUMERA: numerar e não poder selar deixaria
    número de controle preso a um ato que ninguém sabe cobrar.
    """
    item = _texto(codigo_tj)
    if not item:
        raise LivroContabilError(
            "Falta configurar o item da tabela de emolumentos da autenticação "
            "de livro (RCPJ → Livros contábeis → Item da tabela). Sem ele o "
            "selo não sai, e a autenticação não se faz.")
    bd = banco(con)
    if not AS.servico_do_codigo_tj(con, item):
        raise LivroContabilError(
            f"O item {item} configurado não está na tabela de emolumentos "
            "importada. Corrija a configuração.")
    ano = int(str(hoje)[:4])
    bd.travar("rg_livros_contabeis.numero")
    bd._escrita()
    linha = bd.um("SELECT * FROM rg_livros_contabeis WHERE id = %s FOR UPDATE",
                  (int(livro_id),))
    if not linha:
        raise LivroContabilError("Autenticação não encontrada.")
    linha = dict(linha)
    if linha["situacao"] != "PEDIDO":
        raise LivroContabilError(
            "Este pedido já foi autenticado ou cancelado — "
            f"{SITUACOES.get(linha['situacao'], linha['situacao']).lower()}.")
    maior = bd.valor(
        "SELECT max(numero) AS n FROM rg_livros_contabeis WHERE ano = %s",
        (ano,))
    numero = int(maior or 0) + 1
    linha.update({"numero": numero, "ano": ano, "autenticado_em": agora})
    valores = claros(linha, serventia, hoje=hoje, full_name=usuario,
                     funcao=funcao)
    abertura = montar_papel(con, PAPEL_ABERTURA, valores)
    encerramento = montar_papel(con, PAPEL_ENCERRAMENTO, valores)
    bd.escrever(
        """UPDATE rg_livros_contabeis
              SET numero = %s, ano = %s, situacao = 'SUSPENSO_SELO',
                  motivo_suspensao = %s, termo_abertura = %s,
                  termo_encerramento = %s, codigo_tj = %s,
                  autenticado_em = %s, autenticado_por = %s,
                  autenticado_por_funcao = %s
            WHERE id = %s""",
        (numero, ano, "aguardando o selo", abertura, encerramento, item,
         agora, _texto(usuario) or None, _texto(funcao) or None,
         int(livro_id)))
    return {"numero": numero, "ano": ano}


def envelope(linha: dict, *, escrevente: Any, versao_tabela: Any) -> dict:
    """O pedido do selo da autenticação. Só calcula.

    **FORMA POR ANALOGIA, A CONFERIR NA HOMOLOGAÇÃO.** O caminho nunca foi
    usado pela casa e o repositório não tem o schema
    `RtdpjAutenticacaoLivrosContabeis` por campo. Vai a forma do RCPJ/RTD que
    não tem livro nem protocolo (`AtosEmGeral`: escrevente, partes,
    quantidade, ato) — a autenticação não ocupa folha de livro da serventia.
    Se o aparelho recusar, a autenticação fica SUSPENSA com o recado dele, e
    não com selo inventado.
    """
    return AS.envelope_do_rtdpj(
        caminho=AS.CAMINHO_RTDPJ_GERAL, codigo_tj=linha.get("codigo_tj"),
        escrevente=escrevente, versao_tabela=versao_tabela,
        partes=[{"nome": linha.get("pj_nome"),
                 "documento": linha.get("pj_cnpj")}],
        quantidade=1)


def marcar_selado(con: Any, livro_id: int) -> None:
    """A autenticação com selo amarrado fica AUTENTICADA. ESCREVE."""
    banco(con).escrever(
        """UPDATE rg_livros_contabeis
              SET situacao = 'AUTENTICADO', motivo_suspensao = NULL
            WHERE id = %s AND selo IS NOT NULL AND situacao = 'SUSPENSO_SELO'""",
        (int(livro_id),))


def marcar_suspenso(con: Any, livro_id: int, motivo: Any) -> None:
    """O selo não saiu: o motivo fica escrito na autenticação. ESCREVE."""
    banco(con).escrever(
        """UPDATE rg_livros_contabeis SET motivo_suspensao = %s
            WHERE id = %s AND situacao = 'SUSPENSO_SELO'""",
        (_texto(motivo)[:500] or "o selo não saiu", int(livro_id)))


def cancelar(con: Any, livro_id: int, *, motivo: Any, agora: str,
             usuario: Any) -> None:
    """Cancela, com o motivo escrito. ESCREVE.

    O número do controle NÃO volta: ele já pode estar impresso no livro do
    cliente, e reaproveitá-lo daria dois livros com o mesmo número.
    """
    razao = _texto(motivo)
    if len(razao) < 10:
        raise LivroContabilError(
            "Escreva o motivo do cancelamento com pelo menos dez letras — "
            "cancelamento sem motivo é o que a correição não consegue explicar.")
    bd = banco(con)
    bd._escrita()
    linha = bd.um("SELECT situacao FROM rg_livros_contabeis WHERE id = %s "
                  "FOR UPDATE", (int(livro_id),))
    if not linha:
        raise LivroContabilError("Autenticação não encontrada.")
    if linha["situacao"] == "CANCELADO":
        raise LivroContabilError("Esta autenticação já está cancelada.")
    bd.escrever(
        """UPDATE rg_livros_contabeis
              SET situacao = 'CANCELADO', motivo_cancelamento = %s,
                  cancelado_em = %s, cancelado_por = %s
            WHERE id = %s""",
        (razao, agora, _texto(usuario) or None, int(livro_id)))


