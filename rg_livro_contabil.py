def registrar_rotas(app, db, login_required, roles_required, audit) -> None:
    """Pendura as telas da autenticação de livros no app já construído.

    QUEM PEDE É O BALCÃO; QUEM AUTENTICA, CANCELA E CONFIGURA O ITEM É QUEM
    QUALIFICA — a mesma separação do título do RCPJ/RTD (`rg_web`):
    autenticar é ato registral, não de balcão.
    """
    from flask import (abort, flash, redirect, render_template, request,
                       url_for)

    import rg_web
    from serventia import dados as dados_serventia

    quem_opera = rg_web.QUEM_OPERA
    quem_qualifica = rg_web.QUEM_QUALIFICA
    quem_le = (*rg_web.QUEM_OPERA, "AUDITOR")
    usuario_nome = app.extensions["usuario_nome"]
    usuario_funcao = app.extensions["usuario_funcao"]

    # O conferidor dos três papéis (CHAVES), na tela e em quem grava — a régua
    # do `rg_web` (LF06F).
    import modelos_elementos as ELEM
    conferidores = app.extensions.setdefault("conferidores_de_modelo", {})
    for _chave in PAPEIS.values():
        conferidores[_chave] = conferir_modelo
        ELEM.CONFERIDORES[_chave] = conferir_modelo

    def agora() -> str:
        return db.now()

    def hoje() -> str:
        return agora()[:10]

    def sv() -> dict:
        return dados_serventia(db.get_settings)

    def _selar(livro_id: int) -> str:
        """Pede o selo DEPOIS da transação. FALA COM A REDE. Nunca estoura.

        O recado volta para a tela; a falha fica escrita na autenticação e no
        rastro, e ela continua SUSPENSA até «selar de novo».
        """
        with db.connect() as con:
            linha = um(con, livro_id)
        versao = AS.versao_da_tabela_de_custas(
            CAMINHO_DO_SELO, db.get_setting("selo_tabela_custas_em", ""))
        if not versao:
            r = {"selado": False, "motivo": (
                "Falta dizer de que data é a tabela de custas em vigor, em "
                "Administrativo → Configurações.")}
        else:
            try:
                dados = envelope(linha, escrevente=usuario_nome(),
                                 versao_tabela=versao)
            except AS.AtoError as erro:
                r = {"selado": False, "motivo": str(erro)}
            else:
                r = AS.selar_o_ato_lavrado(
                    db, Path(app.config["DATA_DIR"]),
                    tabela="rg_livros_contabeis", ato_id=livro_id,
                    tipo="AUTENTICACAO_LIVRO", atribuicao="RCPJ",
                    agora=agora(), cns=sv().get("ri_cns"),
                    usuario=usuario_nome(), dados=dados,
                    caminho=CAMINHO_DO_SELO,
                    referencia=f"rg_livros_contabeis:{int(livro_id)}")
        with db.transaction() as con:
            if r["selado"]:
                marcar_selado(con, livro_id)
            else:
                marcar_suspenso(con, livro_id, r["motivo"])
        if r["selado"]:
            audit("RCPJ_LIVRO_CONTABIL_SELADO", "rg_livros_contabeis",
                  livro_id, {"selo": r["numero"]})
            return f"Selo {r['numero']}."
        audit("RCPJ_LIVRO_CONTABIL_SELO_FALHOU", "rg_livros_contabeis",
              livro_id, {"motivo": str(r["motivo"])[:500]})
        return (f"A autenticação ficou SUSPENSA, sem selo: {r['motivo']} "
                "Corrija e use «Selar de novo».")

