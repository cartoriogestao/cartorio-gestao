def __getattr__(nome: str):
    """Os nomes dos três papéis no catálogo (`MODELO_<CHAVE>`), lidos da base.

    O TEXTO NUNCA MOROU AQUI: nasceu em `modelos_padrao/rcpj_rtd/` (LG04). O
    catálogo pede um nome por papel, e um nome de função que existe confundiria
    o guarda que separa constante de montador — por isso o nome não existe no
    módulo e responde por aqui, com o MESMO texto que o papel imprime. Nome que
    não é de papel continua sendo `AttributeError`.
    """
    if nome.startswith("__"):
        raise AttributeError(nome)
    return MODELOS.constante_antiga(__name__, nome)
