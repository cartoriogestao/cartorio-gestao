def init_rg_livro_contabil_schema(con: Any) -> None:
    """Cria a tabela e os índices, se faltarem. Idempotente.

    Cada comando é um `CREATE ... IF NOT EXISTS` próprio, e não um bloco
    condicionado à tabela existir: banco que já tinha a tabela também ganha
    o índice que nasceu depois.
    """
    bd = banco(con)
    for comando in SCHEMA:
        bd.escrever(comando)


# ----------------------------------------------------------- o que se calcula


def _texto(v: Any) -> str:
    return str(v if v is not None else "").strip()


def _norm(v: Any) -> str:
    t = unicodedata.normalize("NFD", _texto(v).upper())
    return " ".join("".join(c for c in t
                            if unicodedata.category(c) != "Mn").split())


def _inteiro(v: Any, nome: str) -> int:
    try:
        return int(_texto(v))
    except ValueError:
        raise LivroContabilError(f"Informe {nome} em número.") from None


def rotulo_do_livro(linha: dict) -> str:
    """«Livro Diário» — ou a descrição que o balcão escreveu no «outro»."""
    if linha.get("tipo_livro") == "OUTRO" and _texto(linha.get("tipo_descricao")):
        return _texto(linha["tipo_descricao"])
    return TIPOS_DE_LIVRO.get(linha.get("tipo_livro") or "", "Livro")


def conferir_pedido(dados: dict) -> dict:
    """O pedido arrumado, ou a recusa que diz o que corrigir. Só calcula."""
    nome = _texto(dados.get("pj_nome"))
    if not nome:
        raise LivroContabilError("Informe o nome da pessoa jurídica.")
    cnpj = DOC.so_digitos(dados.get("pj_cnpj"))
    if not DOC.cnpj_valido(cnpj):
        raise LivroContabilError(
            "O CNPJ da pessoa jurídica não confere (dígito verificador). "
            "Confira no cartão do CNPJ — livro autenticado no CNPJ errado é "
            "livro de outra empresa.")
    tipo = _texto(dados.get("tipo_livro")).upper()
    if tipo not in TIPOS_DE_LIVRO:
        raise LivroContabilError("Escolha o tipo do livro.")
    descricao = _texto(dados.get("tipo_descricao")) or None
    if tipo == "OUTRO" and not descricao:
        raise LivroContabilError(
            "No «outro livro», escreva qual é — é o nome que vai no termo.")
    numero_livro = _inteiro(dados.get("numero_livro"),
                            "o número de ordem do livro")
    if numero_livro < 1:
        raise LivroContabilError("O número de ordem do livro começa em 1.")
    folhas = _inteiro(dados.get("folhas"), "a quantidade de folhas")
    if folhas < 1:
        raise LivroContabilError(
            "O livro precisa ter folhas: a autenticação certifica quantas "
            "são e como estão numeradas.")
    folha_de = (_inteiro(dados.get("folha_de"), "a primeira folha")
                if _texto(dados.get("folha_de")) else 1)
    folha_ate = (_inteiro(dados.get("folha_ate"), "a última folha")
                 if _texto(dados.get("folha_ate")) else folha_de + folhas - 1)
    if folha_ate - folha_de + 1 != folhas:
        raise LivroContabilError(
            f"As folhas não batem: de {folha_de} a {folha_ate} são "
            f"{folha_ate - folha_de + 1}, e o pedido diz {folhas}. O termo "
            "afirma as duas coisas, e as duas têm de ser verdade.")
    forma = _texto(dados.get("forma")).upper() or "PAPEL"
    if forma not in FORMAS:
        raise LivroContabilError("Escolha a forma do livro: papel ou eletrônico.")
    registro = _texto(dados.get("registro_id"))
    return {"pj_nome": nome.upper(), "pj_cnpj": cnpj, "tipo_livro": tipo,
            "tipo_descricao": descricao if tipo == "OUTRO" else None,
            "numero_livro": numero_livro, "folhas": folhas,
            "folha_de": folha_de, "folha_ate": folha_ate, "forma": forma,
            "registro_id": int(registro) if registro.isdigit() else None,
            "apresentante_nome": _texto(dados.get("apresentante_nome")) or None,
            "apresentante_documento":
                DOC.so_digitos(dados.get("apresentante_documento")) or None}


def _mesmo_livro(bd, p: dict, *, fora_id: int | None = None) -> dict | None:
    """O pedido vivo do mesmo livro, se houver. Só LÊ — sob a trava de quem chama."""
    return bd.um(
        """SELECT id, numero, ano, situacao FROM rg_livros_contabeis
            WHERE pj_cnpj = %s AND tipo_livro = %s
              AND upper(coalesce(tipo_descricao, '')) = upper(%s)
              AND numero_livro = %s AND situacao <> 'CANCELADO'
              AND id <> %s
            ORDER BY id LIMIT 1""",
        (p["pj_cnpj"], p["tipo_livro"], p.get("tipo_descricao") or "",
         p["numero_livro"], int(fora_id or 0)))


def livro_anterior_ausente(con: Any, p: dict) -> bool:
    """O livro nº n-1 do mesmo tipo e da mesma PJ não consta autenticado aqui?

    É AVISO, e não recusa: a sociedade pode ter mudado de sede e autenticado
    o anterior noutra serventia, ou estar abrindo a escrituração. Mas livro 5
    sem o 4 é o que a fiscalização pergunta, e o balcão precisa ver antes.
    """
    if int(p["numero_livro"]) <= 1:
        return False
    return banco(con).um(
        """SELECT 1 AS ha FROM rg_livros_contabeis
            WHERE pj_cnpj = %s AND tipo_livro = %s
              AND upper(coalesce(tipo_descricao, '')) = upper(%s)
              AND numero_livro = %s AND situacao = 'AUTENTICADO'
            ORDER BY id LIMIT 1""",
        (p["pj_cnpj"], p["tipo_livro"], p.get("tipo_descricao") or "",
         int(p["numero_livro"]) - 1)) is None


def pedir(con: Any, dados: dict, *, agora: str, usuario: Any = None) -> dict:
    """Registra o pedido de autenticação. ESCREVE, na transação de quem chama.

    Devolve `{"id", "avisos"}`. A TRAVA É DO CNPJ e vem ANTES de olhar se o
    livro já existe — sem ela, dois balcões com o mesmo livro passariam juntos
    pela conferência.
    """
    p = conferir_pedido(dados)
    bd = banco(con)
    if p["registro_id"] is not None and not bd.um(
            "SELECT id FROM rg_registros WHERE id = %s AND atribuicao = 3",
            (p["registro_id"],)):
        raise LivroContabilError(
            "O registro da pessoa jurídica indicado não existe no RCPJ.")
    bd.travar(f"rg_livros_contabeis.livro:{p['pj_cnpj']}")
    ja = _mesmo_livro(bd, p)
    if ja:
        onde = (f"sob o nº {ja['numero']}/{ja['ano']}" if ja["numero"]
                else "num pedido ainda não autenticado")
        raise LivroContabilError(
            f"Este livro ({rotulo_do_livro(p)} nº {p['numero_livro']} deste "
            f"CNPJ) já está {onde} — pedido {ja['id']}. O mesmo livro não se "
            "autentica duas vezes; se o anterior estava errado, cancele-o "
            "com o motivo.")
    avisos = []
    if livro_anterior_ausente(con, p):
        avisos.append(
            f"O livro nº {p['numero_livro'] - 1} deste tipo e deste CNPJ não "
            "consta autenticado nesta serventia. Confira com o apresentante "
            "(pode ter sido autenticado em outra sede).")
    try:
        novo = bd.escrever(
            """INSERT INTO rg_livros_contabeis
                   (pj_nome, pj_cnpj, registro_id, tipo_livro, tipo_descricao,
                    numero_livro, folhas, folha_de, folha_ate, forma,
                    apresentante_nome, apresentante_documento, situacao,
                    pedido_em, pedido_por)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,'PEDIDO',%s,%s)
               RETURNING id""",
            (p["pj_nome"], p["pj_cnpj"], p["registro_id"], p["tipo_livro"],
             p["tipo_descricao"], p["numero_livro"], p["folhas"],
             p["folha_de"], p["folha_ate"], p["forma"],
             p["apresentante_nome"], p["apresentante_documento"],
             agora, _texto(usuario) or None))
    except sqlite3.IntegrityError as erro:
        raise LivroContabilError(
            "Este livro já tem pedido vivo nesta serventia — o mesmo livro "
            "não se autentica duas vezes.") from erro
    return {"id": int(novo[0]["id"]), "avisos": avisos}


def um(con: Any, livro_id: int) -> dict:
    linha = banco(con).um("SELECT * FROM rg_livros_contabeis WHERE id = %s",
                          (int(livro_id),))
    if not linha:
        raise LivroContabilError("Autenticação não encontrada.")
    return dict(linha)


def listar(con: Any, *, cnpj: Any = None, de: Any = None, ate: Any = None,
           situacao: Any = None, limite: int = 200) -> list[dict]:
    """As autenticações, das mais novas para as mais velhas. Só LÊ."""
    onde, args = ["1 = 1"], []
    digitos = DOC.so_digitos(cnpj)
    if digitos:
        onde.append("pj_cnpj = %s")
        args.append(digitos)
    if _texto(de):
        onde.append("substring(pedido_em FROM 1 FOR 10) >= %s")
        args.append(_texto(de)[:10])
    if _texto(ate):
        onde.append("substring(pedido_em FROM 1 FOR 10) <= %s")
        args.append(_texto(ate)[:10])
    if _texto(situacao).upper() in SITUACOES:
        onde.append("situacao = %s")
        args.append(_texto(situacao).upper())
    args.append(int(limite))
    return [dict(r) for r in banco(con).ler(
        f"""SELECT * FROM rg_livros_contabeis WHERE {' AND '.join(onde)}
             ORDER BY id DESC LIMIT %s""", args)]


