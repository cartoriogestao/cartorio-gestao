    def _cobrar(livro_id: int) -> str:
        """Lança o item no caixa de quem autenticou, se ele marcou. ESCREVE.

        Opcional, como no registro do RCPJ/RTD (`rg_web._cobrar_se_pedido`):
        sem caixa aberto não se cobra, e a frase diz o que fazer.
        """
        try:
            with db.transaction() as con:
                linha = um(con, livro_id)
                caixa = banco(con).um(
                    """SELECT id FROM cx_caixas
                        WHERE operador_nome = %s AND situacao = 'ABERTO'
                        ORDER BY data DESC, id LIMIT 1""", (usuario_nome(),))
                if not caixa:
                    return ("Não lancei no caixa: você não tem caixa aberto. "
                            "Abra o caixa e cobre depois.")
                servico = AS.servico_do_codigo_tj(con, linha["codigo_tj"])
                if not servico:
                    return "Não lancei no caixa: o item não está na tabela."
                r = AS.cobrar(con, tabela="rg_livros_contabeis",
                              ato_id=livro_id, servico=int(servico["codigo"]),
                              agora=agora(), hoje=hoje(),
                              hora=agora()[11:16], caixa_id=int(caixa["id"]),
                              pagador=linha["pj_nome"],
                              pagador_documento=linha["pj_cnpj"],
                              descricao="AUTENTICAÇÃO DE LIVRO — RCPJ",
                              selo=linha["selo"])
        except AS.AtoError as erro:
            return f"Não lancei no caixa: {erro}"
        audit("RCPJ_LIVRO_CONTABIL_COBRADO", "rg_livros_contabeis", livro_id,
              {"lancamento_id": r["lancamento_id"]})
        from caixa_schema import reais
        return f"Lançado no caixa: R$ {reais(r['total_centavos'])}."

