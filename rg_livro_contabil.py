"""A AUTENTICAÇÃO DE LIVROS CONTÁBEIS NO RCPJ — pedido, termos, selo e controle.

    «Autenticação de livros contábeis (RCPJ/RTD): termo de abertura/
     encerramento, autenticação, livro.»            — LG04, item 4, 19/10/2026

O QUE HAVIA, MEDIDO EM 19/10/2026
    Só o catálogo: o serviço 310 «Autenticação de Livros Contábeis»
    (`atribuicoes.ATOS`, atribuição 3) e o caminho do selador
    `/selo/rtdpj/autenticacao-contabil` (`selador.py`, schema
    `RtdpjAutenticacaoLivrosContabeis`). Nenhuma tabela, tela nem envelope — e
    nenhum selo do acervo saiu por esse caminho: a casa nunca autenticou livro
    por este sistema nem pelo E-Ofício.

A BASE NORMATIVA, E O QUE NÃO ESTÁ NO CÓDIGO DO MARANHÃO
    A sociedade simples, a associação e a fundação levam os livros ao Registro
    Civil das Pessoas Jurídicas onde estão inscritas (Código Civil, art. 1.181;
    Lei 6.015/1973, arts. 114 e seguintes). **O Código de Normas do MA (Prov.
    COGEX 28/2026) não tem seção sobre isto** — procurado no texto da casa
    («livro contábil», «livros mercantis», «1.181», «Sped»): zero. Onde este
    módulo afirma regra que não é do Código Civil, a fonte é «conferir no
    texto oficial».

O FLUXO
    1. O BALCÃO PEDE (`pedir`): a pessoa jurídica, o livro e as folhas. Ainda
       sem número — número dado a pedido que não se autentica seria buraco no
       controle, o mesmo motivo de o ato das Notas nascer EM_LAVRATURA.
    2. QUEM QUALIFICA AUTENTICA (`autenticar`): o número de ordem do controle
       (sequencial por exercício), e os termos de abertura e de encerramento
       montados e CONGELADOS — o que se imprimiu no livro do cliente não muda
       quando o modelo mudar.
    3. O SELO SAI DEPOIS, fora da transação (regra da casa: o pedido ao
       aparelho tem prazo e não segura a escrita de ninguém). Selo que não
       sai deixa a autenticação SUSPENSA, com o motivo — e «selar de novo»
       resolve, com a mesma referência (o SID não vende outro selo).

O MESMO LIVRO NÃO SE AUTENTICA DUAS VEZES
    Mesmo CNPJ, mesmo tipo (e a mesma descrição, quando o tipo é «outro») e
    mesmo número de ordem do livro. A conferência roda SOB A TRAVA do CNPJ e o
    índice único parcial é a segunda tranca: um `SELECT` solto antes do
    `INSERT` deixaria dois balcões passarem juntos.

O ITEM DA TABELA NÃO SE ADIVINHA
    A tabela do TJMA importada não diz com clareza qual item é o da
    autenticação de livro (há 15.7.1–15.7.3, «até cinco folhas / por folha que
    exceder / quando a inscrição for por Sped», sem o cabeçalho; e o acervo
    usou 15.7.1 no registro integral sem valor). Por isso o item é
    CONFIGURAÇÃO (`CHAVE_DO_ITEM`, tela do ADMIN/MANAGER), sem padrão — sem
    ele, a autenticação diz o que falta e o selo não sai.

PostgreSQL nativo, pelo `bd_nativo`.
"""
