def init_rg_schema(con) -> None:
    """Cria as tabelas de RCPJ/RTD. Idempotente. Chamar DEPOIS do núcleo."""
    bd = banco(con)
    # os comentários saem ANTES de separar, como no `rc_pedidos_schema`.
    for comando in re.split(r";[ \t]*\n", re.sub(r"--[^\n]*", "", SCHEMA)):
        if comando.strip():
            bd.escrever(comando)
    for tabela, coluna, tipo in MIGRACOES:
        if not bd.tem_coluna(tabela, coluna):
            bd.escrever(f"ALTER TABLE {tabela} ADD COLUMN {coluna} {tipo}")
