"""A conferência de documento eletrônico no RI, selada a partir do protocolo — 28/10/2026.

    «crie uma PR para podermos emitir selo em um protocolo para conferencia de
     documento digital no RI. quando precisamos efetuar esse servico, a emissao
     do selo pode ser feita a partir do protocolo, gerando uma etiqueta para
     colar na folha fisica (tipo etiqueta de reconhecimento de firma) ou
     comprovante anexado ao arquivamento digital (pdf)» — o oficial

O QUE É
    O item 16.42 da tabela do TJMA: «Conferência de documentos públicos, via
    internet, por documento». O balcão do RI confere na fonte que o emitiu a
    CND, o recibo do ITR, a certidão eletrônica — e o papel (ou o PDF) entra
    no arquivo do título. O serviço é cobrado no protocolo do balcão, e o selo
    não tinha por onde sair: medido na produção em 28/10/2026, **249 unidades
    do 16.42 em 54 protocolos do RI em 2026, e ZERO selos com «Ato: 16.42»
    no razão**.

O CAMINHO DO SELO, E POR QUE ESTE
    `/selo/imovel/atos-em-geral` (schema `AtosEmGeral`), o mesmo do
    arquivamento do RI (16.39, `ato_selado.CAMINHO_ARQUIVAMENTO_RI`): um pedido
    com `quantidade` = número de documentos conferidos, e não N selos. É o
    caminho por onde esta casa selou os itens do capítulo 16 que não são ato
    de matrícula (16.24.4, 16.39, 16.24.1, 16.25.7 — 451 usos medidos em
    `atribuicoes.ITENS_DE_CUSTA_POR_CAMINHO`).

    O ÚNICO PRECEDENTE DO 16.42 NO ACERVO FOI POR OUTRO CAMINHO, e fica
    declarado: um selo de 2020, por `/selo/notas/atos-em-geral`, com
    `quantidade: 5` — o mesmo schema e o mesmo envelope, de outra atribuição.
    Se o aparelho recusar o 16.42 pelo caminho do imóvel, a troca é desta
    constante, e o envelope não muda: `CAMINHO`, abaixo.

POR QUE TABELA PRÓPRIA
    O selo precisa de um ato daqui para se amarrar (a chave é `tabela` +
    `ato_id`), e a conferência não é ato de matrícula nem prenotação: existe
    mesmo quando o título nunca chega ao livro. É a razão da materialização do
    RCPN (`rc_materializacao`).

O PAGAMENTO É O DO PROTOCOLO
    A conferência GASTA as unidades do item 16.42 do protocolo em que é
    emitida (`caixa_protocolo.consumir_item`) — é por essa ligação que a trava
    do selo pago acha o item e confere que ele foi pago. Selo que não sai
    devolve as unidades (`desfazer_o_consumo`) e a conferência fica cancelada
    com o motivo, sem apagar nada.

ESTE MÓDULO NÃO PEDE SELO: ele confere, grava, cancela e monta o pedido, a
etiqueta e o comprovante. Quem fala com o selador é a rota, fora da transação.
"""
from __future__ import annotations

from typing import Any

#: Ver o docstring: o caminho do arquivamento do RI, pelo mesmo schema — uma
#: constante só, a de `ato_selado`, que `caminho_do_ato` também devolve.
from ato_selado import CAMINHO_ARQUIVAMENTO_RI as CAMINHO
from bd_nativo import banco

CODIGO_ATO = "16.42"
TABELA = "ri_conferencias"
#: O protocolo do balcão que pode emitir: o do RI (`cx_protocolos.atribuicao`).
ATRIBUICAO = "RI"
#: Teto por conferência — o mesmo que a tela de multi-selo do RI aceita por linha.
MAXIMO_DE_DOCUMENTOS = 50
#: O que se descreve de cada documento cabe numa linha da etiqueta.
MAXIMO_DA_DESCRICAO = 300

SCHEMA = """
CREATE TABLE IF NOT EXISTS ri_conferencias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo_id bigint NOT NULL,           -- cx_protocolos.id: o atendimento
    item_id bigint NOT NULL,                -- cx_protocolo_atos.id: o 16.42 que paga
    quantidade INTEGER NOT NULL,            -- documentos conferidos (= unidades)
    documentos TEXT NOT NULL,               -- um documento por linha
    requerente TEXT,
    requerente_documento TEXT,
    selo TEXT,
    etiqueta_impressoes INTEGER NOT NULL DEFAULT 0,
    etiqueta_impressa_em TEXT,
    comprovante_anexo_id bigint,            -- attachments.id do PDF no protocolo
    emitida_em TEXT NOT NULL,
    emitida_por TEXT,
    cancelada_em TEXT,
    cancelada_por TEXT,
    cancelada_motivo TEXT
)
"""

INDICE = """
CREATE INDEX IF NOT EXISTS ix_ri_conferencias_protocolo
    ON ri_conferencias (protocolo_id, id)
"""


class ConferenciaError(ValueError):
    """Erro de regra da conferência, com a frase pronta para o balcão."""


def init_ri_conferencia_schema(con) -> None:
    """Cria a tabela. Idempotente."""
    bd = banco(con)
    bd.escrever(SCHEMA)
    bd.escrever(INDICE)


# ------------------------------------------------------------- o protocolo


def itens_do_protocolo(con, protocolo_id) -> list[dict]:
    """Os itens 16.42 do protocolo com saldo, já com `saldo` dentro. Só LÊ."""
    import caixa_protocolo as CXP
    return [i for i in CXP.itens_disponiveis(con, protocolo_id)
            if str(i.get("codigo_ato") or "").strip() == CODIGO_ATO]


def documentos(texto: Any) -> list[str]:
    """As linhas não vazias do campo, sem espaço sobrando. Só calcula."""
    return [" ".join(x.split()) for x in str(texto or "").splitlines() if x.strip()]


def conferir(con, protocolo_id, dados: dict) -> dict:
    """Confere o que a escrevente pediu e devolve limpo. Só LÊ.

    Recusa aqui, em português, o que a trava ou o selador recusariam depois:
    protocolo que não é do RI, sem item 16.42 com saldo, quantidade fora do
    saldo, documento sem descrição."""
    import caixa_protocolo as CXP
    bd = banco(con)
    p = bd.um("SELECT * FROM cx_protocolos WHERE id = %s", (int(protocolo_id),))
    if not p:
        raise ConferenciaError("Protocolo não encontrado.")
    if CXP.esta_encerrado(p.get("situacao")):
        raise ConferenciaError(
            f"O protocolo {p['numero']} está encerrado. Reabra-o (com o motivo) "
            "antes de emitir o selo da conferência.")
    if str(p.get("atribuicao") or "").strip().upper() != ATRIBUICAO:
        raise ConferenciaError(
            f"O protocolo {p['numero']} não é do Registro de Imóveis. A "
            "conferência de documento eletrônico (16.42) sela pelo protocolo do RI.")
    itens = itens_do_protocolo(bd, protocolo_id)
    if not itens:
        raise ConferenciaError(
            f"O protocolo {p['numero']} não tem item 16.42 (conferência de "
            "documento via internet) com unidade sobrando. Acrescente o item ao "
            "protocolo, com a quantidade de documentos, e receba o pagamento.")
    bruto = str(dados.get("item_id") or "").strip()
    if bruto:
        item = next((i for i in itens if str(i["id"]) == bruto), None)
        if item is None:
            raise ConferenciaError(
                "O item escolhido não é um 16.42 deste protocolo com saldo.")
    else:
        item = itens[0]
    lista = documentos(dados.get("documentos"))
    if not lista:
        raise ConferenciaError(
            "Escreva os documentos conferidos, um por linha (ex.: «CND de "
            "débitos relativos a tributos federais nº ...»).")
    longas = [i + 1 for i, x in enumerate(lista) if len(x) > MAXIMO_DA_DESCRICAO]
    if longas:
        raise ConferenciaError(
            f"A linha {longas[0]} passa de {MAXIMO_DA_DESCRICAO} caracteres: "
            "descreva o documento mais curto (nome, número e órgão emissor).")
    try:
        quantidade = int(str(dados.get("quantidade") or len(lista)).strip())
    except ValueError as erro:
        raise ConferenciaError("A quantidade é um número inteiro.") from erro
    if quantidade != len(lista):
        raise ConferenciaError(
            f"A quantidade ({quantidade}) não bate com os documentos escritos "
            f"({len(lista)}): o selo cobra por documento, e cada um precisa da "
            "sua linha — é ela que sai na etiqueta e no comprovante.")
    if not 1 <= quantidade <= MAXIMO_DE_DOCUMENTOS:
        raise ConferenciaError(
            f"Uma conferência leva de 1 a {MAXIMO_DE_DOCUMENTOS} documentos.")
    if quantidade > int(item["saldo"]):
        raise ConferenciaError(
            f"O item 16.42 do protocolo {p['numero']} tem {item['saldo']} "
            f"unidade(s) sobrando, e a conferência pede {quantidade}. "
            "Acrescente as unidades ao protocolo antes.")
    return {"protocolo": p, "item": item, "quantidade": quantidade,
            "documentos": lista,
            "requerente": str(p.get("interessado") or "").strip(),
            "requerente_documento": "".join(
                c for c in str(p.get("interessado_documento") or "") if c.isdigit())}


def registrar(con, conferido: dict, *, agora: str, usuario: Any) -> int:
    """Grava a conferência (ainda sem selo) e gasta as unidades do 16.42. ESCREVE.

    As duas coisas na mesma transação: conferência sem as unidades gastas
    não acharia o pagamento na trava, e unidade gasta sem conferência seria
    o serviço pago e sumido."""
    import caixa_protocolo as CXP
    bd = banco(con)
    novo = int(bd.escrever(
        """INSERT INTO ri_conferencias (protocolo_id, item_id, quantidade,
               documentos, requerente, requerente_documento, emitida_em,
               emitida_por)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
        (int(conferido["protocolo"]["id"]), int(conferido["item"]["id"]),
         int(conferido["quantidade"]), "\n".join(conferido["documentos"]),
         conferido["requerente"] or None, conferido["requerente_documento"] or None,
         agora, str(usuario or "") or None))[0]["id"])
    gastas = CXP.consumir_item(bd, int(conferido["item"]["id"]), ato_id=novo,
                               tabela=TABELA, agora=agora,
                               quantas=int(conferido["quantidade"]),
                               origem=CXP.ORIGEM_CONSUMO, quem=str(usuario or "") or None)
    if gastas < int(conferido["quantidade"]):
        # Outro balcão gastou a unidade entre a conferência e aqui: a exceção
        # desfaz a transação inteira, e nada fica pela metade.
        raise ConferenciaError(
            "O saldo do item 16.42 mudou enquanto a conferência era gravada. "
            "Nada foi gravado: confira o protocolo e emita de novo.")
    return novo


def desfazer_o_consumo(con, conferencia_id: int) -> int:
    """Devolve ao item 16.42 as unidades desta conferência. ESCREVE.

    O espelho de `registrar`, na forma da certidão do RTD
    (`atribuicoes_web`): `devolver_item` e o rastro em `cx_item_do_ato`."""
    import caixa_protocolo as CXP
    bd = banco(con)
    c = uma(bd, conferencia_id)
    if not c:
        return 0
    voltaram = CXP.devolver_item(bd, int(c["item_id"]), quantas=int(c["quantidade"]))
    if bd.tem_tabela("cx_item_do_ato"):
        bd.escrever("""DELETE FROM cx_item_do_ato
                        WHERE tabela = %s AND ato_id = %s AND item_id = %s
                          AND origem = %s""",
                    (TABELA, int(conferencia_id), int(c["item_id"]),
                     CXP.ORIGEM_CONSUMO))
    return voltaram


def cancelar(con, conferencia_id: int, *, motivo: str, agora: str,
             usuario: Any) -> None:
    """Marca a conferência cancelada e devolve as unidades. ESCREVE. Não apaga.

    Conferência com selo não se cancela por aqui: o selo saiu e está no razão,
    e desfazer selo é o cancelamento no aparelho, que é outro ato."""
    bd = banco(con)
    c = uma(bd, conferencia_id)
    if not c or c.get("cancelada_em"):
        return
    if str(c.get("selo") or "").strip():
        raise ConferenciaError(
            "Esta conferência já tem selo. Cancelar o selo é ato do selador, "
            "e não se faz por aqui.")
    desfazer_o_consumo(bd, conferencia_id)
    bd.escrever(
        """UPDATE ri_conferencias
              SET cancelada_em=%s, cancelada_por=%s, cancelada_motivo=%s
            WHERE id=%s AND cancelada_em IS NULL""",
        (agora, str(usuario or "") or None, motivo, int(conferencia_id)))


def uma(con, conferencia_id) -> dict | None:
    """Uma conferência, com a lista de documentos. Só LÊ."""
    bruto = str(conferencia_id or "").strip()
    if not bruto.isdigit():
        return None
    bd = banco(con)
    if not bd.tem_tabela("ri_conferencias"):
        return None
    c = bd.um("SELECT * FROM ri_conferencias WHERE id = %s", (int(bruto),))
    if not c:
        return None
    c = dict(c)
    c["lista"] = documentos(c.get("documentos"))
    return c


def do_protocolo(con, protocolo_id) -> list[dict]:
    """As conferências daquele protocolo, da mais nova à mais velha. Só LÊ."""
    bd = banco(con)
    if not bd.tem_tabela("ri_conferencias"):
        return []
    ids = bd.ler("""SELECT id FROM ri_conferencias WHERE protocolo_id = %s
                     ORDER BY id DESC""", (int(protocolo_id),))
    return [uma(bd, x["id"]) for x in ids]


# ------------------------------------------------------------- o pedido


def envelope(conferido: dict, *, escrevente: Any, versao_tabela: Any) -> dict:
    """O pedido do selo, no schema `AtosEmGeral`. Só calcula.

    A forma é a do arquivamento do RI (`ato_selado.envelope_do_arquivamento_do_ri`)
    e a do único precedente do 16.42 no acervo: escrevente, partes, a
    `quantidade` de documentos e o item com a versão da tabela."""
    if not str(escrevente or "").strip() or not str(versao_tabela or "").strip():
        raise ConferenciaError(
            "O selo da conferência não sai sem o escrevente e a versão da tabela "
            "de custas (Administrativo → Configurações).")
    nome = str(conferido.get("requerente") or "").strip()
    parte = ([{"nome": nome, "documento": conferido.get("requerente_documento") or ""}]
             if nome else [])
    return {
        "escrevente": str(escrevente).strip(),
        "partes": {"nomePartes": [], "parteAto": parte},
        "quantidade": int(conferido["quantidade"]),
        "ato": {"codigo": CODIGO_ATO,
                "codigoTabelaCusta": str(versao_tabela).strip()},
    }


# ------------------------------------------------------------- o papel

#: O texto da tira. Só afirma o que aconteceu — a conferência na fonte, o item
#: e o protocolo —, e não «certifico» nem «dou fé»: afirmação jurídica num
#: papel que a serventia assina é de quem assina, e o oficial a acrescenta se
#: quiser (o texto é este, num lugar só, para as duas saídas).
TEXTO_DA_TIRA = ("CONFERÊNCIA DE DOCUMENTO ELETRÔNICO VIA INTERNET (item {codigo}) — "
                 "{documento} — conferido na fonte emissora. Protocolo {protocolo}. "
                 "{cidade}, {data}.")


def _data(emitida_em: Any) -> str:
    bruto = str(emitida_em or "")[:10]
    if len(bruto) == 10 and bruto[4] == "-":
        return f"{bruto[8:10]}/{bruto[5:7]}/{bruto[:4]}"
    return bruto


def tiras(c: dict, protocolo_numero: Any, serventia: dict) -> list[dict]:
    """Uma tira por documento conferido — cada folha física leva a sua. Só calcula."""
    cidade = " / ".join(x for x in (str(serventia.get("ri_cidade") or "").strip(),
                                    str(serventia.get("ri_uf") or "").strip()) if x)
    total = len(c["lista"])
    saida = []
    for i, doc in enumerate(c["lista"], 1):
        texto = TEXTO_DA_TIRA.format(codigo=CODIGO_ATO, documento=doc,
                                     protocolo=protocolo_numero or "",
                                     cidade=cidade or "—", data=_data(c["emitida_em"]))
        if total > 1:
            texto = f"[{i}/{total}] {texto}"
        saida.append({"texto": texto, "documento": doc, "ordem": i, "total": total})
    return saida


def comprovante_pdf(c: dict, *, protocolo_numero: Any, serventia: dict,
                    texto_do_selo: str = "") -> bytes:
    """O comprovante da conferência em PDF, para o arquivo digital. Só calcula.

    Uma página A4: quem é a serventia, o protocolo, o requerente com o
    documento mascarado, a lista dos documentos conferidos, quem conferiu e
    quando, e o selo — número, valores, endereço da consulta e o QR. Sai com
    os mesmos bytes para a mesma conferência (sem a data de gravação do PDF),
    para o anexo repetido ser reconhecido pela impressão digital."""
    try:
        import pymupdf as fitz
    except ImportError:  # versões antigas
        import fitz
    import ri_odt
    import selo_no_papel as SNP
    from serventia import mascarar_documento

    selo = str(c.get("selo") or "").strip()
    linhas: list[tuple[str, float, bool]] = []

    def linha(texto: Any, tamanho: float = 10, negrito: bool = False) -> None:
        # A fonte padrão do PDF não tem o travessão (sai «?»): vira hífen aqui,
        # e só aqui — a etiqueta, que é HTML, continua com ele.
        texto = str(texto or "").replace("—", "-").replace("–", "-")
        linhas.append((texto, tamanho, negrito))

    linha(serventia.get("unit_name") or "", 12, True)
    cidade = " / ".join(x for x in (str(serventia.get("ri_cidade") or "").strip(),
                                    str(serventia.get("ri_uf") or "").strip()) if x)
    if cidade:
        linha(cidade, 9)
    linha("")
    linha("COMPROVANTE DE CONFERÊNCIA DE DOCUMENTO ELETRÔNICO", 13, True)
    linha(f"Item {CODIGO_ATO} da tabela de emolumentos — conferência de documentos "
          "públicos, via internet, por documento.", 9)
    linha("")
    linha(f"Protocolo: {protocolo_numero or '—'}    Conferência nº {c['id']}")
    if c.get("requerente"):
        doc = mascarar_documento(c.get("requerente_documento") or "")
        linha(f"Requerente: {c['requerente']}" + (f" — {doc}" if doc else ""))
    linha(f"Conferido por: {c.get('emitida_por') or '—'}, em "
          f"{_data(c.get('emitida_em'))} às {str(c.get('emitida_em') or '')[11:16]}")
    linha("")
    linha(f"Documentos conferidos na fonte emissora ({len(c['lista'])}):", 10, True)
    for i, doc in enumerate(c["lista"], 1):
        linha(f"{i}. {doc}")
    linha("")
    if selo:
        linha(f"Selo: {selo}", 11, True)
        valores = SNP.linha_de_valores(texto_do_selo or "")
        if valores:
            linha(valores, 9)
        endereco = SNP.link_de_consulta(selo, texto_do_selo or "")
        if endereco:
            linha(f"Confira em {endereco}", 8)
    else:
        linha("SEM SELO — este comprovante não vale como ato selado.", 11, True)

    doc_pdf = fitz.open()
    pagina = doc_pdf.new_page(width=595, height=842)
    y, margem, largura = 56.0, 56.0, 595 - 112
    for texto, tamanho, negrito in linhas:
        if not texto:
            y += tamanho * 0.8
            continue
        caixa = fitz.Rect(margem, y, margem + largura, y + tamanho * 6)
        sobra = pagina.insert_textbox(caixa, texto, fontsize=tamanho,
                                      fontname="hebo" if negrito else "helv")
        y += (tamanho * 6 - max(0.0, sobra)) + tamanho * 0.35
    # O QR VAI DEPOIS DO SELO, e não no canto de cima: lá ele cobria o título.
    png = ri_odt.png_do_qr_do_selo(selo) if selo else None
    if png:
        lado = 96
        pagina.insert_image(fitz.Rect(margem, y + 6, margem + lado, y + 6 + lado),
                            stream=png)
    doc_pdf.set_metadata({})
    return doc_pdf.tobytes(garbage=3, deflate=True, no_new_id=True)
