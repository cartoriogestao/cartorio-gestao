# -*- coding: utf-8 -*-
"""As tabelas da fila de conferência das fichas (Livros 4 e 5 do RI).

**A FILA NÃO É O DADO.** O endereço continua em `ri_matriculas` e o documento em
`ri_partes`. Aqui ficam a sugestão, a decisão de quem conferiu e o rastro.

`ri_ff_alteracoes` **só recebe INSERT**. Desfazer não apaga nem edita a linha
original: grava outra, com `desfaz_id` apontando para ela.
"""
from __future__ import annotations

import re

from bd_nativo import banco

SCHEMA = """
CREATE TABLE IF NOT EXISTS ri_ff_amostras (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fatia TEXT NOT NULL,
    -- A regra da casa estava ligada quando se sorteou? A amostra só vale para o
    -- que a pessoa viu.
    regra_casa INTEGER NOT NULL DEFAULT 0,
    tamanho INTEGER NOT NULL,
    criada_por TEXT NOT NULL,
    criada_em TEXT NOT NULL,
    lote_por TEXT,
    lote_em TEXT,
    lote_qtd INTEGER
);

CREATE TABLE IF NOT EXISTS ri_ff_itens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro TEXT NOT NULL,
    matricula_id INTEGER NOT NULL REFERENCES ri_matriculas(id),
    -- 0 no Livro 4, onde o item é a ficha inteira.
    parte_id INTEGER NOT NULL DEFAULT 0,
    classe TEXT NOT NULL,
    prioridade INTEGER NOT NULL DEFAULT 4,
    confianca TEXT NOT NULL DEFAULT 'media',
    fatia TEXT NOT NULL DEFAULT '',
    situacao TEXT NOT NULL DEFAULT 'A_CONFERIR',
    marcas TEXT NOT NULL DEFAULT '[]',
    -- Campo a campo: atual, sugerido, origem, trecho do teor, conflito (JSON).
    campos TEXT NOT NULL DEFAULT '[]',
    avisos TEXT NOT NULL DEFAULT '[]',
    bloco TEXT NOT NULL DEFAULT '',
    assinatura TEXT NOT NULL DEFAULT '',
    pronta INTEGER NOT NULL DEFAULT 0,
    amostra_id bigint REFERENCES ri_ff_amostras(id),
    calculado_em TEXT NOT NULL,
    decidido_em TEXT,
    decidido_por TEXT,
    UNIQUE (livro, matricula_id, parte_id)
);

CREATE TABLE IF NOT EXISTS ri_ff_alteracoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES ri_ff_itens(id),
    matricula_id INTEGER NOT NULL,
    parte_id INTEGER NOT NULL DEFAULT 0,
    campo TEXT NOT NULL,
    valor_anterior TEXT,
    valor_novo TEXT,
    -- TEOR | REGRA_CASA | MANUAL | DESFAZER
    origem TEXT NOT NULL,
    motivo TEXT NOT NULL DEFAULT '',
    confirmado_por TEXT NOT NULL,
    confirmado_em TEXT NOT NULL,
    amostra_id bigint REFERENCES ri_ff_amostras(id),
    -- Preenchido só na linha que desfaz outra. UNIQUE: desfaz-se uma vez.
    desfaz_id bigint UNIQUE REFERENCES ri_ff_alteracoes(id)
);
"""

INDICES = (
    "CREATE INDEX IF NOT EXISTS idx_ri_ff_itens_fila "
    "ON ri_ff_itens(livro, situacao, prioridade, confianca)",
    "CREATE INDEX IF NOT EXISTS idx_ri_ff_itens_fatia "
    "ON ri_ff_itens(fatia, situacao)",
    "CREATE INDEX IF NOT EXISTS idx_ri_ff_itens_amostra "
    "ON ri_ff_itens(amostra_id)",
    "CREATE INDEX IF NOT EXISTS idx_ri_ff_alteracoes_item "
    "ON ri_ff_alteracoes(item_id)",
)


def init_ri_fila_fichas_schema(con) -> None:
    """Cria as três tabelas e os índices. Não toca em dado nenhum."""
    bd = banco(con)
    for comando in re.split(r";[ \t]*\n", SCHEMA):
        if re.sub(r"--[^\n]*", "", comando).strip():
            bd.escrever(comando)
    for sql in INDICES:
        bd.escrever(sql)
    con.commit()
