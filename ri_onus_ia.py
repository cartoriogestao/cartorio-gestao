def _nome_comparavel(nome: str) -> str:
    """Sem acento, sem caixa, sem pontuação e sem «de/da/dos/e» — o que sobra é
    o que identifica a pessoa («José da Silva» = «JOSE SILVA»)."""
    palavras = re.sub(r"[^A-Z0-9 ]", " ", _sem_acento(nome)).split()
    return " ".join(p for p in palavras if p not in _PALAVRAS_DE_LIGACAO)


def _mesma_pessoa(a: dict, b: dict) -> bool:
    da, db_ = a.get("documento") or "", b.get("documento") or ""
    if len(da) >= 11 and len(db_) >= 11:
        return da == db_
    return bool(_nome_comparavel(a.get("nome"))) and \
        _nome_comparavel(a.get("nome")) == _nome_comparavel(b.get("nome"))


def conferir_proprietarios(cadastro: list, sugestao: dict | None) -> dict:
    """Compara os proprietários do CADASTRO (o quadro que a certidão imprime) com
    os que a IA leu no teor. SÓ COMPARA: quem decide é quem emite.

    `cadastro` é a lista de partes com `proprietario_ativo` — dicionários ou
    linhas com `nome` e `documento_numero` (ou `documento`)."""
    do_cadastro = []
    for p in cadastro or []:
        nome = normalizar(_campo(p, "nome"))
        if nome:
            doc = _campo(p, "documento_numero") or _campo(p, "documento") or ""
            do_cadastro.append({"nome": nome, "documento": re.sub(r"\D", "", str(doc))})
    base = {"cadastro": do_cadastro, "ia": [], "faltam": [], "sobram": [],
            "ato": "", "trecho": "", "trecho_literal": False}
    if not sugestao or sugestao.get("situacao") in ("PENDENTE", "LENDO"):
        return base | {"situacao": LENDO if sugestao else SEM_LEITURA}
    if sugestao.get("situacao") != "PRONTA" or not sugestao.get("vale"):
        return base | {"situacao": SEM_LEITURA}
    da_ia = sugestao.get("proprietarios") or []
    if not da_ia:
        # Leitura feita antes de a IA ler o dono, ou leitura que não achou quem é:
        # sem o lado da IA não há o que comparar — «não confere» aqui acusaria o
        # cadastro sem prova. Volta para a caixa de quem emite, e a tela diz por quê.
        return base | {"situacao": SEM_LEITURA, "ia_sem_dono": True}
    faltam =[p for p in da_ia if not any(_mesma_pessoa(p, c) for c in do_cadastro)]
    sobram = [c for c in do_cadastro if not any(_mesma_pessoa(c, p) for p in da_ia)]
    situacao = CONFERE if da_ia and not faltam and not sobram else DIVERGE
    return base | {"situacao": situacao, "ia": da_ia, "faltam": faltam, "sobram": sobram,
                   "ato": sugestao.get("proprietarios_ato") or "",
                   "trecho": sugestao.get("proprietarios_trecho") or "",
                   "trecho_literal": bool(sugestao.get("proprietarios_literal"))}


def executar(banco: Path, pasta_dados: Path, sugestao_id: int, conversar=None) -> None:
    """Lê. FALA COM A REDE, com conexão própria e fora de transação de escrita —
    a mesma forma de `revisao_previa.executar`, com o mesmo provedor e modelo."""
    import agente_provedores as AP
    import revisao_previa as RP
    from gestor_expedientes import desmascarar
    conversar = conversar or AP.conversar
    con = banco_pg.conectar(str(banco), timeout=30)
    try:
        bd = Banco(con)       # `banco` aqui é o caminho do arquivo
        init_schema(bd)
        linha = bd.um("SELECT dossie, matricula_id FROM ri_onus_sugestoes WHERE id = %s",
                      (sugestao_id,))
        if linha is None:
            return
        bd.escrever("UPDATE ri_onus_sugestoes SET situacao='LENDO', provedor=%s, modelo=%s "
                    "WHERE id=%s", (RP.PROVEDOR, RP.MODELO, sugestao_id))
        con.commit()
        try:
            # O TETO DO DIA ANTES DA REDE (LX13, B5 da auditoria LS03): passou
            # dele, a sugestão termina em ERRO com a frase, e nada sobe.
            import ia_uso as USO
            passou = USO.passou_do_teto(bd, "ri_onus_ia")
            if passou:
                raise RuntimeError(passou)
            seguro, mapa = RP.preparar_para_ia(bd, linha["dossie"])
            # O REGISTRO DO USO DE IA (LF01): a sugestão, sem o texto da ficha.
            resposta = conversar(pasta_dados, provedor=RP.PROVEDOR, sistema=INSTRUCAO,
                                 conversa=[{"tipo": "user", "texto": seguro}],
                                 ferramentas=[], modelo=RP.MODELO,
                                 maximo_de_saida=MAXIMO_DE_SAIDA,
                                 modulo="ri_onus_ia", finalidade="ri_onus_ia",
                                 atribuicao="RI",
                                 referencia=f"ri_onus_sugestoes:{sugestao_id}",
                                 mascarado=RP.mascarar_na_revisao(bd))
            texto = desmascarar(resposta.get("texto") or "", mapa)
            r = ler_resposta(texto, texto_da_ficha(bd, int(linha["matricula_id"])))
            bd.escrever(
                """UPDATE ri_onus_sugestoes SET situacao='PRONTA', terminado_em=%s,
                       resultado_json=%s, modelo=%s, tokens_entrada=%s, tokens_saida=%s
                    WHERE id=%s""",
                (_agora(), json.dumps(r, ensure_ascii=False),
                 resposta.get("modelo") or RP.MODELO, resposta.get("entrada"),
                 resposta.get("saida"), sugestao_id))
        except Exception as erro:                       # noqa: BLE001 — vai à tabela
            bd.escrever("UPDATE ri_onus_sugestoes SET situacao='ERRO', terminado_em=%s, "
                        "erro=%s WHERE id=%s",
                        (_agora(), f"{type(erro).__name__}: {str(erro)[:300]}", sugestao_id))
        con.commit()
    finally:
        con.close()


def ler_em_segundo_plano(banco: Path, pasta_dados: Path, sugestao_id: int) -> None:
    threading.Thread(target=executar, args=(Path(banco), Path(pasta_dados), sugestao_id),
                     daemon=True, name=f"onus-ia-{sugestao_id}").start()


def _situacao_viva(situacao: str, pedido_em: str | None) -> str:
    """Leitura que passa do prazo sem terminar é tratada como ERRO na tela —
    o servidor pode ter sido reiniciado no meio, e «lendo» para sempre trava
    quem espera."""
    if situacao not in ("PENDENTE", "LENDO") or not pedido_em:
        return situacao
    try:
        idade = (datetime.now() - datetime.fromisoformat(pedido_em)).total_seconds()
    except ValueError:
        return situacao
    return "ERRO" if idade > MINUTOS_PARA_DESISTIR * 60 else situacao


def ultima(con, matricula_id: int) -> dict | None:
    """A sugestão mais nova desta matrícula. SÓ LÊ — e não cria a tabela, porque
    é chamada pela tela da ficha (GET não abre transação de escrita).

    `vale` diz se ela foi feita sobre a ficha COMO ESTÁ: ato lavrado ou
    cancelado depois dela muda a ficha, e a sugestão velha não decide nada."""
    bd = banco(con)
    if not _tem_tabela(bd, "ri_onus_sugestoes"):
        return None
    r = bd.um(
        """SELECT id, situacao, resultado_json, erro, pedido_em, pedido_por, hash_ficha,
                  terminado_em
             FROM ri_onus_sugestoes WHERE matricula_id = %s ORDER BY id DESC LIMIT 1""",
        (matricula_id,))
    if r is None:
        return None
    resultado = json.loads(r["resultado_json"]) if r["resultado_json"] else {}
    return {"id": r["id"], "situacao": _situacao_viva(r["situacao"], r["pedido_em"]),
            "erro": r["erro"], "pedido_em": r["pedido_em"], "pedido_por": r["pedido_por"],
            "terminado_em": r["terminado_em"],
            "vale": r["hash_ficha"] == hash_da_ficha(bd, matricula_id), **resultado}


def itens_da_sugestao(sugestao: dict | None) -> list[dict]:
    """Os itens da IA na forma da linha da certidão. Só os de sugestão PRONTA e
    feita sobre a ficha como ela está."""
    if not sugestao or sugestao.get("situacao") != "PRONTA" or not sugestao.get("vale"):
        return []
    saida = []
    for n, i in enumerate(sugestao.get("itens") or [], start=1):
        saida.append({
            "chave": f"IA:{n}", "origem": "IA", "categoria": i.get("categoria") or ONUS,
            "rotulo": i.get("ato") or rotulo_do_trecho(i.get("trecho") or ""),
            "natureza": i.get("natureza") or "", "data": "",
            "texto": sem_rotulo(i.get("trecho") or ""), "trecho": i.get("trecho") or "",
            "conferir": False, "literal": bool(i.get("literal")),
        })
    return saida


