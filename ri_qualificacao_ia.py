def _agora() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _texto(v) -> str:
    return str(v or "").strip()


def _sem_acento(texto: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFD", texto or "")
                   if unicodedata.category(c) != "Mn").upper()


