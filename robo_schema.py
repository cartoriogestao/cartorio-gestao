"""Tabelas dos robos de rascunho — dentro do Cartorio Gestao.

Decisao do oficial em 07/09/2026: gerenciador de robos no mesmo Flask/SQLite.
Um robo = um tipo de ato. Treino = prompt + exemplos (sem fine-tune nesta fatia).

TABELA NOVA VAI NO SCHEMA, nao em MIGRACAO. MIGRACOES so ALTER TABLE ADD
COLUMN. Indice de coluna nova iria em INDICES_DEPOIS_DA_MIGRACAO.

Chaves de API nunca no codigo: api_key_* e provedor_padrao comecam vazios.
Nunca logar API key. Nunca gravar rascunho de teste no livro/RCPN.

AS CHAVES DE API SAIRAM DO BANCO (LX14, 19/10/2026; A8 do LS03). Moravam em
`robo_config`, em texto claro, e iam em todo backup. Agora `ler_config` e
`gravar_config` mandam as quatro `api_key_*` para o cofre (`robos.cred`,
cifrado, na pasta de dados — ver `cofre_cred`); a linha da tabela fica, vazia,
e o `provedor_padrao`, que nao e segredo, continua nela. A subida move o que
ainda estiver na coluna (`init_robo_schema`). A tela diz so «configurada».
"""
from __future__ import annotations

import re
from datetime import date, timedelta
from typing import Any

import cofre_cred as COFRE
from bd_nativo import banco

PROVEDORES = ("grok", "gpt", "claude", "deepseek")

CHAVE_GROK = "api_key_grok"
CHAVE_GPT = "api_key_gpt"
CHAVE_CLAUDE = "api_key_claude"
CHAVE_DEEPSEEK = "api_key_deepseek"
CHAVE_PADRAO = "provedor_padrao"

CHAVES_API = {
    "grok": CHAVE_GROK,
    "gpt": CHAVE_GPT,
    "claude": CHAVE_CLAUDE,
    "deepseek": CHAVE_DEEPSEEK,
}

CHAVES_CONFIG = (
    CHAVE_GROK, CHAVE_GPT, CHAVE_CLAUDE, CHAVE_DEEPSEEK, CHAVE_PADRAO,
)

# O QUE E SEGREDO, e por isso mora no cofre e nao em `robo_config` (LX14).
SEGREDOS = frozenset(CHAVES_API.values())

MODO_LOCAL = "local"
MODO_API = "api"

SCHEMA = """
CREATE TABLE IF NOT EXISTS robo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    ato TEXT NOT NULL,
    provedor TEXT NOT NULL DEFAULT 'grok',
    prompt TEXT NOT NULL DEFAULT '',
    ativo INTEGER NOT NULL DEFAULT 1,
    criado_em TEXT,
    atualizado_em TEXT
);
CREATE INDEX IF NOT EXISTS idx_robo_ativo ON robo(ativo, nome);

CREATE TABLE IF NOT EXISTS robo_exemplo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robo_id INTEGER NOT NULL REFERENCES robo(id),
    entrada TEXT NOT NULL,
    saida_esperada TEXT NOT NULL,
    peso INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_robo_exemplo_robo
    ON robo_exemplo(robo_id);

CREATE TABLE IF NOT EXISTS robo_config (
    chave TEXT PRIMARY KEY,
    valor TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS robo_teste_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robo_id INTEGER NOT NULL REFERENCES robo(id),
    usuario TEXT,
    pedido TEXT,                 -- MASCARADO desde o LX13 (ver registrar_teste)
    rascunho TEXT,               -- idem
    modo TEXT NOT NULL DEFAULT 'local',
    criado_em TEXT
);
CREATE INDEX IF NOT EXISTS idx_robo_teste_log_robo
    ON robo_teste_log(robo_id, criado_em);
"""

MIGRACOES: tuple[tuple[str, str, str], ...] = ()
INDICES_DEPOIS_DA_MIGRACAO: tuple[str, ...] = ()


def init_robo_schema(con) -> None:
    """Cria as tabelas dos robos. Idempotente."""
    bd = banco(con)
    for comando in re.split(r";[ \t]*\n", SCHEMA):
        if re.sub(r"--[^\n]*", "", comando).strip():
            bd.escrever(comando)
    for tabela, coluna, tipo in MIGRACOES:
        if not bd.tem_coluna(tabela, coluna):
            bd.escrever(f"ALTER TABLE {tabela} ADD COLUMN {coluna} {tipo}")
    for comando in INDICES_DEPOIS_DA_MIGRACAO:
        bd.escrever(comando)
    for chave in CHAVES_CONFIG:
        bd.escrever(
            "INSERT INTO robo_config(chave, valor) VALUES (%s, '') "
            "ON CONFLICT DO NOTHING",
            (chave,),
        )
    # A CHAVE QUE AINDA ESTA NA COLUNA VAI PARA O COFRE — a da instalacao de
    # antes do LX14, ou a de um backup antigo restaurado. Idempotente.
    COFRE.migrar_da_tabela(bd, "robo_config", sorted(SEGREDOS), COFRE.ROBOS)


def ler_config(con, chave: str) -> str:
    if chave in SEGREDOS:
        return COFRE.ler_segredo(con, COFRE.ROBOS, chave)
    valor = banco(con).valor(
        "SELECT valor FROM robo_config WHERE chave = %s", (chave,))
    return valor or ""


def gravar_config(con, chave: str, valor: str) -> None:
    """Grava uma configuracao. A chave de API vai ao cofre, e nao ao banco."""
    if chave in SEGREDOS:
        COFRE.gravar_segredo(con, COFRE.ROBOS, chave, valor)
        return
    banco(con).escrever(
        "INSERT INTO robo_config(chave, valor) VALUES (%s, %s) "
        "ON CONFLICT(chave) DO UPDATE SET valor = excluded.valor",
        (chave, valor or ""),
    )


def mascarar_segredo(valor: str) -> str:
    """Mostra so os ultimos 4. Nunca a chave inteira."""
    t = (valor or "").strip()
    if not t:
        return ""
    if len(t) <= 4:
        return "****"
    return "••••" + t[-4:]


def api_key_do_provedor(con, provedor: str) -> str:
    chave = CHAVES_API.get((provedor or "").strip().lower())
    if not chave:
        return ""
    return ler_config(banco(con), chave)


def config_para_tela(con) -> dict[str, Any]:
    bd = banco(con)
    out: dict[str, Any] = {
        "provedor_padrao": ler_config(bd, CHAVE_PADRAO) or "grok",
        "provedores": list(PROVEDORES),
    }
    # SO «CONFIGURADA», SEM OS ULTIMOS QUATRO (LX14): pedaco de chave na tela
    # e pedaco de chave no HTML de quem abriu a pagina.
    guardado = COFRE.ler(COFRE.pasta_do_banco(bd), COFRE.ROBOS)
    for prov, chave in CHAVES_API.items():
        out[f"tem_{prov}"] = bool(guardado.get(chave))
    return out


def gravar_tela_config(con, form: dict) -> None:
    """Grava o que a tela mandou. Campo de chave vazio = nao altera."""
    bd = banco(con)
    padrao = (form.get("provedor_padrao") or "").strip().lower()
    if padrao in PROVEDORES:
        gravar_config(bd, CHAVE_PADRAO, padrao)
    for prov, chave in CHAVES_API.items():
        novo = (form.get(chave) or form.get(f"api_key_{prov}") or "").strip()
        if novo:
            gravar_config(bd, chave, novo)


def listar_robos(con) -> list[dict]:
    return banco(con).ler(
        "SELECT * FROM robo "
        "ORDER BY ativo DESC, nome COLLATE public.cg_nocase, id"
    )


def obter_robo(con, robo_id: int) -> dict | None:
    return banco(con).um(
        "SELECT * FROM robo WHERE id = %s", (robo_id,)
    )


def exemplos_do_robo(con, robo_id: int) -> list[dict]:
    return banco(con).ler(
        "SELECT * FROM robo_exemplo WHERE robo_id = %s "
        "ORDER BY peso DESC, id",
        (robo_id,),
    )


def criar_robo(
    con,
    *,
    nome: str,
    ato: str,
    provedor: str,
    prompt: str,
    ativo: int,
    agora: str,
) -> int:
    novo = banco(con).escrever(
        "INSERT INTO robo(nome, ato, provedor, prompt, ativo, "
        "criado_em, atualizado_em) VALUES (%s, %s, %s, %s, %s, %s, %s) "
        "RETURNING id",
        (nome, ato, provedor, prompt, 1 if ativo else 0, agora, agora),
    )
    return int(novo[0]["id"])


def atualizar_robo(
    con,
    robo_id: int,
    *,
    nome: str,
    ato: str,
    provedor: str,
    prompt: str,
    ativo: int,
    agora: str,
) -> None:
    banco(con).escrever(
        "UPDATE robo SET nome=%s, ato=%s, provedor=%s, prompt=%s, ativo=%s, "
        "atualizado_em=%s WHERE id=%s",
        (nome, ato, provedor, prompt, 1 if ativo else 0, agora, robo_id),
    )


def adicionar_exemplo(
    con,
    robo_id: int,
    entrada: str,
    saida_esperada: str,
    peso: int = 1,
) -> int:
    novo = banco(con).escrever(
        "INSERT INTO robo_exemplo(robo_id, entrada, saida_esperada, peso) "
        "VALUES (%s, %s, %s, %s) RETURNING id",
        (robo_id, entrada, saida_esperada, int(peso) if peso else 1),
    )
    return int(novo[0]["id"])


def apagar_exemplo(con, robo_id: int, exemplo_id: int) -> None:
    banco(con).escrever(
        "DELETE FROM robo_exemplo WHERE id = %s AND robo_id = %s",
        (exemplo_id, robo_id),
    )


#: Quantos dias o registro dos testes guarda (M5 do LS03; LX13, 19/10/2026).
#: Ninguém lê esta tabela na tela: ela é o rastro de quem testou o quê, e
#: rastro de teste não precisa de um ano de pedidos do balcão no backup.
DIAS_DO_REGISTRO_DE_TESTE = 30


def registrar_teste(
    con,
    *,
    robo_id: int,
    usuario: str,
    pedido: str,
    rascunho: str,
    modo: str,
    agora: str,
) -> int:
    """Grava o teste e apaga os de mais de `DIAS_DO_REGISTRO_DE_TESTE` dias.

    O PEDIDO E O RASCUNHO CHEGAM AQUI JÁ MASCARADOS (quem chama é a tela, que
    mascara antes da rede): até o LX13 o pedido do balcão ficava em claro, sem
    expurgo, e ia em todo backup. A data do corte é calculada no Python (regra
    da casa) e comparada pelo dia, que é o começo de `criado_em`.
    """
    bd = banco(con)
    corte = (date.fromisoformat(str(agora)[:10])
             - timedelta(days=DIAS_DO_REGISTRO_DE_TESTE)).isoformat()
    bd.escrever("DELETE FROM robo_teste_log WHERE left(criado_em, 10) < %s",
                (corte,))
    novo = bd.escrever(
        "INSERT INTO robo_teste_log(robo_id, usuario, pedido, rascunho, "
        "modo, criado_em) VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
        (robo_id, usuario, pedido, rascunho, modo, agora),
    )
    return int(novo[0]["id"])
