"""A PROVA DA INTIMAÇÃO, juntada nos cenários de teste (29/10/2026).

Desde a trava da prova (`protesto_prova`, ordem do oficial de 29/10/2026),
`protesto.lancar_protesto` recusa o título cuja última intimação não está
provada — e a trava não tem chave para desligar. Os testes que lavram protesto
para conferir OUTRA coisa (o livro, o termo, o retorno, o instrumento...)
juntam a prova por aqui, do jeito que a casa a junta:

    PESSOAL — o aviso entregue, com quem recebeu e o comprovante anexado;
    DIGITAL — a Intimação Digital confirmada (INTIMADO) e o histórico guardado;
    EDITAL  — o edital publicado e o comprovante do envio à CENPROT.

E `entregar_com_comprovante` registra a entrega do aviso como a tela registra
desde a mesma data: com quem recebeu e com o arquivo, no mesmo ato.
"""
from __future__ import annotations

import hashlib
import json
import tempfile

from bd_nativo import banco

PDF_DE_TESTE = b"%PDF-1.4\n% comprovante de teste\n"
QUEM_RECEBEU = "RECEBEDOR DE TESTE"


def garantir_anexos(con) -> None:
    """A tabela `attachments` mora no esquema geral (`database.py`), e os
    bancos de unidade só têm o do Protesto: cria a forma mínima dela."""
    bd = banco(con)
    if not bd.tem_tabela("attachments"):
        bd.escrever("""CREATE TABLE IF NOT EXISTS attachments (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            entity_type TEXT NOT NULL, entity_id INTEGER NOT NULL,
            original_name TEXT NOT NULL, stored_name TEXT, stored_path TEXT,
            sha256 TEXT, size_bytes BIGINT, description TEXT,
            uploaded_by INTEGER, uploaded_at TEXT NOT NULL)""")


def _anexar(bd, entidade: str, entity_id: int, quando: str) -> None:
    garantir_anexos(bd)
    valores = {
        "entity_type": entidade, "entity_id": int(entity_id),
        "original_name": "comprovante.pdf", "stored_name": "comprovante.pdf",
        "stored_path": "comprovante.pdf",
        "sha256": hashlib.sha256(f"{entidade}:{entity_id}".encode()).hexdigest(),
        "size_bytes": len(PDF_DE_TESTE), "description": "prova de teste",
        "uploaded_at": quando,
    }
    colunas = [c for c in valores if bd.tem_coluna("attachments", c)]
    bd.escrever(
        f"INSERT INTO attachments({', '.join(colunas)}) "
        f"VALUES ({', '.join(['%s'] * len(colunas))})",
        tuple(valores[c] for c in colunas))


def _proximo(bd, tabela: str, ano: int) -> int:
    linha = bd.um(f"SELECT MAX(numero) AS n FROM {tabela} WHERE ano = %s",
                  (int(ano),))
    return int((linha or {}).get("n") or 0) + 1


def _aviso(bd, titulo_id: int, ano: int, quando: str, *, situacao: str,
           ato_id: int | None) -> int:
    devedor = bd.um("SELECT nome FROM pt_devedores WHERE titulo_id = %s "
                    "ORDER BY id LIMIT 1", (int(titulo_id),))
    return int(bd.escrever(
        """INSERT INTO pt_avisos(titulo_id, numero, ano, devedor_nome,
               situacao, emitido_em, entregue, recebido_por, entrega_em,
               ato_id, criado_em)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
        (int(titulo_id), _proximo(bd, "pt_avisos", ano), int(ano),
         (devedor or {}).get("nome") or "DEVEDOR DE TESTE", situacao, quando,
         1 if situacao == "ENTREGUE" else 0,
         QUEM_RECEBEU if situacao == "ENTREGUE" else None, quando, ato_id,
         quando))[0]["id"])


def juntar_prova(con, titulo_id: int) -> None:
    """Junta à ÚLTIMA intimação válida do título a prova que a trava pede.
    ESCREVE. Chame depois de `lancar_intimacao` e antes de `lancar_protesto`.
    """
    bd = banco(con)
    intim = bd.um(
        """SELECT id, data_ato, detalhe_json FROM pt_atos
            WHERE titulo_id = %s AND tipo = 'INTIMACAO' AND cancelado = 0
            ORDER BY id DESC LIMIT 1""", (int(titulo_id),))
    assert intim, f"o título {titulo_id} não tem intimação para provar"
    intimacao_id = int(intim["id"])
    quando = str(intim["data_ato"])
    if len(quando) == 10:
        quando += "T09:00:00"
    ano = int(quando[:4])
    detalhe = json.loads(intim["detalhe_json"] or "{}") or {}
    modo = str(detalhe.get("modo") or "PESSOAL").upper()
    if modo == "EDITAL":
        edital = bd.um("SELECT id FROM pt_editais WHERE ato_id = %s",
                       (intimacao_id,))
        if edital:
            edital_id = int(edital["id"])
        else:
            aviso_id = _aviso(bd, titulo_id, ano, quando, situacao="EDITAL",
                              ato_id=None)
            edital_id = int(bd.escrever(
                """INSERT INTO pt_editais(numero, ano, aviso_id, titulo_id,
                       publicado_em, teor, ato_id, criado_em)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
                (_proximo(bd, "pt_editais", ano), ano, aviso_id,
                 int(titulo_id), quando[:10], "EDITAL DE TESTE", intimacao_id,
                 quando))[0]["id"])
        _anexar(bd, "PT_EDITAL_CENPROT", edital_id, quando)
    elif detalhe.get("digital"):
        if not bd.tem_tabela("rs_intimacoes"):
            from rs_schema import init_rs_schema
            init_rs_schema(con)
        import centrais_cred as CRED
        bd.escrever(
            """INSERT INTO rs_intimacoes(titulo_id, ambiente, identificador,
                   teor, enviada_em, estado, estado_em, historico)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
            (int(titulo_id), CRED.PRODUCAO, f"PROVA-{intimacao_id}", "{}",
             quando, "INTIMADO", quando, '[{"canal": "EMAIL"}]'))
    else:
        aviso = bd.um("SELECT id FROM pt_avisos WHERE ato_id = %s",
                      (intimacao_id,))
        if aviso:
            aviso_id = int(aviso["id"])
            bd.escrever(
                """UPDATE pt_avisos SET situacao = 'ENTREGUE', entregue = 1,
                          recebido_por = COALESCE(NULLIF(recebido_por, ''), %s)
                    WHERE id = %s""", (QUEM_RECEBEU, aviso_id))
        else:
            aviso_id = _aviso(bd, titulo_id, ano, quando, situacao="ENTREGUE",
                              ato_id=intimacao_id)
        _anexar(bd, "PT_AVISO", aviso_id, quando)


def entregar_com_comprovante(con, aviso_id: int, *, pasta=None,
                             recebido_por: str = QUEM_RECEBEU,
                             nome: str | None = None, **kw) -> dict:
    """`protesto_aviso.registrar_entrega` com `entregue=True`, como a tela a
    faz desde 29/10/2026: com quem recebeu e com o comprovante no mesmo ato.
    O arquivo é um PDF próprio de cada aviso (o mesmo arquivo em dois avisos
    é suspeito, e a trava o recusaria)."""
    import protesto_aviso as AV
    garantir_anexos(con)
    conteudo = PDF_DE_TESTE + f"% aviso {aviso_id}\n".encode()
    return AV.registrar_entrega(
        con, aviso_id, entregue=True, recebido_por=recebido_por,
        comprovante_nome=nome or f"canhoto-aviso-{aviso_id}.pdf",
        comprovante_conteudo=conteudo,
        pasta_de_arquivos=pasta or tempfile.mkdtemp(prefix="cg_comprovante_"),
        **kw)
