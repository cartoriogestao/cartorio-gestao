def test_cada_tipo_de_comprovante_tem_a_sua_regra():
    con = _con()
    pid = _projeto(con)
    outro = _projeto(con, "PRJ-91 — Outro")
    fase = DP.adicionar_fase(con, pid, {"titulo": "Publicar"}, por="ana")
    fase_de_outro = DP.adicionar_fase(con, outro, {"titulo": "Publicar"}, por="ana")
    reg = lambda **k: DP.registrar_comprovante(con, pid, por="ana", **{  # noqa: E731
        "fase_id": fase, "descricao": "prova", "referencia": "", **k})
    with pytest.raises(DP.ProjetoError, match="https://"):
        reg(tipo="LINK", referencia="javascript:alert(1)")
    with pytest.raises(DP.ProjetoError, match="número"):
        reg(tipo="PR", referencia="o de ontem")
    with pytest.raises(DP.ProjetoError, match="arquivo"):
        reg(tipo="ARQUIVO")
    with pytest.raises(DP.ProjetoError, match="tipo"):
        reg(tipo="FOTO")
    with pytest.raises(DP.ProjetoError, match="Descreva"):
        reg(tipo="TEXTO", descricao=" ")
    with pytest.raises(DP.ProjetoError, match="não é deste projeto"):
        reg(tipo="TEXTO", fase_id=fase_de_outro)
    pr = reg(tipo="PR", referencia="#528")
    with pytest.raises(DP.ProjetoError, match="já está registrado"):
        reg(tipo="PR", referencia="528")
    reg(tipo="PR", referencia="528", fase_id=None)    # no projeto, sem fase, é outra chave
    reg(tipo="TEXTO", descricao="Conferido com o oficial")
    reg(tipo="TAREFA", referencia="#12")
    lista = DP.listar_comprovantes(con, pid)
    pr_item = next(c for c in lista if c["id"] == pr)
    assert pr_item["referencia"] == "528" and pr_item["url"] == DP.REPOSITORIO_PR + "528"
    assert next(c for c in lista if c["tipo"] == "TAREFA")["tarefa_id"] == 12


def test_o_arquivo_do_comprovante_vai_para_os_anexos(cg_casa, tmp_path):
    db = cg_casa["db"]
    with db.transaction() as con:
        pid = _projeto(con)
        fase = DP.adicionar_fase(con, pid, {"titulo": "Homologar"}, por="ana")
        with pytest.raises(DP.ProjetoError, match="PDF"):
            DP.guardar_arquivo(con, pid, nome_arquivo="script.exe", conteudo=b"x",
                               pasta=tmp_path, usuario_id=None)
        with pytest.raises(DP.ProjetoError, match="vazio"):
            DP.guardar_arquivo(con, pid, nome_arquivo="a.pdf", conteudo=b"", pasta=tmp_path,
                               usuario_id=None)
        anexo = DP.guardar_arquivo(con, pid, nome_arquivo="C:\\pasta\\relatorio final.pdf",
                                   conteudo=b"%PDF-1.4 ensaio", pasta=tmp_path, usuario_id=None)
        cid = DP.registrar_comprovante(con, pid, fase_id=fase, tipo="ARQUIVO",
                                       descricao="Aceite da homologação", referencia="",
                                       attachment_id=anexo, por="ana")
        linha = banco(con).um("SELECT * FROM attachments WHERE id = %s", (anexo,))
        comp = banco(con).um("SELECT * FROM dev_projetos_comprovantes WHERE id = %s", (cid,))
    assert linha["entity_type"] == DP.ENTIDADE_DO_ANEXO and int(linha["entity_id"]) == pid
    assert linha["original_name"] == "relatorio final.pdf"
    assert Path(linha["stored_path"]).parent == tmp_path and "relatorio" not in linha["stored_name"]
    assert comp["referencia"] == "sha256:" + linha["sha256"] and int(comp["attachment_id"]) == anexo
    with db.transaction() as con:
        outro = _projeto(con, "PRJ-92 — Outro")
        with pytest.raises(DP.ProjetoError, match="não é deste projeto"):
            DP.registrar_comprovante(con, outro, fase_id=None, tipo="ARQUIVO", descricao="x",
                                     referencia="", attachment_id=anexo, por="ana")


