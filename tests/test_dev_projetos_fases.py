def _entrar(cg_casa, nome: str, papel: str):
    cg_casa["db"].create_user(nome, f"{nome.upper()} EXEMPLO LIMA", SENHA, papel)
    c = cg_casa["app"].test_client()
    cg_login(c, nome, SENHA)
    return c


def _token(c) -> str:
    with c.session_transaction() as s:
        return s["csrf_token"]


def _post(c, url, **dados):
    return c.post(url, data={"csrf_token": _token(c), **dados})


def _auditoria(db, acao) -> list[dict]:
    with db.connect() as con:
        return [json.loads(r["details"]) for r in banco(con).ler(
            "SELECT details FROM audit_logs WHERE action = %s ORDER BY id", (acao,))]


def _id_pelo_titulo(db, titulo) -> int:
    with db.connect() as con:
        return int(banco(con).valor("SELECT id FROM dev_projetos WHERE titulo = %s", (titulo,)))


def test_a_ficha_cadastra_fase_comprovante_e_conclui_com_auditoria(cg_casa):
    db = cg_casa["db"]
    c = _entrar(cg_casa, "oficial.exemplo", "ADMIN")
    r = _post(c, f"{BASE}/novo", titulo="PRJ-30 — Ensaio da ficha", codigo="PRJ-30", area="RI",
              responsavel="ti", resultado_pleno="Funciona em produção", prazo="2026-12-01")
    assert r.status_code == 302
    pid = _id_pelo_titulo(db, "PRJ-30 — Ensaio da ficha")
    assert r.headers["Location"].endswith(f"{BASE}/{pid}#nova-fase")
    assert _auditoria(db, "DEV_PROJETO_CRIADO")[-1]["codigo"] == "PRJ-30"
    _post(c, f"{BASE}/novo", titulo="PRJ-30 — Ensaio da ficha")        # repetido: recusa
    assert len(_auditoria(db, "DEV_PROJETO_CRIADO")) == 1

    _post(c, f"{BASE}/{pid}/fases/nova", titulo="Homologar", criterio="Aceite da Central",
          prazo="2026-11-01")
    with db.connect() as con:
        [fase] = DP.listar_fases(con, pid)
    assert _auditoria(db, "DEV_PROJETO_FASE_CRIADA")[-1]["fase_id"] == fase["id"]

    url_fase = f"{BASE}/{pid}/fases/{fase['id']}/alterar"
    _post(c, url_fase, situacao="CONCLUIDA", aguardando_o_que="", observacao="")
    with db.connect() as con:
        assert DP.obter_fase(con, fase["id"])["situacao"] == "A_FAZER"     # sem prova, não conclui
    assert not _auditoria(db, "DEV_PROJETO_FASE_CONCLUIDA")

    r = c.post(f"{BASE}/{pid}/comprovantes", data={
        "csrf_token": _token(c), "fase_id": str(fase["id"]), "tipo": "ARQUIVO",
        "descricao": "Tela do aceite", "referencia": "",
        "arquivo": (io.BytesIO(b"%PDF-1.4 aceite"), "aceite.pdf")},
        content_type="multipart/form-data")
