    [det] = _auditoria(db, "DEV_PROJETO_COMPROVANTE")
    assert det["tipo"] == "ARQUIVO" and det["attachment_id"]

    _post(c, url_fase, situacao="CONCLUIDA", aguardando_o_que="", observacao="")
    [conc] = _auditoria(db, "DEV_PROJETO_FASE_CONCLUIDA")
    assert conc["mudou"]["situacao"] == ["A_FAZER", "CONCLUIDA"]

    _post(c, f"{BASE}/{pid}/editar", titulo="PRJ-30 — Ensaio da ficha", responsavel="gerente")
    assert _auditoria(db, "DEV_PROJETO_ALTERADO")[-1]["mudou"] == {"responsavel": ["ti", "gerente"]}
    _post(c, f"{BASE}/{pid}/andamento", texto="Andamento pela tela")
    assert _auditoria(db, "DEV_PROJETO_ANDAMENTO")

    ficha = c.get(f"{BASE}/{pid}").get_data(as_text=True)
    assert "O que falta para o resultado pleno" in ficha and "Resultado pleno</span>" in ficha
    assert "Funciona em produção" in ficha and "Linha do tempo" in ficha
    assert f"/arquivo/{det['attachment_id']}" in ficha and "aceite.pdf" in ficha
    assert ficha.index("Andamento pela tela") < ficha.index("Projeto cadastrado")   # mais novo antes
    assert c.get(f"/arquivo/{det['attachment_id']}").status_code == 200

    lista = c.get(BASE).get_data(as_text=True)
    assert "1 de 1 fases" in lista and "PRJ-30" in lista
    assert "PRJ-30 — Ensaio da ficha" in c.get(f"{BASE}?area=RI").get_data(as_text=True)
