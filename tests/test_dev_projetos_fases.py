def _contagem(con) -> tuple:
    bd = banco(con)
    return tuple(bd.valor(f"SELECT COUNT(*) FROM {t}") for t in (
        "dev_projetos", "dev_projetos_fases", "dev_projetos_fases_historico",
        "dev_projetos_comprovantes", "dev_projetos_andamento"))


def test_importar_duas_vezes_nao_duplica():
    con = _con()
    r1 = DP.importar(con, _spec(), por="agente-11", agora="2026-11-26T08:00:00")
    assert r1["projeto"] == "CRIADO" and r1["achado_por"] is None and r1["mudou"]
    assert len(r1["fases_criadas"]) == 3 and r1["fases_concluidas"] == [r1["fases_criadas"][0]]
    assert len(r1["comprovantes_criados"]) == 3 and len(r1["andamentos_criados"]) == 1
    antes = _contagem(con)
    r2 = DP.importar(con, _spec(), por="agente-11", agora="2026-11-26T09:00:00")
    assert r2["projeto"] == "SEM_MUDANCA" and r2["achado_por"] == "CODIGO" and not r2["mudou"]
    assert not any(r2[k] for k in ("fases_criadas", "fases_alteradas", "fases_concluidas",
                                   "comprovantes_criados", "andamentos_criados"))
    assert _contagem(con) == antes
