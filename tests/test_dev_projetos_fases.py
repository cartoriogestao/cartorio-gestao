def test_as_regras_da_situacao_da_fase():
    con = _con()
    pid = _projeto(con)
    f1 = DP.adicionar_fase(con, pid, {"titulo": "Levantar", "criterio": "Lista conferida"},
                           por="ana", agora="2026-11-01T10:00:00")
    f2 = DP.adicionar_fase(con, pid, {"titulo": "Homologar"}, por="ana", agora="2026-11-01T10:00:00")
    assert [f["ordem"] for f in DP.listar_fases(con, pid)] == [1, 2]
    with pytest.raises(DP.ProjetoError, match="já tem a fase"):
        DP.adicionar_fase(con, pid, {"titulo": "Levantar"}, por="ana")

    r = DP.alterar_fase(con, f1, {"situacao": "EM_ANDAMENTO"}, por="ana", agora="2026-11-02T08:00:00")
    assert r["mudou"]["situacao"] == ["A_FAZER", "EM_ANDAMENTO"] and r["eventos"] == ["INICIADA"]
    assert DP.obter_fase(con, f1)["iniciada_em"] == "2026-11-02T08:00:00"

    with pytest.raises(DP.ProjetoError, match="aguardando o quê"):
        DP.alterar_fase(con, f1, {"situacao": "AGUARDANDO", "aguardando_o_que": " "}, por="ana")
    DP.alterar_fase(con, f1, {"situacao": "AGUARDANDO", "aguardando_o_que": "a Central responder"},
                    por="ana", agora="2026-11-03T08:00:00")
    assert DP.obter_fase(con, f1)["aguardando_o_que"] == "a Central responder"

    with pytest.raises(DP.ProjetoError, match="anexe um comprovante"):
        DP.alterar_fase(con, f1, {"situacao": "CONCLUIDA"}, por="ana")
    assert DP.obter_fase(con, f1)["situacao"] == "AGUARDANDO"      # a recusa não grava
    DP.registrar_comprovante(con, pid, fase_id=f1, tipo="PR", descricao="o PR que fecha",
                             referencia="#528", por="ana", agora="2026-11-04T08:00:00")
    r = DP.alterar_fase(con, f1, {"situacao": "CONCLUIDA"}, por="bia", agora="2026-11-04T09:00:00")
    assert r["concluida"]
    fase = DP.obter_fase(con, f1)
    assert (fase["concluida_em"], fase["concluida_por"]) == ("2026-11-04T09:00:00", "bia")
    assert fase["aguardando_o_que"] == ""

    # reabrir: a conclusão sai da fase, o primeiro início fica
    DP.alterar_fase(con, f1, {"situacao": "EM_ANDAMENTO"}, por="ana", agora="2026-11-05T08:00:00")
    fase = DP.obter_fase(con, f1)
    assert fase["concluida_em"] is None and fase["iniciada_em"] == "2026-11-02T08:00:00"

    # concluir sem comprovante vale com a observação que explica
    DP.alterar_fase(con, f2, {"situacao": "CONCLUIDA", "observacao": "Conferido na tela da Central"},
                    por="ana")
    with pytest.raises(DP.ProjetoError, match="dispensar"):
        DP.alterar_fase(con, f1, {"situacao": "DISPENSADA", "observacao": ""}, por="ana")
    with pytest.raises(DP.ProjetoError, match="Situação da fase"):
        DP.alterar_fase(con, f1, {"situacao": "QUASE"}, por="ana")
    with pytest.raises(DP.ProjetoError, match="observação"):
        DP.alterar_fase(con, f2, {"observacao": ""}, por="ana")   # concluída sem prova nenhuma


