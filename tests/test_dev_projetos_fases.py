def _semear(db) -> tuple[int, int]:
    with db.transaction() as con:
        pid = _projeto(con)
        fid = DP.adicionar_fase(con, pid, {"titulo": "Primeira"}, por="ana")
        DP.adicionar_fase(con, pid, {"titulo": "Segunda"}, por="ana")
    return pid, fid


