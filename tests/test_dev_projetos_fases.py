def test_o_esquema_so_acrescenta_e_o_projeto_antigo_fica():
    con = conexao_de_teste()
    bd = banco(con)
    # o banco como era antes do S006: só as colunas antigas, com um projeto
    bd.escrever("""CREATE TABLE dev_projetos (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, titulo TEXT NOT NULL UNIQUE,
        status_geral TEXT NOT NULL DEFAULT 'EM_ANDAMENTO', criado_em TEXT NOT NULL,
        atualizado_em TEXT NOT NULL, proximo_passo TEXT)""")
    bd.escrever("INSERT INTO dev_projetos (titulo, criado_em, atualizado_em) "
                "VALUES ('PRJ-01 — Antigo', '2026-10-01', '2026-10-01')")
    DP.init_dev_projetos_schema(con)
    DP.init_dev_projetos_schema(con)          # de novo: nada muda
