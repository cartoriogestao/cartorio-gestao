# ------------------------------------------------------------------ a pessoa (régua larga)


def _parte(con, mid, nome, doc, dono):
    banco(con).escrever(
        """INSERT INTO ri_partes(matricula_id, nome, nome_norm, documento_numero, proprietario_ativo)
           VALUES (%s,%s,%s,%s,%s)""", (mid, nome, nome.lower(), doc, dono))


def _pedido_pessoa(con, dados) -> dict:
    pid = _pedido(con, tipo="1", por="6", matricula_id=None)
    banco(con).escrever("UPDATE onr_cert_pedidos SET dados_json=%s WHERE id=%s",
                        (json.dumps({"TIPO_COBRANCA": "1", **dados}), pid))
    return dict(banco(con).um("SELECT * FROM onr_cert_pedidos WHERE id=%s", (pid,)))


def test_a_mesma_pessoa_partida_em_dois_cadastros_sai_positiva_e_nao_negativa():
    """Com CPF num cadastro (não dona ali) e só com o nome noutro (dona): a
    régua larga acha a dona — a sugestão é POSITIVA, e a negativa é recusada."""
    import ri_certidao_negativa as RINEG
    con = _con()
    _parte(con, 77, "MARIA EXEMPLO", "00000000272", 0)
    _parte(con, 78, "MARIA EXEMPLO", "", 1)
    p = _pedido_pessoa(con, {"CERTIDAO/PESSOA/CPF": "000.000.002-72",
                             "CERTIDAO/PESSOA/NOME": "MARIA EXEMPLO"})
    sug = AUTO.sugerir(con, p)
    assert (sug["etapa"], sug["tipo_ri"]) == (AUTO.A_REVISAR, RINEG.TIPO_POSITIVA)
    with pytest.raises(AUTO.AutoError, match="não se emite negativa"):
        AUTO.conferir_negativa_do_pedido(con, json.loads(p["dados_json"]))


def test_o_pedido_que_traz_so_o_cpf_nao_sai_negativa_sozinho():
    """Só o CPF, e a pessoa está nos livros só pelo nome: a busca pelo CPF
    não acha — e a negativa NÃO é sugerida nem aceita."""
    con = _con()
    _parte(con, 78, "MARIA EXEMPLO", "", 1)
    p = _pedido_pessoa(con, {"CERTIDAO/PESSOA/CPF": "000.000.002-72"})
    sug = AUTO.sugerir(con, p)
    assert sug["etapa"] == AUTO.A_MAO and "só o documento" in sug["motivo"]
    with pytest.raises(AUTO.AutoError, match="só o documento"):
        AUTO.conferir_negativa_do_pedido(con, json.loads(p["dados_json"]))


def test_a_negativa_so_com_documento_e_nome_sem_ninguem():
    import ri_certidao_negativa as RINEG
    con = _con()
