class _DbFalso:
    """A conexão de teste como `ctx.db`: a mesma conexão, e o `log` anotado."""

    def __init__(self, con):
        self.con, self.logs = con, []

    def transaction(self):
        import contextlib
        return contextlib.nullcontext(self.con)

    connect = transaction

    def log(self, user_id, username, action, entity_type=None, entity_id=None,
            details=None, ip_address=None, *, agente=None, a_mando_de=None):
        self.logs.append({"username": username, "action": action,
                          "entity_id": entity_id, "details": details,
                          "agente": agente, "a_mando_de": a_mando_de})


class _CtxFalso:
    def __init__(self, con, pasta):
        self.db, self.pasta_dados, self.parametros = _DbFalso(con), pasta, {}

    def setting(self, chave, padrao=""):
        return padrao


class _SessaoFalsa:
    def __init__(self):
        self.enviados, self.finalizados = [], []

    def enviar_anexos_da_certidao(self, protocolo, lista):
        self.enviados.append((protocolo, [x["NomeArquivo"] for x in lista]))

    def finalizar_certidao(self, protocolo, interesse_social=False):
        self.finalizados.append(protocolo)


P7S = b"0\x82envelope-de-exemplo"


def _para_enviar(con, tmp_path, monkeypatch):
    pasta = tmp_path / "arquivos" / "ri" / "onr" / "certidoes" / "pdf"
    pid, a = _pdf_guardado(con, tmp_path, pasta=pasta)
    gasto = []

