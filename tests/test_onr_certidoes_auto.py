# -*- coding: utf-8 -*-
"""As certidões do ONR no automático, e a exceção «pago no ONR» da trava do selo.

    «o agente 4 vezes por dia [...] prepara a certidao [...] o escrevente
     verifica [...] e aprova o envio» — o oficial, 25/10/2026

O QUE ESTES TESTES PROVAM
    - a régua do «pago no ONR» (`ato_selado.e_certidao_paga_no_onr`): só com a
      aprovação, o orçamento DESTA casa antes do status, cobrança INTEGRAL, o
      status vivo aceito e dentro da janela; mais de um pedido casando: não;
    - TIPO_COBRANCA ausente, «2», «3» ou estranho NÃO cai em integral;
    - a sincronização põe cada pedido na etapa do status dele, e o pago sem o
      nosso orçamento vai para «fazer à mão»;
    - o segundo clique, o pedido que já tem certidão, o status não pago: recusa;
    - a amarra é pelo banco: nenhuma certidão volta a revisar, duas viram erro.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
from banco_de_teste import conexao_de_teste  # noqa: E402

import ato_selado as AS  # noqa: E402
import onr_certidoes as OC  # noqa: E402
import onr_certidoes_auto as AUTO  # noqa: E402
from bd_nativo import banco  # noqa: E402

AGORA = "2026-10-26T14:00:00"
ANTES = "2026-10-26T09:00:00"


def _con():
    con = conexao_de_teste()
    bd = banco(con)
    bd.escrever("""CREATE TABLE ri_matriculas (id bigint PRIMARY KEY, numero TEXT,
                   livro_norm TEXT, tipo_imovel TEXT, rural_urbano TEXT, logradouro TEXT,
                   numero_predial TEXT, complemento_endereco TEXT, bairro TEXT, cidade TEXT,
                   uf TEXT, area_valor TEXT, area_unidade TEXT, encerrada INTEGER DEFAULT 0)""")
    bd.escrever("INSERT INTO ri_matriculas(id, numero) VALUES (78, '1300')")
    bd.escrever("""CREATE TABLE ri_partes (id bigint GENERATED BY DEFAULT AS IDENTITY
                   PRIMARY KEY, matricula_id bigint, nome TEXT, nome_norm TEXT,
                   documento_numero TEXT, documento_tipo TEXT, proprietario_ativo INTEGER)""")
    bd.escrever("INSERT INTO ri_matriculas(id, numero) VALUES (77, '1234')")
    bd.escrever("""CREATE TABLE ri_certidoes (id bigint GENERATED BY DEFAULT AS IDENTITY
                   PRIMARY KEY, numero INTEGER, ano INTEGER, tipo TEXT, matricula_id bigint,
                   finalidade TEXT, emitida_em TEXT, cancelada INTEGER DEFAULT 0)""")
    OC.init_schema(con)
    AUTO.init_schema(con)
    return con


def _pedido(con, *, protocolo="S1", status="Em aberto", cobranca="1", custas_em=ANTES,
            tipo="3", por="4", matricula_id=77) -> int:
    dados = {"PROTOCOLO_SOLICITACAO": protocolo}
    if cobranca is not None:
        dados["TIPO_COBRANCA"] = cobranca
    return int(banco(con).escrever(
        """INSERT INTO onr_cert_pedidos(ambiente, protocolo, tipo_certidao, data_pedido,
               valor, pesquisa_por, status_onr, solicitante, matricula_numero, matricula_id,
               dados_json, xml_pedido, situacao, custas_em, recebido_em, atualizado_em)
           VALUES ('PRODUCAO',%s,%s,%s,'60.00',%s,%s,'BANCO EXEMPLO','1234',%s,%s,'<x/>',
                   'NOVO',%s,%s,%s) RETURNING id""",
        (protocolo, tipo, ANTES, por, status, matricula_id, json.dumps(dados),
         custas_em, ANTES, ANTES))[0]["id"])


def _aprovado(con, pid, *, status="Em aberto", conferido=AGORA):
    banco(con).escrever(
        """INSERT INTO onr_cert_auto(pedido_id, etapa, via, tipo_ri, aprovado_por_user_id,
               aprovado_por_nome, aprovado_em, status_onr_conferido, status_conferido_em,
               finalidade_marca, emitindo_desde, criado_em, atualizado_em)
           SELECT id, 'EMITINDO', 'MATRICULA', 'INTEIRO_TEOR', 1, 'Mario Exemplo', %s, %s, %s,
                  'Pedido ONR ' || protocolo, %s, %s, %s FROM onr_cert_pedidos WHERE id=%s""",
        (conferido, status, conferido, conferido, conferido, conferido, pid))


def _certidao(con, protocolo="S1", emitida=AGORA, tipo="INTEIRO_TEOR") -> int:
    return int(banco(con).escrever(
        """INSERT INTO ri_certidoes(numero, ano, tipo, matricula_id, finalidade, emitida_em)
           VALUES (1, 2026, %s, 77, %s, %s) RETURNING id""",
        (tipo, f"Pedido ONR {protocolo}", emitida))[0]["id"])


ENVELOPE = {"codigoAto": "16.24.4"}


# ------------------------------------------------------------------ a cobrança


@pytest.mark.parametrize("valor,integral", [
    (None, False), ("", False), ("2", False), ("3", False), ("XYZ", False),
    ("1", True), ("INTEGRAL", True)])
def test_so_a_cobranca_integral_abre_e_o_resto_recusa(valor, integral):
    dados = {} if valor is None else {"TIPO_COBRANCA": valor}
    assert AS.cobranca_integral_do_pedido_onr(json.dumps(dados)) is integral
    pedido = {"dados_json": json.dumps(dados), "custas_em": ANTES}
    assert (AUTO.motivo_sem_selo_pago_no_onr(pedido) is None) is integral


# ------------------------------------------------------------------ a trava


def test_a_certidao_aprovada_e_paga_no_onr_passa_a_trava():
    con = _con()
    pid = _pedido(con)
    _aprovado(con, pid)
    cid = _certidao(con)
    assert AS.e_certidao_paga_no_onr(banco(con), "ri_certidoes", cid, ENVELOPE, AGORA)
    # e só para a certidão do RI, com item 16.24
    assert not AS.e_certidao_paga_no_onr(banco(con), "rc_certidoes", cid, ENVELOPE, AGORA)
    assert not AS.e_certidao_paga_no_onr(banco(con), "ri_certidoes", cid,
                                         {"codigoAto": "16.1"}, AGORA)


@pytest.mark.parametrize("mudanca", [
    {"custas_em": None},                       # sem o orçamento desta casa
    {"custas_em": "2026-10-26T15:00:00"},       # orçamento DEPOIS da conferência
    {"cobranca": "3"},                         # isenção total
    {"cobranca": None},                        # sem o campo
])
def test_sem_orcamento_nosso_ou_sem_cobranca_integral_nao_passa(mudanca):
    con = _con()
    pid = _pedido(con, **mudanca)
    _aprovado(con, pid)
    cid = _certidao(con)
    assert not AS.e_certidao_paga_no_onr(banco(con), "ri_certidoes", cid, ENVELOPE, AGORA)


def test_status_nao_pago_ou_fora_da_janela_nao_passa():
    con = _con()
    pid = _pedido(con)
    _aprovado(con, pid, status="Aguardando pagamento")
    cid = _certidao(con)
    assert not AS.e_certidao_paga_no_onr(banco(con), "ri_certidoes", cid, ENVELOPE, AGORA)
    con = _con()
    pid = _pedido(con)
    _aprovado(con, pid, conferido="2026-10-26T13:00:00")      # 60 min antes
    cid = _certidao(con)
    assert not AS.e_certidao_paga_no_onr(banco(con), "ri_certidoes", cid, ENVELOPE, AGORA)


def test_dois_pedidos_casando_a_mesma_certidao_nao_passa():
    con = _con()
    for _ in range(2):
        _aprovado(con, _pedido(con, protocolo="S1" if _ == 0 else "S2"))
    banco(con).escrever("UPDATE onr_cert_auto SET finalidade_marca='Pedido ONR S1'")
    cid = _certidao(con)
    assert not AS.e_certidao_paga_no_onr(banco(con), "ri_certidoes", cid, ENVELOPE, AGORA)


def test_o_selar_depois_exige_nova_conferencia_dentro_da_janela():
    con = _con()
    pid = _pedido(con)
    _aprovado(con, pid)
    cid = _certidao(con)
    banco(con).escrever("UPDATE onr_cert_auto SET certidao_id=%s, etapa='SEM_SELO'", (cid,))
    dia_seguinte = "2026-10-27T10:00:00"
    assert not AS.e_certidao_paga_no_onr(banco(con), "ri_certidoes", cid, ENVELOPE, dia_seguinte)
