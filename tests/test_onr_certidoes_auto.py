PDF = b"%PDF-1.4\n% certidao de exemplo\n%%EOF\n"


def _pdf_guardado(con, tmp_path, *, conteudo=PDF, pasta=None, auditar=True,
                  certidao_da_auditoria=None):
    import hashlib
    pid = _pedido(con)
    _aprovado(con, pid)
    cid = _certidao(con)
    pasta = pasta or (tmp_path / "pdf")
    sha = AUTO.guardar_pdf(con, pid, conteudo, pasta=pasta, usuario_id=1, agora=AGORA)
    assert sha == hashlib.sha256(conteudo).hexdigest()
    banco(con).escrever("UPDATE onr_cert_auto SET certidao_id=%s, etapa='A_ASSINAR' "
                        "WHERE pedido_id=%s", (cid, pid))
    if auditar:
        banco(con).escrever(
            "INSERT INTO audit_logs(ts, action, entity_type, entity_id, details) "
            "VALUES (%s,%s,'onr_cert_pedidos',%s,%s)",
            (AGORA, AUTO.ACAO_PDF_GERADO, pid,
             json.dumps({"certidao_id": certidao_da_auditoria or cid, "sha256": sha})))
    return pid, AUTO.preparo(con, pid)


