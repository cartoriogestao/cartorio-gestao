def test_pdf_apontado_por_fora_ou_trocado_o_robo_recusa(tmp_path):
    """O caso do achado: alguém escreve na linha um PDF de outro lugar, com o
    sha dele — ou troca o arquivo e a linha juntos."""
    con = _con()
    _, a = _pdf_guardado(con, tmp_path, pasta=tmp_path / "outra")
    with pytest.raises(AUTO.RecusaDoRobo, match="fora da pasta"):
        AUTO.pdf_conferido(con, a, tmp_path / "pdf")
    con = _con()
    pid, a = _pdf_guardado(con, tmp_path)
    Path(a["pdf_caminho"]).write_bytes(b"%PDF-1.4\n% outro papel\n%%EOF\n")
