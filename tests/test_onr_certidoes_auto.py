def _pedido(con, *, protocolo="S1", status="Em aberto", cobranca="1", custas_em=ANTES,
            tipo="3", por="4", matricula_id=77) -> int:
    dados = {"PROTOCOLO_SOLICITACAO": protocolo}
    if cobranca is not None:
        dados["TIPO_COBRANCA"] = cobranca
    return int(banco(con).escrever(
        """INSERT INTO onr_cert_pedidos(ambiente, protocolo, tipo_certidao, data_pedido,
               valor, pesquisa_por, status_onr, solicitante, matricula_numero, matricula_id,
               dados_json, xml_pedido, situacao, custas_em, recebido_em, atualizado_em)
           VALUES ('PRODUCAO',%s,%s,%s,'60.00',%s,%s,'BANCO EXEMPLO','1234',%s,%s,'<x/>',
                   'NOVO',%s,%s,%s) RETURNING id""",
        (protocolo, tipo, ANTES, por, status, matricula_id, json.dumps(dados),
         custas_em, ANTES, ANTES))[0]["id"])


def _aprovado(con, pid, *, status="Em aberto", conferido=AGORA):
    banco(con).escrever(
        """INSERT INTO onr_cert_auto(pedido_id, etapa, via, tipo_ri, aprovado_por_user_id,
               aprovado_por_nome, aprovado_em, status_onr_conferido, status_conferido_em,
               finalidade_marca, emitindo_desde, criado_em, atualizado_em)
           SELECT id, 'EMITINDO', 'MATRICULA', 'INTEIRO_TEOR', 1, 'Mario Exemplo', %s, %s, %s,
                  'Pedido ONR ' || protocolo, %s, %s, %s FROM onr_cert_pedidos WHERE id=%s""",
        (conferido, status, conferido, conferido, conferido, conferido, pid))


def _certidao(con, protocolo="S1", emitida=AGORA, tipo="INTEIRO_TEOR") -> int:
    return int(banco(con).escrever(
        """INSERT INTO ri_certidoes(numero, ano, tipo, matricula_id, finalidade, emitida_em)
           VALUES (1, 2026, %s, 77, %s, %s) RETURNING id""",
        (tipo, f"Pedido ONR {protocolo}", emitida))[0]["id"])


