"""As certidões do ONR no automático, e a exceção «pago no ONR» da trava do selo.

    «o agente 4 vezes por dia [...] prepara a certidao [...] o escrevente
     verifica [...] e aprova o envio» — o oficial, 25/10/2026

O QUE ESTES TESTES PROVAM
    - a régua do «pago no ONR» (`ato_selado.e_certidao_paga_no_onr`): só com a
      aprovação, o orçamento DESTA casa antes do status, cobrança INTEGRAL, o
      status vivo aceito e dentro da janela; mais de um pedido casando: não;
    - TIPO_COBRANCA ausente, «2», «3» ou estranho NÃO cai em integral;
    - a sincronização põe cada pedido na etapa do status dele, e o pago sem o
      nosso orçamento vai para «fazer à mão»;
    - o segundo clique, o pedido que já tem certidão, o status não pago: recusa;
    - a amarra é pelo banco: nenhuma certidão volta a revisar, duas viram erro.
"""
