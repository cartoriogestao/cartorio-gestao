def test_o_estorno_prende_o_item_antes_do_deposito():
    """O estorno prendia o depósito e depois o item — o contrário de
    `pagar_item`. O balcão que cobre outro ato do mesmo protocolo (item →
    depósito) e o que estorna (depósito → item) davam deadlock no PostgreSQL.
    Com o item seguro por outro balcão, o estorno espera por ele SEM ter
    prendido o depósito."""
    con = _casa()
    p = _protocolo(con)
    item = _item(con, p["protocolo_id"], valor="80,00")
    _ligar(con, item)
    dep = _deposito(con, p["protocolo_id"], valor="100,00")
    _reservar_e_cair(con)
    segura, olho = _outra_conexao(con), _outra_conexao(con)
    _ABERTAS.extend([segura, olho])
    segura.execute("BEGIN")
    segura.execute("SELECT id FROM cx_protocolo_atos WHERE id = %s FOR UPDATE", (item,))
    con_b = sqlite3.connect(str(_ARQUIVOS[id(con)]))
    _ABERTAS.append(con_b)
    saida = {}

    def estorno():
        try:
            saida["feitas"] = AS.estornar_reservas_orfas(con_b, agora="2026-10-19T11:00:00")
            con_b.commit()
        except Exception as erro:              # noqa: BLE001
            saida["erro"] = erro
    t = threading.Thread(target=estorno)
    t.start()
    esperando = False
    try:
        for _ in range(100):
            esperando = bool(olho.execute(
                """SELECT count(*) FROM pg_stat_activity
                    WHERE datname = current_database() AND wait_event_type = 'Lock'
                      AND query ILIKE %s""",
                ("%FROM cx_protocolo_atos%FOR UPDATE%",)).fetchone()[0])
            if esperando or not t.is_alive():
                break
            time.sleep(0.05)
        assert esperando, saida or "o estorno não chegou a esperar pelo item"
        assert _linha_livre(olho, "cx_depositos", dep), \
            "o estorno prendeu o depósito antes do item"
    finally:
        segura.execute("ROLLBACK")
        t.join(30)
    assert not t.is_alive() and "erro" not in saida, saida.get("erro")
    assert saida["feitas"] == [{"referencia": "pt_atos:1", "resultado": "ESTORNADA"}]
    assert _saldo(con, dep) == 10000


