def _lx21b_contar_consultas(monkeypatch) -> list:
    """Cada comando que o `bd_nativo` manda ao PostgreSQL entra na lista."""
    import bd_nativo
    feitas = []
    original = bd_nativo.Banco._rodar

    def contando(self, sql, parametros=None):
        feitas.append(sql)
        return original(self, sql, parametros)

    monkeypatch.setattr(bd_nativo.Banco, "_rodar", contando)
    return feitas


