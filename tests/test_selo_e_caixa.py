def _em_outro_balcao(arquivo, **kw):
    """Roda `_selar` noutra conexão e noutro fio; devolve (resultado, segundos)."""
    con_b = sqlite3.connect(str(arquivo))
    saida = {}

    def balcao():
        inicio = time.monotonic()
        try:
            saida["r"] = _selar(con_b, **kw)
        except Exception as erro:              # noqa: BLE001
            saida["erro"] = erro
        saida["segundos"] = time.monotonic() - inicio
    t = threading.Thread(target=balcao)
    t.start()
    t.join(30)
    con_b.close()
    assert not t.is_alive(), "o outro balcão ficou preso esperando o aparelho"
    assert "erro" not in saida, saida.get("erro")
    return saida["r"], saida["segundos"]


