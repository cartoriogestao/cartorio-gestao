def test_unlock_que_falha_depois_do_selo_nao_desfaz_a_reserva_nem_o_debito(
        tmp_path, monkeypatch, caplog):
    """A soltura da trava do SID mora no fim do `selar`. Quando o
    `pg_advisory_unlock` falhava no caminho de SUCESSO, ela desfazia a
    transação de quem chamou — e com ela a reserva da cobertura e o débito
    no depósito —, e o `selar` seguia: gravava o selo pago no razão e o
    devolvia. Só a saída por erro desfaz; no sucesso fica o log, e a reserva,
    o débito e o selo ficam juntos."""
    pytest.importorskip("cryptography")
    import bd_nativo
    import selador_cliente as CL
    from selador_falso import SeladorFalso
    con = _casa()
    p = _protocolo(con)
    _ligar(con, _item(con, p["protocolo_id"], valor="80,00"), ato_id=3)
    dep = _deposito(con, p["protocolo_id"], valor="100,00")
    caminho, envelope = _apontamento()

    class UnlockQuebrado(bd_nativo.Banco):
        def _rodar(self, sql, parametros=None):
            if "pg_advisory_unlock(" in sql:
                raise sqlite3.OperationalError("o unlock falhou de propósito")
            return super()._rodar(sql, parametros)

    with SeladorFalso() as s:
        _apontar_o_selador_falso(con, tmp_path, s)
        # A transação de quem chama: a reserva e o débito AINDA sem commit.
        feito = AS.cobrir_o_selo(con, tabela="pt_atos", ato_id=3, referencia="pt_atos:3",
                                 dados=envelope, usuario=ESCREVENTE, agora=AGORA,
                                 cns=CNS, atribuicao="PROTESTO")
        assert feito["reserva"]["situacao"] == AS.RESERVADA
        monkeypatch.setattr(CL, "banco", UnlockQuebrado)
        try:
            with caplog.at_level(logging.WARNING, logger="selador_cliente"):
                selos = CL.selar(con, tmp_path, caminho, envelope, referencia="pt_atos:3",
                                 atribuicao="PROTESTO", agora=AGORA, cns=CNS,
                                 usuario=ESCREVENTE)
            con.commit()
        finally:
            # A trava ficou presa nesta conexão (o log diz): solta-se aqui, para
            # a conexão não voltar ao reservatório com ela.
            _banco(con).ler("SELECT pg_advisory_unlock_all() AS ok")
    assert (_cobertura(con, "pt_atos:3") or {}).get("situacao") == AS.RESERVADA, \
        "o unlock que falhou desfez a reserva"
    assert _saldo(con, dep) == 2000, "o unlock que falhou devolveu o débito"
    assert _banco(con).valor("SELECT count(*) AS n FROM sd_selos WHERE numero = %s",
                             (selos[0].numero,)) == 1
    assert "depois do selo obtido" in caplog.text
    assert "ficou presa nesta conexão" in caplog.text


def _rodar_a_conferencia(con) -> dict:
    """`tools/conferir_referencias_de_selo.sql` no schema deste teste, como o
    psql o rodaria: sem as linhas de comando do psql e com o schema no lugar."""
    texto = (RAIZ / "tools" / "conferir_referencias_de_selo.sql").read_text(encoding="utf-8")
    linhas = [ln for ln in texto.splitlines()
              if not ln.lstrip().startswith("\\") and not ln.lstrip().startswith("--")]
    sql = "\n".join(linhas).replace(':"schema"', f'"{con.schema}"')
    outra = _outra_conexao(con)
    _ABERTAS.append(outra)
    saida = {}
    for comando in (c.strip() for c in sql.split(";")):
        if not comando:
            continue
        cur = outra.execute(comando)
        if cur.description:
            nomes = [d.name for d in cur.description]
            saida = {r[0]: dict(zip(nomes, r)) for r in cur.fetchall()}
    return saida


