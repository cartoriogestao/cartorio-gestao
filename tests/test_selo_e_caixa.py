class _Db:
    """O que `obter_selo` usa de `db`: transação própria, que confirma, e a
    conexão sem transação do pedido ao aparelho (o `with` dela confirma)."""

    def __init__(self, con):
        self.con = con

    def connect(self):
        return self.con

    def transaction(self):
        from contextlib import contextmanager

        @contextmanager
        def _abrir():
            try:
                yield self.con
                self.con.commit()
            except BaseException:
                self.con.rollback()
                raise
        return _abrir()

    def get_setting(self, chave, padrao=""):
        return padrao

    def list_users(self, active_only=True):
        return []


