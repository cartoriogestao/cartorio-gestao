def _outra_conexao(con):
    """Uma conexão de fora, no schema deste teste: o outro balcão."""
    import psycopg

    import banco_pg
    outra = psycopg.connect(banco_pg.dsn(), autocommit=True)
    outra.execute(f'SET search_path TO "{con.schema}", public')
    return outra


def _linha_livre(outra, tabela, id_) -> bool:
    import psycopg
    try:
        outra.execute(f"SELECT id FROM {tabela} WHERE id = %s FOR UPDATE NOWAIT", (id_,))
    except psycopg.errors.LockNotAvailable:
        return False
    return True


def _trava_livre(outra, chave) -> bool:
    if isinstance(chave, int):
        return bool(outra.execute("SELECT pg_try_advisory_xact_lock(%s)",
                                  (chave,)).fetchone()[0])
    return bool(outra.execute("SELECT pg_try_advisory_xact_lock(hashtext(%s))",
                              (chave,)).fetchone()[0])


