def test_dois_balcoes_nao_gastam_o_mesmo_saldo():
    """O segundo débito espera o primeiro (FOR UPDATE) e lê o saldo de depois."""
    con_a = _casa()
    p = _protocolo(con_a)
    item_a = _item(con_a, p["protocolo_id"], valor="80,00")
    item_b = _item(con_a, p["protocolo_id"], valor="80,00")
    dep = _deposito(con_a, p["protocolo_id"], valor="100,00")
    # A segunda conexão abre o MESMO banco de teste.
    con_b = sqlite3.connect(str(_ARQUIVOS[id(con_a)]))
    feito_a = DEP.pagar_item(con_a, item_a, agora=AGORA, quem="A")
    assert feito_a and feito_a["saldo_centavos"] == 2000
    resultado = {}

    def balcao_b():
        try:
            resultado["b"] = DEP.pagar_item(con_b, item_b, agora=AGORA, quem="B")
            con_b.commit()
        except Exception as erro:              # noqa: BLE001
            resultado["erro"] = erro

    t = threading.Thread(target=balcao_b)
    t.start()
    time.sleep(0.8)
    assert t.is_alive(), "o segundo balcão não esperou a trava do primeiro"
    con_a.commit()
    t.join(20)
    assert not t.is_alive()
    assert "erro" not in resultado, resultado.get("erro")
    assert resultado["b"] is None, "o segundo débito gastou um saldo que não havia"
    assert _saldo(con_a, dep) == 2000
    assert _banco(con_a).valor("SELECT quitado FROM cx_protocolo_atos WHERE id = %s",
                               (item_b,)) == 0
    con_b.close()


# ------------------- o «usar» da tela do caixa quita o item (LD06, art. 202)


def test_usar_o_deposito_quita_o_item_inteiro_e_pula_o_que_nao_cabe():
    """Meio item pago não existe no caixa: o valor usado quita, na ordem do
    protocolo, cada item que ele cobre inteiro, e o débito de cada um fica em
    `cx_deposito_usos` com o item — o rastro que o livro lê (art. 198, IV)."""
    con = _casa()
    p = _protocolo(con, atribuicao="RI")
    caro = _item(con, p["protocolo_id"], codigo="16.24.1", valor="80,00")
    barato = _item(con, p["protocolo_id"], codigo="16.24.4", valor="15,00")
    dep = _deposito(con, p["protocolo_id"])
    itens = DEP.prender_itens_a_pagar(con, p["protocolo_id"])
    feitos = DEP.quitar_itens_com_o_deposito(con, dep, itens, 2000, agora=AGORA,
                                             quem=ESCREVENTE)
    con.commit()
    assert [f["item"]["id"] for f in feitos] == [barato]
    assert _saldo(con, dep) == 8500
    bd = _banco(con)
    assert bd.valor("SELECT quitado FROM cx_protocolo_atos WHERE id = %s", (caro,)) == 0
    assert bd.valor("SELECT quitado_por FROM cx_protocolo_atos WHERE id = %s",
                    (barato,)) == "DEPÓSITO PRÉVIO DP2026.10.1"
    assert [(u["item_id"], int(u["valor_centavos"])) for u in bd.ler(
        "SELECT item_id, valor_centavos FROM cx_deposito_usos ORDER BY id")] == [
        (barato, 1500)]


def test_usar_e_o_selo_no_mesmo_item_nao_pagam_duas_vezes():
    """O «usar» prende o item ANTES do depósito, na ordem do selo (`pagar_item`):
    o selo do mesmo item, ao mesmo tempo, espera — e, solto, acha o item pago
    e não debita de novo. Presos em ordens contrárias, os dois se esperariam um
    ao outro, e o PostgreSQL derrubaria um deles por deadlock."""
    con_a = _casa()
    p = _protocolo(con_a, atribuicao="RI")
    item = _item(con_a, p["protocolo_id"], codigo="16.24.1", valor="40,00")
    dep = _deposito(con_a, p["protocolo_id"], valor="100,00")
    con_b = sqlite3.connect(str(_ARQUIVOS[id(con_a)]))
    _ABERTAS.append(con_b)
    itens = DEP.prender_itens_a_pagar(con_a, p["protocolo_id"])
    feitos = DEP.quitar_itens_com_o_deposito(con_a, dep, itens, 4000, agora=AGORA,
                                             quem="A")
    assert [f["item"]["id"] for f in feitos] == [item]
    resultado = {}

    def selo_b():
        try:
            resultado["b"] = DEP.pagar_item(con_b, item, agora=AGORA, quem="B")
            con_b.commit()
        except Exception as erro:              # noqa: BLE001
            resultado["erro"] = erro

    t = threading.Thread(target=selo_b)
    t.start()
    time.sleep(0.8)
    assert t.is_alive(), "o selo não esperou a trava do «usar»"
    con_a.commit()
    t.join(20)
    assert not t.is_alive()
    assert "erro" not in resultado, resultado.get("erro")
    assert resultado["b"] == {"ja_quitado": True}
    assert _saldo(con_a, dep) == 6000
    assert _banco(con_a).valor(
        "SELECT count(*) AS n FROM cx_deposito_usos WHERE item_id = %s", (item,)) == 1


def test_a_certidao_cancelada_solta_so_a_marca_inteira_dela():
    """`soltar_itens_do_ato` (LD06) devolve ao protocolo o item que a tela ligou
    à certidão cancelada — e só ele: o item de outra certidão continua dela, e
    o consumo por unidade (`consumir_item`) tem o seu espelho, `devolver_item`."""
    con = _casa()
    p = _protocolo(con, atribuicao="RTD")
    deste = _item(con, p["protocolo_id"], codigo="15.10.1")
    de_outro = _item(con, p["protocolo_id"], codigo="15.10.1")
    por_unidade = _item(con, p["protocolo_id"], codigo="15.10.1", quantidade=2)
    bd = _banco(con)
    for item, ato in ((deste, 7), (de_outro, 8)):
        bd.escrever("""UPDATE cx_protocolo_atos SET usado_em = %s, usado_por_ato_id = %s,
                              usado_por_tabela = 'at_certidoes' WHERE id = %s""",
                    (AGORA, ato, item))
    con.commit()
    _ligar(con, por_unidade, ato_id=7, tabela="at_certidoes")
    assert CXP.soltar_itens_do_ato(con, "at_certidoes", 7) == 1
    con.commit()
    linhas = {int(r["id"]): r for r in bd.ler(
        "SELECT * FROM cx_protocolo_atos ORDER BY id")}
    assert (linhas[deste]["usado_em"], linhas[deste]["usado_por_ato_id"],
            linhas[deste]["usado_por_tabela"]) == (None, None, None)
    assert linhas[de_outro]["usado_por_ato_id"] == 8
    assert (linhas[por_unidade]["usado_por_ato_id"],
            linhas[por_unidade]["quantidade_usada"]) == (7, 1)


