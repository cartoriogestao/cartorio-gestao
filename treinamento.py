SCHEMA = """CREATE TABLE IF NOT EXISTS tr_tentativas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES users(id), aula text NOT NULL,
    versao text NOT NULL, feito_em text NOT NULL,
    acertos bigint NOT NULL, total bigint NOT NULL, aprovado boolean NOT NULL,
    respostas text NOT NULL, UNIQUE(usuario_id,aula,versao,feito_em,respostas)
)"""


def init_schema(con):
    bd = banco(con)
    if not bd.tem_tabela("tr_tentativas"):
        bd.escrever(SCHEMA)
    if not bd.tem_tabela("tr_orientacoes"):
        bd.escrever("""CREATE TABLE IF NOT EXISTS tr_orientacoes (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            aula text NOT NULL, conteudo text NOT NULL, fontes text NOT NULL,
            motivo text NOT NULL, publicado_em text NOT NULL,
            usuario_id bigint NOT NULL REFERENCES users(id), nome_snapshot text NOT NULL
        )""")
    if not bd.tem_tabela("ix_tr_tentativas_usuario_aula"):
        bd.escrever("CREATE INDEX IF NOT EXISTS ix_tr_tentativas_usuario_aula ON tr_tentativas (usuario_id,aula,id)")


def normal(texto):
    return "".join(c for c in unicodedata.normalize("NFD", str(texto or "")).lower()
                   if unicodedata.category(c) != "Mn")


