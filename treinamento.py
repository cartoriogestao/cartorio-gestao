def progresso(con, usuario_id):
    return {r["aula"]: r for r in banco(con).ler("""SELECT aula,versao,feito_em,aprovado,acertos,total
        FROM (SELECT *,row_number() OVER (PARTITION BY aula ORDER BY id DESC) AS ordem
              FROM tr_tentativas WHERE usuario_id=%s) x WHERE ordem=1""", (int(usuario_id),))}


def avaliar(con, aula_atual, respostas, *, usuario_id, agora, versao):
    if versao != aula_atual["versao"]:
        raise ValueError("A aula foi atualizada. Releia a versão atual antes de refazer a prática.")
    qs = aula_atual["questoes"]
    if len(respostas) != len(qs) or any(type(v) is not int or not 0 <= v < len(q["opcoes"]) for v, q in zip(respostas, qs)):
        raise ValueError("Responda todas as situações da prática.")
    acertos = sum(v == q["correta"] for v,q in zip(respostas,qs))
    aprovado = acertos == len(qs)
    banco(con).escrever("""INSERT INTO tr_tentativas
        (usuario_id,aula,versao,feito_em,acertos,total,aprovado,respostas)
        VALUES (%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING""",
        (int(usuario_id),aula_atual["id"],versao,agora,acertos,len(qs),aprovado,json.dumps(respostas)))
    return {"acertos": acertos, "total": len(qs), "aprovado": aprovado,
            "devolutiva": [{"acertou": v==q["correta"],"texto":q["texto"],
                            "orientacao":q["opcoes"][q["correta"]],"explica":q["explica"]}
                           for v,q in zip(respostas,qs)]}


def aula_da_tela(endpoint, papel):
    exata = next((x for x in aulas(papel) if x.get("endpoint") == endpoint and x["tipo"] == "funcao"), None)
    if exata:
        return exata
    if endpoint in ("caixa_protocolo", "at_ficha"):
        return aula("roteiro-atendimento", papel)
    if endpoint.startswith(("ri_nota", "caixa_exigencia")):
        return aula("roteiro-nota", papel)
    if endpoint.startswith("ri_qualifica"):
        return aula("roteiro-qualificacao", papel)
    return None
